/**
 * Очередь: следующая работа начинается только после конца предыдущей.
 *
 * Зачем такая мелочь отдельным файлом. Очередей в node-host две — запись в
 * secure-store и отправка сообщений, — и обе держатся на одной неочевидной
 * детали: `then(fn, fn)`. Хвост цепочки принимает и успех, и отказ одинаково;
 * с обычным `then(fn)` первое же исключение остановило бы очередь навсегда, а
 * не только свою работу. Вторая деталь — гашение самой цепочки (`undefined` на
 * оба исхода): отказ вызывающий забирает себе, и без этого он вторым концом
 * считался бы никем не обработанным.
 *
 * Очередь у каждого потребителя своя: общая связала бы независимые дела — а
 * ради чего заведена каждая из них, сказано на месте.
 */
export type SerialQueue = <T>(fn: () => Promise<T>) => Promise<T>;

export function makeSerialQueue(): SerialQueue {
  let chain: Promise<unknown> = Promise.resolve();
  return <T>(fn: () => Promise<T>): Promise<T> => {
    const next = chain.then(fn, fn);
    chain = next.then(
      () => undefined,
      () => undefined
    );
    return next;
  };
}
