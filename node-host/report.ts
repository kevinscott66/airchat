/**
 * Печать хода проверки и её итог — общая для `proofBody.ts` и `mcp/scenario.ts`.
 *
 * Обе проверки — не «упало или нет», а список утверждений с фактами, и обе
 * читаются не человеком построчно, а глазами по столбцу `OK`/`FAIL`. Поэтому
 * формат строки и её ширина — часть проверки, а не оформление: разойдись они,
 * два вывода перестали бы читаться одинаково.
 *
 * Счётчик провалов живёт здесь же, и здесь же он превращается в код возврата:
 * его нельзя было оставить на вызывающем, потому что забытый `process.exitCode`
 * означал бы «всё хорошо» для надзирателя при полном экране `FAIL`.
 */
export function say(line: string): void {
  process.stdout.write(`${line}\n`);
}

let failures = 0;

/** Утверждение с печатью факта: и успех, и провал видны в выводе одинаково. */
export function check(ok: boolean, label: string, fact: string): void {
  if (!ok) failures += 1;
  say(`  ${ok ? 'OK  ' : 'FAIL'} ${label}: ${fact}`);
}

/**
 * Итог и код возврата. `lastLine` — то, что у каждой проверки своё: куда она
 * сложила оставленный после себя каталог.
 */
export function finish(lastLine: string): void {
  say(`ИТОГ: провалов ${failures}`);
  say(lastLine);
  if (failures > 0) process.exitCode = 1;
}
