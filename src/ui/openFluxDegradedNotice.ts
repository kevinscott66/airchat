/**
 * Сказать человеку, что после смены сети туннель не поднялся.
 *
 * Политика самого туннеля — fail-open, и она осознанная: ядро не поднялось —
 * трафик идёт напрямую, потому что без туннеля переписка хотя бы работает, а
 * без связи не работает ничего (см. шапку `openFluxNetworkGuard`). Спорить с
 * этим здесь не о чем.
 *
 * Не прикрыто выбором другое — молчание. Единственным подписчиком на
 * `addOpenFluxReviveListener` был экран настроек OpenFlux, то есть человек
 * узнавал о переходе на прямой трафик, только если у него в эту секунду открыт
 * этот экран. А включают туннель как раз те, кому важно, каким путём идёт их
 * трафик: вышел на улицу, Wi-Fi сменился на LTE, ядро не поднялось — и дальше
 * всё выглядит работающим. Тихий fail-open и fail-open, о котором сказали, —
 * это разные вещи, и вторая честнее.
 *
 * Тост, а не окно: чинить человеку в этот момент нечего, решение за него
 * никто не принимает, а перегораживать переписку сообщением о том, что
 * переписка работает, — издевательство.
 */
import { log } from '../core/logger';
import {
  addOpenFluxReviveListener,
  type OpenFluxRevived,
} from '../core/vpn/openFluxNetworkGuard';
import { pushToast } from './components/appNotify';

/**
 * Что показать по итогам захода. `null` — показывать нечего: всё поднялось.
 *
 * Два отказа здесь разные, и человеку они означают разное. Ядро не поднялось —
 * связь есть, туннеля нет, делать ничего не надо. Ядро поднялось, а соединения
 * не переоткрылись — связи нет вовсе, и это единственный случай, когда идти в
 * настройки имеет смысл.
 */
export function openFluxNoticeText(r: OpenFluxRevived): string | null {
  if (r.transport === 'failed') {
    return 'Сеть сменилась, и соединение не переоткрылось. Откройте настройки OpenFlux.';
  }
  if (r.status === 'failed') {
    return 'Сеть сменилась, туннель не поднялся. Связь идёт напрямую, без него.';
  }
  return null;
}

/**
 * Следить за переподъёмом туннеля и сообщать о неудачах. Возвращает отписку.
 *
 * Сообщается переход, а не состояние: в метро или лифте сеть переключается
 * подряд по нескольку раз, и туннель падает на каждом переключении. Человеку
 * от пятого подряд одинакового тоста не становится понятнее — ему становится
 * нечем пользоваться. Поэтому повтор молчит, а следующий удачный заход снимает
 * запрет, и о новой поломке скажут снова.
 */
export function startOpenFluxDegradedNotice(): () => void {
  let told = false;
  return addOpenFluxReviveListener((r) => {
    const text = openFluxNoticeText(r);
    if (!text) {
      told = false;
      return;
    }
    if (told) return;
    told = true;
    // Тост показывать некому только до монтирования хоста — то есть до того,
    // как приложение вообще открылось. Смена сети в этот момент возможна, и
    // молча терять её нельзя: в журнале это останется.
    if (!pushToast('error', text)) log.warn('openflux_degraded_notice_unseen');
  });
}
