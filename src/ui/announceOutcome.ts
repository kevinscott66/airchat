/**
 * Как расхождение попадает на экран (v4.32.454).
 *
 * Правило одно на все служебные конверты: при успехе молчим — человек и так
 * видит результат у себя на экране; при отказе называем, что теперь
 * расходится. Вокруг этого правила уже стояли две обёртки (группа и токен
 * пригласительной ссылки), третья — закрепление в личке — сделала бы копию
 * неизбежной. Обёртки остаются типизированными, а само правило живёт здесь.
 */

import { showError } from './components/userFeedback';

/** Показывает расхождение, когда оно есть. Успех молчит. */
export function announceNow<T>(outcome: T, problem: (o: T) => string | null): void {
  const text = problem(outcome);
  if (text) showError(text);
}

/**
 * То же для ещё не пришедшего исхода. Отдельная функция, а не `void` у каждого
 * вызова: потерянные отказы появлялись ровно так — по одному `void` за раз.
 */
export function announceLater<T>(sending: Promise<T>, problem: (o: T) => string | null): void {
  void sending.then((o) => announceNow(o, problem));
}
