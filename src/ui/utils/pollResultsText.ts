/**
 * Опрос в буфере обмена и значок опроса — по одному разу на дом.
 *
 * v4.32.930. Пузырь опроса написан дважды: в личной переписке и в группе. Это
 * осознанно — вокруг них разная переписка, разные права и разные источники
 * голосов. Но текст, который уезжает в буфер по кнопке «скопировать», от этого
 * не зависит вовсе, и он тоже был написан дважды. Причём разным почерком:
 * `map` + `join` в личной, `forEach` + `push` в групповой. Вывод при этом
 * совпадал до байта — то есть две копии не расходились ПОКА.
 *
 * Пока — потому что в этой самой паре файлов расхождение случалось уже дважды.
 * v4.32.250: «всего голосов» в личном пузыре считало галочки, а не людей, и
 * при нескольких ответах давало число больше числа голосовавших. v4.32.254:
 * счёт по вариантам в списке шёл по уникальным голосующим, а в «скопировать»
 * — по строкам таблицы. Оба раза чинили одну копию из двух. Третьего раза
 * здесь не будет: считает по-прежнему каждый пузырь сам, а называет —
 * общий текст.
 *
 * Значок в заголовке — та же история и та же пара файлов: полная тройка
 * `isQuiz ? '🧠' : allowMultiple ? '☑️' : '📊'` дважды в заголовках пузырей и
 * жёсткое «📊» дважды в буфере. Из-за жёсткого викторина, вставленная в
 * заметки, оказывалась обычным опросом. Значок теперь один и тот же во всех
 * четырёх местах: это одно и то же утверждение о том, что это за опрос.
 *
 * Чего здесь нет намеренно. Строка состояния под пузырём — «Завершён», «Без
 * имён» — в буфер не уезжает и не уезжала: это про то, что можно делать с
 * опросом здесь, а не про его исход. И число в подвале остаётся значением при
 * подписи («Всего голосов: 12»), а не фразой: весь скопированный текст — это
 * столбец «подпись: значение», и «12 голосов» посреди него выбивалось бы
 * сильнее, чем согласуется.
 */
/** Длина полосы в знаках: доля округляется до десятой. */
const BAR_CELLS = 10;

/** 🧠 викторина · ☑️ несколько ответов · 📊 обычный опрос. */
export function pollIcon(isQuiz: boolean, allowMultiple: boolean): string {
  if (isQuiz) return '🧠';
  return allowMultiple ? '☑️' : '📊';
}

export type PollResultsSnapshot = {
  question: string;
  options: readonly string[];
  /** Сколько ЧЕЛОВЕК выбрало каждый вариант, по порядку `options`. */
  counts: readonly number[];
  /** Сколько человек проголосовало всего — людей, а не галочек. */
  total: number;
  isQuiz: boolean;
  allowMultiple: boolean;
};

/**
 * Текст, который уезжает в буфер обмена по кнопке «скопировать результаты».
 *
 * Считать здесь нечего, кроме доли: счёт по вариантам и число голосовавших
 * приходят готовыми — их знает только пузырь, у которого на руках голоса.
 */
export function pollResultsText(p: PollResultsSnapshot): string {
  const rows = p.options.map((opt, idx) => {
    const cnt = p.counts[idx] ?? 0;
    const pct = p.total > 0 ? Math.round((cnt / p.total) * 100) : 0;
    const full = Math.max(0, Math.min(BAR_CELLS, Math.round(pct / 10)));
    const bar = '█'.repeat(full) + '░'.repeat(BAR_CELLS - full);
    return `${opt}: ${cnt} (${pct}%) ${bar}`;
  });
  return [
    `${pollIcon(p.isQuiz, p.allowMultiple)} ${p.question}`,
    '',
    ...rows,
    '',
    `Всего голосов: ${p.total}`,
  ].join('\n');
}
