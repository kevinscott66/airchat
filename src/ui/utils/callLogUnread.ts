/**
 * Что показать в истории звонков, когда журнал не прочитался (v4.32.1069).
 *
 * Отметку «столбец не открылся» завели в v4.32.979 ради записи: не прочитав
 * журнал, писать поверх него нельзя — иначе первый же входящий кладёт одну
 * строку на место сотни. Наружу её не отдавали, и экран истории звонков строил
 * вид по пустой памяти: значок трубки и подпись «Нет звонков». То есть
 * непрочитанное выдавалось за утверждение «звонков не было».
 *
 * Правило лежит отдельно от экрана и без импортов: оно решает только «что
 * сказать», и проверить его можно, не поднимая ни хранилища, ни службы звонков.
 */

/**
 * `none` — журнал прочитан, говорить нечего.
 * `unread_empty` — не прочитан, и показывать нечего вовсе.
 * `unread_shown` — не прочитан, но в памяти есть звонки этого запуска.
 */
export type CallLogNotice = 'none' | 'unread_empty' | 'unread_shown';

export function callLogNotice(unreadable: boolean, shown: number): CallLogNotice {
  if (!unreadable) return 'none';
  return shown > 0 ? 'unread_shown' : 'unread_empty';
}

/** Журнал прочитан и правда пуст: звонков не было. */
export const CALL_LOG_EMPTY_TITLE = 'Нет звонков';

/** Журнал не прочитан: под значком трубки стоит другое слово, а не «нет». */
export const CALL_LOG_UNREAD_TITLE = 'Журнал не прочитался';

export const CALL_LOG_UNREAD_EMPTY =
  'Это не «звонков не было»: записи на месте, открыть их сейчас не вышло. ' +
  'Чаще всего столбец занят в первую секунду после запуска.';

/**
 * Про «Очистить» сказано прямо: она стирает столбец целиком, вместе с тем, что
 * сюда не поднялось. Нажимая её над одной строкой, человек иначе не узнал бы,
 * что уносит ещё сотню.
 */
export const CALL_LOG_UNREAD_SHOWN =
  'Здесь только звонки с этого запуска: прежний журнал не прочитался. ' +
  'Остальные записи на месте — «Очистить» сотрёт и их.';

export const CALL_LOG_RETRY = 'Повторить';
