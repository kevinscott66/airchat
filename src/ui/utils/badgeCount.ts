/**
 * Счётчик в кружке: один вид и одно имя для озвучки (v4.32.931).
 *
 * Дефект. Правило «больше сотни — пиши «99+»» было выписано восемь раз, в
 * четырёх файлах, тремя разными способами сразу: `String(n)`, голое `n` и
 * `n > 99 ? '99+' : n`. Рядом жило второе правило, для кружков поменьше —
 * «9+», ещё три копии. Одиннадцать мест, одна мысль.
 *
 * И ни одно из них не имело имени. Кружок — это `Text` с числом внутри
 * нажимаемого без подписи: озвучка читает «Чаты. 3» — и человек не знает,
 * три чего. А на переполнении читает «99 плюс»: знак «+» проговаривается
 * вслух, потому что для экрана это украшение, а для синтезатора — символ.
 *
 * Цена. Расходится такое молча. Порог уже разный там, где разным ему быть
 * незачем, и следующий кружок сядет на четвёртый способ записи. Для незрячего
 * же нижние вкладки — единственный вход в приложение, и счётчик над ними
 * сейчас безымянный.
 *
 * Правка. `badgeText` рисует, `unreadA11yLabel` называет. Порог — аргумент, а
 * не отдельная копия правила: кружок у заявок в группу меньше, и в него
 * влезает одна цифра, а не две.
 *
 * Границы. Что именно считает кружок, здесь не решается: «непрочитанные» —
 * только у переписок, а у заявок на вступление подпись своя и уже написана
 * на месте. Поэтому `badgeText` не знает слов вовсе, а имя даётся отдельной
 * подписью там, где известно, чего именно счёт.
 */
import { pluralRu } from '../../core/storage/ruPlural';

/** Две цифры: непрочитанные в переписках и в группах. */
export const BADGE_MAX = 99;

/** Одна цифра: кружок поверх значка, места в нём на один знак. */
export const SMALL_BADGE_MAX = 9;

/**
 * Число в кружке. Пустая строка — значит кружка нет: ноль, отрицательное и
 * нечисло рисовать нечем.
 */
export function badgeText(n: number, max: number = BADGE_MAX): string {
  const k = Math.trunc(n);
  if (!Number.isFinite(k) || k <= 0) return '';
  return k > max ? `${max}+` : String(k);
}

/**
 * Как счётчик непрочитанного звучит. «+» словами: синтезатор проговорит его
 * сам, и «99 плюс непрочитанных» — не то, что человек ожидает услышать.
 */
export function unreadA11yLabel(n: number, max: number = BADGE_MAX): string {
  const k = Math.trunc(n);
  if (!Number.isFinite(k) || k <= 0) return '';
  const word = (v: number): string => pluralRu(v, 'непрочитанное', 'непрочитанных', 'непрочитанных');
  return k > max ? `больше ${max} ${word(max)}` : `${k} ${word(k)}`;
}

/** Имя вкладки для озвучки: название, а за ним счёт, если он есть. */
export function tabA11yLabel(title: string, unread: number, max: number = BADGE_MAX): string {
  const tail = unreadA11yLabel(unread, max);
  return tail ? `${title}, ${tail}` : title;
}
