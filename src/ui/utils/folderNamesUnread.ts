/**
 * Что предложить для цветной метки, когда названия папок не прочитались
 * (v4.32.1067).
 *
 * Названия папок лежат одной шифрованной записью профиля, и чтение её умеет
 * не состояться: `tryReadFolderNames` отвечает `null` именно об этом. Запись
 * (`setFolderName`) на такой ответ давно отказывается — иначе переименование
 * одной папки стирало бы остальные (v4.32.699). Показ же сводил `null` к
 * пустому набору, а пустой набор в этом экране значит «папок нет».
 *
 * Разница видна в одном месте особенно: у метки без названия окно предлагает
 * «Создать папку с этой меткой». Не прочитали — не знаем, есть ли она, и
 * предлагать создание значит утверждать, что её нет.
 */

/** Что окно метки может честно предложить. */
export type FolderTagAction = 'rename' | 'create' | 'unknown';

/**
 * `named` — у метки есть прочитанное название; `unread` — набор названий не
 * прочитался. Прочитанное название важнее незнания: оно пришло с удачного
 * чтения, а переименование и без того перечитывает набор перед записью.
 */
export function folderTagAction(named: boolean, unread: boolean): FolderTagAction {
  if (named) return 'rename';
  return unread ? 'unknown' : 'create';
}

/** Строка под вкладками: почему их нет и что папки при этом целы. */
export const FOLDERS_UNREAD_NOTE =
  'Названия папок не прочитались: вкладок папок сейчас нет. ' +
  'Сами папки на месте — откройте список ещё раз.';

/** Та же беда в окне метки, где вместо неё предлагали создать папку. */
export const FOLDER_TAG_UNKNOWN_HINT =
  'Названия папок не прочитались — есть ли здесь папка, сейчас не узнать';
