/**
 * Что показывает лента сторис, когда прочитать её не вышло (v4.32.1075).
 *
 * ДЕФЕКТ. `reload()` в StoriesRow не имел ни одного `catch`, а звался тремя
 * `void reload()` и одним `await` в конце публикации. Внутри — три похода в
 * базу: `deleteExpiredStories()`, `listActiveStories(pid)` и `listContacts()`.
 * Первые два бросают на отказе базы или ключа шифрования (`db()`,
 * `getOrCreateDataEncryptionKey()`), и бросок уходил в необработанный промис:
 * `groups` оставался `[]`, а ряд рисовал ровно то же, что при пустом ответе, —
 * один кружок «Добавить».
 *
 * ЦЕНА. «У ваших контактов нет историй» — это утверждение, и оно было ложным.
 * Сторис живёт сутки и исчезает сама: пропущенную нельзя открыть позже, в
 * переписке её нет, уведомления о ней нет. Отказ базы чаще всего случается в
 * первую секунду после запуска — то есть ровно тогда, когда ряд и
 * отрисовывается. Человек видел пустоту, уходил, и сторис истекала.
 *
 * ПРАВКА. Отказ ловится и называется: в ряду появляется кружок
 * «Не открылись», по нажатию — повтор чтения и объяснение словами. Пустота
 * остаётся пустотой только тогда, когда чтение удалось.
 *
 * ГРАНИЦЫ. Если прежнее чтение прошло и кружки на экране есть, они настоящие:
 * при позднейшем отказе показанное не стирается, а рядом встаёт тот же кружок
 * — «показано прежнее». Публикация своей сторис своих ошибок не теряла и
 * говорит о них по-прежнему сама.
 */

/** Подпись под кружком отказа. Во всю ширину кружка помещается только это. */
export const STORIES_ROW_FAILED_LABEL = 'Не открылись';

/** Что прочитать вслух: подписи из двух слов для этого мало. */
export function storiesRowFailedA11yLabel(hasShown: boolean): string {
  return hasShown
    ? 'Список историй не обновился. Нажмите, чтобы повторить'
    : 'Истории не открылись. Нажмите, чтобы повторить';
}

/**
 * Объяснение по нажатию. Два разных случая: ряд пуст — и тогда важно сказать,
 * что это не «историй нет»; ряд не пуст — и тогда важно сказать, что
 * показанное устарело.
 */
export function storiesRowFailedHint(hasShown: boolean): string {
  return hasShown
    ? 'Список историй не обновился: показано то, что удалось прочитать раньше. ' +
        'Новые истории могли не попасть в него.'
    : 'Истории не открылись — это не «историй нет». Чаще всего база занята в первую ' +
        'секунду после запуска. Истории живут сутки, так что стоит повторить.';
}
