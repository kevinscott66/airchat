/**
 * Почему не вышло скачать вложение ради «Поделиться» (v4.32.1076).
 *
 * ДЕФЕКТ. `downloadCapped` в просмотрщике отвечал `string | null`, и `null`
 * означал сразу два разных события: файл не влез в потолок — и закачка
 * сорвалась (`downloadAsync().catch(() => null)`: нет сети, оборванный TLS,
 * отменённая задача). Единственный вызывающий на любой `null` писал «Файл
 * слишком большой, чтобы им поделиться». Третий случай не замечали вовсе:
 * ответ сервера 404, 403 или 500 приходит УСПЕШНО — `downloadAsync` отдаёт
 * результат со `status`, а на диск ложится тело ошибки. Просмотрщик отдавал
 * этот файл в «Поделиться» с типом image/jpeg.
 *
 * ЦЕНА. Про свой интернет человеку говорили «файл большой»: искать нечего,
 * ждать нечего, повторять незачем — приговор окончательный и ложный. Про
 * удалённое или протухшее вложение — то же самое. А страница ошибки,
 * подписанная как фотография, уходила дальше: в другое приложение, в чужую
 * переписку, в облако.
 *
 * ПРАВКА. `downloadCapped` отвечает исходом, а не «строка или ничего»:
 * `{ ok: true; uri }` либо `{ ok: false; why }` с тремя причинами. Текст на
 * каждую свой и лежит здесь, отдельно от закачки. Ответ сервера от 400 и выше
 * — отказ, а не файл: частичное скачанное стирается, как и при обрыве.
 *
 * ГРАНИЦЫ. Модуль не знает ни сети, ни файловой системы: он про слова и про
 * одно правило — какой ответ сервера считать файлом. Сама закачка и потолок
 * остаются в просмотрщике, где им и место.
 */
import { formatByteSize } from '../../core/media/byteSize';

/** Потолок для файла, который скачивается ради «Поделиться». */
export const MAX_SHARE_BYTES = 50 * 1024 * 1024;

/** Почему файла нет. Три причины, и человеку они нужны разными. */
export type ShareDownloadFail = 'too_big' | 'server' | 'network';

/** Исход закачки: либо файл, либо причина, по которой его нет. */
export type ShareDownloadOutcome = { ok: true; uri: string } | { ok: false; why: ShareDownloadFail };

/**
 * Ответ сервера — отказ, а не файл.
 *
 * Считаем отказом только явное 400 и выше. Нижняя граница нарочно не
 * проверяется: если платформа однажды отдаст `0` или ничего вместо статуса,
 * ошибиться лучше в сторону «файл настоящий» — прежнее поведение, — чем
 * отказать по скачанному файлу, с которым всё в порядке.
 */
export function shareStatusRefused(status: number | null | undefined): boolean {
  return typeof status === 'number' && Number.isFinite(status) && status >= 400;
}

/** Что сказать человеку. Ни одна из трёх причин не выдаётся за другую. */
export function shareDownloadFailText(why: ShareDownloadFail): string {
  if (why === 'too_big') {
    // Округление вниз: подпись предела не имеет права назвать больше, чем
    // пропустит сама проверка.
    return (
      `Файл тяжелее ${formatByteSize(MAX_SHARE_BYTES, { roundDown: true })} — столько ` +
      'приложение за раз не скачивает, поделиться им не выйдет.'
    );
  }
  if (why === 'server') {
    return (
      'Сервер не отдал файл: по этой ссылке сейчас ничего нет. Возможно, вложение ' +
      'удалили или истёк срок хранения.'
    );
  }
  return 'Не удалось скачать файл: связь оборвалась. Проверьте интернет и попробуйте ещё раз.';
}
