/**
 * Строка состояния сервера доставки (v4.32.1080).
 *
 * ДЕФЕКТ. Настройки ретранслятора, VPN и туннеля лежат в
 * Documents/airchat-config.json. Читателей у файла было два, и они отвечали
 * по-разному: пишущий (readConfigOverride) различал «файла нет» и «не
 * прочитали», а читающий при старте (readUserOverride) сводил любую беду —
 * занятую песочницу, обрывок после прерванной записи, подложенный файл сверх
 * потолка — к пустому `{}`. Пустой патч означает заводские умолчания, то есть
 * публичный ntfy.sh. Приложение молча уходило на него, а эта секция настроек
 * рисовала зелёную точку и подпись «Общий ntfy.sh» — как будто так и
 * настроено.
 *
 * ЦЕНА. Свой ретранслятор ставят ровно затем, чтобы список тем и время
 * отправки не видел посторонний: сами сообщения зашифрованы, а вот кто с кем
 * и когда — нет. Человек открывает настройки, видит зелёную точку и уходит,
 * не узнав, что этот запуск он проговорил через чужой сервер. Настройки при
 * этом целы — файл на месте, следующий запуск прочитает его как надо, — и
 * потому беда невидима совсем.
 *
 * ПРАВКА. Читатель при старте остался один — тот, что различает три исхода;
 * `null` для запуска по-прежнему значит «идём на умолчаниях» (решение
 * v4.32.729 в силе: один запуск на умолчаниях обратим, а стёртый файл нет).
 * Но исход теперь запоминается, и секция настроек о нём говорит: янтарная
 * точка вместо зелёной и прямая подпись.
 *
 * ГРАНИЦЫ. Ни загрузка конфига, ни транспорт не меняются: подпись говорит о
 * том, что уже произошло, а не отменяет это. Прочитанный файл — прежние
 * слова и прежний цвет.
 */

/** Цвет точки и подписи: зелёный — знаем и работает, серый — выключено, янтарный — не знаем. */
export type RelayStatusTone = 'ok' | 'muted' | 'warn';

export type RelayStatusLine = { text: string; tone: RelayStatusTone };

export type RelayStatusFacts = {
  /** Доставка через интернет включена. */
  enabled: boolean;
  /** Адрес, на котором транспорт работает сейчас. */
  activeBase: string;
  /** Это свой адрес, а не общий ntfy.sh. */
  custom: boolean;
  /** Файл своих настроек есть, но прочитать его не удалось. */
  unread: boolean;
};

export function relayStatusLine(f: RelayStatusFacts): RelayStatusLine {
  // Незнание идёт первым: при непрочитанном файле и «включено», и адрес —
  // это заводские умолчания, а не то, что человек настраивал. Сказать
  // «выключен» или «общий ntfy.sh» как о его выборе здесь нельзя.
  if (f.unread) {
    const now = f.custom ? f.activeBase : 'общий ntfy.sh';
    return { tone: 'warn', text: `Свои настройки не прочитались. Сейчас работает ${now}` };
  }
  if (!f.enabled) return { tone: 'muted', text: 'Выключен — только локальная сеть' };
  return { tone: 'ok', text: f.custom ? f.activeBase : 'Общий ntfy.sh' };
}
