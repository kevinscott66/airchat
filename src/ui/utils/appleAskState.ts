/**
 * Спросили ли сервер про вход через Apple ID — и что об этом сказать
 * (v4.32.1068).
 *
 * Список входов приходит с сервера и умеет не прийти. Пустой список значит
 * «вход выключен»: это ответ, а не молчание. Кнопку рисуем только когда вход
 * есть и на устройстве, и на сервере — мёртвая кнопка хуже отсутствующей, она
 * обещает и не делает. Но и отсутствие кнопки без слов — обещание наоборот:
 * «такого входа тут нет».
 */

/** `ready` — вход есть; `off` — сервер сказал «нет»; `unknown` — не спросили. */
export type AppleAskState = 'ready' | 'off' | 'unknown';

/** `providers` — ответ сервера; `null` — спросить не вышло. */
export function appleAskState(providers: readonly string[] | null): AppleAskState {
  if (providers === null) return 'unknown';
  return providers.includes('apple') ? 'ready' : 'off';
}

