/**
 * Как назвать пункт «Заблокировать» и что сказать о непрочитанном списке
 * (v4.32.1066).
 *
 * Список запретов читается один раз при подъёме модуля и умеет не
 * прочитаться: `rateLimiter.blockedListReadable()` заведён ровно затем, чтобы
 * отличить «никого не блокировал» от «выяснить не удалось». Переписка
 * (v4.32.1048) и карточка собеседника (v4.32.1051) спрашивают его и называют
 * этот случай одними и теми же словами. Здесь эти слова лежат один раз:
 * третье место — список контактов — берёт их отсюда, а проверка рядом следит,
 * чтобы все три говорили одинаково.
 *
 * Кнопку при непрочитанном списке не гасим: запрет мог и не стоять, а отнятое
 * действие из-за занятой базы — вред больше, чем подпись. Что запись при этом
 * не ляжет, человеку скажет сам ограничитель (BLOCK_NOT_SAVED_ON/OFF).
 */

/** Подпись пункта меню: заблокирован / не прочитано / обычный случай. */
export function blockActionLabel(blocked: boolean, unknown: boolean): string {
  if (blocked) return 'Разблокировать';
  return unknown ? 'Заблокировать (список запретов не прочитан)' : 'Заблокировать';
}

/**
 * Строка над списком контактов. Без неё отметки «заблокирован» просто не
 * рисуются, и список выглядит так, будто никто не заблокирован, — а это
 * ответ, которого никто не давал.
 */
export const BLOCKED_LIST_UNKNOWN_NOTE =
  'Список запретов не прочитан: отметки «заблокирован» могут быть не показаны. ' +
  'Потяните список вниз, чтобы повторить.';

/** Приписка к шапке меню строки — там, где у заблокированного стоит 🚫. */
export const BLOCKED_UNKNOWN_HEAD = '\n\nЗапрет проверить не удалось';
