/**
 * Компоненты объявляются на уровне модуля, а не внутри других компонентов.
 *
 * Объявленный внутри компонент создаётся заново на каждый рендер родителя.
 * Для React это каждый раз НОВЫЙ ТИП, а на новый тип он не обновляет
 * поддерево, а сносит его и строит заново: теряется состояние всего, что
 * стоит ниже. Найдено это было трижды и каждый раз стоило разного:
 *
 *  - в настройках — потерянный фокус посреди набора в поле ввода;
 *  - в группах — сброс анимации свайпа, в том числе посреди жеста, и полное
 *    перемонтирование ленты сообщений при каждом изменении счётчика
 *    непрочитанного, то есть прямо во время переписки;
 *  - в панели эмодзи — пересоздание сотен ячеек на каждое нажатие клавиши в
 *    поиске.
 *
 * Проверяется исходник: это свойство формы кода, и ломается оно правкой кода.
 * `useCallback` от этого НЕ спасает — он лишь реже меняет identity, а внутри
 * компонента остаются хуки, ради которых приходится глушить правило. Поэтому
 * заодно держится и отсутствие таких заглушек: они и есть след антипаттерна.
 */
import { readFileSync, readdirSync, statSync } from 'fs';
import { join } from 'path';

const UI = join(__dirname, '..');

function tsxFiles(dir: string): string[] {
  const out: string[] = [];
  for (const name of readdirSync(dir)) {
    if (name === '__tests__' || name === 'node_modules') continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...tsxFiles(p));
    else if (name.endsWith('.tsx')) out.push(p);
  }
  return out;
}

const files = tsxFiles(UI);

/**
 * Код без комментариев. Комментарии здесь цитируют убранный антипаттерн
 * дословно — чтобы следующий читатель понял, чего именно делать нельзя, — и
 * сканирование по сырому тексту ловило бы эти объяснения как нарушения.
 * Директивы `eslint-disable` при этом сами живут в комментариях, поэтому
 * строчные комментарии, начинающиеся с неё, сохраняются.
 */
function code(src: string): string {
  return src
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/(^|[^:])\/\/(?!\s*eslint-disable).*$/gm, '$1');
}

describe('компоненты не объявляются внутри компонентов', () => {
  it('проверяемых файлов действительно много', () => {
    // Страховка от «зелено, потому что ничего не просмотрено».
    expect(files.length).toBeGreaterThan(50);
  });

  it('правило хуков нигде не заглушено', () => {
    // Хуки внутри вложенного компонента — единственная причина, по которой
    // это правило приходилось глушить в этом дереве.
    const guilty = files.filter((f) => {
      const src = code(readFileSync(f, 'utf8'));
      return /eslint-disable(-next-line)?\s+[^\n]*react-hooks\/rules-of-hooks/.test(src);
    });
    expect(guilty.map((f) => f.slice(UI.length + 1))).toEqual([]);
  });

  it('никакой JSX-компонент не заводится через useCallback', () => {
    // `const Foo = useCallback(({ ... }) => …)` с Заглавной буквы — ровно та
    // форма, которой был GrpSwipeRow: выглядит защищённой, типом быть не
    // перестаёт.
    const guilty: string[] = [];
    for (const f of files) {
      const src = code(readFileSync(f, 'utf8'));
      if (/\bconst\s+[A-Z]\w*\s*=\s*useCallback\s*\(\s*\(?\s*\{/.test(src)) {
        guilty.push(f.slice(UI.length + 1));
      }
    }
    expect(guilty).toEqual([]);
  });
});
