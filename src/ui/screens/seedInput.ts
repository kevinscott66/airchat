/**
 * seedInput — приведение введённой резервной фразы к виду, который понимает bip39.
 *
 * v4.32.340: раньше вся подготовка была одной строкой прямо в экране:
 * trim + lowercase + схлопывание пробелов. Для аккуратно набранной вручную
 * фразы этого хватает, а вот для вставленной из буфера — почти никогда.
 *
 * Свои же 24 слова экран сидки показывает нумерованными («1. abandon»), и
 * человек, скопировавший их оттуда или из своей заметки, получал «Неверные
 * секретные слова» — при полностью правильной фразе. То же с переносами строк,
 * запятыми между словами и неразрывными пробелами, которые охотно подставляют
 * заметочники и мессенджеры.
 *
 * Разбор намеренно снисходителен к оформлению и ничего не прощает по существу:
 * слова bip39 состоят только из строчных латинских букв, поэтому выброшенная
 * нумерация и запятые не могут превратить неверную фразу в верную — проверку
 * контрольной суммы дальше по-прежнему делает validateMnemonic.
 */

/** Токен, который является только порядковым номером: «1», «12.», «7)». */
const ENUM_ONLY_RE = /^\d+[.)]?$/;

/** Номер, приклеенный к слову: «1.abandon», «12)ability». */
const ENUM_PREFIX_RE = /^\d+[.)]\s*/;

/**
 * Приводит введённый текст к «слова через один пробел, строчными».
 * Разделителями считаются пробелы любого вида, переводы строк, запятые и
 * точки с запятой.
 */
export function normalizeSeedInput(raw: string): string {
  return raw
    .toLowerCase()
    .split(/[\s,;]+/)
    .map((token) => token.replace(ENUM_PREFIX_RE, ''))
    .filter((token) => token.length > 0 && !ENUM_ONLY_RE.test(token))
    .join(' ');
}

export type SeedWordCountResult = { ok: true } | { ok: false; message: string };

/**
 * Проверяет количество слов до обращения к bip39 — чтобы на самую частую
 * ошибку (слово потерялось при копировании) ответить понятно, а не общим
 * «неверные секретные слова».
 *
 * 12 слов AirChat никогда не выдавал — он всегда генерирует 24, — но bip39 их
 * принимает, и фразу из другого приложения мы не отвергаем. В тексте ошибки
 * называем только 24: при 12 словах она не показывается вовсе.
 */
export function checkSeedWordCount(normalized: string): SeedWordCountResult {
  if (normalized.length === 0) {
    return { ok: false, message: 'Введите секретные слова — 24 слова через пробел.' };
  }
  const count = normalized.split(' ').length;
  if (count === 12 || count === 24) return { ok: true };
  return {
    ok: false,
    message:
      `Введено слов: ${count}, а нужно 24. ` +
      'Проверьте, все ли слова на месте и нет ли лишних символов.',
  };
}
