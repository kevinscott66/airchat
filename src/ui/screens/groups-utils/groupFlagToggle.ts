/**
 * Четыре переключателя настроек группы: слова и патч в одном месте.
 *
 * v4.32.531. Дефект был не в самих словах, а в том, что каждый переключатель
 * нёс свою копию всего: пункт меню, надпись об успехе, системную строку в
 * ленту и объект для записи в базу — четыре почти одинаковых куска JSX по
 * шесть строк каждый. Копии разошлись незаметно: у «Закреплять могут все»
 * подпись инвертирована относительно флага adminOnlyPinning (и это верно,
 * потому что подпись называет действие, а не состояние), но убедиться в этом
 * можно было только сверив четыре ветки глазами.
 *
 * Хуже другое. Каждая копия сама решала, когда объявить успех, и объявляла
 * его до того, как запись подтвердилась: updateGroupMeta вызывался через
 * `void ... .then(...)` без `.catch`, поэтому отказ базы не доходил ни до
 * человека, ни до логов — переключатель просто не двигался, а рядом уже
 * висело «Писать могут все». Здесь только выбор слов и патча; кто и когда их
 * показывает — дело экрана, но выбор больше не зависит от того, в какой из
 * четырёх веток мы стоим.
 */

export type GroupFlagKey =
  | 'adminOnlyPosting'
  | 'adminOnlyPinning'
  | 'requireApproval'
  | 'anonymousPosting';

export type GroupFlagCopy = {
  /** Подпись пункта меню: называет действие, а не текущее состояние. */
  readonly menu: string;
  /** Тост после подтверждённой записи. */
  readonly success: string;
  /** Системная строка в ленту группы. */
  readonly sys: string;
  /** Запасной текст ошибки, если база отказала. */
  readonly failure: string;
};

export type GroupFlagPatch = {
  adminOnlyPosting?: boolean;
  adminOnlyPinning?: boolean;
  requireApproval?: boolean;
  anonymousPosting?: boolean;
};

/** Нажатие всегда переводит флаг в противоположное значение. */
export function groupFlagNext(current: boolean): boolean {
  return !current;
}

/**
 * Патч ровно одного поля — типизированный, а не вычисляемый ключ.
 *
 * Один и тот же объект годится и для updateGroupMeta, и для ctl-конверта
 * `op: 'meta'`, поэтому запись у себя и рассылка остальным не могут
 * разъехаться по составу полей.
 */
export function groupFlagPatch(key: GroupFlagKey, next: boolean): GroupFlagPatch {
  switch (key) {
    case 'adminOnlyPosting':
      return { adminOnlyPosting: next };
    case 'adminOnlyPinning':
      return { adminOnlyPinning: next };
    case 'requireApproval':
      return { requireApproval: next };
    case 'anonymousPosting':
      return { anonymousPosting: next };
  }
}

/**
 * Все четыре текста переключателя по его текущему значению.
 *
 * `menu` считается от текущего состояния (что будет, если нажать), остальные
 * три — от будущего.
 */
export function groupFlagCopy(key: GroupFlagKey, current: boolean): GroupFlagCopy {
  const next = groupFlagNext(current);
  switch (key) {
    case 'adminOnlyPosting':
      return {
        menu: current ? 'Режим только для админов: выкл' : 'Режим только для админов: вкл',
        success: next ? 'Теперь писать могут только администраторы' : 'Писать могут все',
        sys: next
          ? 'Режим «только для администраторов» включён'
          : 'Режим «только для администраторов» выключен',
        failure: 'Не удалось изменить режим публикации',
      };
    case 'adminOnlyPinning':
      // Подпись говорит про «закреплять могут все», то есть про обратное
      // флагу состояние — отсюда перевёрнутые «вкл/выкл».
      return {
        menu: current ? 'Закреплять могут все: вкл' : 'Закреплять могут все: выкл',
        success: next ? 'Закреплять могут только администраторы' : 'Закреплять могут все участники',
        sys: next
          ? 'Закреплять сообщения могут только администраторы'
          : 'Закреплять сообщения могут все участники',
        failure: 'Не удалось изменить права на закрепление',
      };
    case 'requireApproval':
      return {
        menu: current ? 'Одобрение входа: выкл' : 'Одобрение входа: вкл',
        success: next ? 'Новые участники требуют одобрения' : 'Вход по ссылке без одобрения',
        sys: next ? 'Вход по ссылке теперь требует одобрения' : 'Вход по ссылке без одобрения',
        failure: 'Не удалось изменить правило входа',
      };
    case 'anonymousPosting':
      return {
        menu: current ? 'Анонимные посты: выкл' : 'Анонимные посты: вкл',
        success: next ? 'Имена отправителей скрыты' : 'Имена отправителей видны',
        sys: next ? 'Имена отправителей скрыты' : 'Имена отправителей видны',
        failure: 'Не удалось изменить анонимность',
      };
  }
}
