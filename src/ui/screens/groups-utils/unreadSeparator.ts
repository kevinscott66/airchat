/**
 * Разделитель «N непрочитанных» ставился не с того конца списка (v4.32.529).
 *
 * `listGroupMessages` читает `ORDER BY created_at DESC`, а лента отрисована
 * `inverted` — то есть в массиве сначала идёт САМОЕ НОВОЕ сообщение, и оно же
 * визуально внизу. Расстановка разделителей считала наоборот («messages are
 * oldest-first») и брала индекс `msgs.length - unread`. При шестидесяти
 * загруженных сообщениях и пяти непрочитанных полоса вставала перед
 * пятьдесят пятым по новизне — то есть посреди давно прочитанной истории,
 * на несколько дней выше того места, где человек остановился.
 *
 * Хуже того, кнопка «перейти к непрочитанным» ищет ту же полосу через
 * `findIndex`, поэтому прыгала туда же — в середину прочитанного.
 *
 * А когда непрочитанных было не меньше, чем загружено (вернулись в группу
 * после сотни сообщений), индекс получался нулевым, и условие `i > 0`
 * убирало полосу совсем: ровно в том случае, когда она нужнее всего.
 *
 * Правило: непрочитанные — это `unread` самых новых сообщений, они лежат в
 * начале массива, и полоса идёт СРАЗУ ЗА ними. Если непрочитанных больше,
 * чем загружено, полоса встаёт в самый конец массива — визуально над всей
 * лентой: «всё, что ниже, новое».
 *
 * Оговорка: счётчик группы считает только чужие сообщения, а в массив входят
 * и свои. Свои среди непрочитанных сдвигают полосу на несколько строк вниз —
 * это та же приблизительность, что и в личных чатах, и она безопасна:
 * полоса окажется чуть ниже нужного места, а не в другом дне.
 *
 * Без зависимостей: только арифметика, чтобы её можно было проверить.
 */

/**
 * Индекс в массиве «новые первыми», ПЕРЕД которым вставляется полоса.
 *
 * @param loaded сколько сообщений загружено в список;
 * @param unread сколько было непрочитанных на момент открытия группы.
 * @returns индекс вставки, либо -1 — полосы нет. Значение, равное `loaded`,
 *          означает вставку после последнего элемента.
 */
export function unreadSeparatorIndex(loaded: number, unread: number): number {
  if (!Number.isFinite(loaded) || !Number.isFinite(unread)) return -1;
  if (loaded <= 0 || unread <= 0) return -1;
  return Math.min(Math.floor(unread), Math.floor(loaded));
}
