/**
 * Тексты карточки разрешения: как назвать состояние и что подсказать (v4.32.1060).
 *
 * Отдельным модулем, а не внутри экрана, по той же причине, по которой рядом
 * лежит `permissionStatus`: разбор и слова должны проверяться без всего
 * React Native вокруг. Экран только рисует то, что здесь написано.
 */
import type { PermissionId } from './permissionDefs';
import type { PermissionStatus } from './permissionStatus';

export const STATUS_LABEL: Record<PermissionStatus, string> = {
  unknown: 'Не запрошено',
  granted: 'Разрешено ✓',
  limited: 'Частично',
  denied:  'Отказано',
  // «Отклонено» и «Отказано» на слух одно и то же, а состояния разные:
  // первое чинится нажатием, второе — только настройками системы.
  blocked: 'Запрещено',
};

/**
 * Подсказка под карточкой — только там, где без неё непонятно, что делать.
 *
 * «Частично» тут написано про галерею: до v4.32.1060 частичная выдача была
 * только у неё.
 */
export const STATUS_HINT: Partial<Record<PermissionStatus, string>> = {
  limited: 'Доступ только к выбранным фото. Расширить — в настройках системы, нажмите, чтобы открыть их.',
  denied: 'Нажмите, чтобы спросить ещё раз.',
  blocked: 'Выдать можно только в настройках системы — нажмите, чтобы открыть их.',
};

/**
 * Своя подсказка там, где общая соврала бы (v4.32.1060).
 *
 * С этой версии частичная выдача бывает и у уведомлений: iOS умеет выдать их
 * тихо (provisional) — они приходят, но без баннера и звука, сразу в
 * «Историю». Состояние ровно то же самое `limited`: расширяется только в
 * настройках системы, повторный запрос вернёт тот же ответ без диалога, — а
 * вот текст про «выбранные фото» на карточке уведомлений был бы про другое
 * разрешение.
 */
const HINT_OVERRIDE: Partial<Record<PermissionId, Partial<Record<PermissionStatus, string>>>> = {
  notifications: {
    limited: 'Уведомления приходят тихо, без баннера и звука. Включить полностью — в настройках системы, нажмите, чтобы открыть их.',
  },
};

export function statusHint(id: PermissionId, status: PermissionStatus): string | undefined {
  return HINT_OVERRIDE[id]?.[status] ?? STATUS_HINT[status];
}
