/**
 * Нажатие на одноразовый снимок — одно правило на оба экрана (v4.32.516).
 *
 * Порядок здесь тонкий, и каждый его шаг оплачен отдельной правкой:
 *
 *   • расшифровка вложения занимает время, за которое экран успевают закрыть
 *     (v4.32.125). Продолжать после этого нельзя ВООБЩЕ: показывать снимок
 *     некому, а удалять его — значит уничтожить одноразовое фото, которого
 *     никто не увидел;
 *   • пустой список адресов — это не «ничего не делать», а «снимок больше
 *     недоступен»: вложение живёт на relay около трёх часов (v4.32.359);
 *   • показали не всё — не удаляем ничего (v4.32.359): строка в базе держит
 *     единственную ссылку на нерасшифрованные снимки;
 *   • удаляем с задержкой: просмотрщик ещё открывается, а содержимое берёт из
 *     уже собранного списка адресов, не из строки в базе.
 *
 * Правило было написано дважды — в личной переписке и в группе, — и вторая
 * копия растеряла ровно то, что перечислено первым пунктом: ни проверки перед
 * показом, ни проверки перед удалением, ни проверки перед перечитыванием
 * списка. То есть в группе уход с экрана во время расшифровки заканчивался
 * удалением непоказанного снимка. Своего текста об этом у обеих копий не было
 * тоже: отказ удаления улетал необработанным отклонением обещания, и
 * «одноразовый» снимок молча оставался в переписке навсегда.
 *
 * Обратная сторона того же: в личной переписке отложенное удаление ОТМЕНЯЛОСЬ
 * уходом с экрана (`if (!isMountedRef.current) return` внутри таймера). Снимок
 * к этому мгновению уже показан, так что «одноразовое» фото оставалось в
 * переписке навсегда у всякого, кто успевал выйти из чата за 0,8 секунды.
 * Удаление больше не отменяется; от размонтирования защищено то, что и должно
 * быть, — перечитывание списка.
 *
 * Модуль без импортов: всё, что снаружи, приходит зависимостями, поэтому
 * порядок проверяется без просмотрщика, базы и рендеринга.
 */

/**
 * Задержка перед удалением показанного снимка.
 *
 * Была выписана числом в обоих экранах. Значение одно и то же и по одной и той
 * же причине — просмотрщик должен успеть открыться, — так что и жить ему в
 * одном месте.
 */
export const VIEW_ONCE_DELETE_DELAY_MS = 800;

export interface ViewOnceTapDeps {
  /** Собрать адреса вложений; `missing` — сколько расшифровать не удалось. */
  resolve: () => Promise<{ uris: string[]; missing: number }>;
  /** Экран ещё жив? */
  alive: () => boolean;
  /**
   * Открыть просмотрщик.
   *
   * `allowShare` приходит отсюда, а не из вызывающего экрана (v4.32.804): в
   * просмотрщике есть «Поделиться», и для одноразового снимка это кнопка
   * «сохранить навсегда» — кадр уходит в «Фото» или в файлы, откуда его уже
   * ничем не достать. Запрет не может зависеть от того, вспомнил ли о нём
   * автор очередного экрана: снимок ничем не отличается от обычного, и
   * забывается такое молча.
   */
  open: (uris: string[], opts: { allowShare: boolean }) => void;
  /**
   * Отложить удаление на VIEW_ONCE_DELETE_DELAY_MS.
   *
   * Именно отложить, а не «отложить, пока экран открыт»: снимок к этому
   * моменту УЖЕ показан, и не удалить его значит оставить «одноразовое» фото
   * доступным навсегда. Уход с экрана в эти доли секунды ничего не отменяет —
   * от него защищает alive() перед reload(), а не отмена таймера.
   */
  later: (fn: () => void) => void;
  /**
   * Удалить сообщение у себя. `false` — строка осталась в базе.
   *
   * v4.32.805: ответ, а не исключение. Оба экрана звали удаление, которое свой
   * отказ гасило само и возвращало `void`, — то есть `catch` ниже не мог
   * сработать ни при каком стечении обстоятельств, а показанный снимок при
   * занятой базе молча оставался в переписке читаемым. «Строки не нашлось» —
   * не отказ: её либо уже стёрли, либо не было, и в обоих случаях снимка в
   * переписке нет.
   */
  remove: () => Promise<boolean>;
  /** Перечитать список сообщений. */
  reload: () => void;
  /** Показать «снимок больше недоступен». */
  onUnavailable: () => void;
  /**
   * Сказать, что снимок остался.
   *
   * Не «не удалось удалить»: человек его уже увидел, и важно ему не то, что
   * сорвалась запись, а то, что одноразовое фото никуда не делось.
   */
  onRemoveFailed: () => void;
}

export async function runViewOnceTap(deps: ViewOnceTapDeps): Promise<void> {
  const { uris, missing } = await deps.resolve();
  // Единственная проверка, которой в группе не было ни в каком виде.
  if (!deps.alive()) return;
  if (uris.length === 0) {
    deps.onUnavailable();
    return;
  }
  deps.open(uris, { allowShare: false });
  if (missing > 0) return;
  deps.later(() => {
    void deps
      .remove()
      .then((gone) => {
        if (!gone) deps.onRemoveFailed();
        // Список перечитывается в обоих случаях: если строка осталась, человек
        // должен видеть её на месте, а не верить на слово, что снимок сгорел.
        if (deps.alive()) deps.reload();
      })
      .catch(() => deps.onRemoveFailed());
  });
}
