/**
 * Переход к сообщению, которого нет в загруженном окне (v4.32.877).
 *
 * Переписка открывается последней страницей (40 сообщений в личной, 60 в
 * группе), а нажать можно на цитату в ответе, на плашку закрепа, на пункт
 * списка закреплённых и на ссылку из упоминания. Все четыре перехода искали
 * строку только среди загруженных и при промахе выходили молча: ни прокрутки,
 * ни подсветки, ни слова. Закреп при этом почти всегда старше окна — его
 * читают по всей истории, — поэтому нажатие на плашку закрепа не работало
 * практически всегда.
 *
 * Решение простое и общее для обоих экранов: не нашли — догружаем страницы
 * тем же способом, которым их догружает прокрутка, и пробуем снова. Кончилась
 * история — значит сообщения больше нет; упёрлись в потолок попыток — значит
 * оно слишком далеко, и об этом говорят словами, а не молчанием.
 */

/**
 * Сколько страниц готовы догрузить ради одного перехода.
 *
 * 25 страниц — это около тысячи сообщений в личной переписке и полутора тысяч
 * в группе: дальше ожидание становится заметнее пользы, и честнее сказать
 * «слишком далеко», чем держать человека перед замершим экраном.
 */
export const JUMP_MAX_STEPS = 25;

/** Историю прошли до конца — такого сообщения в переписке нет. */
export const JUMP_MISSING_TEXT = 'Сообщение не найдено — возможно, его удалили';

/** Потолок попыток — сообщение есть, но до него ещё далеко. */
export const JUMP_TOO_FAR_TEXT =
  'Сообщение слишком далеко — прокрутите переписку к нему';

export type JumpStep = 'scroll' | 'load' | 'missing' | 'too-far';

/**
 * Что делать дальше: чистое решение без списка, ссылок и таймеров.
 *
 * `found` — строка уже в загруженном списке; `hasMore` — есть ли что догружать;
 * `steps` — сколько догрузок уже сделано.
 */
export function nextJumpStep(
  found: boolean,
  hasMore: boolean,
  steps: number,
  maxSteps: number = JUMP_MAX_STEPS,
): JumpStep {
  if (found) return 'scroll';
  if (!hasMore) return 'missing';
  if (steps >= maxSteps) return 'too-far';
  return 'load';
}

/** Слова для того исхода, где перехода не случилось. */
export function jumpFailureText(step: 'missing' | 'too-far'): string {
  return step === 'missing' ? JUMP_MISSING_TEXT : JUMP_TOO_FAR_TEXT;
}

export type JumpDriver = {
  /** Строка с этим id уже есть в списке на экране. */
  found: () => boolean;
  /** Есть ли ещё непрогруженная история. */
  hasMore: () => boolean;
  /** Догрузить одну страницу — ровно то же, что делает прокрутка вниз. */
  loadOlder: () => Promise<void>;
  /** Дать списку перерисоваться, прежде чем искать снова. */
  settle: () => Promise<void>;
  /** Прокрутить и подсветить. */
  scroll: () => void;
  /** Сказать словами, что перехода не будет. */
  fail: (text: string) => void;
  /** Экран закрыли — дальше не ходим. */
  alive?: () => boolean;
  maxSteps?: number;
};

/**
 * Довести переход до одного из трёх исходов: прокрутка, «нет такого»,
 * «слишком далеко». Молчаливого четвёртого здесь нет.
 */
export async function runJump(d: JumpDriver): Promise<JumpStep> {
  for (let steps = 0; ; steps++) {
    if (d.alive && !d.alive()) return 'missing';
    const step = nextJumpStep(d.found(), d.hasMore(), steps, d.maxSteps ?? JUMP_MAX_STEPS);
    if (step === 'scroll') {
      d.scroll();
      return step;
    }
    if (step !== 'load') {
      d.fail(jumpFailureText(step));
      return step;
    }
    await d.loadOlder();
    await d.settle();
  }
}
