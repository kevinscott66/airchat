/**
 * Что из настроек видит обычный человек, а что — только в режиме разработчика.
 *
 * Правило, по которому делится список: настройка остаётся на виду, если два
 * разумных человека выберут в ней разное. Звук уведомления, тема, срок
 * автоудаления — выберут. Адрес сервера доставки, ссылка vless:// и ключ моста
 * для внешнего агента — нет: у обычного человека нет данных, чтобы заполнить
 * эти поля, и нет способа проверить, что он заполнил их верно. Пункт, который
 * нельзя осмысленно выбрать, — это не свобода, а невынесенное нами решение,
 * переложенное на него.
 *
 * Мост стоит отдельной строкой ещё и потому, что он не просто непонятный, а
 * опасный: его ключ разрешает сменить сервер доставки, то есть увести чужую
 * переписку на чужой сервер (см. agentBridgeCommands). Такой кнопке не место
 * на экране, куда заходят включить обход блокировок.
 *
 * Решения собраны здесь, а не расставлены условиями по разметке, чтобы их
 * можно было проверить тестом целиком: экран настроек — 3000 строк, и правило
 * «не показывать инженерное» там легко потерять при следующей правке.
 */

export type SettingsVisibilityInput = {
  /** Скрытый режим, включается семью нажатиями по номеру версии. */
  devMode: boolean;
  /** Собрано ли в этой сборке ядро OpenFlux (iOS 17+/Android). */
  openFluxAvailable: boolean;
  /** Есть ли встроенный VPN-клиент, которому можно дать ссылку vless://. */
  embeddedVpnAvailable: boolean;
};

export type SettingsVisibility = {
  /** Пункт «Обход блокировок» в главном меню. */
  bypassRow: boolean;
  /** Секция своего VPN-сервера внутри «Обхода блокировок». */
  vpnSection: boolean;
  /** Секция моста для внешнего агента там же. */
  bridgeSection: boolean;
  /** Счётчик соединений туннеля (включается необратимо до перезапуска). */
  tunnelStats: boolean;
  /** Пункт «Сервер доставки». */
  relayRow: boolean;
  /** Пункт «Диагностика связи». */
  diagnosticsRow: boolean;
  /** Заголовок раздела «Для разработчика» — есть ли под ним хоть что-то. */
  developerSection: boolean;
};

export function settingsVisibility(input: SettingsVisibilityInput): SettingsVisibility {
  const { devMode, openFluxAvailable, embeddedVpnAvailable } = input;
  const vpnSection = devMode && embeddedVpnAvailable;
  return {
    // Без режима разработчика на экране «Обхода блокировок» остаётся один
    // OpenFlux. Звать туда, где его нет, незачем: человек откроет пустоту.
    bypassRow: openFluxAvailable || vpnSection,
    vpnSection,
    bridgeSection: devMode,
    tunnelStats: devMode,
    relayRow: devMode,
    diagnosticsRow: devMode,
    developerSection: devMode,
  };
}
