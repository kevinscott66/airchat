/**
 * durationLabel — сколько длится звонок, голосовое, видео. Одна арифметика.
 *
 * v4.32.423. Длительность считалась четырьмя копиями, и все четыре расходились:
 *
 *   вход      звонок     голосовое   видео в галерее   журнал звонков
 *   59.6 с    0:59       1:00        0:59              0 мин 59 с
 *   1 ч 2 м   1:02:05    62:05       62:05             62 мин 5 с
 *   −1 с      -1:-1      -1:-1       -1:-1             -1 мин -1 с
 *   NaN       NaN:NaN    NaN:NaN     NaN:NaN           NaN мин NaN с
 *
 * Три вещи здесь неправильны на экране:
 *
 *  1. Часов не знал никто, кроме звонка. Часовое видео из галереи подписано
 *     «62:05» — это читается как минуты и секунды, то есть как минута с
 *     небольшим.
 *
 *  2. Голосовое округляло секунды к ближайшей, а звонок отбрасывал дробную
 *     часть. Одна и та же запись в 59.6 секунды — «1:00» и «0:59». Отсчёт
 *     воспроизведения при округлении показывает конец раньше конца.
 *
 *  3. Ни одна копия не проверяла вход. `durationMillis` у expo-av приходит
 *     отрицательным или отсутствующим на части потоков — на экране оказывалось
 *     «-1:-1» и «NaN:NaN».
 *
 * Отрицательное и нечисло здесь означают ноль: длительности «минус секунда» не
 * бывает, а показать «0:00» честнее, чем показать «NaN».
 *
 * v4.32.426. Сюда же переехал остаток времени «без звука»: он был записан
 * ТРИЖДЫ — в списке чатов, в списке групп и в меню переписки, — и копии
 * разошлись в тексте («45м» против «45 мин»), так что одна и та же выключенная
 * до утра переписка подписывалась в списке одним, а в своём же меню другим.
 * Все три брали `Date.now()` внутри — то есть проверить их было нечем, — и все
 * три на последней минуте часа выдавали «60 мин» вместо «1 ч».
 */

/** Секунды, которым можно верить: целые, конечные, неотрицательные. */
function wholeSeconds(ms: number): number {
  if (typeof ms !== 'number' || !Number.isFinite(ms) || ms <= 0) return 0;
  return Math.floor(ms / 1000);
}

/**
 * Длительность как на часах: «0:07», «12:34», «1:02:05».
 *
 * Часы появляются только когда они есть: «0:12:34» на экране звонка выглядело
 * бы как двенадцать часов при беглом взгляде.
 */
export function formatClockDuration(ms: number): string {
  const total = wholeSeconds(ms);
  const h = Math.floor(total / 3600);
  const m = Math.floor((total % 3600) / 60);
  const s = total % 60;
  const mm = h > 0 ? String(m).padStart(2, '0') : String(m);
  return `${h > 0 ? `${h}:` : ''}${mm}:${String(s).padStart(2, '0')}`;
}

/**
 * Длительность словами: «7 с», «5 мин», «5 мин 12 с», «1 ч 2 мин».
 *
 * Нулевой хвост не пишется: «1 мин 0 с» — это «1 мин». Секунды при часах
 * опускаются: на этом масштабе они не значат ничего.
 */
export function formatSpokenDuration(ms: number): string {
  const total = wholeSeconds(ms);
  if (total < 60) return `${total} с`;
  if (total < 3600) {
    const s = total % 60;
    return s === 0 ? `${Math.floor(total / 60)} мин` : `${Math.floor(total / 60)} мин ${s} с`;
  }
  const m = Math.floor((total % 3600) / 60);
  return m === 0 ? `${Math.floor(total / 3600)} ч` : `${Math.floor(total / 3600)} ч ${m} мин`;
}

/**
 * Сколько ещё молчит выключенная переписка: «45 мин», «2 ч», «3 д».
 *
 * Единица повышается по факту, а не по порогу: 59 минут 30 секунд — это «1 ч»,
 * а не «60 мин». «Сейчас» приходит аргументом, иначе подпись нечем проверить.
 */
export function muteRemainingLabel(until: number, now: number = Date.now()): string {
  if (!Number.isFinite(until)) return '';
  const diff = until - now;
  if (diff <= 0) return '';
  const minutes = Math.ceil(diff / 60_000);
  if (minutes < 60) return `${minutes} мин`;
  const hours = Math.ceil(diff / 3_600_000);
  if (hours < 24) return `${hours} ч`;
  return `${Math.ceil(diff / 86_400_000)} д`;
}
