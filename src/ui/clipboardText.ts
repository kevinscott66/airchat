/**
 * Тексты про буфер обмена — в одном месте (v4.32.469).
 *
 * До этого одно и то же действие называлось по-разному, и разброс проходил
 * ровно там, где его виднее всего:
 *  - в меню сообщения группы на iOS пункт назывался «Копировать», а на
 *    Android — «Скопировать»: один и тот же жест в одном и том же чате
 *    подписан двумя разными словами;
 *  - в меню сообщения личной переписки на iOS оба слова стояли рядом в ОДНОМ
 *    списке: «Скопировать» и следом «Копировать ссылку»;
 *  - кнопка под QR-кодом говорила «Скопировать ID», а то же действие в
 *    карточке контакта — «Копировать ID»; подсказка «попросите друга нажать
 *    „Скопировать ID“» вела к кнопке, которую человек ищет по другому слову;
 *  - на экране профиля один и тот же ключ копировался с двумя разными
 *    сообщениями: «Идентификатор скопирован» и «ID скопирован».
 *
 * Выбран несовершенный вид — «Копировать», как в системных меню Android и в
 * большинстве уже написанных пунктов: слов меньше меняется, а привычка у
 * человека остаётся та же. Подтверждения — в прошедшем времени: там действие
 * уже произошло.
 *
 * Пункты меню и подтверждения к ним лежат парами: если появится новый способ
 * что-то скопировать, ему видно, какой текст ему полагается.
 */

/** Пункт меню: скопировать текст сообщения. */
export const COPY_ACTION = 'Копировать';
/** Пункт меню: скопировать ссылку на сообщение или группу. */
export const COPY_LINK_ACTION = 'Копировать ссылку';
/** Пункт меню: скопировать идентификатор пользователя (did:key). */
export const COPY_ID_ACTION = 'Копировать ID';

/**
 * Жест: скопировать отпечаток сообщения в сети (v4.32.915).
 *
 * Пункта меню у него нет — отпечаток копируется нажатием на строку в окне
 * сведений, — но озвучке для незрячих слово всё равно нужно, и брать его
 * врозь с остальными значило бы завести тринадцатое «Скопировать».
 * Подтверждение к нему — общее `COPIED_TEXT`: в буфер ложится строка.
 */
export const COPY_FINGERPRINT_ACTION = 'Копировать отпечаток';

/** Подтверждение: текст в буфере. */
export const COPIED_TEXT = 'Скопировано';
/** Подтверждение: ссылка в буфере. */
export const COPIED_LINK = 'Ссылка скопирована';
/** Подтверждение: идентификатор в буфере. */
export const COPIED_ID = 'ID скопирован';
/** Подтверждение: результаты опроса в буфере. */
export const COPIED_POLL_RESULTS = 'Результаты скопированы';

/**
 * Подтверждение: секрет в буфере, и буфер уберут за собой (v4.32.839).
 *
 * Отдельный текст, потому что и действие другое: `copySecretToClipboard` кладёт
 * копию с истечением, и человеку про срок надо сказать — буфер, который
 * чистится сам, приятная неожиданность только в одну сторону. До этой версии
 * фраза стояла литералом у seed-фразы; со вторым таким местом (ключ моста
 * агента) ей место здесь, рядом с остальной парой.
 */
export const COPIED_WITH_SWEEP = `${COPIED_TEXT} — буфер очистится через минуту`;

