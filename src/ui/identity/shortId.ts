/**
 * shortId — как назвать личность, когда имени нет.
 *
 * v4.32.425. Сокращённый идентификатор — это то, чем пользователь отличает
 * одного незнакомца от другого: подпись под записью в ленте, строка в списке
 * поставивших реакцию, заголовок карточки контакта. Правило «как его
 * сократить» было записано в двенадцати местах, и все двенадцать давали разный
 * ответ об одном и том же человеке:
 *
 *   did:key:z6MkhaXgBZDvotDkL5257faiztiGiC2QtKLGpbnnEGta2doK
 *     профиль            did:key:z6Mk…ta2doK
 *     лента, автор       did:key:z6Mk…
 *     лента, просмотры   did:key:z6Mkha…ta2doK
 *     контакты           did:key:z6Mkha…EGta2doK
 *     список чатов       did:ke…2doK
 *     переписка          EGta2doK
 *     карточка контакта  did:key:z6MkhaXgBZDv…
 *     чёрный список      did:key:z6MkhaXg…
 *     карточка профиля   z6MkhaXg…EGta2doK
 *
 * Отсюда три беды, и только третья — косметика.
 *
 * Первая. `did:key:` у всех одинаков, а первые четыре знака ключа Ed25519 —
 * это multicodec 0xED01 в base58btc, то есть `z6Mk` у КАЖДОГО. Поэтому форма
 * «двенадцать знаков с головы и многоточие» давала `did:key:z6Mk…` — одну и ту
 * же строку для всех людей на свете. В списке поставивших реакцию все, кого
 * нет в контактах, подписывались одинаково.
 *
 * Вторая. Голова и хвост брались без проверки длины, и на коротком значении
 * они перекрывались: `slice(0, 14)…slice(-6)` от восьмизначного `z6MkhaXg`
 * давало `z6MkhaXg…MkhaXg` — строку ДЛИННЕЕ исходной, в которой знаки стоят не
 * на своих местах. Сокращение, дописывающее знаки, — это не сокращение.
 *
 * Третья. Одни места показывали голову, другие — хвост. Один и тот же человек
 * в ленте и в переписке подписан непересекающимися кусками, и сверить его
 * глазами между экранами нельзя.
 *
 * Здесь правило одно: постоянная приставка снимается (в ней нет различий),
 * дальше — голова и хвост поровну, и только если сокращать вообще есть что.
 */

/** Приставка did:key: одинакова у всех и различать никого не помогает. */
const DID_KEY_PREFIX = 'did:key:';

/** Сколько знаков показывать с каждого конца по умолчанию. */
export const SHORT_ID_KEEP = 6;

/**
 * Значащая часть идентификатора: то, чем один человек отличается от другого.
 *
 * Снимается только точная приставка `did:key:`. Всё остальное — публичный ключ
 * в base64, идентификатор группы, что угодно ещё — возвращается как есть:
 * угадывать формат чужой строки здесь нечем.
 */
export function identityBody(value: string): string {
  return value.startsWith(DID_KEY_PREFIX) ? value.slice(DID_KEY_PREFIX.length) : value;
}

/**
 * Сокращённая подпись личности: `z6MkhaXg…EGta2doK`.
 *
 * Многоточие ставится, только если что-то действительно выброшено: короткое
 * значение возвращается целиком. Иначе подпись обещает продолжение, которого
 * нет, а на совсем коротком — ещё и повторяет знаки.
 *
 * @param keep сколько знаков показать с каждого конца
 */
export function shortIdentity(value: unknown, keep: number = SHORT_ID_KEEP): string {
  if (typeof value !== 'string' || value === '') return '';
  const body = identityBody(value);
  const n = Math.max(1, Math.floor(keep));
  // Ровно 2n + 1 знак сокращать незачем: многоточие заняло бы место того
  // единственного знака, который оно скрывает.
  if (body.length <= n * 2 + 1) return body;
  return `${body.slice(0, n)}\u2026${body.slice(-n)}`;
}
