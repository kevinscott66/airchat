export type AppColors = typeof darkColors;

export type ThemeMode = 'dark' | 'light' | 'system';
/** Разрешённая схема — то, что в итоге нарисовано, без варианта 'system'. */
export type ColorScheme = 'dark' | 'light';

/** Схема, в которую разворачивается выбранный режим: 'system' спрашивает у ОС. */
export function resolveScheme(mode: ThemeMode): ColorScheme {
  if (mode === 'dark' || mode === 'light') return mode;
  return Appearance.getColorScheme() === 'light' ? 'light' : 'dark';
}

/** Палитра по уже разрешённой схеме. */
export function colorsForScheme(scheme: ColorScheme): AppColors {
  return scheme === 'light' ? lightColors : darkColors;
}

/** Активные цвета на основе выбранной темы и системных настроек. */
export function resolveColors(mode: ThemeMode): AppColors {
  return colorsForScheme(resolveScheme(mode));
}

/** Относительная яркость по WCAG 2.1 для каналов sRGB 0…255. */
function relativeLuminance(rgb: readonly number[]): number {
  const weights = [0.2126, 0.7152, 0.0722];
  return rgb.reduce((acc, raw, i) => {
    const v = raw / 255;
    return acc + weights[i] * (v <= 0.03928 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4));
  }, 0);
}

/** Каналы #RRGGBB, либо null, если строка не такого вида. */
function parseHex(hex: string): number[] | null {
  if (!/^#[0-9a-fA-F]{6}$/.test(hex)) return null;
  const n = parseInt(hex.slice(1), 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}

/**
 * Чёрный или белый — тот из двух, что читается на заданной заливке.
 *
 * Нужен там, где цвет фона выбирает пользователь и в палитре его нет: образцы
 * «цвета акцента» в настройках. Раньше поверх них всегда писали белым, и на
 * светлых образцах (#00bcd4, #4caf50, #ff9800) галочка выбора давала 2.2–2.8:1
 * при пороге 3:1 для нетекстовых элементов — то есть терялась именно там, где
 * должна была показывать, что выбрано.
 *
 * Порог 0.179 — точка, в которой контраст с белым и с чёрным совпадает:
 * (1.05/(L+0.05)) = ((L+0.05)/0.05).
 */
export function contrastingInk(background: string): '#000000' | '#ffffff' {
  const rgb = parseHex(background);
  if (!rgb) return '#ffffff';
  return relativeLuminance(rgb) > 0.179 ? '#000000' : '#ffffff';
}

/**
 * Контраст двух цветов по WCAG 2.1, 1:1 … 21:1. Нераспознанный цвет даёт 1 —
 * то есть «считать проходящим нельзя», а не «сойдёт».
 *
 * Формула нарочно продублирована в themeContrast.test.ts: тест должен
 * проверять палитру, а не совпадать с ней в общей ошибке.
 */
export function contrastRatio(a: string, b: string): number {
  const ra = parseHex(a);
  const rb = parseHex(b);
  if (!ra || !rb) return 1;
  const la = relativeLuminance(ra);
  const lb = relativeLuminance(rb);
  return la > lb ? (la + 0.05) / (lb + 0.05) : (lb + 0.05) / (la + 0.05);
}

