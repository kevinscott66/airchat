/** Минимальный контраст белой надписи на заливке `primary`. */
const ACCENT_MIN_CONTRAST = 4.5;

/**
 * Приводит выбранный пользователем акцент к тому, на чём читается белый текст.
 *
 * `accentColor` из настроек подменяет `primary` целиком, а `primary` — это
 * заливка: кнопки, FAB, бейджи непрочитанного, чипы, исходящий пузырь в
 * групповом чате. Надпись поверх неё в 99 местах написана белым, и это не
 * небрежность, а инвариант — обе палитры его держат (4.5:1 закреплено тестом).
 * Инвариант ломался ровно в одном месте: пользователь выбирал светлый акцент, и
 * весь интерфейс разом получал белые надписи на светлой заливке — 2.2:1 на
 * оранжевом. Починить это в 99 местах нельзя, а вот сохранить инвариант на
 * входе — можно.
 *
 * Каналы умножаются на общий множитель: в HSV это меняет только value, поэтому
 * тон и насыщенность выбранного цвета остаются, темнеет он ровно настолько,
 * насколько нужно. Значения из ACCENT_SWATCHES проходят без изменений.
 *
 * Верхней границы яркости здесь нет намеренно: тексту на тёмном фоне нужно
 * наоборот посветлее, и свести оба требования в одном значении невозможно —
 * белый на заливке требует яркости ≤0.183, текст на фоне #0b1020 при 4.5:1
 * требует ≥0.201. Поэтому у одного пользовательского выбора два производных
 * токена: `primary` (заливка) — отсюда, `accent` (текст) — из readableOn().
 *
 * Возвращает null на строке, которая не является #RRGGBB, — в хранилище с
 * прошлых версий могло остаться что угодно.
 */
export function normalizeAccent(hex: string): string | null {
  const rgb = parseHex(hex);
  if (!rgb) return null;
  let channels = rgb;
  // Сходится всегда: floor(v * 0.99) строго убывает до нуля, а чёрный даёт 21:1.
  while (1.05 / (relativeLuminance(channels) + 0.05) < ACCENT_MIN_CONTRAST) {
    channels = channels.map((v) => Math.floor(v * 0.99));
  }
  return toHex(channels);
}

function toHex(channels: readonly number[]): string {
  return '#' + channels.map((v) => v.toString(16).padStart(2, '0')).join('');
}

/**
 * Тот же цвет, но доведённый до читаемости НА заданном фоне.
 *
 * Парная функция к normalizeAccent(): та готовит цвет к роли заливки со светлой
 * надписью поверх, эта — к роли текста поверх фона. Требования противоположные
 * (заливке нужно темнее, тексту на тёмном фоне светлее), поэтому и значения
 * получаются разные — это и есть причина существования двух токенов, `primary`
 * и `accent`, при одном пользовательском выборе.
 *
 * Направление задаёт фон: на тёмном цвет подмешивается к белому (растёт
 * светлота, тон сохраняется), на светлом каналы умножаются на общий множитель
 * (в HSV меняется только value). Цвет, который уже проходит порог, возвращается
 * как есть.
 */
export function readableOn(hex: string, background: string, minContrast = 4.5): string | null {
  const rgb = parseHex(hex);
  const bg = parseHex(background);
  if (!rgb || !bg) return null;
  const bgLum = relativeLuminance(bg);
  const ratio = (lum: number): number =>
    bgLum > lum ? (bgLum + 0.05) / (lum + 0.05) : (lum + 0.05) / (bgLum + 0.05);
  const lighten = bgLum < 0.5;
  let channels: number[] = rgb;
  // Шагов заведомо хватает: 0.98^256 ≈ 0.005 в одну сторону, столько же
  // приближений к белому — в другую, а чёрный и белый дают 21:1 на своём фоне.
  for (let i = 0; i < 256 && ratio(relativeLuminance(channels)) < minContrast; i++) {
    channels = lighten
      ? channels.map((v) => Math.min(255, v + Math.ceil((255 - v) * 0.02)))
      : channels.map((v) => Math.floor(v * 0.98));
  }
  return toHex(channels);
}

/**
 * Акцентная надпись ВНУТРИ пузыря, а не на фоне страницы.
 *
 * v4.32.352: ссылка и упоминание в собственном сообщении лежат на заливке
 * пузыря, а `accent` подобран под фон страницы. Разница не косметическая:
 * на светлой теме `accent` #036B96 на заливке #0068D6 даёт 1.11:1 — ссылку
 * в своём же сообщении не видно вовсе. Отсчёт ведём от заливки; тон
 * исходного цвета readableOn сохраняет, так что ссылка остаётся «той же
 * синей», просто в светлоте, различимой на этом фоне.
 *
 * fallback нужен на случай нераспознанного hex (например, rgba-строки из
 * пользовательской темы): тогда берём заведомо контрастный цвет содержимого
 * пузыря, а не оставляем нечитаемый.
 */
export function accentOnFill(accent: string, fill: string, fallback: string): string {
  return readableOn(accent, fill) ?? fallback;
}

/** Знаки поверх непрозрачной заливки. Считается из палитры, см. `inkOn`. */
export interface FillInk {
  /** Основной текст. */
  text: string;
  /** Второстепенный текст: цитата, подпись. */
  secondary: string;
  /** Значок «отправлено / доставлено / в очереди». */
  muted: string;
  /** Значок «прочитано». */
  accent: string;
  /** Значок «не отправлено». */
  error: string;
  /** Значок «в избранном». */
  star: string;
  /** Значок «идёт прямо сейчас»: живая геолокация, запись. */
  success: string;
}

const inkCache = new Map<string, FillInk>();

/**
 * Токен, поднятый до порога контраста на заданной заливке.
 *
 * readableOn обещает порог, но не гарантирует его: шаги упираются в белое или
 * чёрное, и дальше он возвращает лучшее, до чего дошёл. На светлой заливке
 * разница доходила до 4.47:1 при обещанных 4.5 — молча, потому что проверял
 * результат никто (v4.32.387). Здесь результат проверяется, и если порога нет,
 * берётся чёрное или белое — последняя опора, годная и для rgba-строк из
 * пользовательской темы, которые как hex не разбираются вовсе.
 *
 * v4.32.391: вынесено из inkOn — порог у роли свой (надпись 4.5:1, знак 3:1), и
 * набор ролей у пузыря сообщения и у пузыря опроса разный, а правило подъёма
 * одно. Второй его копии быть не должно.
 */
export function readableInk(token: string, fill: string, min: number): string {
  const raised = readableOn(token, fill, min);
  return raised && contrastRatio(raised, fill) >= min ? raised : contrastingInk(fill);
}

/**
 * Чернила поверх заливки, отличной от фона страницы.
 *
 * v4.32.386. С 344-го содержимое исходящего пузыря красилось вписанными руками
 * значениями — '#7ecbff' у «прочитано», '#ff8a8a' у «не отправлено», '#8e8e93'
 * у остальных галочек, '#9aa3c0' у цитаты — под объяснением «пузырь тёмный в
 * обеих темах, значит тема ни при чём». Объяснение было неверным: тёмный он
 * только в тёмной теме, а в светлой это #0068D6 — синий средней светлоты. На
 * нём те же значения дают 1.63:1, 2.34:1 и 2.12:1, то есть галочки в
 * собственном сообщении у светлой темы практически не видно. Проверить это
 * было нечем: значения не лежали в палитре, и контрастный тест их не видел.
 *
 * Правило то же, что у ссылки в пузыре с 352-го (см. accentOnFill): отсчёт от
 * ЗАЛИВКИ, а не от фона страницы, тон исходного токена сохраняется. Поэтому в
 * тёмной теме возвращаются ровно прежние значения — правка ничего не двигает
 * там, где и так работало, — а в светлой те же цвета поднимаются до порога.
 *
 * Пороги разные не для красоты: текст — 4.5:1, знаки — 3:1. Ниже 3:1 значок
 * перестаёт быть различим по форме.
 *
 * `text` можно задать явно: у пузыря цвет содержимого выбран дизайном
 * (`bubbleOutText`), и выводить его из `colors.text` значило бы заменить белую
 * надпись в светлой теме на серую.
 */
export function inkOn(colors: AppColors, fill: string, text?: string): FillInk {
  const key = [fill, text ?? '', colors.text, colors.textSecondary, colors.textMuted, colors.accent, colors.error, colors.star, colors.success].join('|');
  const cached = inkCache.get(key);
  if (cached) return cached;
  // Чёрный или белый: последняя опора, когда цвет не разбирается как hex
  // (например, rgba-строка из пользовательской темы) или когда поднять его до
  // порога не удаётся вовсе.
  const lift = (token: string, min: number): string => readableInk(token, fill, min);
  const ink: FillInk = {
    text: text ?? lift(colors.text, 4.5),
    secondary: lift(colors.textSecondary, 4.5),
    muted: lift(colors.textMuted, 3),
    accent: lift(colors.accent, 3),
    error: lift(colors.error, 3),
    star: lift(colors.star, 3),
    success: lift(colors.success, 3),
  };
  inkCache.set(key, ink);
  return ink;
}

/** Чернила внутри исходящего пузыря — частный случай `inkOn`. */
export function bubbleInk(colors: AppColors): FillInk {
  return inkOn(colors, colors.bubbleOut, colors.bubbleOutText);
}

/**
 * Чернила внутри заливки-акцента.
 *
 * v4.32.398. Исходящий пузырь ГРУППОВОГО чата залит не `bubbleOut`, а
 * `primary` — то есть цветом, который выбирает пользователь в настройках.
 * Правку 386-го он не получил: всё его содержимое оставалось написанным белым
 * руками — '#fff' у текста и 'rgba(255,255,255,0.5…0.85)' у времени, галочек,
 * подписей, разделителей и плёнки «один просмотр».
 *
 * Полупрозрачный белый здесь особенно плох. Его нельзя проверить (что
 * получится, зависит от того, что под ним) и нельзя поднять: на синем #3d5afe
 * 60%-й белый даёт 2.8:1 при пороге 4.5:1 — время в собственном сообщении не
 * читается даже в тёмной теме, а на светлом акценте («оранжевый», «серо-синий»)
 * не читается и остальное.
 *
 * Единственное место, где `bubbleInk` всё-таки применили (звезда «в
 * избранном»), считало от `bubbleOut` — от заливки ДРУГОГО пузыря: в тёмной
 * теме это #1a2e5e против #3d5afe, цвета разные, совпадение случайное.
 *
 * Белый на `primary` — инвариант, и его держит `normalizeAccent`. Но держит он
 * ровно его: у второстепенных ролей запаса нет, поэтому их считают от заливки.
 */
export function primaryInk(colors: AppColors): FillInk {
  return inkOn(colors, colors.primary, contrastingInk(colors.primary));
}

/** Вид переписки: 1:1 или групповая. Заливка своего пузыря у них разная. */
export type BubbleKind = 'chat' | 'group';

/** Всё, что рисуется внутри пузыря: заливка, чернила, вложенная плашка, линия. */
export interface BubbleSurface {
  /** Заливка самого пузыря. */
  fill: string;
  /** Чернила на этой заливке. */
  ink: FillInk;
  /** Вложенный блок внутри пузыря: превью, врезка кода, плашка. */
  plate: { fill: string; ink: FillInk };
  /** Значок-действие: в своём пузыре — как текст, в чужом — цвет действия. */
  icon: string;
  /** Волосяная линия внутри пузыря. */
  hairline: string;
}

/**
 * Содержимое пузыря переписки.
 *
 * v4.32.411. Правку 386-го («чернила считаются от заливки») пузыри получили
 * только на уровне экрана: сам текст сообщения красится `bubbleOutText`. А
 * всё, что рисуют вложенные компоненты — размер файла, номер телефона,
 * «Показать полностью», подписи под картой, — до сих пор писалось руками
 * полупрозрачным белым 'rgba(255,255,255,0.7)'. Одно правило, восемь копий,
 * все восемь мимо.
 *
 * Замерено на исходящем пузыре: в светлой теме белый под 70 % даёт на #0068D6
 * 3.40:1 при пороге текста 4.5:1, то есть каждая такая подпись в своём
 * сообщении не читается. В групповом чате пузырь залит выбранным акцентом, и
 * там хуже: 2.84:1 на «малиновом» и 2.96:1 на «красном». Волосяная линия
 * 'rgba(255,255,255,0.3)' не берёт даже графический порог 3:1 — 2.55:1 в
 * тёмной теме и 1.70:1 в светлой.
 *
 * Отдельная находка — вложенные плашки. Превью видео во ВХОДЯЩЕМ пузыре
 * заливалось `surfaceHigh` поверх пузыря, залитого тем же `surfaceHigh`:
 * блок был не виден вовсе. Порядок тот же, что и везде (v4.32.395): подложка
 * от пузыря, потом чернила от подложки.
 */
/**
 * Чернила пузыря по его заливке. Две заливки из палитры имеют свой подобранный
 * набор (`bubbleOutText`, `primaryText`), остальные выводятся из заливки.
 */
function bubbleInkOn(colors: AppColors, fill: string): FillInk {
  if (fill === colors.bubbleOut) return bubbleInk(colors);
  if (fill === colors.primary) return primaryInk(colors);
  return inkOn(colors, fill, colors.text);
}

/**
 * То же, что и `bubbleSurface`, но заливка известна вызывающему. Нужна там, где
 * содержимое пузыря рисует сам экран, а не отдельный компонент: у сообщения из
 * одних эмодзи пузыря нет вовсе и подложка там — фон списка.
 *
 * `mine` здесь значит не «сообщение исходящее», а «содержимое лежит на
 * собственной цветной заливке»: исходящие эмодзи лежат на фоне, и акцентная
 * иконка там уместнее белой.
 */
export function bubbleSurfaceOn(colors: AppColors, fill: string, mine: boolean): BubbleSurface {
  const ink = bubbleInkOn(colors, fill);
  const plateFill = nestedFill(fill);
  return {
    fill,
    ink,
    plate: { fill: plateFill, ink: inkOn(colors, plateFill, contrastingInk(plateFill)) },
    icon: mine ? ink.text : ink.accent,
    // В своём пузыре линия — графика на заливке, порог 3:1 держат приглушённые
    // чернила. В чужом остаётся `border`: он и задуман как тихая линия на
    // поверхности, а поднимать его здесь значило бы утяжелить весь список.
    hairline: mine ? ink.muted : colors.border,
  };
}

export function bubbleSurface(colors: AppColors, mine: boolean, kind: BubbleKind = 'chat'): BubbleSurface {
  const fill = mine
    ? (kind === 'group' ? colors.primary : colors.bubbleOut)
    : (kind === 'group' ? colors.surface : colors.surfaceHigh);
  return bubbleSurfaceOn(colors, fill, mine);
}

/**
 * Цвет кружка-различителя: аватар без фотографии, окрашенный по хешу ключа.
 *
 * v4.32.398. Такой цвет — ДАННЫЕ, а не роль темы: он не должен меняться ни от
 * схемы, ни от выбранного акцента, иначе собеседника перестанут узнавать в
 * списке. Незаконно здесь было другое: цвет задавался строкой 'hsl(…)',
 * которую `contrastingInk` разобрать не может, — и буква поверх писалась белой
 * руками, на слово. Светлота там зафиксирована, так что белый и правда верен;
 * но проверить это было нечем, а разойтись значения могли молча.
 *
 * Возвращается #RRGGBB — из него буква считается тем же способом, что и везде.
 */
export function identityFill(hue: number, saturation = 0.45, lightness = 0.4): string {
  const c = (1 - Math.abs(2 * lightness - 1)) * saturation;
  const h = ((((hue % 360) + 360) % 360)) / 60;
  const x = c * (1 - Math.abs((h % 2) - 1));
  const rgb =
    h < 1 ? [c, x, 0] :
    h < 2 ? [x, c, 0] :
    h < 3 ? [0, c, x] :
    h < 4 ? [0, x, c] :
    h < 5 ? [x, 0, c] : [c, 0, x];
  const m = lightness - c / 2;
  return toHex(rgb.map((v) => Math.round((v + m) * 255)));
}

/**
 * Тон различителя, выведенный из строки.
 *
 * v4.32.399. Правило вывода было написано в пяти местах и в двух версиях:
 * `seed.charCodeAt(0) * 31` (список чатов, аватар группы, аватар участника, две
 * модалки) и хеш всей строки (аватар отправителя в переписке, цвет его имени).
 * Первая смотрит на ОДИН символ, поэтому все «Александр», «Алексей» и «Анна»
 * получают ровно один цвет — различитель, который не различает.
 *
 * Хуже другое: совпадать эти две версии не были обязаны и не совпадали. В
 * переписке кружок отправителя выводился из имени, в списке участников — из
 * ключа: один человек, два разных цвета, — а подпись «matches avatar hue» у
 * функции цвета имени была попросту неверна.
 */
export function identityHue(seed: string): number {
  let acc = 0;
  for (let i = 0; i < seed.length; i += 1) acc = (acc * 31 + seed.charCodeAt(i)) & 0x7fffffff;
  return acc % 360;
}

/** Кружок различителя: заливка по хешу и буква, посчитанная из неё. */
export interface IdentityCircle {
  fill: string;
  ink: string;
}

/**
 * Кружок-заглушка вместо фотографии.
 *
 * Число вместо строки — когда тон задан, а не выведен (канал: у него один цвет
 * на все каналы, а не свой на каждый).
 */
export function identityAvatar(seed: string | number): IdentityCircle {
  const fill = identityFill(typeof seed === 'number' ? seed : identityHue(seed));
  return { fill, ink: contrastingInk(fill) };
}

/**
 * Имя, окрашенное тем же различителем, но читаемое.
 *
 * v4.32.399. Цвет имени отправителя строился как hsl(тон, 58%, 36%) в светлой
 * теме и hsl(тон, 70%, 72%) в тёмной: светлота одна на все тона, а яркость у
 * тонов разная. На жёлто-зелёном (тон ≈60) это 3.34:1 на белом пузыре при
 * пороге 4.5:1 — то есть у части участников имя в светлой теме не читается, и
 * у кого именно, зависит от их имени.
 *
 * Здесь тон сохраняется, а до порога цвет доводит расчёт — тот же, что у
 * ссылки в пузыре и у значка меню.
 */
export function identityInk(seed: string, host: string): string {
  return readableInk(identityFill(identityHue(seed), 0.6, 0.45), host, 4.5);
}

/**
 * Заливка вложенного блока — цитаты внутри сообщения.
 *
 * v4.32.387: блок цитаты был залит 'rgba(61,90,254,0.12)' — постоянной
 * подмесью синего, одинаковой во всех темах и на всех поверхностях. Считать от
 * неё было невозможно: цвет получался разный (внутри пузыря, внутри входящего
 * сообщения, на фоне ленты), а полоска и текст поверх стояли фиксированными.
 * В светлой теме текст цитаты давал на ней 1.8–2.1:1 — прочитать, на что
 * отвечают, было нельзя нигде.
 *
 * Здесь заливка выводится из ТОЙ поверхности, на которой блок лежит: сдвиг на
 * 10% по светлоте, тон не заносится. Дальше по этой заливке считается `inkOn`,
 * поэтому порядок важен: сначала фон, потом чернила, — и подгонять руками
 * нечего.
 *
 * Направление сдвига не постоянное. Обычно вложенный блок двигают в сторону
 * контрастных чернил (на тёмном — светлее, на светлом — темнее): так он
 * заметнее. Но этот сдвиг съедает запас самих чернил, а у светлого пузыря
 * #0068D6 запаса нет — белым по нему всего 5.3:1, и после сдвига остаётся
 * 4.47:1, то есть блок стал бы виден ценой текста в нём. Поэтому если сдвиг «к
 * чернилам» роняет их ниже порога, блок уходит в другую сторону — становится
 * не приподнятым, а утопленным. Обе стороны читаются одинаково; выбирать между
 * ними по вкусу, а не по запасу, значит выбирать вслепую.
 */
export function nestedFill(host: string, minInkContrast = 4.5): string {
  const inkHex = contrastingInk(host);
  const toward = mixHex(inkHex, host, 0.1);
  if (contrastRatio(inkHex, toward) >= minInkContrast) return toward;
  return mixHex(inkHex === '#ffffff' ? '#000000' : '#ffffff', host, 0.1);
}

/**
 * НЕПРОЗРАЧНЫЙ результат наложения `fg` с прозрачностью `alpha` на `bg`.
 *
 * v4.32.392. Полупрозрачную подложку («цвет плюс `22`») нельзя проверить
 * контрастным тестом: цвет, который получится на экране, зависит от того, что
 * окажется под ней, а под ней бывает и нажатое состояние строки, и подсветка
 * поиска. Считаем результат заранее — тогда он один и тот же и в тесте, и на
 * экране.
 */
function mixHex(fg: string, bg: string, alpha: number): string {
  const f = parseHex(fg);
  const b = parseHex(bg);
  if (!f || !b) return fg;
  return toHex(f.map((v, i) => Math.round(v * alpha + b[i] * (1 - alpha))));
}

