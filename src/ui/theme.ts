export interface SwitchTone {
  /** Дорожка выключенного переключателя — заливка, порог 3:1 к поверхности. */
  trackOff: string;
  /** Дорожка включённого — выбранный пользователем акцент. */
  trackOn: string;
  /** Бегунок: он лежит НА дорожке, поэтому считается к ней, а не к странице. */
  thumb: string;
}

/**
 * Цвета переключателя.
 *
 * v4.32.400. Шестнадцать переключателей в трёх файлах были написаны одинаково
 * и одинаково неправильно:
 *
 *     trackColor={{ false: colors.border, true: colors.primary }}
 *     thumbColor="#fff"
 *
 * `border` — токен ВОЛОСЯНОЙ ЛИНИИ, он подобран так, чтобы разделитель был
 * едва заметен. Как ЗАЛИВКА дорожки он даёт в светлой теме 1.52:1 к белой
 * карточке, а белый бегунок поверх него — 1.52:1 к дорожке. То есть в светлой
 * теме выключенный переключатель невидим целиком: белый кружок на белёсой
 * полоске на белой карточке. Пользователь не может ни увидеть состояние, ни
 * найти сам элемент управления.
 *
 * Правило: дорожка отвечает за видимость НА СТРАНИЦЕ, бегунок — за видимость
 * НА ДОРОЖКЕ. Поэтому `trackOff` берётся из `mutedFill` (токен «заливка, на
 * которой лежит белое»: 5.9:1 к белой карточке, 3.1:1 к самой светлой из
 * тёмных поверхностей), а бегунок — из чернил включённой дорожки, чтобы он
 * оставался одним и тем же кружком при переключении.
 *
 * Включённая дорожка — акцент, а его выбирает пользователь; гарантировать её
 * контраст К СТРАНИЦЕ нельзя (`normalizeAccent` держит только белое поверх
 * акцента). В этом состоянии видимость несёт бегунок, чей контраст к дорожке
 * гарантирован в обоих состояниях.
 */
export function switchTone(colors: AppColors): SwitchTone {
  return {
    trackOff: colors.mutedFill,
    trackOn: colors.primary,
    thumb: contrastingInk(colors.primary),
  };
}

