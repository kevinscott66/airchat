/**
 * Цвета экрана звонка.
 *
 * v4.32.405. Экран звонка тёмный при любой теме — это установлено в 388-м:
 * он занимает всё и появляется поверх чего угодно. Но «тёмный» до сих пор
 * означало два литерала: '#111' у завершённого звонка и '#1a6b3c' у идущего,
 * а поверх них — девять белых значений с прозрачностью.
 *
 * Из-за этого не был виден главный размер: круглые кнопки «принять» и
 * «сбросить» на зелёном фоне '#1a6b3c' давали 1.38:1 — они отличались от
 * фона почти только цветом. Здесь фон выводится из того же токена, что и
 * кнопка ответа, но приглушён к тёмной странице ровно настолько, чтобы
 * кнопки на нём взяли порог графики 3:1.
 *
 * Отдельно стоит запомнить: successFill и errorFill СОВПАДАЮТ по яркости
 * (1.00:1). Значит «принять» и «отклонить» в монохромном зрении не
 * различаются заливкой вовсе — их различают повёрнутый значок и подписи
 * «Принять» / «Отклонить». Ни того, ни другого убирать нельзя.
 */
export function callTone(phase: CallPhase): CallTone {
  const fill =
    phase === 'ended'
      ? darkColors.background
      : mixHex(darkColors.successFill, darkColors.background, 0.22);
  const ink = inkOn(darkColors, fill);
  const avatarFill = mixHex(ink.text, fill, 0.22);
  return {
    fill,
    ink: ink.text,
    inkMuted: ink.secondary,
    avatarFill,
    avatarInk: contrastingInk(avatarFill),
    chip: mixHex(ink.text, fill, 0.15),
    chipActive: mixHex(ink.text, fill, 0.32),
    accept: darkColors.successFill,
    acceptInk: contrastingInk(darkColors.successFill),
    hangup: darkColors.errorFill,
    hangupInk: contrastingInk(darkColors.errorFill),
    ring: mixHex(ink.text, fill, 0.38),
  };
}
