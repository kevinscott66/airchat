export function withAlpha(hex: string, alpha: number): string {
  const m = hex.trim().match(/^#([0-9a-f]{6})$/i);
  if (!m) return 'transparent';
  const n = parseInt(m[1], 16);
  const a = Math.min(1, Math.max(0, alpha));
  return `rgba(${(n >> 16) & 255}, ${(n >> 8) & 255}, ${n & 255}, ${a})`;
}

/**
 * Волна нажатия на ЦВЕТНОЙ кнопке.
 *
 * Токен палитры `ripple` выведен из акцента и годится для кнопок на
 * поверхностях оболочки — так он и применён в настройках. Но у кнопки
 * «отправить» заливка и есть акцент, и акцент поверх акцента не виден вовсе:
 * замер даёт 1.000 на всех девяти образцах. Поэтому в обоих композерах было
 * написано 'rgba(255,255,255,0.3)'.
 *
 * Белое там и вправду верно — но верно по инварианту `normalizeAccent`,
 * который держит акцент достаточно тёмным для белых чернил. Инвариант этот
 * записан в другой функции и в другом файле, а у кнопки не записан никак:
 * ровно та форма, которую разбирали 407-й и 411-й — правило, известное
 * только автору строки (v4.32.414).
 *
 * Здесь волна берётся от ЗАЛИВКИ, как и чернила. Сегодня на всех девяти
 * акцентах это байт в байт прежний цвет — в том и смысл: меняется не
 * картинка, а то, откуда цвет взялся. Прозрачность тут по делу — это отклик
 * на касание, а не поверхность, и мерить его к порогам WCAG нечего.
 */
export function rippleOn(fill: string): string {
  return withAlpha(contrastingInk(fill), 0.3);
}

