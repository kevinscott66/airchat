/** Плашка реакции: заливка, счётчик, контур. См. `reactionInk`. */
export interface ReactionInk {
  /** Заливка плашки — вложенный блок на поверхности-хозяине. */
  fill: string;
  /** Счётчик «сколько человек поставили» — надпись на заливке, порог 4.5:1. */
  count: string;
  /** Контур плашки (лента) — графика, порог 3:1 к поверхности-хозяину. */
  border: string;
}

/**
 * Плашка реакции — тот же вложенный блок, что и цитата (см. `nestedFill`).
 *
 * v4.32.395. Плашка была залита 'rgba(61,90,254,0.18)' — акцентом по
 * умолчанию с прозрачностью, — а счётчик прибит к '#9aa3c0'. Обе величины не
 * зависели ни от темы, ни от того, на чём плашка лежит, и обе на этом
 * ломались:
 *
 *   • На СВОЁМ сообщении в светлой теме пузырь и есть акцент (#0068D6).
 *     Подмешать акцент в акцент значит не изменить ничего: плашка давала к
 *     пузырю 1.01:1, то есть её не было видно вовсе — ни границ, ни формы.
 *   • Счётчик на светлой теме давал 2.14:1 на своём пузыре, 1.67:1 на чужом и
 *     1.77:1 на фоне ленты при пороге 4.5:1 — число рядом со смайликом не
 *     читалось нигде.
 *
 * Отсюда правило: подмешивать акцент в плашку нельзя в принципе — поверхность
 * под ней бывает акцентом. Плашка выводится из ХОЗЯИНА тем же сдвигом по
 * светлоте, что и блок цитаты, а счётчик — уже из получившейся заливки.
 * Порядок обязателен: сначала фон, потом чернила.
 */
export function reactionInk(colors: AppColors, host: string): ReactionInk {
  const fill = nestedFill(host);
  return {
    fill,
    count: inkOn(colors, fill).secondary,
    // Контур отделяет плашку от того, что СНАРУЖИ, поэтому считается к хозяину,
    // а не к заливке.
    border: readableInk(colors.accent, host, 3),
  };
}

/**
 * Цвет палитры с прозрачностью — плёнка поверх неизвестного основания.
 *
 * v4.32.401. Подсветка строки в переписке лежит на ОБОЯХ, а обои выбирает
 * пользователь — из десяти цветов или картинкой. Что получится под плёнкой,
 * посчитать нельзя в принципе, поэтому здесь есть жёсткое условие: от плёнки
 * не должно зависеть ничего читаемого. Она сообщает «эта строка отмечена», а
 * сами пузыри лежат сверху и непрозрачны — их контраст плёнка не меняет.
 *
 * Возвращается именно `rgba(...)`, а не восьмизначный hex: RN умеет
 * интерполировать анимацию только между такими строками.
 *
 * Разбор не удался (в теме может стоять уже готовая rgba-строка) — плёнки
 * просто не будет: `transparent` честнее, чем цвет наугад.
 */
/**
 * Палитра с учётом выбранного пользователем акцента.
 *
 * v4.32.348: выбор пользователя разворачивается в ДВА токена, а не в один.
 * `primary` — заливка со светлой надписью поверх, `accent` — текст поверх
 * фона; требования у них противоположные, поэтому и значения разные.
 *
 * v4.32.407: жил в ThemeContext и делал `primaryMuted: accent + '33'` —
 * то есть стоило выбрать любой акцент, и один токен палитры переставал быть
 * непрозрачным. Последствий два, и оба тихие. Первое: `contrastRatio` и
 * `contrastingInk` не разбирают восьмизначный цвет — первая возвращает 1,
 * вторая молча отвечает БЕЛЫМ. Второе: то, что нарисовано на экране,
 * зависело от того, что окажется под подложкой, и потому не проверялось
 * вовсе — а `accent` на ней давал 3.40–4.44:1 в светлой теме и 3.48–4.01:1
 * в тёмной, ни на одном из девяти образцов не дотягивая до 4.5:1.
 *
 * Теперь подложка считается заранее и непрозрачна, а волна нажатия, которой
 * прозрачность нужна по делу, получила собственный токен `ripple`.
 *
 * `accent` сюда попадает уже прошедшим normalizeAccent() — и на записи, и
 * при чтении из хранилища.
 */
export function applyAccent(base: AppColors, accent: string | null): AppColors {
  if (!accent) return base;
  return {
    ...base,
    primary: accent,
    primaryMuted: mixHex(accent, base.background, 0x33 / 255),
    ripple: accent + '33',
    accent: readableOn(accent, base.background) ?? base.accent,
  };
}
