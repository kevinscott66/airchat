/**
 * Значок на подложке своего же тона.
 *
 * v4.32.392: подложка бралась как `${цвет}22`, а значок — тем же цветом
 * as-is. На светлой поверхности из тринадцати значков восемь не дотягивали до
 * порога 3:1 на собственной подложке: бирюзовый 2.04:1, оранжевый 1.94:1,
 * голубой 2.31:1, зелёный 2.45:1 — то есть значок сливался с квадратом, на
 * котором нарисован, и роль «найти пункт взглядом» терялась именно там, где
 * цвет для того и вводился. В тёмной теме то же с фиолетовым (2.57:1).
 *
 * Порядок тот же, что и у вложенного блока (см. `nestedFill`): сначала
 * подложка от поверхности, потом чернила от подложки. Тон сохраняется —
 * поднимается только светлота, поэтому оранжевый остаётся оранжевым.
 */
export function tintedIcon(hue: MenuIconHue, colors: AppColors): TintedIcon {
  const base = hue === 'accent' ? colors.primary : MENU_ICON_HUES[hue];
  // Значок различим по форме — порог графики.
  return tintedPlate(base, colors.surface, 3);
}

/**
 * Подложка тона `base` на поверхности `host` и содержимое на ней.
 *
 * 0x22 — прежняя прозрачность подложек, сохранённая как есть: спор был не о
 * ней, а о том, что цвет содержимого не отсчитывался от результата. Порядок
 * тот же, что и у вложенного блока (см. `nestedFill`): сначала подложка от
 * поверхности, потом чернила от подложки.
 *
 * v4.32.409: сделана открытой. `tintedIcon` берёт тон из декоративного
 * набора, `badgeTint` — из палитры по смыслу; журналу администратора нужен
 * третий набор («создал» — звезда, «переименована» — основной цвет), и он
 * рисовал подложку сам как `цвет + '22'`, то есть без чернил от подложки.
 * Открыть общую реализацию дешевле, чем завести третий список тонов.
 */
export function tintedPlate(base: string, host: string, min = 4.5): TintedIcon {
  const fill = mixHex(base, host, 0x22 / 255);
  return { fill, ink: readableInk(base, fill, min) };
}

/**
 * Приглушённый оттенок цвета на ИЗВЕСТНОЙ подложке — непрозрачный.
 *
 * v4.32.416. Раунды 407–409 убрали склейку `цвет + 'NN'` отовсюду, где она
 * несла смысл, и оставили два места, где приглушение казалось безобидным:
 * рамка полоски состояния (`ink + '55'`) и прошедшие столбики живой
 * осциллограммы (`colors.error + 'aa'`). Обе пережили храповик по случайности
 * формы записи: одна прячет прозрачность в именованную константу, вторая
 * собирает её тернаром, и регулярное выражение не видело ни ту, ни другую.
 *
 * Безобидность тут мнимая ровно в одном: восьмизначный хекс не разбирается
 * `parseHex`, `contrastRatio` отвечает на него 1, и контрастный тест молча
 * проходит мимо. Полоска состояния — пример: её чернила и заливка проверяются
 * с 385-го, а рамка не проверялась НИ РАЗУ, потому что измерить её было нечем.
 *
 * `min` по умолчанию нулевой — и это не лазейка, а утверждение: бывают метки,
 * смысл которых несут соседи (у полоски — значок и текст), и держать их
 * приглушёнными правильно. Разница с прежней записью в том, что теперь такая
 * метка ИЗМЕРИМА: тест может потребовать, чтобы она осталась тихой, а не
 * молча согласиться с любым значением. Где метка смысл несёт — как столбик
 * осциллограммы, единственный признак того, что запись идёт, — там `min`
 * ставят графическим, и приглушение поднимается ровно до порога.
 */
export function fadedOn(base: string, host: string, alpha: number, min = 0): string {
  const steps = 8;
  for (let step = 0; step <= steps; step++) {
    const mixed = mixHex(base, host, alpha + ((1 - alpha) * step) / steps);
    if (contrastRatio(mixed, host) >= min) return mixed;
  }
  return base;
}

/**
 * Слой, скрывающий текст до нажатия, — спойлер.
 *
 * v4.32.417. Был вписан как '#888' в трёх файлах сразу: `RichText`,
 * `SpoilerSpan` и `GrpSpoilerSpan` — одно правило, три копии, ни одна не
 * спрашивает ни тему, ни пузырь. Спойлер лежит НА пузыре, а пузырей четыре
 * (свой и чужой в двух темах), и серединный серый попадает по-разному:
 * на исходящем пузыре светлой темы (#0068D6) '#888' даёт 1.44:1 — плашка
 * почти сливается с пузырём, и то, что текст скрыт, видно плохо.
 *
 * Порог здесь графический: букв на плашке нет (они прозрачны), смысл несёт
 * сам факт «здесь что-то закрыто». Цвет берётся не из палитры, а от пузыря:
 * на тёмном — светлеет, на светлом — темнеет, ровно до порога.
 */
export function spoilerPlate(host: string): string {
  return fadedOn(contrastingInk(host), host, 0.5, 3);
}

/**
 * Подсветка найденного куска ВНУТРИ строки — не строки целиком.
 *
 * v4.32.417. Была вписана парой '#ffe082' и '#000' в двух ветках `RichText`
 * (обычной и запасной, без приведения регистра). Пара сама по себе читается —
 * чёрное по бледно-янтарному, — но она не спрашивает, на чём лежит. А лежит
 * она на пузыре: в светлой теме чужой пузырь белый, и бледный янтарь на нём
 * даёт 1.25:1. Подсветка есть, найденное слово — нет.
 *
 * Отличать здесь надо два разных: плашку от пузыря (порог графический — это
 * метка) и букву от плашки (порог текстовый). Поэтому янтарь палитры
 * подтягивается до 3:1 к пузырю, а чернила считаются уже от полученной
 * плашки — сперва заливка, потом чернила, правило 395-го.
 */
export function searchMark(colors: AppColors, host: string): TintedIcon {
  const fill = readableOn(colors.star, host, 3) ?? colors.star;
  return { fill, ink: contrastingInk(fill) };
}

