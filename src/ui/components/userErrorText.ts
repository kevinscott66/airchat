/**
 * Что именно показать человеку, когда что-то упало (v4.32.428).
 *
 * Измеренный дефект. В `src/ui` 88 мест писали одно и то же руками:
 * `e instanceof Error ? e.message : String(e)`. Из них 54 отдавали результат
 * прямо на экран — `showError(...)`, `Alert.alert(...)`, строка состояния, — а
 * остальные 34 клали в журнал. Одна запись, две совершенно разные задачи.
 *
 * Почему это плохо на экране. Интерфейс приложения русский целиком, а
 * `e.message` — это чаще всего НЕ наш текст. Это `Network request failed` от
 * fetch, это `documentDirectory unavailable` от expo-file-system, это
 * `"point" expected Uint8Array of length 32, got length=10` от noble, и это 47
 * машинных опознавателей, которые мы бросаем сами: `invalid_send_at`,
 * `send_at_out_of_range`, `no_pc`, `feed_storage_profile_unset`,
 * `lan_sender_did_too_long`, `invite_token_bad_random`. Человек, который
 * промахнулся временем отправки, читал `send_at_out_of_range`.
 *
 * Хуже того: семь мест уже написали русский запасной текст — «Ошибка
 * экспорта», «Не удалось переименовать», «Ошибка создания» — но поставили его
 * в ветку `: <текст>`, то есть в ветку «брошено не-Error». Эта ветка почти
 * никогда не срабатывает: бросают у нас всегда Error. Запасной текст был
 * написан, был виден в коде и не показывался никогда — выигрывал английский
 * `e.message`.
 *
 * Правило, по которому здесь различают. У приложения нет второго языка:
 * наши собственные сообщения для человека написаны кириллицей, а сообщения
 * библиотек и наши машинные опознаватели — нет. Значит «есть кириллица» и
 * есть достаточный признак «этот текст писали для чтения человеком». Правило
 * дешёвое и проверяемое, и оно перестанет работать ровно тогда, когда
 * появится английская локализация — к тому моменту различать надо будет по
 * классу ошибки, и менять это придётся в одном месте, здесь.
 *
 * Модуль намеренно без единого импорта: его зовут и экраны, и модальные окна,
 * и он не должен тянуть за собой ни react-native, ни журнал.
 */

/** Кириллица в тексте — признак того, что текст писали для человека. */
const CYRILLIC = /[А-Яа-яЁё]/;

/**
 * Длиннее этого на всплывающую подсказку не поместится, а `ToastAndroid`
 * молча обрежет. Дамп JSON с русским полем внутри — не сообщение об ошибке.
 */
const MAX_USER_TEXT = 160;

/** Журналу нужен весь текст, но не многомегабайтный. */
const MAX_RAW_TEXT = 500;

/**
 * Сырой текст ошибки — для журнала, НЕ для экрана.
 *
 * Ровно то же, что делали 88 мест руками, но одной записью: `String(e)` на
 * не-Error даёт `[object Object]`, зато не теряет сам факт падения.
 */
export function rawErrorText(e: unknown): string {
  const text = e instanceof Error ? e.message : String(e);
  return text.length > MAX_RAW_TEXT ? `${text.slice(0, MAX_RAW_TEXT)}…` : text;
}

/**
 * Наш ли это текст — то есть можно ли его показывать человеку как есть.
 *
 * Пусто, многострочно или слишком длинно — значит это дамп, а не фраза.
 */
export function isUserFacingMessage(text: string): boolean {
  const trimmed = text.trim();
  if (!trimmed || trimmed.length > MAX_USER_TEXT) return false;
  if (trimmed.includes('\n')) return false;
  return CYRILLIC.test(trimmed);
}

/**
 * Текст ошибки для экрана: наш — показываем, чужой — заменяем на `fallback`.
 *
 * `fallback` обязателен и не имеет значения по умолчанию: общего «Ошибка» на
 * все случаи не бывает, человеку нужно знать, ЧТО не получилось. Вызывающий
 * знает это лучше всех — он рядом с местом падения.
 */
export function userErrorText(e: unknown, fallback: string): string {
  const text = e instanceof Error ? e.message : '';
  return isUserFacingMessage(text) ? text.trim() : fallback;
}
