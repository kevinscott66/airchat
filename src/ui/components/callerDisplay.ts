/**
 * Кого показывать на экране входящего звонка, пока замок приложения заперт
 * (v4.32.627).
 *
 * Правило здесь то же, что у баннеров (см. previewAllowed в
 * notifications/pushNotifications): замок ставят от человека, у которого
 * телефон уже в руках. Звонок этот замок обходил целиком — CallOverlay
 * рисуется рядом с экраном пароля, а не внутри разблокированной ветки, и
 * поверх запертого приложения во весь экран выкладывалось сохранённое имя
 * звонящего. Хуже того, имя для этого поднималось из зашифрованной книги
 * контактов: замок не мешал даже читать её.
 *
 * Сам звонок никуда не девается: он звонит, его можно принять и отклонить.
 * Исчезает только личность звонящего — ровно как текст сообщения в баннере.
 *
 * Пустое `avatarName` — не оплошность: nameInitials на пустой строке отдаёт
 * «?», и в кружке оказывается вопрос, а не чьи-то инициалы.
 */
export type CallerDisplay = {
  /** Подпись под аватаром и в шапке видео. */
  name: string;
  /** Имя, из которого берутся инициалы аватара. */
  avatarName: string;
};

/** Подпись вместо имени, пока замок заперт. */
export const HIDDEN_CALLER_NAME = 'Имя скрыто';

export function callerDisplay(locked: boolean, peerName: string): CallerDisplay {
  if (!locked) return { name: peerName, avatarName: peerName };
  return { name: HIDDEN_CALLER_NAME, avatarName: '' };
}
