/**
 * Марка AirChat — знак без слова.
 *
 * v4.32.592. Знак нарисован тем же пером, что и подпись: замкнутый штрих с
 * переменной нажимом толщиной — толстый снизу слева, тонкий сверху справа, —
 * и хвост, уходящий росчерком. Геометрически это овал со смещённой внутрь
 * дыркой: смещение и даёт разнотолщинность, как её даёт наклон пера.
 *
 * Почему не буква. Первая попытка ставила рядом с подписью рисованную «A» —
 * тот же силуэт, что был у прежней марки. Рядом со словом, которое само
 * начинается с росчерковой «A», это читалось как «A AirChat»: две разные «A»
 * подряд выглядят опиской, а не знаком. Реплика не повторяет ни одной буквы
 * и при этом говорит то же, что и название.
 *
 * Контуры, а не `<Image source={require(...)}>`: PNG пришлось бы держать в
 * трёх плотностях, он не следует за темой и за выбранным акцентом, а на
 * пол-точки промахивается по краю. `react-native-svg` уже в зависимостях.
 * Геометрия повторяет `assets/logo/airchat-mark.svg` один в один — это
 * стережёт тест, потому что из того же файла растёт иконка приложения.
 *
 * Рамка обрезана по чернилам: в файле вокруг знака оставлены поля под маску
 * иконки iOS, а в строке рядом с подписью они читались бы отступом непонятно
 * откуда. Заданный `size` — это габарит самого знака.
 *
 * Заливка — из палитры (accent → primary), как у подписи: знак идёт за темой
 * и за акцентом, выбранным в настройках. В файле те же две краски вписаны
 * шестнадцатеричными, потому что растеризатору взять их неоткуда.
 */
import React, { useId } from 'react';
import { StyleSheet } from 'react-native';
import Svg, { Defs, LinearGradient, Path, Stop } from 'react-native-svg';
import type { StyleProp, ViewStyle } from 'react-native';
import { useColors } from '../ThemeContext';

/**
 * Чернильные границы знака в координатах файла: слева хвост, справа и снизу
 * штрих. Ширина меньше высоты — знак не квадратный, и `size` задаёт высоту.
 */
const BOX = { x: 127.4, y: 120, w: 265.5, h: 296 } as const;

/**
 * Штрих реплики: внешний обход по часовой, внутренний против — дырку делает
 * правило nonzero. Разводить их на два `<Path>` нельзя: второй закрасил бы
 * первый, а не вырезал.
 */
const BUBBLE = [
  'M275.2 120Q329.5 120.7 364.2 154Q397.6 188.2 392.2 236Q385.2 283.8 342.8 318',
  'Q299.5 351.3 245.1 352Q190.8 351.3 156.2 318Q122.7 283.8 128.2 236Q135.1 188.2 177.5 154',
  'Q220.8 120.7 275.2 120ZM288.6 140Q249 140.5 217.6 164Q186.9 188.2 182 222',
  'Q178.1 255.8 202.6 280Q227.8 303.5 267.3 304Q306.9 303.5 338.3 280Q369 255.8 374 222',
  'Q377.8 188.2 353.4 164Q328.1 140.5 288.6 140Z',
].join('');

/** Хвост: сходит в остриё, как перо, отрываемое от бумаги. */
const TAIL = 'M174.5 304.4Q198.1 388.9 130.8 416Q214.9 399.5 224 335.6L174.5 304.4Z';

/** Ширина знака относительно высоты — им же и задаётся размер в связке. */
export const MARK_ASPECT = BOX.w / BOX.h;

export type AirChatMarkProps = {
  /** Высота знака в точках. Ширина берётся из пропорции. */
  size?: number;
  /** Начало градиента. По умолчанию — акцент темы. */
  from?: string;
  /** Конец градиента. По умолчанию — основной цвет темы. */
  to?: string;
  style?: StyleProp<ViewStyle>;
};

export function AirChatMark({ size = 28, from, to, style }: AirChatMarkProps): React.ReactElement {
  const colors = useColors();
  // Свой идентификатор градиента на экземпляр: общий отобрал бы заливку у той
  // марки, что нарисована позже (та же причина, что у подписи).
  const gradientId = `airchat-mark-${useId()}`;
  const paint = `url(#${gradientId})`;
  return (
    <Svg
      width={size * MARK_ASPECT}
      height={size}
      viewBox={`${BOX.x} ${BOX.y} ${BOX.w} ${BOX.h}`}
      style={[styles.mark, style]}
    >
      <Defs>
        <LinearGradient id={gradientId} x1="0" y1="0" x2="1" y2="1">
          <Stop offset="0" stopColor={from ?? colors.accent} />
          <Stop offset="1" stopColor={to ?? colors.primary} />
        </LinearGradient>
      </Defs>
      <Path d={BUBBLE} fill={paint} />
      <Path d={TAIL} fill={paint} />
    </Svg>
  );
}

const styles = StyleSheet.create({
  /**
   * `position: relative` — не оформление, а web.
   *
   * `react-native-svg` отдаёт в браузере обычный `<svg>`, и он, в отличие от
   * `View`, остаётся статичным в потоке. Внутри `GlassSurface` слои стекла
   * лежат абсолютом, а по правилам отрисовки CSS позиционированный элемент
   * с z-index 0 красится ПОВЕРХ непозиционированных — то есть `BlurView`
   * забирал статичный `<svg>` себе в подложку и размывал знак. На устройстве
   * этого нет вовсе: там порядок задаётся деревом, а не позиционированием.
   */
  mark: { position: 'relative' },
});
