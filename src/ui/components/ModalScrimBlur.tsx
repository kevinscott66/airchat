/**
 * Размытие под окном поверх экрана (v4.32.604).
 *
 * Подложка диалога до сих пор была плоской плёнкой: приложение под ней читалось
 * буквой в букву и спорило с текстом окна. Плёнку трогать нельзя — её
 * прозрачность подобрана по контрасту листа и фона (см. `scrim` в theme.ts), —
 * а вот детали фона под ней не нужны никому. Размытие их и убирает, оставляя
 * контекст: видно, что под окном экран, но не видно, какой именно.
 *
 * Оттенок здесь всегда тёмный, в отличие от `GlassSurface`, где он идёт от темы.
 * У поверхности задача слиться с окружением, у подложки — обратная: увести фон
 * от листа. Тёмный оттенок делает это в обе стороны — на светлой теме фон
 * уходит от почти белой карточки, на тёмной он уходит в чёрное, тогда как
 * приподнятая поверхность остаётся на месте. Светлый оттенок на светлой теме
 * работал бы против контраста, ради которого плёнка и заведена.
 *
 * Ставится ПЕРВЫМ ребёнком подложки: слой абсолютный и не участвует в раскладке,
 * но всё, что идёт после него, рисуется поверх.
 */
import React from 'react';
import { StyleSheet } from 'react-native';
import { BlurView } from 'expo-blur';
import { useReducedTransparency } from '../motionPrefs';
import { glass } from '../theme';

export function ModalScrimBlur(): React.ReactElement | null {
  // Просили меньше прозрачности — значит и размытия быть не должно: под ним
  // тот же эффект движущегося фона, от которого настройка и защищает.
  const solid = useReducedTransparency();
  if (solid) return null;
  return (
    <BlurView
      pointerEvents="none"
      intensity={glass.intensity.clear}
      tint="dark"
      style={StyleSheet.absoluteFill}
    />
  );
}

export default ModalScrimBlur;
