export type AirChatSignatureProps = {
  /** Высота росчерка в точках. */
  height?: number;
  /** Начало градиента. По умолчанию — акцент темы. */
  from?: string;
  /** Конец градиента. По умолчанию — основной цвет темы. */
  to?: string;
  /**
   * Перелив: три цвета и больше вместо простой пары from → to. Раскладываются
   * по длине ровно, поэтому подпись играет по всей ширине, а не гаснет к концу.
   */
  stops?: readonly string[];
  style?: StyleProp<ViewStyle>;
};

export function AirChatSignature({
  height = 20,
  from,
  to,
  stops,
  style,
}: AirChatSignatureProps): React.ReactElement {
  const colors = useColors();
  // Идентификатор градиента обязан быть свой у каждого экземпляра: две подписи
  // на одном экране с общим id забрали бы заливку у отрисованной позже.
  const gradientId = `airchat-signature-${useId()}`;
  const palette = stops ?? [from ?? colors.accent, to ?? colors.primary];
  return (
    <Svg
      width={height * ASPECT}
      height={height}
      viewBox={`0 0 ${100 * ASPECT} 100`}
      style={[styles.signature, style]}
      accessibilityRole="image"
      accessibilityLabel="AirChat"
    >
      <Defs>
        <LinearGradient id={gradientId} x1="0" y1="0" x2="1" y2="1">
          {palette.map((color, i, all) => (
            <Stop
              key={`${i}-${color}`}
              offset={all.length > 1 ? i / (all.length - 1) : 0}
              stopColor={color}
            />
          ))}
        </LinearGradient>
      </Defs>
      <Path d={SIGNATURE_PATH} fill={`url(#${gradientId})`} />
    </Svg>
  );
}

const styles = StyleSheet.create({
  /**
   * `position: relative` — не оформление, а web.
   *
   * В браузере это обычный `<svg>`, и он, в отличие от `View`, остаётся
   * статичным в потоке. Внутри `GlassSurface` слои стекла лежат абсолютом, а
   * по правилам отрисовки CSS позиционированный элемент с z-index 0 красится
   * ПОВЕРХ непозиционированных, — то есть `BlurView` забирал бы подпись себе
   * в подложку и размывал её. На устройстве порядок задаётся деревом.
   */
  signature: { position: 'relative' },
});
