/**
 * Подписи под пустыми «Стеной», «Историями» и «Архивом» в профиле.
 *
 * v4.32.600. Прежние подписи говорили «видно только те записи, что дошли до
 * ЭТОГО телефона» — так было, пока лента жила одним устройством. Теперь она
 * уезжает в облачную копию аккаунта целиком (`liveAccountSync`, сущности
 * `feed_post` / `feed_comment` / `story_album`), и полученная запись открывается
 * на любом устройстве владельца. Говорить про «этот телефон» стало неправдой, а
 * человеку это и не адрес его вопроса: он смотрит на пустой раздел и хочет
 * знать, чего тут не хватает.
 *
 * Что осталось правдой и потому осталось в тексте:
 *  - чужие записи приходят доставкой, а не выдаются сервером по запросу, —
 *    поэтому пустая чужая стена не значит «он ничего не публиковал»;
 *  - история живёт сутки и раздаётся в момент публикации: пропущенную не
 *    догнать ни с какого устройства.
 *
 * Про облачную копию говорим только когда она включена в конфигурации: с
 * выключенной синхронизацией обещание «на любом вашем устройстве» было бы
 * ровно таким же враньём, каким было «до этого телефона».
 */

import type { ProfilePostsMode } from './profilePostsMode';

export type ProfilePostsEmptyInput = {
  mode: ProfilePostsMode;
  /** Свой ли это профиль. */
  isSelf: boolean;
  /** Включена ли облачная копия аккаунта. */
  accountSync: boolean;
};

export function profilePostsEmptyNote({
  mode,
  isSelf,
  accountSync,
}: ProfilePostsEmptyInput): string {
  if (mode === 'archive') {
    return 'В архиве пусто. Сюда попадают записи, которые вы убрали из своей ленты.';
  }
  if (mode === 'stories') {
    return isSelf
      ? 'Историй нет. История живёт сутки и исчезает сама — опубликуйте новую, когда будет что показать.'
      : 'Историй нет. Они живут сутки и приходят в момент публикации: то, что было раньше, уже не догнать.';
  }
  if (!isSelf) {
    return 'Здесь пусто. Либо автор ничего не публиковал, либо его записи к вам пока не пришли.';
  }
  return accountSync
    ? 'Здесь пусто. Ваши записи хранятся в аккаунте и открываются на любом вашем устройстве — опубликуйте первую.'
    : 'Здесь пусто. Опубликуйте первую запись — она появится тут.';
}
