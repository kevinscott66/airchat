/**
 * ownProfileEditModel — правка своего профиля: пределы полей и слова отказа
 * (v4.32.572).
 *
 * До этой версии своё имя, юзернейм, местоимения, «О себе», статус и ссылки
 * правились прямо в карточке профиля: возле каждой строки карандаш, у каждого
 * карандаша своё состояние «сейчас редактируется», у каждого — своя пара
 * кнопок «Отмена/Сохранить». Шесть маленьких редакторов на одном экране, и
 * человек, менявший имя, не догадывался, что «О себе» правится точно так же,
 * пока не наводил на него палец.
 *
 * Теперь редактор один и отдельный. Здесь — то, что в нём не про разметку:
 * сколько символов принимает каждое поле и какими словами объясняется отказ.
 * Отказ по юзернейму приходит кодом (`UsernameRejection`), и превратить код в
 * человеческую фразу — решение, а не оформление: «Юзернейм не может состоять
 * из одних цифр» и «Юзернейм короче пяти символов» отправляют человека в
 * разные стороны, и перепутать их нельзя молча.
 *
 * У одной группы отказов решение обратное (v4.32.594). Почему имя НЕДОСТУПНО —
 * не дело того, кто его набрал. Занято живым человеком, оставлено приложению,
 * отклонено реестром — со стороны это одно и то же событие: имя не ваше,
 * наберите другое. Разные фразы здесь ничего не подсказывают, зато отвечают
 * постороннему на вопрос, который он не должен задавать: перебирая имена, по
 * тексту отказа можно было читать список оставленных приложению и отличать
 * «занято кем-то» от «свободно, но запрещено». Поэтому все три отказа говорят
 * одной строкой — `USERNAME_TAKEN`.
 */
import type { UsernameRejection } from '../../../../core/identity/reservedUsernames';
import { USERNAME_MIN_SELF_SERVICE } from '../../../../core/identity/reservedUsernames';

/** Местоимения: короткая строка, а не второе «О себе». */
export const PRONOUNS_MAX = 30;
/** Ссылка профиля. Столько же принимает и чистка на записи. */
export const PROFILE_LINK_MAX = 256;

/**
 * Единственная фраза на все случаи «имя не ваше». Одна строка, а не три
 * похожих: причина недоступности — не сведения для того, кто перебирает имена.
 */
export const USERNAME_TAKEN = 'Этот юзернейм занят — выберите другой';

/** Почему юзернейм не приняли — словами, которые человеку что-то говорят. */
export function usernameClaimErrorText(reason: UsernameRejection): string {
  switch (reason) {
    case 'empty': return 'Введите юзернейм';
    case 'charset': return 'Только латиница, цифры и «_» — без пробелов и знаков';
    case 'digits_only': return 'Юзернейм не может состоять из одних цифр';
    case 'too_long': return 'Юзернейм длиннее 32 символов';
    case 'too_short': return `Юзернейм короче ${USERNAME_MIN_SELF_SERVICE} символов`;
    // Оставленное приложению имя — это тоже занятое имя, и различать их вслух
    // незачем: см. заголовок файла.
    case 'reserved': return USERNAME_TAKEN;
  }
}

/** Почему реестр не записал юзернейм за этим аккаунтом. */
export function usernameSaveErrorText(reason: 'taken' | 'rejected' | 'local'): string {
  switch (reason) {
    case 'taken': return USERNAME_TAKEN;
    case 'rejected': return USERNAME_TAKEN;
    // Свой же второй аккаунт на этом телефоне — не чужая тайна, а причина,
    // которую человек может устранить сам, и она остаётся названной.
    case 'local': return 'Юзернейм уже используется другим аккаунтом на этом устройстве';
  }
}

/**
 * Что сказать после удачной записи.
 *
 * Разница не косметическая: `local` означает, что имя закреплено только на
 * этом телефоне и его в эту же минуту может занять кто-то ещё. Обещать
 * «закреплён за вами» в этом случае — обещать то, чего пока нет.
 */
export function usernameSavedText(scope: 'global' | 'local'): string {
  return scope === 'global'
    ? 'Юзернейм закреплён за вами'
    : 'Юзернейм сохранён, но реестр недоступен — закрепим при следующем выходе в сеть';
}

export type ProfileFilled = {
  name: string;
  bio: string;
  avatar: boolean;
  handle: string;
  status: string;
  pronouns: string;
  links: string;
};

/**
 * Насколько профиль заполнен, 0–100.
 *
 * Считается здесь, а не на экране: это единственное место, где записано, что
 * вообще считается «профилем» — и полосу заполненности, и состав редактора
 * надо менять вместе, иначе редактор предложит поле, которого счётчик не
 * знает, и до ста процентов человек не дойдёт никогда.
 */
export function profileCompletionPct(v: ProfileFilled): number {
  const fields = [
    !!v.name.trim(),
    !!v.bio.trim(),
    v.avatar,
    !!v.handle.trim(),
    !!v.status.trim(),
    !!v.pronouns.trim(),
    !!v.links.trim(),
  ];
  return Math.round((fields.filter(Boolean).length / fields.length) * 100);
}
