/**
 * Сколько может длиться голосовое — и что сказать, если оно всё равно велико
 * (v4.32.562).
 *
 * Дефект. У записи не было верхней границы вообще: кнопка микрофона писала
 * ровно столько, сколько человек держал палец. Вложение при этом обрезано
 * жёстко — uploadEncryptedBlob отказывается от файла больше MAX_BLOB_BYTES
 * (8 000 000 байт). Пресет записи — 128 кбит/с, то есть 16 000 байт в секунду,
 * и порог приходится примерно на 8 минут 20 секунд. Дальше происходило вот
 * что: человек отпускал кнопку, приложение читало многомегабайтный файл в
 * память, шифровало его, получало от загрузки null — и показывало
 * «Голосовое не загрузилось. Проверьте соединение и повторите.» Соединение
 * было ни при чём: сообщение просто нельзя было отправить никогда, но текст
 * звал повторить. Сама запись при этом стиралась, то есть девять минут речи
 * пропадали вместе с ложным объяснением.
 *
 * Граница здесь — пять минут, а не восемь с третью: битрейт пресета это цель
 * кодека, а не гарантия, контейнер добавляет своё, и упереться в предел на
 * последней секунде значит потерять всю запись. Пять минут — это 4 800 000
 * байт при заявленном битрейте, то есть 40% запаса.
 *
 * Достигнув границы, запись не выбрасывается: она заканчивается сама и
 * уходит как сообщение. Выбросить записанное — то же самое, чем этот дефект и
 * был плох. За полминуты до конца появляется обратный отсчёт: человек должен
 * узнать о границе до того, как в неё упрётся, а не после.
 *
 * Модуль намеренно без импортов: решение о границе проверяется без микрофона,
 * без файловой системы и без отрисовки — как и соседний recorderGate.
 */

/** Предел длительности записи. */
export const VOICE_MAX_MS = 5 * 60_000;

/** За сколько до предела показывать обратный отсчёт. */
export const VOICE_COUNTDOWN_MS = 30_000;

/** Минимальная длительность: нажатие короче — это не сообщение, а промах. */
export const VOICE_MIN_MS = 500;

/** Сколько времени осталось; никогда не отрицательное. */
export function voiceRemainingMs(elapsedMs: number): number {
  if (typeof elapsedMs !== 'number' || !Number.isFinite(elapsedMs) || elapsedMs <= 0) {
    return VOICE_MAX_MS;
  }
  return Math.max(0, VOICE_MAX_MS - elapsedMs);
}

/**
 * Пора ли заканчивать запись саму, не дожидаясь пальца.
 *
 * Нечисло и отрицательное здесь означают «нет»: таймер, сломавшийся в другую
 * сторону, не должен обрывать запись на первой же секунде.
 */
export function shouldAutoStopVoice(elapsedMs: number): boolean {
  if (typeof elapsedMs !== 'number' || !Number.isFinite(elapsedMs)) return false;
  return elapsedMs >= VOICE_MAX_MS;
}

/**
 * Секунды обратного отсчёта — или null, пока до предела далеко.
 *
 * Округление вверх: показать «1», когда осталось 200 мс, честнее, чем показать
 * «0» у ещё идущей записи.
 */
export function voiceCountdownSeconds(elapsedMs: number): number | null {
  const left = voiceRemainingMs(elapsedMs);
  if (left > VOICE_COUNTDOWN_MS) return null;
  return Math.ceil(left / 1000);
}

/**
 * Что не так с готовым файлом — или null, если с ним всё в порядке.
 *
 * `bytes === null` означает, что файловая система размера не назвала; это не
 * повод отказывать — пусть решает сама загрузка, у неё есть своя проверка.
 * Отдельный текст на «слишком велико» нужен затем, что старый общий текст звал
 * повторить попытку, которая не могла удаться ни разу.
 */
export function voiceUploadRefusal(bytes: number | null, maxBytes: number): string | null {
  if (bytes === null || !Number.isFinite(bytes)) return null;
  if (bytes <= 0) return 'Запись не получилась. Попробуйте ещё раз.';
  if (bytes > maxBytes) return 'Голосовое слишком длинное — оно не поместится во вложение. Запишите короче.';
  return null;
}
