/**
 * Что сказать человеку, когда звонок не начался (v4.32.747).
 *
 * Дефект был не в звонках, а в надписи. `initiateCall` отвечал `boolean`, и
 * все пять мест, откуда звонят, — заголовок переписки (два), меню списка
 * бесед (два) и карточка профиля — писали на отказ одну и ту же фразу: «Не
 * удалось начать звонок». Отказов же девять, и человеку они велят разное:
 * сходить в настройки телефона за микрофоном, снять блокировку, проверить
 * интернет, закончить текущий звонок, подождать секунду после запуска.
 * «Не удалось» не подсказывало ни одного из этих действий, а половину из них
 * подсказать больше некому: экрана, где видно, что микрофону отказано, в
 * приложении нет.
 *
 * Разбор союза здесь полный и без `default`: новый исход в `CallStartResult`
 * не соберётся, пока его не назовут словами.
 *
 * Модуль без импортов, кроме типа (он стирается при сборке): его зовут из
 * экранов, и тянуть за собой службу звонков с WebRTC он не должен.
 */
import type { CallStartResult } from '../core/social/callService';
import { NOT_READY_TEXT } from './commonText';

/**
 * Фраза для человека или `null`, если показывать нечего.
 *
 * `null` — это два случая. Звонок пошёл, и говорить не о чем. Либо человек сам
 * нажал отбой, пока прогревался микрофон: ошибка на собственное действие
 * выглядит поломкой там, где всё сработало.
 *
 * `isVideo` меняет и существительное («звонок» / «видеозвонок»), и список
 * запрошенного: у видеозвонка спрашивают ещё и камеру, и человеку важно
 * знать, чего именно не хватает.
 */
export function callStartText(result: CallStartResult, isVideo: boolean): string | null {
  const what = isVideo ? 'видеозвонок' : 'звонок';
  switch (result) {
    case 'started':
    case 'cancelled':
      return null;
    case 'busy':
      return 'Сначала завершите текущий звонок';
    case 'blocked':
      return 'Вы заблокировали этого человека — сначала снимите блокировку';
    case 'no-identity':
      return NOT_READY_TEXT;
    case 'no-webrtc':
      return 'Звонки в этой сборке приложения не работают';
    case 'no-signaling':
      return 'Нет связи с сервером звонков — проверьте интернет и повторите';
    case 'no-permission':
      return isVideo
        ? 'Нет доступа к микрофону или камере — разрешите их в настройках телефона'
        : 'Нет доступа к микрофону — разрешите его в настройках телефона';
    case 'failed':
      return `Не удалось начать ${what}`;
  }
}
