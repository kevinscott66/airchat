/**
 * Что платформа физически умеет — для решений интерфейса.
 *
 * Появилось вместе с веб-сборкой. Разница между «выключено», «ничего не
 * нашлось» и «здесь такого не бывает» для пользователя огромная, а в коде она
 * легко теряется: строка «Wi-Fi LAN — нет устройств рядом» в браузере читается
 * как «поискали и не нашли», хотя браузер не искал и искать не может — ему
 * запрещено и слушать сокет, и рассылать mDNS. Показывать нулевой счётчик там,
 * где счёта не было, — это врать нулём.
 *
 * Поэтому правило: возможности, которых на платформе нет, из интерфейса
 * убираются целиком, а не показываются пустыми. Соответствующие транспорты уже
 * так и устроены изнутри (`lanTransport` выходит по `Platform.OS === 'web'`,
 * `wifiMesh` — по `Platform.OS !== 'android'`); здесь та же граница, но для UI,
 * и записана она один раз, а не при каждом использовании.
 */
import { Platform } from 'react-native';

/**
 * Транспорты поверх локального радио: Wi-Fi LAN (TCP-сокеты + mDNS-обзор) и
 * Wi-Fi Direct. Требуют слушающего сокета и multicast — страница не получает ни
 * того, ни другого ни при каких разрешениях.
 */
export const LOCAL_RADIO_TRANSPORTS_AVAILABLE = Platform.OS !== 'web';

/**
 * Встроенный защищённый канал: Xray в нативном процессе и локальный SOCKS.
 *
 * Реализация есть только на Android. На iOS и web не показываем настройку,
 * которая всё равно не сможет создать канал; на web модуль дополнительно
 * подменён на `null` (см. web/shims/airchat-vpn.ts).
 */
export const EMBEDDED_VPN_AVAILABLE = Platform.OS === 'android';
