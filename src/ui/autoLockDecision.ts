/**
 * Запирать ли приложение при возврате из фона (v4.32.724).
 *
 * Решение вынесено из App.tsx отдельно ровно затем, чтобы его можно было
 * проверить фактом, а не чтением исходника: сама ветка живёт внутри обработчика
 * AppState на две с половиной тысячи строк ниже начала файла.
 *
 * Дефект, ради которого модуль заведён. Настройка читалась через `kvGet`, а он
 * отвечает одинаковым `null` и на «человек выключил замок», и на «прочитать не
 * удалось». Отказ базы — заблокированная SQLite или подъём приложения до первой
 * разблокировки устройства — превращался в «замок выключен», и телефон
 * открывался прямо в переписку. Ни строки в журнале на месте решения, ни следа
 * на экране; в настройках переключатель при этом обещал обратное.
 *
 * Правило здесь то же, что уже записано рядом для пароля: непрочитанное
 * состояние решается в пользу замка. Цена ошибки несимметрична — лишний ввод
 * пароля против открытой переписки в чужих руках.
 */

/** Ответ хранилища: `{ value }` — прочитали, `null` — не смогли. */
export type KvRead = { value: string | null } | null;

/**
 * Включён ли замок. Непрочитанная настройка считается включённой.
 *
 * Запирание без пароля этим решением не грозит: вызывающий отдельно проверяет,
 * что пароль хоть раз был виден, — иначе человека без пароля заперло бы на
 * экране, от которого у него нет ключа.
 */
export function autoLockEnabled(read: KvRead): boolean {
  if (read === null) return true;
  return read.value === 'true';
}
