/**
 * Надписи, которые встречаются больше чем на одном экране.
 *
 * Зачем отдельный файл. Одно и то же состояние приложение называло по-разному
 * в девяти местах: «Пара ключей не готова», «Пара ключей ещё не готова —
 * попробуйте позже», «Ваш ID ещё не готов», «Сервис не готов.», «Сервис не
 * готов», «Сервис не готов. Подождите.», «Сервис не готов. Подождите и
 * повторите.». Человек, наткнувшийся на две из них подряд, решает, что у него
 * две разные поломки, — а поломки нет вообще ни одной: приложение ещё
 * запускается.
 *
 * Слова «пара ключей» и «сервис» сюда попали из кода. Для того, кто открыл
 * мессенджер, ни то ни другое ничего не значит; ему нужно знать ровно одно —
 * подождать секунду и повторить.
 *
 * Класть сюда надпись стоит тогда, когда её видят на разных экранах и
 * расхождение между ними сбивает с толку. Надпись, живущая в одном месте,
 * пусть остаётся в этом месте: файл общих строк, куда сносят всё подряд,
 * быстро перестаёт читаться.
 */

