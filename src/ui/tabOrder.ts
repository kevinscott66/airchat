/**
 * Порядок вкладок нижней панели (v4.32.575).
 *
 * Список ведёт ровно одну вещь — соседство: по нему ходит свайп влево-вправо.
 * Сами кнопки собраны в `App.tsx` вручную: у каждой свой значок, счётчик
 * непрочитанного и поведение повторного тапа, — разворачивать панель из этого
 * массива нечего, и он намеренно не пытается быть её описанием.
 */
import type { TabName } from './TabRefContext';

/** Слева направо, как они и стоят в панели. */
export const TAB_ORDER: readonly TabName[] = ['feed', 'chat', 'groups', 'profile', 'settings'];

/** Шаг по панели: −1 — предыдущая вкладка, +1 — следующая. */
export type TabStep = -1 | 1;

/**
 * Соседняя вкладка или `null`, если её нет.
 *
 * Края не заворачиваются: за «Ещё» и перед «Новостями» вкладок нет, а прыжок
 * через всю панель на противоположный край читался бы как сбой, а не как шаг.
 */
export function stepTab(from: TabName, step: TabStep): TabName | null {
  const at = TAB_ORDER.indexOf(from);
  if (at < 0) return null;
  return TAB_ORDER[at + step] ?? null;
}
