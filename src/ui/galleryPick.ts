/**
 * Вход в галерею — одно место для отказа (v4.32.884).
 *
 * Обработчики выбора в галерее — асинхронные: они спрашивают разрешение,
 * открывают системный выбор и разбирают выбранное. Звали их отовсюду одинаково
 * — `void pickImage()`, — то есть обещание отпускали без ловца. Любой отказ по
 * дороге (модуль выбора не отозвался, разрешение спросить не удалось, галерея
 * упала на возврате) улетал в необработанное отклонение: окно не открывалось,
 * и человек оставался перед экраном, где нажатие просто ничего не делает.
 *
 * Цена одинакова во всех трёх местах: жать будут ещё раз, потом ещё, потом
 * решат, что сломано приложение целиком. Причина при этом не попадала даже в
 * журнал — разбирать потом было не по чему.
 *
 * Обёртка та же по смыслу, что и у фона чата (v4.32.717): ждёт обещание,
 * называет отказ по-русски и пишет причину в журнал. Ставится она на вызове, а
 * не внутри обработчика, — тела `pickImage`/`pickGroupImage` закреплены
 * проверкой v4.32.871 вплоть до отступов.
 */
import { log } from '../core/logger';
import { rawErrorText, userErrorText } from './components/userErrorText';
import { showError } from './components/userFeedback';

/** Своего текста у отказа галереи обычно нет — этот подставляется вместо него. */
export const GALLERY_PICK_FAILED = 'Не удалось выбрать файл из галереи.';

/**
 * Открыть галерею и не потерять отказ.
 *
 * @param open сам обработчик выбора — вызывается здесь же
 * @param fallback запасной текст, если исключение своего не принесло
 */
export function runGalleryPick(open: () => Promise<void>, fallback: string = GALLERY_PICK_FAILED): void {
  const failed = (e: unknown): void => {
    log.warn('gallery_pick_failed', { err: rawErrorText(e) });
    showError(userErrorText(e, fallback));
  };
  try {
    void open().catch(failed);
  } catch (e) {
    // Обработчик может отказать и до первого `await` — такое исключение
    // приходит броском, а не отклонением обещания.
    failed(e);
  }
}
