/**
 * Высота плавающего таббара — для содержимого экранов (v4.32.543).
 *
 * Пункт 4 разбора звучал как «фон должен проходить и под плашками (на весь
 * экран)». Сверху это было сделано в 540-й: отступ под часы и «остров» сняли с
 * оболочки и роздали экранам. Снизу оставалась половина, о которой в App.tsx
 * честно висела оговорка: таббар стоял в потоке, содержимое под него не
 * уезжало, и стекло размывало не ленту, а пустую заливку под ней — то есть
 * выглядело как матовая полоса, а не как стекло.
 *
 * Оверлей эту половину закрывает, но в одиночку он обрезает последнюю карточку
 * списка и прячет композер переписки под капсулой. Поэтому высота капсулы
 * раздаётся экранам тем же способом, что и верхний отступ: список добавляет её
 * в `contentContainerStyle`, композер — в `marginBottom`. Значение приходит из
 * `onLayout` самой капсулы, а не из константы: в неё входит `insets.bottom`,
 * который на каждом аппарате свой.
 *
 * При открытой клавиатуре таббар прячется, и здесь становится 0 — в этот
 * момент внизу стоит spacer в потоке, и второй отступ был бы двойным.
 */
import { createContext, useContext } from 'react';

const TabBarInsetContext = createContext(0);

export const TabBarInsetProvider = TabBarInsetContext.Provider;

/** Сколько пикселей внизу экрана занимает плавающий таббар. 0 — если он скрыт. */
export function useTabBarInset(): number {
  return useContext(TabBarInsetContext);
}

export default TabBarInsetContext;
