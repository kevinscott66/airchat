/**
 * Строка, которую нельзя ни выгрузить, ни забыть (v4.32.588).
 *
 * Синхронизация выгружает ленту расшифрованной: слой синхронизации шифрует
 * каждую строку заново — своим ключом, из мнемоники аккаунта. Столбец,
 * который ключ этого устройства не открывает, приходил к выгрузке пустой
 * строкой, и наверх уезжала пустота с новым номером ревизии. Другое
 * устройство, у которого ключ в порядке, принимало эту ревизию как более
 * свежую и затирало ею свою читаемую запись. Одно расхождение ключей на
 * одном устройстве — и текст записи пропадал на всех.
 *
 * Просто выбросить такую строку из выгрузки нельзя, и это главное, ради чего
 * написан этот модуль. Строки, которых в выгрузке нет, а в списке голов есть,
 * считаются удалёнными: на них выписывается надгробие, и оно разъезжается по
 * всем устройствам. Пропуск лечил бы порчу текста уничтожением всей строки.
 *
 * Отсюда третье состояние выгрузки — «придержана»: ключ строки остаётся на
 * месте (надгробие не выписывается), а изменение не отправляется. Устройство
 * с исправным ключом синхронизирует ту же строку само.
 *
 * Модуль намеренно чистый: ни сети, ни SQLite, ни ключей.
 */

/** Ровно то, что нужно решению: признак «придержана». */
export interface HoldableEntity {
  hold?: boolean;
}

/** Строки, которые действительно отправляются наверх. */
export function pushableEntities<T extends HoldableEntity>(entities: readonly T[]): T[] {
  return entities.filter((e) => e.hold !== true);
}

/** Сколько строк придержано — это число стоит записать в журнал. */
export function heldEntityCount(entities: readonly HoldableEntity[]): number {
  let n = 0;
  for (const e of entities) if (e.hold === true) n++;
  return n;
}

/**
 * Ключи всех строк, включая придержанные.
 *
 * Именно здесь и живёт защита от надгробия: придержанная строка обязана
 * попасть в этот набор, иначе следующий проход объявит её удалённой.
 */
export function presentEntityKeys<T extends HoldableEntity>(
  entities: readonly T[],
  keyOf: (entity: T) => string
): Set<string> {
  const keys = new Set<string>();
  for (const e of entities) keys.add(keyOf(e));
  return keys;
}
