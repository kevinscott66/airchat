/**
 * Что сказать, когда часть данных не уезжает в облачную копию (v4.32.845).
 *
 * Дефект. У синхронизации аккаунта четыре места, где запись выбывает насовсем,
 * и все четыре молчали — писали строку в журнал и шли дальше:
 *
 *   1. `encryptEntity` отдавал `null`, если шифротекст перевалил предел на одну
 *      сущность. Голова при этом не сохранялась, значит запись собиралась
 *      заново каждым проходом — и каждым проходом выбрасывалась. Вечно.
 *   2. Придержанная строка (`hold`): её нечем показать на другом устройстве,
 *      и она нарочно не уезжает. Счёт был, но только в `log.warn`.
 *   3. Сервер отвергал один и тот же набор, и проход, распознав, что топчется
 *      на месте, переставал повторять — правильно, но тоже молча.
 *   4. Входящая строка, которая здесь не проецируется, после трёх попыток
 *      признавалась испорченной, курсор уходил за неё, и она не возвращалась.
 *
 * Цена. Экран настроек в это самое время писал под заголовком
 * «Синхронизация»: «Переписка и настройки открываются на других ваших
 * устройствах» — и зелёный значок «Вкл». Обещание неверное ровно для тех
 * записей, о которых человеку важнее всего знать: он видит их на этом телефоне
 * и уверен, что они есть и на втором. Узнать правду было неоткуда — журнал
 * читает разработчик, а не владелец телефона.
 *
 * Здесь только счёт и слова: ни сети, ни базы, ни шифрования.
 */

import { ruPlural } from '../text/ruPlural';

export type SyncStuck = {
  /** Своё: зашифрованная запись больше предела — сервер её не примет. */
  oversize: number;
  /** Своё: строка не читается на этом устройстве, отправлять нечего. */
  held: number;
  /** Своё: сервер отверг один и тот же набор, и проход перестал повторять. */
  rejected: number;
  /** Чужое: приехавшая строка здесь не разбирается и пропущена насовсем. */
  poisoned: number;
};

export const NO_SYNC_STUCK: SyncStuck = { oversize: 0, held: 0, rejected: 0, poisoned: 0 };

export function syncStuckCount(s: SyncStuck): number {
  return s.oversize + s.held + s.rejected + s.poisoned;
}

/** Своё, что не уехало наверх, — против чужого, что не приехало вниз. */
function mineCount(s: SyncStuck): number {
  return s.oversize + s.held + s.rejected;
}

function records(n: number): string {
  return `${n} ${ruPlural(n, ['запись', 'записи', 'записей'])}`;
}

/** Сказуемое к числу: «1 запись не уезжает», но «2 записи не уезжают». */
function verb(n: number, one: string, many: string): string {
  return ruPlural(n, [one, many, many]);
}

/**
 * Одна фраза под строкой «Синхронизация с сервером». `null` — всё уехало.
 *
 * Причины не перечисляются поимённо: «слишком велика», «не читается здесь» и
 * «сервер не принял» человек не различает и ничего с ними по отдельности не
 * сделает. Различать важно другое — своё против чужого: в первом случае на
 * втором устройстве записи нет, во втором она есть, но не здесь, и это разные
 * беды с разными последствиями.
 */
export function syncStuckText(s: SyncStuck): string | null {
  if (syncStuckCount(s) === 0) return null;
  const said: string[] = [];
  const mine = mineCount(s);
  if (mine > 0) {
    said.push(
      `${records(mine)} не ${verb(mine, 'уезжает', 'уезжают')} в облачную копию — на других устройствах ${mine === 1 ? 'её' : 'их'} не будет`,
    );
  }
  if (s.poisoned > 0) {
    const n = s.poisoned;
    said.push(
      `${records(n)} с другого устройства не ${verb(n, 'открылась', 'открылись')} здесь — там ${n === 1 ? 'она осталась' : 'они остались'}`,
    );
  }
  return `${said.join('. ')}.`;
}

/** Короткая подпись на значок состояния. */
export function syncStuckBadge(s: SyncStuck): string | null {
  return syncStuckCount(s) === 0 ? null : 'Не всё';
}
