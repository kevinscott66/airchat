/**
 * Где стоять проверке сети — перед локальной записью или перед рассылкой.
 *
 * Измеренный дефект (v4.32.553). В ленте четыре действия построены одинаково:
 * сначала запись в свою базу, потом рассылка конверта контактам, а если
 * доставка неполная — очередь на повтор. Очередь у комментариев существует с
 * v4.32.164 ровно ради случая «сети сейчас нет». И перед всеми четырьмя
 * первой строкой стоял `requireOnlineWrite()`:
 *
 *   • реакция на пост (addAndBroadcastReaction),
 *   • комментарий (addAndBroadcastComment),
 *   • удаление комментария (deleteFeedComment),
 *   • реакция на комментарий (toggleCommentReaction).
 *
 * То есть проверка отменяла и локальную запись, и постановку в ту самую
 * очередь, которую завели для этого случая. Особенно заметно на удалении:
 * оно документировано как «локальное удаление комментария» — и всё равно
 * ждало сети, чтобы стереть строку в своей же базе.
 *
 * Разница, которой не хватало, — между двумя формами записи:
 *
 *   network-only  смысл действия в том, что оно ушло по сети. Нет сети —
 *                 отказ, и это честно (см. writePathDecision, v4.32.550).
 *   local-first   действие уже имеет смысл на устройстве. Отсутствие сети
 *                 меняет не право писать, а только судьбу рассылки: есть
 *                 очередь — в очередь, нет очереди — рассылку пропускаем.
 *
 * Модуль без единого импорта: решение здесь про две формы и наличие очереди,
 * и проверяется оно без сети, без базы и без транспорта.
 */

/** Две формы записи. */
export type WriteShape = 'network-only' | 'local-first';

/** Что делать, когда сети точно нет. */
export type OfflineAction = 'reject' | 'write-and-queue' | 'write-only';

/**
 * Решение по форме записи и наличию очереди повторов.
 *
 * `hasOutbox` — не украшение: у реакции на пост очереди нет, и обещать
 * человеку отложенную доставку там было бы неправдой.
 */
export function offlineAction(shape: WriteShape, hasOutbox: boolean): OfflineAction {
  if (shape === 'network-only') return 'reject';
  return hasOutbox ? 'write-and-queue' : 'write-only';
}

/** Запрещает ли решение саму локальную запись. */
export function blocksLocalWrite(action: OfflineAction): boolean {
  return action === 'reject';
}

/** Ляжет ли рассылка в очередь повторов. */
export function queuesForLater(action: OfflineAction): boolean {
  return action === 'write-and-queue';
}

/**
 * Стоит ли вообще пытаться разослать конверт прямо сейчас.
 *
 * Оффлайн-попытка не бесплатна: она уходит в таймауты транспорта и лишь потом
 * возвращает «не доставлено» — тот же ответ, что известен заранее.
 */
export function shouldAttemptBroadcast(online: boolean): boolean {
  return online;
}
