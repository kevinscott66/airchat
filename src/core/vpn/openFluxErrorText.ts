/**
 * Текст ошибки ядра OpenFlux — без ссылки на документ (v4.32.723).
 *
 * Ссылка на документ и есть право писать в него: обе нативные части
 * (`AirChatOpenFluxModule.swift`, `AirChatOpenFluxModule.kt`) специально не
 * пишут её в журнал и объясняют почему — «logcat читается с устройства кем
 * угодно». Но ровно этот текст они отдают наверх исключением, а JS его
 * записывал целиком: защита, поставленная в двух местах, снималась в третьем.
 * Тот же текст показывается человеку в кнопке «Повторить», а такой экран
 * фотографируют и присылают в поддержку.
 *
 * Самого ядра в репозитории нет, поэтому доказать, что оно кладёт адрес в
 * текст ошибки, нельзя. Весь слой ниже написан исходя из того, что кладёт, —
 * и цена ошибки несимметрична: лишняя замена стоит одного неразборчивого
 * слова в журнале, пропущенная — чужого доступа к транзиту.
 *
 * Поэтому убирается не конкретная ссылка, а любой адрес: ядро может напечатать
 * не ту строку, что мы ему дали, а её переписанный вид — конечную точку API,
 * адрес с добавленным параметром, адрес после перенаправления. Сравнение с
 * известной ссылкой такой случай пропустило бы.
 */

/**
 * Адрес в тексте: от схемы до первого пробела или кавычки.
 *
 * Скобки и запятые не отсекаем — они встречаются внутри адресов, а лишний
 * прихваченный символ никому не мешает: строка всё равно уходит целиком.
 */
const URL_LIKE = /\b[a-z][a-z0-9+.-]*:\/\/[^\s"'<>]+/gi;

/** Что остаётся на месте адреса. Не пусто — иначе текст теряет смысл. */
const URL_MARK = '<адрес скрыт>';

/** Длиннее этого текст ошибки ядра не бывает; остальное — дамп. */
const MAX_LEN = 300;

/**
 * Привести текст ошибки ядра к виду, пригодному для журнала и экрана.
 *
 * Отдаёт непустую строку всегда: отсутствие текста — это тоже сведение
 * («ядро упало молча»), и подменять его пустотой значит терять его.
 */
export function openFluxErrorText(e: unknown): string {
  const raw = e instanceof Error ? e.message : String(e);
  const text = raw.replace(URL_LIKE, URL_MARK).trim();
  if (text === '') return 'ядро не назвало причину';
  return text.length > MAX_LEN ? `${text.slice(0, MAX_LEN)}…` : text;
}
