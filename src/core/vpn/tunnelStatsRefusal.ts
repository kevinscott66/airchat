/**
 * Почему счётчик соединений не показался (v4.32.1081).
 *
 * ДЕФЕКТ. `enableOpenFluxTunnelStats()` отвечал одним `false` на три разных
 * случая: платформа без ядра, ядро без метода `enableTunnelStats`, и ядро,
 * которое на этот метод отказалось (исключение). Кнопка в инженерном разделе
 * говорила на все три «В этой версии приложения счётчик недоступен».
 *
 * ЦЕНА. Счётчик — единственный способ узнать, что перехват HTTP не встал и
 * запросы тихо идут мимо туннеля (см. noteHttpLayer). Человек, который до
 * него добрался, получал утверждение о своей сборке: счётчика тут нет,
 * искать нечего. На деле счётчик в сборке есть, отказало ядро сию минуту, и
 * второе нажатие чаще всего срабатывает. Тот же файл в своём заголовке
 * объясняет, почему состояний туннеля намеренно шесть, а не четыре, — здесь
 * ровно та же ошибка, только в отладочном углу.
 *
 * ПРАВКА. Ядро отвечает разрядом, а не «да/нет». Разрядов три, и к ним
 * добавлен четвёртый, который виден только экрану: включили, а первый отсчёт
 * ядро не отдало — тогда строка статистики просто не появлялась, и нажатие
 * выглядело как пустое.
 *
 * ГРАНИЦЫ. Ничего не чинится автоматически и ничего не повторяется само:
 * включение счётчика печатает в журнал адрес каждого соединения, и делать
 * это за спиной пользователя нельзя — потому кнопка и отдельная. Меняется
 * только то, что́ ему сказано.
 */

/** Разряд отказа. Ровно один из них — про сборку. */
export type TunnelStatsRefusal =
  /** Ядра или метода нет: в этой сборке считать нечем. */
  | 'unsupported'
  /** Ядро есть, но на просьбу ответило отказом — повтор имеет смысл. */
  | 'refused'
  /** Счётчик включён, а первого отсчёта ядро не отдало. */
  | 'silent';

const TEXT: Record<TunnelStatsRefusal, string> = {
  unsupported: 'В этой сборке счётчика соединений нет',
  refused: 'Ядро отказалось включить счётчик. Нажмите ещё раз — обычно помогает',
  silent: 'Счётчик включён, но ядро не отдало ни одного отсчёта. Нажмите ещё раз через несколько секунд',
};

/** Что сказать человеку. Один разряд — одна подпись. */
export function tunnelStatsRefusalText(why: TunnelStatsRefusal): string {
  return TEXT[why];
}
