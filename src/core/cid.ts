/**
 * cid — форма настоящего IPFS-CID. Один дом.
 *
 * v4.32.432. Одна и та же литеральная форма была выписана от руки в девяти
 * файлах: карточка профиля, очередь исходящих, лента, разбор конверта,
 * payload повторной отправки, обход истории, контакты и сборка адреса шлюза.
 * Девять копий одного правила — девять мест, где оно может разойтись, и они
 * уже разошлись: рядом жила вторая, более слабая проверка «не начинается с
 * lan:/fallback:», которая пропускала и пустую строку, и любой другой
 * плейсхолдер, а в повторной отправке из очереди проверки не было вовсе.
 *
 * Форма намеренно широкая: CIDv0 — 46 символов, CIDv1 base32 — 59, свои CID
 * мы сужаем при загрузке (transport/ipfs/node), а входящие приходят с чужих
 * шлюзов. Здесь проверяется главное: что это вообще CID, а не плейсхолдер
 * (`lan:`, `fallback:`, `nb:`) и не кусок адреса — ни '/', ни ':', ни '?',
 * ни '#', ни '@', ни '..' сюда не проходят.
 */
export const PLAIN_CID_RE = /^[A-Za-z0-9]{46,128}$/;

/** true только для строки формы настоящего CID. */
export function isPlainCid(v: unknown): v is string {
  return typeof v === 'string' && PLAIN_CID_RE.test(v);
}
