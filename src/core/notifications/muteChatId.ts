/**
 * Каноническое имя собеседника в записи «без звука» — v4.32.510.
 *
 * Дефект. Ключ записи собирается как `mute:<вид>:<id>`, и у вида `chat` над
 * сборкой стояло прямым текстом: «id — contact did:key / groupId / postId».
 * Записывали при этом ДРУГОЕ. Все шесть мест, где человек глушит переписку —
 * список чатов, сама переписка, карточка контакта, — передавали открытый ключ
 * в base64:
 *
 *     muteSet('chat', peerB64, …)          →  mute:chat:PsG3…/Qk=
 *
 * а все три места, которые перед показом уведомления спрашивают «а не
 * заглушён ли он», передавали did:key:
 *
 *     isMuted('chat', contactDid)          →  mute:chat:did:key:z6Mk…
 *
 * did:key — это base58btc над теми же байтами с двухбайтным префиксом, то
 * есть строка заведомо другая. Совпасть эти два имени не могли никогда.
 * Следствие простое и полное: заглушение личной переписки не глушило ничего.
 * Значок «без звука» в списке чатов загорался (он живёт в своей колонке в
 * базе), человек считал вопрос закрытым — и продолжал получать баннер на
 * каждое сообщение от того, кого только что заглушил: и при открытом
 * приложении (pushNotifications), и при закрытом (фоновый обработчик push), и
 * в ленте на публикации того же автора (App.tsx).
 *
 * Отдельно горько, что v4.32.502 сводила ЗНАЧЕНИЕ записи у обоих читателей до
 * последней ветки — ровно ради того, чтобы «заглушённый собеседник не будил
 * телефон». Значение сошлось, а имя ключа так и осталось разным, и та правка
 * не могла ничего исправить.
 *
 * Канонической формой выбран did:key, и выбор здесь не на вкус. Фоновый
 * обработчик push поднимается вне приложения, получает из полезной нагрузки
 * только `cid` и `contactDid` и ходит в таблицу напрямую: открытого ключа у
 * него нет и взяться ему неоткуда. Значит, из двух форм в общий знаменатель
 * годится ровно одна — та, которую он способен собрать.
 *
 * Приведение живёт здесь, а не в вызывающих: шесть мест записи и три чтения —
 * это девять шансов написать правило заново и разойтись снова.
 */
import { didFromPubB64 } from '../identity/did';
import type { MuteKind } from './muteValue';

/** Начало did:key — по нему видно, что приводить уже нечего. */
export const DID_KEY_PREFIX = 'did:key:';

/**
 * Приводит идентификатор к той форме, под которой запись лежит в хранилище.
 *
 * Группы, каналы и публикации не трогаем: там обе стороны всегда передавали
 * один и тот же собственный id, и придумывать ему вторую форму незачем.
 *
 * Значение, которое не удалось разобрать как открытый ключ, возвращается как
 * есть. Это не молчаливое согласие с мусором, а отказ терять запись: под
 * такой строкой могло быть заглушено что-то, чего мы уже не понимаем, и
 * подменять её на пустоту хуже, чем оставить.
 */
export function canonicalMuteId(kind: MuteKind, id: string): string {
  if (kind !== 'chat') return id;
  if (typeof id !== 'string' || id.length === 0) return id;
  if (id.startsWith(DID_KEY_PREFIX)) return id;
  return didFromPubB64(id) ?? id;
}

/** Лежит ли запись под каноническим именем — вопрос уборки старых записей. */
export function isCanonicalMuteId(kind: MuteKind, id: string): boolean {
  return canonicalMuteId(kind, id) === id;
}
