/**
 * reminderSchedule — когда должно сработать напоминание о сообщении.
 *
 * v4.32.257. До этой версии один и тот же список вариантов был выписан
 * ТРИЖДЫ: в меню сообщения личного чата, в его же быстром меню и в меню
 * сообщения группы. Копии успели разойтись: в личном чате «Завтра утром»
 * рапортовало то «Напоминание завтра в 09:00», то «Напоминание завтра утром»,
 * а в группах варианта «Через неделю» не было вовсе — не по замыслу, а потому
 * что третью копию писали отдельно.
 *
 * Модуль чистый и без импортов: время срабатывания — единственная здесь
 * логика, которую есть смысл проверять тестами, и её нельзя привязывать к
 * notifee, который в тестовой среде не поднимается.
 */

export type ReminderKind = 'hour' | 'morning' | 'week';

/**
 * Тело напоминания, когда текст сообщения показывать нельзя (v4.32.857).
 *
 * Напоминание — единственное уведомление приложения, которое человек ставит
 * себе сам, и до этой версии оно уносило текст сообщения на заблокированный
 * экран мимо всех запретов: ни «Показывать текст сообщений» (notify_preview),
 * ни пароль на вход ему были не указ, хотя в обычных уведомлениях оба
 * проверяются (previewAllowed в pushNotifications).
 *
 * Решать приходится в момент постановки, а не срабатывания: сработает оно
 * через неделю, в чужих руках и без запущенного приложения — спросить тогда
 * будет не у кого. Поэтому «заблокирована ли сейчас сессия» здесь не годится
 * (через неделю она заблокирована наверняка), и вопрос ставится иначе: есть
 * ли у человека пароль вообще. Есть — текст на замок не выносим.
 */
export const REMINDER_BODY_HIDDEN = 'Откройте приложение, чтобы прочитать';

/** Что показать в напоминании: сам текст или нейтральную строку. */
export function reminderBody(preview: string, previewAllowed: boolean): string {
  return previewAllowed ? preview : REMINDER_BODY_HIDDEN;
}

/**
 * Начало идентификатора напоминания. Своего имени у отложенных уведомлений не
 * было вовсе — notifee выдавал случайное, и отличить своё напоминание от
 * чужого было нечем. Имя нужно не для красоты: при удалении ОДНОЙ личности
 * снимать надо ровно её напоминания, а напоминания остальных — не трогать.
 */
export const REMINDER_ID_PREFIX = 'airchat.reminder.';

/** Имя отложенного уведомления: личность + различающий хвост. */
export function reminderNotificationId(profileId: number, uniq: string): string {
  return `${REMINDER_ID_PREFIX}${profileId}.${uniq}`;
}

/**
 * Отобрать из списка отложенных уведомлений те, что принадлежат этой личности.
 *
 * Имена, поставленные до v4.32.857, префикса не имеют и сюда не попадут: снять
 * их прицельно нечем, а снести все подряд значило бы отменить напоминания
 * личностей, которые остаются. При полном сбросе устройства берётся весь
 * список целиком, и старые уходят вместе с остальными.
 */
export function reminderIdsOfProfile(ids: readonly string[], profileId: number): string[] {
  const own = `${REMINDER_ID_PREFIX}${profileId}.`;
  return ids.filter((id) => id.startsWith(own));
}

const HOUR_MS = 3_600_000;

/** Час, в который приходит напоминание «завтра утром» (местное время). */
export const REMINDER_MORNING_HOUR = 9;

export type ReminderChoice = {
  kind: ReminderKind;
  /** Текст кнопки в диалоге. */
  label: string;
  /** Текст подтверждения после того, как напоминание реально создано. */
  success: string;
};

export const REMINDER_CHOICES: readonly ReminderChoice[] = [
  { kind: 'hour', label: 'Через 1 час', success: 'Напоминание через 1 час' },
  { kind: 'morning', label: 'Завтра утром', success: 'Напоминание завтра в 09:00' },
  { kind: 'week', label: 'Через неделю', success: 'Напоминание через неделю' },
];

/**
 * Момент срабатывания в миллисекундах эпохи. `nowMs` передаётся явно, чтобы
 * функция оставалась чистой; «завтра утром» считается по местному календарю —
 * следующий день, 09:00, независимо от того, сколько сейчас времени.
 */
export function reminderTimestamp(kind: ReminderKind, nowMs: number): number {
  switch (kind) {
    case 'hour':
      return nowMs + HOUR_MS;
    case 'week':
      return nowMs + 7 * 24 * HOUR_MS;
    case 'morning': {
      const d = new Date(nowMs);
      d.setDate(d.getDate() + 1);
      d.setHours(REMINDER_MORNING_HOUR, 0, 0, 0);
      return d.getTime();
    }
  }
}
