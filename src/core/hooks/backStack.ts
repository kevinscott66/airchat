/**
 * Внутриприложенческий стек обработчиков «Назад» (v4.32.540).
 *
 * До этой версии «Назад» существовало только на Android: `useBackHandler`
 * подписывался на системную кнопку, а на iOS не делал ничего — там кнопки нет.
 * Возврат оставался единственной кнопкой в шапке, и промахнуться по ней на
 * большом экране одной рукой — обычное дело.
 *
 * Жест «Назад» не может звать `BackHandler`: на iOS его нет, а на Android
 * событие туда шлёт система, а не приложение. Поэтому здесь заведён такой же
 * LIFO-стек, в который `useBackHandler` кладёт свой колбэк на ЛЮБОЙ
 * платформе, а жест этот стек прокручивает. Порядок тот же, что у системного:
 * последний зарегистрированный (самая верхняя модалка) отвечает первым.
 *
 * Двойного срабатывания нет: системная кнопка идёт через `BackHandler` и сюда
 * не заходит, а жест идёт сюда и `BackHandler` не трогает.
 */

type BackHandlerFn = () => boolean | void;

const stack: BackHandlerFn[] = [];

/** Положить обработчик наверх стека. Возвращает функцию снятия. */
export function pushBackHandler(fn: BackHandlerFn): () => void {
  stack.push(fn);
  return () => {
    const i = stack.lastIndexOf(fn);
    if (i >= 0) stack.splice(i, 1);
  };
}

/**
 * Прокрутить стек сверху вниз до первого обработчика, который поглотил
 * событие. `false` — возвращаться некуда: жест делает вид, что его не было
 * (в отличие от системной кнопки, приложение по нему НЕ закрывается).
 *
 * Копия списка снимается до обхода: обработчик обычно закрывает оверлей, а тот
 * в ответ снимает себя со стека — правка массива по ходу цикла пропустила бы
 * следующий элемент.
 */
export function runBackHandlers(): boolean {
  for (const fn of [...stack].reverse()) {
    let handled = false;
    try {
      handled = fn() !== false;
    } catch {
      // Сломавшийся обработчик не должен блокировать те, что под ним.
      handled = false;
    }
    if (handled) return true;
  }
  return false;
}

/** Только для тестов: очистить стек между кейсами. */
export function resetBackHandlersForTest(): void {
  stack.length = 0;
}
