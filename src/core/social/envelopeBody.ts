/**
 * envelopeBody — общее начало разбора любого конверта с префиксом.
 *
 * v4.32.380. Четырнадцать конвертов начинаются одинаково: проверить префикс,
 * проверить потолок длины ДО JSON.parse, разобрать в try, убедиться, что вышел
 * объект, а не число, строка или массив. Одинаково — но написано было
 * четырнадцать раз, и там, где строку набирали заново, шаги терялись:
 *
 *   - docEnvelope, locationEnvelope (оба разборщика) и pollEnvelope не имели
 *     потолка вовсе. Текст сообщения доезжает до них длиной с сам транспорт, а
 *     parsePollText вызывается не при приёме, а при ОТРИСОВКЕ пузыря
 *     (PollBubble, DmPollBubble, FeedScreen) — то есть чужая строка на
 *     мегабайт разбиралась заново на каждом проходе списка, синхронно в JS-
 *     потоке, и прокрутка вставала.
 *   - storyEnvelope и groupControlEnvelope проверяли typeof === 'object', но
 *     не отсеивали массив: typeof [] тоже 'object'.
 *   - decodeGroupMsgEnvelope не проверял форму совсем и отдавал вызывающему
 *     то, что вернул JSON.parse, — хоть число.
 *
 * Чинить это по одному месту значит оставить пятнадцатому конверту тот же
 * набор граблей. Поэтому шаг общий, а потолок — обязательный параметр: забыть
 * его теперь нельзя, не написав вызов, который не компилируется.
 *
 * Модуль без единого импорта.
 */

/**
 * Проверяет префикс и потолок длины, разбирает тело конверта и возвращает его,
 * только если это объект (не массив, не null, не примитив).
 *
 * `maxLen` меряется по ВСЕЙ строке, вместе с префиксом, — она и приходит из
 * сети целиком. Возвращает null на любом несовпадении: вызывающему остаётся
 * проверить свои поля, а не форму.
 *
 * Приведение к T — то же самое, что делал каждый разборщик своим `as`, но
 * теперь после проверки формы, а не вместо неё.
 */
export function readEnvelopeBody<T = Record<string, unknown>>(
  text: string,
  prefix: string,
  maxLen: number
): T | null {
  if (!text.startsWith(prefix)) return null;
  if (text.length > maxLen) return null;
  let raw: unknown;
  try {
    raw = JSON.parse(text.slice(prefix.length));
  } catch {
    return null;
  }
  if (!raw || typeof raw !== 'object' || Array.isArray(raw)) return null;
  return raw as T;
}
