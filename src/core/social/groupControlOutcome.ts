/** «Приняли N из M» — хвост, общий для всех частичных текстов. */
function shortfall(recipients: number, of: number): string {
  return `приняли ${recipients} из ${of}`;
}

/** Почему не ушло — одной причиной на все тексты этого модуля. Сама фраза
 *  живёт в controlFanout: у группы и у лички она разная, но дом у неё один. */
function why(reason: FanoutUndelivered): string {
  return fanoutReasonText(reason, 'group');
}

/** Текст расхождения, либо null — если рассылка состоялась полностью. */
export function groupControlProblem(outcome: GroupControlOutcome): string | null {
  if (!outcome.sent) return `${DIVERGENCE[outcome.op]} (${why(outcome.reason)}).`;
  // v4.32.850: частичная доставка — тоже расхождение, просто не со всеми.
  // Сравнение через `> 0`, а не `!==`: у мока или старого вызова без `of`
  // разность обращается в NaN, и молчание остаётся молчанием, а не ложной
  // тревогой «приняли 3 из NaN».
  const missed = outcome.of - outcome.recipients;
  if (!(missed > 0)) return null;
  return `${PARTIAL[outcome.op]} (${shortfall(outcome.recipients, outcome.of)}).`;
}

/**
 * Заявка на вступление (v4.32.451) — не управляющий конверт группы, а личное
 * письмо администратору, поэтому у неё свой текст. Расхождение здесь другого
 * рода: у меня «запрос отправлен», у администратора — ни строчки в списке
 * заявок, и ждать можно бесконечно.
 */
export function joinRequestProblem(res: FanoutResult): string | null {
  // Частичной доставки здесь нет намеренно (v4.32.850): заявку рассылают всем
  // администраторам, но решение принимает один. Если её принял хоть кто-то —
  // заявка на рассмотрении, и говорить заявителю «дошло не до всех» значило бы
  // звать его переотправлять то, что уже лежит у администратора.
  if (res.sent) return null;
  return res.reason === 'no_peer'
    ? 'Запрос отправить некому: в ссылке нет администратора группы.'
    : `Запрос на вступление не ушёл (${why(res.reason)}). Откройте ссылку ещё раз, когда появится связь.`;
}

/**
 * Заявка ушла, а отметка о ней не легла (v4.32.989).
 *
 * Отметка «я сам просился именно к этому администратору» — единственное, что
 * пускает его приглашение в аккаунт, где включено «в группы добавляют только
 * контакты», а самого администратора в контактах нет (v4.32.465). Пишется она
 * в тот момент, когда телефону тяжелее всего: переход по ссылке поднимает
 * приложение с нуля. Ответ записи выбрасывался, и отказ был неотличим от
 * удачи: человек читал «Запрос отправлен», администратор нажимал «Принять», а
 * приглашение на этой стороне отбрасывалось — молча у обоих.
 *
 * Фраза называет расхождение, а не «ошибку записи»: у администратора заявка
 * принята, а группы у заявителя может не появиться.
 */
export const JOIN_REQUEST_NOT_REMEMBERED =
  'Запрос отправлен, но телефон его не запомнил: даже если администратор вас примет, ' +
  'группа может не появиться. Откройте ссылку ещё раз.';

/**
 * Сброс пригласительной ссылки не разошёлся по администраторам (v4.32.452).
 *
 * Общая фраза 'meta' здесь была бы правдой, но бесполезной: важна не
 * «настройка», а то, что кнопка «Пригласительная ссылка» у второго
 * администратора продолжает выдавать ссылки, которые группа уже не пускает.
 * Отзыв ссылки при этом выглядит состоявшимся — в том и беда.
 */
export function inviteTokenSpreadProblem(outcome: GroupControlOutcome): string | null {
  if (!outcome.sent) {
    return (
      `Ссылка сброшена только у вас (${why(outcome.reason)}) — у других администраторов ` +
      'кнопка «Пригласительная ссылка» продолжит выдавать ссылки, которые группа уже не пускает.'
    );
  }
  // v4.32.850: одного не узнавшего администратора достаточно, чтобы отзыв
  // ссылки был мнимым, — он продолжит раздавать старую.
  const missed = outcome.of - outcome.recipients;
  if (!(missed > 0)) return null;
  return (
    `Сброс ссылки дошёл не до всех администраторов (${shortfall(outcome.recipients, outcome.of)}) — ` +
    'у остальных кнопка «Пригласительная ссылка» продолжит выдавать ссылки, которые группа уже не пускает.'
  );
}
