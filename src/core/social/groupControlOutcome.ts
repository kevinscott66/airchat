/**
 * Чем закончилась рассылка управляющего конверта группы — словами (v4.32.449).
 *
 * Бан, кик, смена роли, «удалить у всех», настройки группы — всё это меняется
 * сначала в своей БД, а потом рассылается участникам. Рассылка могла не
 * состояться (нет сервиса отправки, нет связи), и до этой версии узнать об
 * этом было неоткуда: fanoutGroupControl возвращал void, а все двадцать с
 * лишним вызовов писали `void fanoutGroupControl(...)`. Повторной отправки у
 * служебного конверта нет, поэтому «не ушло» значит «не уйдёт»: у себя
 * забанен, у остальных пишет.
 *
 * Текст здесь называет не «ошибку отправки», а расхождение: что именно теперь
 * по-разному у меня и у остальных. Это единственное, что человеку нужно знать,
 * — и единственное, чего он не может увидеть на своём экране.
 */

import type { FanoutResult, FanoutUndelivered } from './controlFanout';
import { fanoutReasonText } from './controlFanout';
import type { GroupCtlOp } from './groupControlEnvelope';

/**
 * Итог рассылки вместе с операцией, которой он принадлежит.
 *
 * Операция вшита в итог, а не передаётся отдельно в текстовку: иначе отказ
 * бана можно было бы по недосмотру объявить отказом кика.
 */
export type GroupControlOutcome = { op: GroupCtlOp['op'] } & FanoutResult;

/**
 * Что теперь расходится. Record по всем операциям: новый вид конверта не
 * соберётся, пока ему не написали фразу.
 */
const DIVERGENCE: Record<GroupCtlOp['op'], string> = {
  ban: 'Участник заблокирован только у вас — остальные по-прежнему видят его сообщения',
  unban: 'Участник разблокирован только у вас — для остальных он остаётся заблокированным',
  kick: 'Участник удалён только у вас — в чужих списках он остался',
  add: 'Участник добавлен только у вас — остальные его сообщения не примут',
  role: 'Роль изменена только у вас — остальные считают по-старому',
  del: 'Сообщение удалено только у вас — у остальных оно осталось',
  edit: 'Правка сохранена только у вас — у остальных прежний текст',
  pin: 'Закрепление изменено только у вас — у остальных в шапке чата прежнее',
  meta: 'Настройка изменена только у вас — у остальных прежняя',
  leave: 'Вы вышли из группы, но участники об этом не узнали — для них вы остались в списке',
  join: 'Вы в группе, но участники об этом не узнали — ваши сообщения у них не появятся',
  invite: 'Приглашение не ушло — группа у приглашённых не появится, а их сообщения к вам не дойдут',
  joinres: 'Ответ на заявку не ушёл — заявитель решения не увидит и останется ждать',
};

/** Почему не ушло — одной причиной на все тексты этого модуля. Сама фраза
 *  живёт в controlFanout: у группы и у лички она разная, но дом у неё один. */
function why(reason: FanoutUndelivered): string {
  return fanoutReasonText(reason, 'group');
}

/** Текст расхождения, либо null — если рассылка состоялась. */
export function groupControlProblem(outcome: GroupControlOutcome): string | null {
  if (outcome.sent) return null;
  return `${DIVERGENCE[outcome.op]} (${why(outcome.reason)}).`;
}

/**
 * Заявка на вступление (v4.32.451) — не управляющий конверт группы, а личное
 * письмо администратору, поэтому у неё свой текст. Расхождение здесь другого
 * рода: у меня «запрос отправлен», у администратора — ни строчки в списке
 * заявок, и ждать можно бесконечно.
 */
export function joinRequestProblem(res: FanoutResult): string | null {
  if (res.sent) return null;
  return res.reason === 'no_peer'
    ? 'Запрос отправить некому: в ссылке нет администратора группы.'
    : `Запрос на вступление не ушёл (${why(res.reason)}). Откройте ссылку ещё раз, когда появится связь.`;
}

/**
 * Сброс пригласительной ссылки не разошёлся по администраторам (v4.32.452).
 *
 * Общая фраза 'meta' здесь была бы правдой, но бесполезной: важна не
 * «настройка», а то, что кнопка «Пригласительная ссылка» у второго
 * администратора продолжает выдавать ссылки, которые группа уже не пускает.
 * Отзыв ссылки при этом выглядит состоявшимся — в том и беда.
 */
export function inviteTokenSpreadProblem(outcome: GroupControlOutcome): string | null {
  if (outcome.sent) return null;
  return (
    `Ссылка сброшена только у вас (${why(outcome.reason)}) — у других администраторов ` +
    'кнопка «Пригласительная ссылка» продолжит выдавать ссылки, которые группа уже не пускает.'
  );
}
