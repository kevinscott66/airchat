/**
 * groupActor — кто человек в группе: один запрос, один разбор роли.
 *
 * v4.32.429. Право «реагировать и голосовать» (canInteractInGroup) живёт в
 * groupSendPolicy в одном экземпляре — а вот подготовка данных для него была
 * переписана от руки пять раз: три на приёме конвертов (реакция, голос,
 * завершение опроса) и две на отправке. Каждая копия делала одно и то же:
 *
 *   const groups = await listGroups(pid);
 *   if (!groups.some((g) => g.id === env.groupId)) { … }      // анти-спуф
 *   const members = await listGroupMembers(env.groupId);
 *   const member = members.find((m) => m.peerPubB64 === senderPubB64);
 *   const verdict = canInteractInGroup((member?.role as SendRole | undefined) ?? null);
 *
 * Копии уже расходились: комментарий v4.32.273 в pollVoteSync («не только бан,
 * но и read-only») отмечает ровно тот момент, когда одну из них починили, а
 * остальные пришлось догонять правкой в каждой. Пока строк пять, следующее
 * расхождение — вопрос времени: оно не ломает сборку, не роняет тест и видно
 * только по расходящимся счётчикам на двух телефонах.
 *
 * v4.32.511. Строка группы берётся по идентификатору (`getGroup`), а не
 * выбирается из списка активных. Процитированный выше образец копий содержал
 * `listGroups`, и вместе с ними сюда переехала его оговорка: этот запрос
 * отдаёт только `archived = 0`. Значит, группа, убранная в архив — а это один
 * жест по строке в списке, и подписан он «скрыть», — становилась для всех
 * пятерых вызывающих ЧУЖОЙ: реакции, голоса, завершение опроса и отметки о
 * прочтении в ней переставали приниматься. Архив — это «убрать с глаз», а не
 * «выйти». Заодно запрос стал дешевле: одна строка по индексу вместо
 * расшифровки каждой группы профиля.
 *
 * Здесь две функции и ни одной проверки прав — решение по-прежнему выносит
 * groupSendPolicy. Это исключительно чтение и приведение типа: `role` в базе
 * лежит строкой, и `as SendRole` — то самое место, где строка становится
 * ролью. Раньше этот `as` стоял пять раз; теперь один.
 */

import { getGroup, listGroupMembers, type GroupMemberRow, type GroupRow } from '../storage/local';
import type { SendRole } from './groupSendPolicy';

/**
 * Роль по публичному ключу. null — такого участника в группе нет.
 *
 * Отдельно от lookupGroupActor, потому что отправляющая сторона список
 * участников уже держит в руках (он же идёт в fanout) и второй запрос к базе
 * ей не нужен.
 */
export function roleOf(members: GroupMemberRow[], pubB64: string): SendRole | null {
  const row = members.find((m) => m.peerPubB64 === pubB64);
  return (row?.role as SendRole | undefined) ?? null;
}

export type GroupActor = {
  /**
   * Строка группы из базы активного профиля. null — конверт про группу, о
   * которой мы не знаем: применять его нечему, и это не ошибка, а обычный
   * мусор из сети (или попытка накрутить счётчики в чужой группе, зная её id).
   *
   * Возвращается целиком, а не флагом «знаем/не знаем»: правила отправки
   * зависят от типа группы и от «пишут только администраторы», и вызывающему
   * иначе пришлось бы читать её вторым запросом.
   */
  group: GroupRow | null;
  /** Участники группы. Пустой массив, если группы нет — запроса не было. */
  members: GroupMemberRow[];
  /** Роль отправителя. null — его нет в списке участников. */
  role: SendRole | null;
};

/**
 * Кто отправитель конверта в названной группе.
 *
 * Роль берётся из ЛОКАЛЬНОЙ таблицы участников по подписанному ключу
 * отправителя — не из конверта. Конверт про роль не спрашивают вообще: в нём
 * можно написать что угодно.
 */
export async function lookupGroupActor(
  groupId: string,
  actorPubB64: string,
  ownerProfileId: number
): Promise<GroupActor> {
  const group = await getGroup(groupId, ownerProfileId);
  if (!group) return { group: null, members: [], role: null };
  const members = await listGroupMembers(groupId, ownerProfileId);
  return { group, members, role: roleOf(members, actorPubB64) };
}
