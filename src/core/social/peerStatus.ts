/**
 * peerStatus — «статус» собеседника, который виден под его именем.
 *
 * v4.32.375. Строку задаёт сам человек в своём профиле, она едет в конверте
 * присутствия и показывается получателю в двух местах: подзаголовком в шапке
 * переписки (ChatScreen) и в кавычках в карточке контакта. Из всех текстовых
 * полей, приходящих по сети, это оставалось последним, которое не чистилось
 * вовсе: на приёме стояла одна обрезка по длине.
 *
 * Отсюда три вещи.
 *
 * 1. U+202E разворачивал строку в шапке — ровно там, где приложение говорит
 *    своим голосом («в сети», «печатает», «Исчезают через 5 минут»).
 * 2. Управляющие символы доезжали как есть, а перевод строки в подзаголовке
 *    шапки — это вторая строка там, где место рассчитано на одну.
 * 3. Статус в шапке ПЕРЕКРЫВАЕТ строку присутствия: проверка там на
 *    истинность. Статус из одного U+200D её проходит, места не занимает — и
 *    «был(а) недавно» пропадало без следа, а причину увидеть нельзя.
 *
 * Правило берётся то же, что для имени, а не для многострочного текста: это
 * однострочная подпись под именем, и перевод строки в ней не нужен — он
 * становится пробелом.
 */

import { displayNameOrNull } from './sysLineGuard';

/**
 * Предел длины статуса — общий для обоих своих редакторов и для чужого конверта.
 *
 * Раньше их было три, и все разные. Редактор в профиле не давал набрать больше
 * 60 символов и был однострочным; редактор в настройках (тот же статус, второй
 * вход к нему) давал 100 и был многострочным; на приёме стояло 140. «Всё, что
 * нельзя отправить, нельзя и принять» — то же правило, по которому сведены
 * сборка и разбор опроса (pollEnvelope).
 */
export const MAX_CUSTOM_STATUS_LEN = 60;

/**
 * Чужой статус к виду, годному для показа. null — статуса нет: и когда поле
 * пустое, и когда в нём не осталось ничего видимого.
 */
export function sanitizePeerStatus(v: unknown): string | null {
  return displayNameOrNull(v, MAX_CUSTOM_STATUS_LEN);
}

/**
 * Свой статус перед записью в базу — тем же правилом, что и чужой на приёме.
 *
 * Чистка на отправке спасает собеседника, но не автора: без неё в базе лежит
 * одно, а до контактов доезжает другое, и владелец видит у себя строку, которой
 * больше ни у кого нет. Пустая строка здесь значит «статуса нет» — так это поле
 * и хранится (ownFieldSet с '').
 */
export function normalizeOwnStatus(v: unknown): string {
  return sanitizePeerStatus(v) ?? '';
}

/**
 * Подзаголовок в шапке переписки: присутствие и статус в одной строке.
 *
 * До v4.32.375 это были две ветки, и статус стоял первым — значит собеседник,
 * однажды написавший «на созвоне», навсегда забирал у шапки строку «в сети» /
 * «был(а) недавно». Убрать её насовсем нельзя: ради неё в шапку и смотрят, а
 * статус висит месяцами. Порядок здесь и решает, чему достанется место, если
 * строка не влезет: присутствие короче и важнее, поэтому идёт первым, и по краю
 * обрезается хвост статуса.
 */
export function presenceSubtitle(label: string | null | undefined, status: string | null | undefined): string {
  if (label && status) return `${label} · ${status}`;
  return label || status || '';
}
