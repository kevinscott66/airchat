/**
 * sysLineGuard — защита системных строк от подделки собеседником.
 *
 * v4.32.238. Строки вида «Вы заблокированы в группе», «Группа переименована»,
 * «Исчезающие сообщения включены» хранятся в тех же таблицах, что и обычные
 * сообщения, и отличаются только префиксом '\x0bsys:'. Экраны рисуют такую
 * строку серым текстом по центру — то есть от имени приложения, а не человека.
 *
 * Текст же приходит из недоверенного источника: и обычное сообщение группы
 * ('\x02grp:'), и правка своего сообщения ('\x0egctl:' op 'edit'), и обычное
 * личное сообщение переносят произвольную строку. Никакой проверки не было,
 * поэтому участник, отправив текст, начинающийся с '\x0bsys:', показывал всей
 * группе поддельное системное уведомление — например, что кто-то заблокирован
 * или что администратор сменил настройки. В личных чатах то же самое стало
 * возможным вместе с системными строками таймера.
 *
 * Правило: системную строку создаёт только своё устройство. Всё, что пришло
 * по сети, теряет этот префикс и остаётся обычным видимым текстом — сообщение
 * не пропадает, но выдать его за голос приложения больше нельзя.
 *
 * Модуль без импортов: применяется в горячем пути приёма, тестируется без
 * SQLite и транспорта.
 */

/** Префикс системной строки. Должен совпадать с GROUP_SYS_PREFIX/DM_SYS_PREFIX. */
export const SYS_LINE_PREFIX = '\x0bsys:';

/**
 * Снимает префикс системной строки с недоверенного текста.
 *
 * Цикл обязателен: одиночная проверка оставляла бы '\x0bsys:\x0bsys:текст'
 * системной строкой после снятия первого префикса.
 */
export function stripSpoofedSysPrefix(text: string): string {
  let out = text;
  while (out.startsWith(SYS_LINE_PREFIX)) out = out.slice(SYS_LINE_PREFIX.length);
  return out;
}

/**
 * Приводит чужое отображаемое имя к виду, безопасному для системной строки.
 *
 * Ту же дверь, что закрывает stripSpoofedSysPrefix, открывает имя человека:
 * системную строку приложение собирает подстановкой («X вступил(а) в
 * группу»), и перевод строки внутри имени дописывает к ней вторую строку —
 * визуально неотличимую от настоящего уведомления AirChat. Поэтому вычистка
 * управляющих символов обязательна КАЖДОМУ имени из сети, а не только тем,
 * что попадают в списки участников.
 *
 * Возвращает null, если это вообще не строка — вызывающий решает, отбросить
 * конверт или подставить значение по умолчанию.
 *
 * v4.32.369: диапазона C0 для этого мало. Перевод строки — не только '\n':
 * обязательный разрыв строки дают семь символов (UAX #14, класс BK), и три из
 * них лежат за пределами C0 — U+0085 (NEL), U+2028 (LINE SEPARATOR) и U+2029
 * (PARAGRAPH SEPARATOR). Android и iOS ломают строку на каждом из них так же,
 * как на '\n', то есть ровно та подделка системной строки, ради которой
 * функция и написана, проходила насквозь через имя с U+2028. Заодно вырезаем
 * весь C1 (U+0080…U+009F): это управляющие коды, в имени им делать нечего.
 */
export function sanitizeDisplayName(v: unknown, maxLen = 64): string | null {
  if (typeof v !== 'string') return null;
  // v4.32.374: обрезка по краям. Пробелы по краям функция создаёт сама —
  // управляющие символы она заменяет пробелом, поэтому имя, начинавшееся с
  // перевода строки, после замены начинается с пробела. А имя, начинающееся с
  // шестидесяти пробелов и буквы, проверку «ничего не видно» проходит честно
  // (буква-то есть) и уезжает в списке чатов за правый край строки.
  const cut = stripBidiControls(v.replace(CONTROL_AND_BREAKS, ' ')).trim().slice(0, maxLen).trimEnd();
  // v4.32.371: проверка стоит ПОСЛЕ обрезки. Имя из шестидесяти четырёх
  // склеек и настоящих букв после них видимо целиком, но в предел попадает
  // только невидимая часть — и то, что дальше увидит вызывающий, пусто.
  return isVisiblyBlank(cut) ? '' : cut;
}

/**
 * То же имя, но «ничего не видно» отдаётся как отсутствие имени.
 *
 * v4.32.371. Правило «имени нет» во всём приложении — это проверка на
 * истинность: `displayName || peerName`, `senderName ?? '?'`,
 * `actorName ?? 'Администратор'`. Пустая строка её проходит правильно, а
 * строка из невидимых символов — нет: для кода она полноценное имя, на экране
 * от неё не остаётся ничего. Собеседник, назвавшийся одним U+200D, получал
 * безымянную строку в списке чатов, безымянного участника в группе и
 * системную строку « добавил(а) вас в группу» без действующего лица. Двое
 * таких неразличимы между собой — а подпись под сообщением и есть всё, чем
 * они отличаются.
 *
 * Отдельная функция, а не поведение sanitizeDisplayName: у той null уже
 * означает «это вообще не строка», и вызывающие на этом стоят.
 */
export function displayNameOrNull(v: unknown, maxLen = 64): string | null {
  return sanitizeDisplayName(v, maxLen) || null;
}

/**
 * Не осталось ли в строке ничего, что рисуется.
 *
 * Пробелы сюда входят целиком (`\s` в JS — это и U+00A0, и U+3000, и
 * U+FEFF), а рядом с ними — символы, которые пробелами не считаются, под
 * `trim()` не попадают и при этом не рисуют ничего:
 *
 * - U+200C и U+200D общая вычистка оставляет намеренно: без первой не пишутся
 *   фарси и деванагари, без второй распадаются составные эмодзи;
 * - U+2060 (склейка слов), U+2061…U+2064 (невидимые математические операторы),
 *   U+034F (склейка графем), U+FE00…U+FE0F (селекторы начертания) и
 *   U+E0000…U+E007F (языковые метки) — v4.32.424. Их тут не было, и это дыра
 *   ровно в том, ради чего функция написана: имя из одних таких символов
 *   считалось настоящим. Собеседник получал пустую подпись под сообщением,
 *   пустую строку в списке чатов и системную строку «„“ добавил(а) вас в
 *   группу», а двое безымянных неразличимы между собой;
 * - U+200B (ноль-ширины пробел) — того же рода, но до сети он и раньше не
 *   доходил: stripBidiControls вырезает его вместе с метками направления
 *   письма. В набор он добавлен потому, что isVisiblyBlank зовут и напрямую —
 *   из nameOrNull и nameInitial, поверх строк, через sanitizeDisplayName не
 *   проходивших (старые записи в таблице, имя из чужого клиента);
 * - U+2800 (пустой символ Брайля), U+3164 и U+FFA0 (хангыль-заполнители),
 *   U+115F и U+1160 (заполнители чосон и чунсон) — ими и набивают пустое имя
 *   в чужих мессенджерах, буквами они при этом не являются;
 * - U+180E и U+17B4…U+17B5 — служебные разделители монгольского и кхмерского.
 *
 * Вырезать их из середины имени нельзя — там они часть письма. Речь только о
 * строке, в которой, кроме них, нет ничего.
 */
export function isVisiblyBlank(s: string): boolean {
  for (const ch of s) {
    if (BLANK_CODE_POINTS.has(ch.codePointAt(0) as number)) continue;
    if (/\s/.test(ch)) continue;
    return false;
  }
  return true;
}

/**
 * Кодовые точки, которые ничего не рисуют и пробелами при этом не считаются.
 *
 * Множеством, а не символьным классом: U+115F и U+1160 в классе образуют
 * сочетание, U+200D — склейку, и регулярное выражение из них читается
 * двусмысленно (eslint no-misleading-character-class). Перебор по кодовым
 * точкам заодно правильно проходит суррогатные пары: эмодзи — это один шаг
 * цикла, а не два непонятных кода.
 */
const BLANK_CODE_POINTS = new Set([
  0x034f, // склейка графем: сама по себе не рисуется
  0x115f, 0x1160, // заполнители чосон и чунсон
  0x17b4, 0x17b5, // кхмерские гласные, не имеющие начертания
  0x180e, // монгольский разделитель гласных
  0x200b, // ноль-ширины пробел
  0x200c, 0x200d, // разделитель фарси и склейка эмодзи
  0x2060, // склейка слов — тот же ноль-ширины, но «неразрывный»
  0x2061, 0x2062, 0x2063, 0x2064, // невидимые математические операторы
  0x2800, // пустой символ Брайля
  0x3164, 0xffa0, // хангыль-заполнители, обычный и полуширинный
  // Селекторы начертания: меняют вид предыдущего символа, своего не имеют.
  ...Array.from({ length: 16 }, (_, i) => 0xfe00 + i),
  // Языковые метки (U+E0000…U+E007F): не рисуются нигде и ничем.
  ...Array.from({ length: 0x80 }, (_, i) => 0xe0000 + i),
]);

/**
 * Управляющие символы и всё, что рвёт строку помимо C0.
 *
 * '\u007F-\u009F' — это DEL и весь C1 одним диапазоном, '\u2028\u2029' —
 * разделители строки и абзаца, которых нет ни в C0, ни в C1.
 */
// eslint-disable-next-line no-control-regex -- вырезание control-символов из недоверенного ввода и есть цель
const CONTROL_AND_BREAKS = /[\u0000-\u001F\u007F-\u009F\u2028\u2029]/g;

/**
 * Убирает невидимые символы управления направлением письма.
 *
 * v4.32.241. U+202E (RIGHT-TO-LEFT OVERRIDE) и соседние символы разворачивают
 * порядок вывода всего, что идёт после них. Они не видны, но меняют то, что
 * человек читает на экране: имя файла «отчет<RLO>exe.pdf» показывается как
 * «отчетfdp.exe» — безобидный .pdf на экране оказывается .exe при открытии.
 * Точно так же переворачивается чужое имя в системной строке.
 *
 * Вырезаем только сами управляющие символы; арабский и иврит от этого не
 * страдают — их направление определяет сам текст, а не эти метки. Заодно
 * убираем пробел нулевой ширины и BOM, которыми набивают невидимую длину.
 * U+200D (склейка эмодзи) и U+200C (нужен фарси и деванагари) остаются.
 */
export function stripBidiControls(s: string): string {
  return s.replace(/[\u061C\u200B\u200E\u200F\u202A-\u202E\u2066-\u2069\uFEFF]/g, '');
}

/**
 * Чужой текст перед показом человеку.
 *
 * v4.32.327 — жил в src/ui/utils/renderText.ts, пока был нужен только трём
 * отрисовщикам тела сообщения. v4.32.328: та же строка показывается ещё и в
 * списке диалогов, в списке групп и в результатах поиска — то есть в местах,
 * которые про UI-слой ничего не знают, — поэтому функция переехала сюда, к
 * остальным правилам обращения с недоверенным текстом.
 *
 * Убирает метки направления письма (см. stripBidiControls) и управляющие
 * символы C0 и C1, кроме перевода строки, возврата каретки и табуляции — без
 * них текст рассыплется. Остальные не рисуются, но попадают в подсчёт длины и
 * в поиск, а '\x0b' — ещё и в префикс системной строки.
 *
 * U+2028 и U+2029 здесь, в отличие от имени, остаются: в теле сообщения
 * перевод строки разрешён, и разделитель строки — это он и есть.
 */
export function sanitizeBodyForRender(raw: string): string {
  if (typeof raw !== 'string') return '';
  // eslint-disable-next-line no-control-regex -- вырезание control-символов из недоверенного ввода и есть цель
  return stripBidiControls(raw.replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F-\u009F]/g, ''));
}

/**
 * Чужой многострочный текст, который рисуют не пузырём сообщения (v4.32.373).
 *
 * Тело сообщения чистит sanitizeBodyForRender, но зовут её отрисовщики —
 * FormattedText, GrpFormattedText, RichText. Поля, которые рисуются обычным
 * <Text> и мимо них, оставались нечищеными вовсе:
 *
 *   описание группы  — GroupsScreen, {group.description}
 *   текст сторис     — StoriesRow, {story.text} и подпись поверх картинки
 *
 * Оба приходят по сети, оба показываются на чужом экране, и в обоих конвертах
 * стояла одна проверка длины. То есть U+202E, ради которого stripBidiControls
 * и написан в v4.32.241, разворачивал в них текст ровно так же, как в имени
 * файла: читается не то, что написано.
 *
 * Отличие от sanitizeBodyForRender — три вещи, каждая из-за того, что это не
 * пузырь:
 *
 * 1. U+2028 и U+2029 приводятся к обычному переводу строки. В теле сообщения
 *    они остаются (разделитель строки — это они и есть), но здесь текст
 *    попадает и в места, которые считают строки, и разнобой из трёх видов
 *    перевода строки в одном поле пользы не приносит.
 * 2. Пустых строк подряд остаётся не больше одной. Описание в 512 символов
 *    может состоять из 512 переводов строки — это не текст, а способ
 *    растянуть карточку группы на весь экран у всех участников.
 * 3. Обрезка по длине и пустой результат как null: вызывающему нужно уметь
 *    отличить «описание убрали» от «описание пришло, но в нём ничего нет».
 */
export function sanitizeParagraphText(v: unknown, maxLen: number): string | null {
  if (typeof v !== 'string') return null;
  const cleaned = sanitizeBodyForRender(v)
    .replace(/\r\n?|[\u2028\u2029]/g, '\n')
    .replace(/\n[ \t]*(?:\n[ \t]*)+/g, '\n\n')
    .trim()
    .slice(0, maxLen)
    .trim();
  return cleaned && !isVisiblyBlank(cleaned) ? cleaned : null;
}
