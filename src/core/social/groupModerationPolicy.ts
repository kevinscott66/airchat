/**
 * Кто кого может модерировать в группе.
 *
 * Правило одно и то же на обоих концах, но написано было только на приёме
 * (groupMessaging: владелец неприкосновенен, чужого админа трогает только
 * владелец). Экран этих правил не знал и применял изменение локально, а
 * потом рассылал конверт, который у всех остальных отбрасывался. Получалось
 * молчаливое расхождение: у администратора участник исключён, у всех
 * остальных — на месте, и никто об этом не узнаёт.
 *
 * Поэтому вердикт вынесен сюда и вызывается с обеих сторон: экран
 * показывает его заранее, приёмник — проверяет по-настоящему. Приёмник
 * остаётся единственным, кому можно верить: он считает роль отправителя по
 * подписи, а не по тому, что тот о себе сообщил.
 */
import type { MemberRole } from '../storage/local';

export type ModerationVerdict = { allowed: true } | { allowed: false; reason: string };

const ALLOWED: ModerationVerdict = { allowed: true };

/**
 * Может ли `actor` применить к `target` действие модерации — исключение,
 * блокировку, снятие блокировки, выдачу или снятие прав администратора.
 *
 * `target` = undefined означает «такого участника у нас ещё нет» (например,
 * добавление нового): запрещать нечего, ограничение только на роль актора.
 */
export function canModerate(actor: MemberRole | undefined, target: MemberRole | undefined): ModerationVerdict {
  if (actor !== 'owner' && actor !== 'admin') {
    return { allowed: false, reason: 'Это может сделать только администратор группы.' };
  }
  if (target === 'owner') {
    return { allowed: false, reason: 'Владельца группы нельзя исключить или лишить прав.' };
  }
  // Админ админа не трогает — иначе двое администраторов могли бы разжаловать
  // друг друга, и чем кончится, зависело бы от того, чей конверт дошёл первым.
  if (target === 'admin' && actor !== 'owner') {
    return { allowed: false, reason: 'Действие с другим администратором доступно только владельцу группы.' };
  }
  return ALLOWED;
}
