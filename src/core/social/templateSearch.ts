/**
 * Быстрые ответы, которые не открылись ключом данных (v4.32.582).
 *
 * `listQuickReplies` читала текст шаблона через `decryptAtRestString`, а он на
 * неудаче отдаёт пустую строку. Дальше эта пустота расходилась в три места и
 * везде выглядела не тем, чем была:
 *
 *  • в настройках строка шаблона рисовалась без текста — карандаш и корзина
 *    по краям пустоты, как будто человек когда-то сохранил пустой шаблон;
 *  • во вкладке «Ответ» такая строка тоже пустая, и нажатие на неё вставляло
 *    в поле ввода пустую строку: нажал — ничего не произошло, лист закрылся;
 *  • поиск по шаблонам сравнивал запрос с пустой строкой, поэтому шаблон
 *    исчезал из выдачи, и «ничего не найдено» звучало как утверждение, хотя
 *    про непрочитанный шаблон нельзя утверждать ни что он подходит, ни что
 *    нет.
 *
 * Здесь три правила про это, и все три — про честность, а не про удобство:
 * непрочитанный шаблон нельзя вставить (текста у него нет), его нельзя
 * прятать из выдачи поиска (мы не знаем, подходит ли он) и его нельзя
 * показывать пустой строкой (см. UNREADABLE_TEMPLATE_TEXT).
 *
 * Ни одного импорта: правила проверяются без базы, ключей и отрисовки.
 */

/** Ровно те поля шаблона, которые нужны решениям ниже. */
export type TemplateLike = {
  text: string;
  /** Проставляет слой чтения, увидев непрочитанный столбец. */
  unreadable?: boolean;
};

/** Прочитался ли шаблон. */
export function templateReadable(t: TemplateLike | null | undefined): boolean {
  return !!t && t.unreadable !== true;
}

/**
 * Можно ли вставить шаблон в поле ввода.
 *
 * У непрочитанного шаблона текста нет — есть пустая строка. Вставить её
 * значит выдать пустоту за содержимое, теперь уже в отправляемое сообщение.
 */
export function mayPickTemplate(t: TemplateLike | null | undefined): boolean {
  return templateReadable(t);
}

/**
 * Подходит ли шаблон под запрос.
 *
 * Непрочитанный подходит всегда: спрятать его — значит сказать «такого нет»,
 * а мы этого не знаем. Пусть остаётся на виду с пометкой.
 */
export function templateMatchesQuery(t: TemplateLike, query: string): boolean {
  const needle = query.trim().toLowerCase();
  if (!needle) return true;
  if (!templateReadable(t)) return true;
  return t.text.toLowerCase().includes(needle);
}

/** Отбор списка шаблонов под запрос — по правилу выше. */
export function filterTemplates<T extends TemplateLike>(list: readonly T[], query: string): T[] {
  return list.filter((t) => templateMatchesQuery(t, query));
}
