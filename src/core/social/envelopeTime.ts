/**
 * envelopeTime — время, пришедшее от чужого клиента.
 *
 * v4.32.382. Метку времени в конверте ставит отправитель, а значит, она
 * произвольная: и 1970 год, и 2140-й — такие же законные числа, как настоящее
 * время. Правило «неделя назад — пять минут вперёд» в проекте уже было
 * написано дважды, слово в слово, с одними и теми же числами (обычное
 * сообщение группы и системная строка группы), и оба раза руками. Третье
 * место, где то же самое время уезжает в базу, — joinedAt участника — правила
 * не получило вовсе, хотя пишется из того же конверта.
 *
 * Чем это оборачивалось: по joined_at идёт сортировка состава группы
 * (`ORDER BY role ASC, joined_at ASC`), и любой администратор мог выставить
 * участнику дату вступления в 1970-м, навсегда подняв его в начало списка,
 * или в 2140-м, утопив в конец. Убрать это было нечем: даты вступления
 * интерфейс не показывает и не даёт править.
 *
 * Окна здесь два, потому что величины разные:
 *
 *   clampEnvelopeTs — «когда это произошло». Событие приехало сейчас, значит
 *     неделя назад и пять минут вперёд — с запасом на расхождение часов между
 *     устройствами и на задержку доставки.
 *   clampJoinedAt  — «когда человек вступил». Это может быть и два года
 *     назад — законно; невозможно другое: раньше, чем появилось приложение,
 *     и позже, чем сейчас.
 *
 * Модуль без единого импорта: время из недоверенного источника проверяется
 * тестами без SQLite и транспорта.
 */

/** Насколько старым может быть событие, приехавшее сейчас. */
export const ENVELOPE_MAX_AGE_MS = 7 * 24 * 60 * 60 * 1000;

/** Запас на расхождение часов между устройствами. */
export const ENVELOPE_MAX_SKEW_MS = 5 * 60 * 1000;

/**
 * 2020-01-01 UTC. Раньше этого приложения не существовало, а значит, не
 * существовало и вступления в группу. Граница намеренно грубая: задача не
 * угадать настоящую дату, а отсечь ту, которой не может быть.
 */
export const APP_EPOCH_MS = Date.UTC(2020, 0, 1);

/**
 * Время события из конверта. Не число и не конечное число — берём текущее:
 * отбрасывать из-за этого само событие (бан, выход, переименование) нельзя,
 * оно от этого не перестаёт быть настоящим.
 */
export function clampEnvelopeTs(v: unknown, now: number = Date.now()): number {
  if (typeof v !== 'number' || !Number.isFinite(v)) return now;
  return Math.min(Math.max(v, now - ENVELOPE_MAX_AGE_MS), now + ENVELOPE_MAX_SKEW_MS);
}

/**
 * Дата вступления участника в группу.
 *
 * Ноль и отрицательное — это «не задано» (в таблице у колонки DEFAULT 0), а не
 * «вступил в 1970-м»: подставляем текущее время, как делал прежний
 * `member.joinedAt || Date.now()`.
 *
 * Верхняя граница берётся не меньше нижней — иначе на устройстве с часами,
 * переведёнными в прошлое, окно вывернулось бы наизнанку.
 */
export function clampJoinedAt(v: unknown, now: number = Date.now()): number {
  if (typeof v !== 'number' || !Number.isFinite(v) || v <= 0) return now;
  const upper = Math.max(now + ENVELOPE_MAX_SKEW_MS, APP_EPOCH_MS);
  return Math.min(Math.max(v, APP_EPOCH_MS), upper);
}
