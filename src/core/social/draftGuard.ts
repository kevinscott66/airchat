/**
 * Черновик, который не открылся ключом данных (v4.32.583).
 *
 * Столбец draft_text читался через `decryptAtRestNullable`, а он на неудаче
 * отдаёт пустую строку. Дальше пустота проходила через три проверки на
 * истинность и везде означала «черновика нет»:
 *
 *  • в списке диалогов и групп не появлялась подпись «Черновик: …» — строка
 *    выглядела ровно как переписка без начатого ответа;
 *  • при открытии переписки поле ввода не заполнялось — человек видел пустой
 *    ввод и был уверен, что ничего не начинал;
 *  • а дальше самое неприятное: стоило набрать букву и стереть её, отложенная
 *    запись сохраняла `pending.trim() || null`, то есть NULL — и целый
 *    шифртекст черновика затирался. Человек не знал ни что черновик был, ни
 *    что он только что его удалил.
 *
 * Правило здесь одно и узкое: пустотой поверх непрочитанного столбца не
 * писать. Всё остальное пишется как раньше — новый текст поверх непрочитанного
 * черновика это законная замена, ею его и лечат. Пустой черновик поверх
 * прочитанного столбца — тоже законное «я передумал отвечать», и запрещать его
 * нельзя, иначе черновик станет неудаляемым.
 *
 * Ни одного импорта: правило проверяется без базы, ключей и отрисовки.
 */

/** Решение о записи черновика и причина отказа. */
export type DraftWriteDecision = {
  write: boolean;
  reason: 'ok' | 'clearOverUnreadable';
};

/** Пустой черновик — это null или строка из одних пробелов. */
export function draftIsEmpty(next: string | null | undefined): boolean {
  return next == null || next.trim() === '';
}

/**
 * Можно ли записать в столбец черновика то, что собрались.
 *
 * Отказ ровно один: стереть непрочитанный черновик пустотой. Именно так его и
 * теряли — молча, за одно нажатие на клавиатуре.
 */
export function decideDraftWrite(next: string | null | undefined, unreadable?: boolean): DraftWriteDecision {
  if (unreadable === true && draftIsEmpty(next)) return { write: false, reason: 'clearOverUnreadable' };
  return { write: true, reason: 'ok' };
}

/**
 * Перестал ли столбец быть непрочитанным после нашей записи.
 *
 * Запись непустого текста заменяет столбец нашим шифртекстом — с этого
 * мгновения он читается, и держать признак дальше значило бы запретить
 * человеку стереть уже свой, только что написанный черновик.
 */
export function unreadableAfterWrite(next: string | null | undefined, unreadable?: boolean): boolean {
  if (unreadable !== true) return false;
  return draftIsEmpty(next);
}

/** Есть ли черновик, который можно показать и вернуть в поле ввода. */
export function hasReadableDraft(text: string | null | undefined, unreadable?: boolean): boolean {
  return unreadable !== true && !!text && text.trim() !== '';
}

/** Есть ли черновик, о котором можно сказать только то, что он не прочитался. */
export function draftIsUnreadable(unreadable?: boolean): boolean {
  return unreadable === true;
}
