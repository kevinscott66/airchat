/**
 * Кому принадлежит принятый групповой конверт (v4.32.465).
 *
 * Конверт расшифрован конкретной парой ключей: MessagingService создаётся под
 * неё и пересоздаётся при каждом переключении профиля. Групповые обработчики,
 * однако, спрашивали «кто я» у двух глобальных источников — активного профиля
 * (`profileManager.getActiveProfile()`) и текущего слота SecureStore
 * (`loadKeyPair()`, который `switchProfileInner` перезаписывает при
 * переключении). Между расшифровкой и этим вопросом стоят await'ы: поиск
 * контакта, ECDH, `refreshSubscriptions()` — «это секунды» по комментарию в
 * самом коде. Человек за это время успевает открыть другой аккаунт.
 *
 * Что из этого выходило:
 *  - обычное сообщение группы: `listGroups` спрашивался у чужого профиля,
 *    группа не находилась, сообщение объявлялось `group_msg_unknown_group` и
 *    съедалось навсегда — повторной доставки у конверта нет, в истории группы
 *    остаётся дыра без единого признака;
 *  - приглашение: группа заводилась в чужом аккаунте, а в участники писался
 *    ключ этого чужого аккаунта. Восстановить нельзя: `groups.id` —
 *    первичный ключ, поэтому настоящий адресат эту группу уже не заведёт, а
 *    все её сообщения будут вечно падать в `group_msg_unknown_group`;
 *  - ответ на заявку ('joinres') сравнивался с чужим публичным ключом и молча
 *    выбрасывался — то есть человек оставался ровно в той немоте, ради
 *    устранения которой в v4.32.266 этот ответ и завели.
 *
 * Поэтому «кто я» приходит сюда одним значением от того, кто это точно знает.
 * Публичный ключ выводится из пары, а не передаётся рядом: два поля, которые
 * можно рассогласовать, — это тот же дефект, только записанный руками.
 */

import { Buffer } from 'buffer';

import type { KeyPairBytes } from '../crypto/keyManager';

export type GroupRecipient = {
  /** Профиль, которому принадлежит расшифрованный конверт. */
  readonly pid: number;
  /** Пара ключей, которой он расшифрован. */
  readonly pair: KeyPairBytes;
  /** Свой публичный ключ в base64 — им нас ищут в `group_members`. */
  readonly myPub: string;
};

/** Единственный способ собрать получателя: ключ и его номер профиля вместе. */
export function groupRecipient(pid: number, pair: KeyPairBytes): GroupRecipient {
  return { pid, pair, myPub: Buffer.from(pair.publicKey).toString('base64') };
}
