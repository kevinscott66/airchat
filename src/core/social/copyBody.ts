/**
 * Что из сообщения можно положить в буфер обмена (v4.32.872).
 *
 * Правило это уже существовало — в одном месте из шести. В меню сообщения
 * группы пункт «Копировать» показан под условием `isTextMsg`: не опрос, не
 * голосовое, не документ, не геометка, не системная строка. Остальные пять
 * мест клали в буфер `m.text` как есть и говорили «Скопировано»:
 *
 *   - пачка выделенных в переписке и такая же пачка в группе — там нет вообще
 *     никакой проверки, и голосовое уезжает в буфер строкой `\x01voice:{…}`;
 *   - быстрое меню сообщения в переписке — там условие есть, но одно:
 *     `text.startsWith('\x01')`. Опрос, документ, геометка, контакт, GIF и
 *     одноразовое под него не попадают;
 *   - быстрое меню сообщения в группе — условие шире (опрос, голосовое,
 *     системная строка), но документа, геометки и контакта в нём нет;
 *   - и сам пункт в меню группы копирует `item.text`, то есть у пересылки
 *     выносит наружу служебный байт конверта вместе с именем.
 *
 * Цена одинаковая во всех случаях: человек нажимает «Копировать», видит
 * «Скопировано» и вставляет в чужую переписку `\x06doc:{"path":"/var/mobile/
 * …"}` или `\x07loc:{…}` со своими координатами. Ни увидеть заранее, ни
 * заметить после он этого не может — буфер показывает только то, что вставил.
 *
 * Поэтому правило одно и живёт здесь, рядом с `exportBody`, который решает ту
 * же задачу для выгрузки в файл. Отличие ровно одно и оно намеренное: файл
 * пишет пометку `[Голосовое сообщение]`, потому что строка в нём обязана
 * остаться — иначе реплика пропадёт из документа, который читают как всю
 * переписку. Буфер же ничего не обязан: пометка в скобках, вставленная в
 * чужой чат, выглядит как слова автора. Копировать нечего — значит нечего, и
 * сказать об этом надо прямо.
 *
 * Модуль чистый: ни хранилища, ни RN, ни времени, — как и соседи, у которых
 * он берёт разбор конвертов.
 */
import { FORWARD_PREFIX } from './forwardEnvelope';
import { bodyKind, isControlOnlyText } from './messagePreview';
import { SYS_LINE_PREFIX, sanitizeBodyForRender } from './sysLineGuard';

/** Служебный префикс вложения в теле сообщения. */
const MEDIA_PREFIX = '\x01';

/** Насколько глубоко разворачивается пересылка пересылки. Как в выгрузке. */
const FORWARD_DEPTH_MAX = 8;

/** Ровно те поля, которые проставляет слой чтения. */
export interface CopyableRow {
  text?: string | null;
  unreadable?: boolean;
}

/**
 * Текст сообщения для буфера обмена. `null` — копировать нечего.
 *
 * Порядок проверок тот же, что в выгрузке: сперва «не открылось», иначе
 * пустой текст непрочитанной реплики свалился бы в общий случай.
 */
export function copyableBody(row: CopyableRow | null | undefined): string | null {
  if (row?.unreadable === true) return null;
  return copyableText(typeof row?.text === 'string' ? row.text : '', 0);
}

function copyableText(text: string, depth: number): string | null {
  if (!text) return null;
  // Машинное тело: у него нет текста, который человек видел глазами.
  if (bodyKind(text)) return null;
  if (text.startsWith(MEDIA_PREFIX)) return null;
  // Системную строку рисует само приложение — это не слова автора.
  if (text.startsWith(SYS_LINE_PREFIX)) return null;
  if (text.startsWith(FORWARD_PREFIX)) return copyableForward(text, depth);
  if (isControlOnlyText(text)) return null;
  // Та же чистка, что перед показом: в буфер идёт ровно то, что на экране.
  const clean = sanitizeBodyForRender(text);
  return clean.trim() ? clean : null;
}

/**
 * Пересылка: наружу идёт только тело.
 *
 * Имя автора в буфер не выносится намеренно. В выгрузке оно уместно — файл
 * читают как документ, и строка там устроена как «[время] Имя: текст». Буфер
 * же вставляют в чужую переписку, где подставленное имя читается как часть
 * сообщения того, кто вставил. А вот служебный байт конверта не должен
 * уезжать никуда: до этой версии он уезжал вместе с именем.
 */
function copyableForward(text: string, depth: number): string | null {
  if (depth >= FORWARD_DEPTH_MAX) return null;
  const rest = text.slice(FORWARD_PREFIX.length);
  const nl = rest.indexOf('\n');
  return copyableText(nl < 0 ? rest : rest.slice(nl + 1), depth + 1);
}

/** Сколько реплик легло в буфер и сколько осталось за бортом. */
export interface CopySelection {
  /** Готовая строка. Пустая, когда `copied === 0`. */
  text: string;
  copied: number;
  skipped: number;
}

/** Текст выделенных реплик одной строкой — через пустую строку, как в чате. */
export function copySelection(rows: readonly CopyableRow[]): CopySelection {
  const parts: string[] = [];
  for (const r of rows) {
    const t = copyableBody(r);
    if (t !== null) parts.push(t);
  }
  return { text: parts.join('\n\n'), copied: parts.length, skipped: rows.length - parts.length };
}

/** Отказ: в выделенном не нашлось ни одной строки, которую можно вставить. */
export const COPY_NOTHING_TEXT =
  'Копировать нечего: в выделенном нет текста — голосовые, файлы и метки в буфер не кладутся.';

/**
 * Что сказать после копирования пачки. `null` — обычное «Скопировано».
 *
 * Про пропущенные говорят числом: «скопировано три из семи» и «скопировано
 * всё» — разные новости, и узнать вторую вместо первой человек должен не при
 * вставке в чужую переписку.
 */
export function copySelectionText(sel: CopySelection): string | null {
  if (sel.copied === 0) return COPY_NOTHING_TEXT;
  if (sel.skipped === 0) return null;
  const total = sel.copied + sel.skipped;
  // Согласование по числу пропущенных напрямую, а не через `pluralRu`:
  // подлежащее здесь не само число, а «остальное». Русское правило относит к
  // единственному и 21, и 31 — «остальное» при двадцати одном пропущенном
  // было бы ошибкой.
  const tail = sel.skipped === 1 ? 'остальное в буфер не кладётся' : 'остальные в буфер не кладутся';
  return `Скопировано ${sel.copied} из ${total}: ${tail}`;
}
