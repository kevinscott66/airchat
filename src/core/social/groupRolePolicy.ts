/**
 * groupRolePolicy — роли участника группы: что можно назначить и как это
 * называется на экране.
 *
 * v4.32.257. Роль 'restricted' («только чтение») существовала в типах с самого
 * появления ролей и честно проверялась и на отправке (groupSendPolicy), и на
 * закреплении (groupPinPolicy), — но назначить её было нечем: конверт op:'role'
 * принимал только 'admin' и 'member', команды в интерфейсе не было, а подпись
 * роли в списке участников знала лишь владельца и админа. То есть половина
 * функции была написана и покрыта тестами, а вторая половина отсутствовала, и
 * ограничить болтуна администратор мог только полным исключением из группы.
 *
 * Модуль чистый: тексты системных строк — то, что видит пользователь, и они не
 * должны разъезжаться между отправителем (тост) и получателем (системная
 * строка), как это уже случалось с настройками группы.
 */

import type { MemberRole } from '../storage/local';

/**
 * Порядок ролей в списке участников (v4.32.468).
 *
 * До этого список отдавался с `ORDER BY role ASC` — то есть по алфавиту, и
 * это был порядок не по старшинству, а по первой букве названия роли:
 * admin, banned, member, owner, restricted. Создатель группы оказывался в
 * списке НИЖЕ обычных участников, а «только чтение» — в самом конце, после
 * него. На экране это читалось как «владелец тут кто-то другой»: в группе на
 * десяток человек владельца приходилось искать глазами среди рядовых.
 *
 * Порядок один и живёт здесь: сначала те, у кого больше прав, забаненные —
 * последними (их отдельно отфильтровывают, но если строка всё же попала в
 * список, ей место в конце). Внутри одной роли порядок задаёт дата
 * вступления, чтобы список не прыгал между открытиями.
 */
export const MEMBER_ROLE_ORDER: readonly MemberRole[] = ['owner', 'admin', 'member', 'restricted', 'banned'];

/** Место роли в списке. Неизвестная роль — в конец, но раньше забаненных не лезет. */
export function memberRoleRank(role: string | undefined): number {
  const i = MEMBER_ROLE_ORDER.indexOf(role as MemberRole);
  return i < 0 ? MEMBER_ROLE_ORDER.length : i;
}

/**
 * Тот же порядок для SQL. Собирается из того же списка, а не пишется рядом
 * второй раз: две таблицы старшинства — это две таблицы, которые разъедутся.
 * Подставляются только литералы из MemberRole, никаких данных снаружи.
 */
export const MEMBER_ROLE_ORDER_SQL =
  `CASE role ${MEMBER_ROLE_ORDER.map((r, i) => `WHEN '${r}' THEN ${i}`).join(' ')} ELSE ${MEMBER_ROLE_ORDER.length} END`;

/** Тот же порядок для уже загруженного списка: копия, исходный массив не трогаем. */
export function sortMembersByRole<T extends { role: string; joinedAt: number }>(members: readonly T[]): T[] {
  return [...members].sort((a, b) => memberRoleRank(a.role) - memberRoleRank(b.role) || a.joinedAt - b.joinedAt);
}

/** Роли, которые администратор может назначить конвертом op:'role'. */
export type AssignableRole = 'admin' | 'member' | 'restricted';

export function isAssignableRole(v: unknown): v is AssignableRole {
  return v === 'admin' || v === 'member' || v === 'restricted';
}

/** Подпись роли в списке участников. Для обычного участника — пусто. */
export function roleLabel(role: MemberRole | undefined): string {
  switch (role) {
    case 'owner':
      return 'Владелец';
    case 'admin':
      return 'Админ';
    case 'restricted':
      return 'Только чтение';
    case 'banned':
      return 'Заблокирован';
    default:
      return '';
  }
}

/**
 * Токен палитры, которым красится подпись роли.
 *
 * v4.32.383. Внешний вид роли был описан дважды и по-разному: у подписи под
 * именем в шапке сообщения — своя таблица `{ owner: '#f9a825', admin:
 * colors.primary }` с `textMuted` для всего остального; в списке участников и в
 * карточке участника — `colors.accent` для ЛЮБОЙ роли, кроме 'member'. Отсюда
 * три следствия:
 *
 *   • '#f9a825' мимо палитры — значит, одинаковый в тёмной и светлой темах и
 *     невидимый для themeContrast.test.ts. На белом фоне светлой темы это
 *     1.9:1 при пороге 4.5:1, то есть подпись владельца там попросту не видна;
 *   • `colors.primary` — это токен ЗАЛИВКИ со светлой надписью поверх, а не
 *     цвет текста (см. заголовок theme.ts): на тёмном фоне он даёт 3.7:1;
 *   • звание ('Владелец', 'Админ') и взыскание ('Только чтение',
 *     'Заблокирован') рисовались одинаково, а в списке участников подпись
 *     заблокированного шла фирменным акцентом — тем же цветом, что ссылки и
 *     «прочитано».
 *
 * Возвращается имя токена, а не цвет: модуль остаётся чистым (палитра зависит
 * от темы, а тема — от react-native), правило внешнего вида лежит рядом с
 * правилом подписи, и оба разъехаться уже не могут.
 */
export type RoleToneToken = 'warning' | 'accent' | 'textSecondary' | 'error';

export function roleTone(role: MemberRole | undefined): RoleToneToken | null {
  switch (role) {
    case 'owner':
      return 'warning';
    case 'admin':
      return 'accent';
    // Взыскания — не звания: серый «пониженного» участника и красный
    // заблокированного не должны выглядеть как отличие.
    case 'restricted':
      return 'textSecondary';
    case 'banned':
      return 'error';
    default:
      return null;
  }
}

/**
 * Считается ли участник с этой ролью в «N участников».
 *
 * v4.32.267. Число участников группы не вычислялось НИ РАЗУ: его вели
 * арифметикой ±1 в восьми местах, от четырёх разных оснований —
 * `group.memberCount` (снимок строки, замороженный при открытии экрана),
 * `members.length` (состояние React), `allMembers.length`, `roster.size`.
 * Отсюда:
 *   • два подряд /ban считались от одного и того же устаревшего снимка, и
 *     второй просто затирал первый — счётчик уезжал навсегда, пересчитать его
 *     было нечем;
 *   • повторный конверт ban (второй администратор забанил того же человека)
 *     вычитал второй раз;
 *   • упреждающий бан того, кого в группе нет, вычитал из числа участников
 *     того, кто в нём никогда не учитывался;
 *   • одобрение заявки считало от React-состояния, хотя строкой выше уже был
 *     свежий список из БД.
 * Правда — таблица group_members, и она всегда под рукой. Правило «кто
 * считается» живёт здесь, чтобы у пересчёта и у списка на экране оно было
 * одно (забаненные остаются строками — это чёрный список группы, но не
 * участники).
 */
export function countsAsMember(role: MemberRole | undefined | null): boolean {
  return role !== 'banned';
}

/** Сколько участников в списке из group_members. */
export function countMembers(rows: ReadonlyArray<{ role?: MemberRole | null }>): number {
  let n = 0;
  for (const r of rows) if (countsAsMember(r.role)) n += 1;
  return n;
}

/**
 * Роль уже такая — что сказать вместо смены. null означает «менять есть что».
 *
 * v4.32.514. Приёмник конверта op:'role' идемпотентен с самого начала:
 * `if (!target || target.role === env.role) return true` — повтор он
 * выбрасывает молча и правильно. Отправитель этого вопроса не задавал:
 * /promote на том, кто уже администратор, и /demote на обычном участнике
 * писали свою системную строку, показывали тост и рассылали конверт, который
 * все получатели отбрасывали.
 *
 * Получалось расхождение историй на ровном месте: у администратора в группе
 * стоит «X снят(а) с должности администратора», у остальных этой строки нет, и
 * появиться ей неоткуда — конверт повторной отправки не имеет. Для /demote
 * текст к тому же был ложью дважды: снимали с должности того, кто её не
 * занимал.
 *
 * У /mute такая проверка была написана прямо в обработчике команды —
 * единственная из трёх. Правило одно на всех и живёт рядом с текстом самой
 * смены роли: разъехавшись, они дадут «уже ограничен» на одном экране и
 * «ограничен» на другом.
 */
export function roleChangeNoopText(
  next: AssignableRole,
  role: MemberRole | undefined,
  label: string
): string | null {
  if (role !== next) return null;
  switch (next) {
    case 'admin':
      return `${label} уже администратор.`;
    case 'restricted':
      return `${label} уже ограничен(а) в отправке сообщений.`;
    default:
      // 'member' — это отсутствие и прав, и взыскания сразу, поэтому одним
      // «не администратор» не отделаться: сюда приходит и /demote, и снятие
      // ограничения.
      return `${label} — обычный участник: ни прав администратора, ни ограничений.`;
  }
}

/**
 * Системная строка о смене роли. `prev` нужен, потому что 'member' — это и
 * «снят с админов», и «снято ограничение»: без прежней роли обе ситуации
 * описывались бы одним и тем же неверным текстом.
 */
export function roleChangeSysText(
  next: AssignableRole,
  prev: MemberRole | undefined,
  label: string,
  isMe: boolean
): string {
  if (next === 'admin') {
    // Роль одна на человека, поэтому назначение админом снимает ограничение —
    // о чём надо сказать вслух: иначе тот, кого только что «замьютили»,
    // молча получает и права, и право писать обратно.
    if (prev === 'restricted') {
      return isMe
        ? 'Ограничение снято, вы назначены администратором'
        : `${label}: ограничение снято, назначен(а) администратором`;
    }
    return isMe ? 'Вы назначены администратором' : `${label} назначен(а) администратором`;
  }
  if (next === 'restricted') {
    // Обратная сторона той же одной роли: ограничить администратора значит
    // сперва разжаловать его. Раньше строка сообщала только об ограничении, и
    // потеря админских прав оставалась незамеченной всеми, включая его самого.
    if (prev === 'admin') {
      return isMe
        ? 'С вас сняты права администратора, отправка сообщений ограничена'
        : `${label} снят(а) с администраторов и ограничен(а) в отправке сообщений`;
    }
    return isMe ? 'Вам ограничена отправка сообщений' : `${label} ограничен(а) в отправке сообщений`;
  }
  if (prev === 'restricted') {
    return isMe ? 'Ограничение снято, вы снова можете писать' : `${label} снова может писать`;
  }
  return isMe ? 'С вас сняты права администратора' : `${label} снят(а) с должности администратора`;
}
