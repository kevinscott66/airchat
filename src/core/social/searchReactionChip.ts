/**
 * Плашка реакций в строке поиска (v4.32.605).
 *
 * Дефект. Обе выдачи поиска — по личным чатам и по группам — строили плашку
 * одинаково: `Object.keys(parseReactionMap(r.message.reactions)).join('')`.
 * У сообщения, чей столбец `reactions` не открыл ключ этого устройства, в
 * поле приходит пустая строка (с v4.32.544 туда же запрещено и писать), из
 * неё выходит пустая карта, и плашка не рисуется вовсе. На экране это
 * неотличимо от «на это сообщение никто не реагировал» — та же подмена, что
 * v4.32.600 убрала в пузыре сообщения, но в поиске она осталась.
 *
 * Почему пометка короткая. В строке выдачи плашка стоит между именем и
 * временем, и полная фраза выдавила бы оба. Знак берёт на себя роль «здесь
 * что-то не прочиталось», а полная фраза уходит в подпись для озвучки, —
 * так строка остаётся читаемой и не врёт.
 *
 * Модуль чистый: единственный импорт — такой же чистый разбор карты.
 */
import { parseReactionMap } from './reactionMapPolicy';

/**
 * Знак вместо плашки, когда столбец не прочитан.
 *
 * Рядом обязана идти подпись `UNREADABLE_REACTIONS_TEXT` — знак сам по себе
 * ничего не сообщает тому, кто слушает экран.
 */
export const UNREADABLE_REACTION_MARK = '\u26a0';

/** Три исхода, а не два: «нет реакций» и «не прочитались» — разные вещи. */
export type SearchReactionChip =
  | { kind: 'none' }
  | { kind: 'emoji'; text: string }
  | { kind: 'unreadable' };

/**
 * Что рисовать в строке выдачи вместо реакций.
 *
 * Порядок проверок именно такой: сперва «не прочиталось», иначе пустая карта
 * непрочитанного столбца свалилась бы в `none` — ровно тем дефектом, от
 * которого решение и заводится.
 */
export function searchReactionChip(
  reactions: string | null | undefined,
  unreadable: boolean | undefined
): SearchReactionChip {
  if (unreadable === true) return { kind: 'unreadable' };
  const text = Object.keys(parseReactionMap(reactions)).join('');
  return text.length > 0 ? { kind: 'emoji', text } : { kind: 'none' };
}
