/**
 * Код безопасности переписки: строка, которую двое сверяют голосом.
 *
 * v4.32.574: вынесен из карточки контакта в ядро. Карточка была одна, стала
 * частью общего профиля, а правило про длину кода — не про разметку и должно
 * жить там, где его видно проверкам.
 */
import { publicKeyFromB64 } from '../crypto/pubKeyFormat';

/** Сколько байтов ключей участвует в коде безопасности. */
export const SAFETY_CODE_BYTES = 12;

/** Прочерк вместо кода: показывать нечего, и это сказано знаком, а не пустотой. */
export const SAFETY_CODE_UNKNOWN = '—';

/**
 * Код безопасности из двух открытых ключей: XOR первых 12 байт, шестнадцатерично.
 *
 * v4.32.427. Раньше длина кода бралась как `Math.min(a.length, b.length, 12)`,
 * то есть КОРОТКИЙ ключ УКОРАЧИВАЛ КОД. Строка контакта, испорченная до десяти
 * байт, давала не отказ, а код из десяти байт — короче настоящего, но с виду
 * такой же. Люди сверяют этот код голосом именно затем, чтобы поймать подмену;
 * молча ослаблять его на порченых данных — ровно обратное тому, зачем он есть.
 * Код показывается только когда оба ключа настоящие, иначе — прочерк.
 */
export function computeSafetyCode(aPubB64: string, bPubB64: string): string {
  const a = publicKeyFromB64(aPubB64);
  const b = publicKeyFromB64(bPubB64);
  if (!a || !b) return SAFETY_CODE_UNKNOWN;
  const xored: number[] = [];
  for (let i = 0; i < SAFETY_CODE_BYTES; i++) xored.push((a[i] ^ b[i]) & 0xff);
  // Группами по четыре знака: так строку диктуют вслух и так её сверяют.
  const hex = xored.map((v) => v.toString(16).padStart(2, '0')).join('');
  return hex.match(/.{1,4}/g)?.join(' ') ?? hex;
}
