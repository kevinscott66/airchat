/**
 * Операция из двух половин: у себя и у собеседника (v4.32.555).
 *
 * «Удалить у всех» и «Изменить у всех» состоят из двух разных действий:
 * правки собственной строки в своей базе и служебного конверта собеседнику.
 * Первое — локальное и от сети не зависит; второе зависит целиком.
 *
 * В v4.32.431 порядок уже выправляли: до неё удаление у себя стояло после
 * сетевой части и при неудаче не происходило вовсе — человек нажимал
 * «Удалить», меню закрывалось, сообщение оставалось на месте. Тогда же завели
 * правило: у себя выполняется всегда, а человеку сообщается ровно про вторую
 * половину.
 *
 * В v4.32.550 перед обеими операциями появилась проверка сети, и правило
 * сломалось обратно: без интернета локальная половина снова не выполнялась, а
 * текст, написанный в расчёте на неё, продолжал утверждать «Сообщение удалено
 * у вас» — прямая неправда, сообщение оставалось на экране.
 *
 * Чтобы это не собиралось заново, исход перестал быть словом про одну лишь
 * сеть. Их три, и каждое честно называет обе половины:
 *  - `both-sides`      — сделано у себя, доставлено собеседнику;
 *  - `your-side-only`  — сделано у себя, до собеседника не дошло;
 *  - `nothing-happened` — не вышло даже у себя.
 *
 * Тип обязывает вызывающего различать второе и третье: именно их смешение и
 * превращало отказ в ложное «удалено у вас».
 */

/** Судьба второй половины — служебного конверта собеседнику. */
export type PeerDelivery =
  /** Ушло: подтвердил IPFS или прямой транспорт. */
  | 'sent'
  /** Не доставим: нет канала, нет сети или ни одна ступень фолбэка не сработала. */
  | 'unreachable';

/**
 * Что в итоге произошло с обеими половинами.
 *
 * v4.32.607: исходов стало четыре. В «Заметках для себя» собеседника нет —
 * переписка ведётся с собственным ключом, — и вторая половина не просто не
 * доставлена, её не существует. Прежде этот случай попадал в
 * `your-side-only`, и человек, поправивший свою же заметку, читал «собеседнику
 * отправить не удалось»: сообщение про несуществующего адресата, из которого
 * следует, что правка где-то не применилась.
 */
export type TwoSidedOutcome = 'both-sides' | 'your-side-only' | 'no-peer-half' | 'nothing-happened';

/**
 * Собрать исход из двух половин. Если локальная не удалась, судьба сетевой уже
 * не важна: показывать «удалено у вас» нельзя ни при каком ответе сети.
 */
export function combineHalves(localDone: boolean, peer: PeerDelivery): TwoSidedOutcome {
  if (!localDone) return 'nothing-happened';
  return peer === 'sent' ? 'both-sides' : 'your-side-only';
}

/**
 * Исход операции, у которой второй половины нет: переписка с самим собой.
 * Локальная половина здесь — вся операция целиком.
 */
export function selfChatOutcome(localDone: boolean): TwoSidedOutcome {
  return localDone ? 'no-peer-half' : 'nothing-happened';
}

/** Выполнена ли половина у себя — единственное, что человек видит сразу. */
export function localHalfDone(outcome: TwoSidedOutcome): boolean {
  return outcome !== 'nothing-happened';
}

/** Дошла ли половина до собеседника. */
export function peerHalfDone(outcome: TwoSidedOutcome): boolean {
  return outcome === 'both-sides';
}

/** Была ли вторая половина вообще. `false` — переписка с самим собой. */
export function hasPeerHalf(outcome: TwoSidedOutcome): boolean {
  return outcome !== 'no-peer-half';
}

/**
 * Стоит ли пробовать сетевую половину. Локальная к этому моменту уже сделана:
 * без неё спрашивать сеть бессмысленно — отправлять нечего.
 */
export function shouldTryPeerHalf(localDone: boolean, online: boolean): boolean {
  return localDone && online;
}
