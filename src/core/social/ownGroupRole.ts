/**
 * ownGroupRole — своя роль в группе берётся оттуда же, откуда чужая.
 *
 * v4.32.512. У строки группы есть колонка `is_admin` — «я здесь
 * администратор». Пишет её ровно одно место: `createGroup`, в момент
 * появления группы. Дальше она не менялась НИКОГДА — ни когда меня повышают,
 * ни когда понижают, ни когда банят. А роли живут в другой таблице,
 * `group_members`, и вот они меняются постоянно: управляющий конверт 'role'
 * зовёт `updateGroupMemberRole`, и на этом всё.
 *
 * Две записи об одном и том же разъезжались в обе стороны, и каждая сторона
 * ломалась по-своему.
 *
 * Повысили. В `group_members` роль 'admin', в `groups.is_admin` по-прежнему 0.
 * Системная строка «теперь администратор» написана, подпись в списке
 * участников стоит — а прав нет: заявки на вступление такой администратор
 * отбрасывал молча (`handleIncomingGroupJoinRequest`), пересказ вступивших
 * остальным не делал, отзыв ссылки не принимал, отказ по отозванной ссылке не
 * отправлял. Со стороны заявителя это выглядит как «меня никто не замечает»:
 * заявка ушла, ответа нет, спросить некого.
 *
 * Понизили. Зеркально и хуже: в `group_members` роль 'member', в
 * `groups.is_admin` осталась 1. Экран группы читал флаг ПЕРВЫМ
 * (`if (amAdmin) return 'admin'`), то есть строка в таблице участников на него
 * не влияла вовсе. Понизивший — и даже забаненный — видел у себя полный набор
 * админских кнопок, нажимал их, получал системную строку у себя и ничего у
 * остальных: его конверты отбивает `canModerate` на приёме, потому что там
 * роль спрашивают у `group_members`. Ровно та «чистая имитация прав», которую
 * v4.32.231 убрала для вступивших по ссылке, — только приходящая позже.
 *
 * Здесь одно правило: своя роль — это своя строка в `group_members`, та же
 * таблица и то же поле, по которым нас судят все остальные участники.
 * `groups.is_admin` остаётся запасным ответом на единственный случай, когда
 * своей строки ещё нет: список участников не дочитан с диска (экран рисуется
 * до первого запроса) или группа только что создана. Ошибиться этот запас не
 * даёт: у создателя флаг 1 и роль 'owner', у вступившего по ссылке 0 и
 * 'member' — они совпадают, пока их не разведёт первое же повышение.
 *
 * Модуль без единого импорта, кроме типа роли: решение о правах обязано
 * проверяться без SQLite и без рендера, и вызываться одинаково на приёме
 * конверта и на экране. Расхождение этих двух мест и есть весь описанный выше
 * дефект.
 */

import type { SendRole } from './groupSendPolicy';

/** Строка участника в том виде, в каком её отдаёт `group_members`. */
export type MemberLike = { peerPubB64: string; role: string };

/**
 * Роль даёт админские права? Тот же ответ, что и внутри groupSendPolicy: для
 * прав владелец и администратор равны, различает их только модерация
 * (чужого администратора вправе тронуть лишь владелец).
 */
export function isAdminRole(role: SendRole | null | undefined): boolean {
  return role === 'owner' || role === 'admin';
}

/**
 * Своя роль в группе.
 *
 * Порядок ответов — это и есть правка v4.32.512: сначала строка участника,
 * и только при её отсутствии — флаг `groups.is_admin`. Раньше флаг стоял
 * первым и перебивал строку, из-за чего понижение и бан не действовали на
 * своём же экране.
 */
export function ownGroupRole(
  members: MemberLike[],
  myPubB64: string | null | undefined,
  storedIsAdmin: boolean
): SendRole {
  const row = myPubB64 ? members.find((m) => m.peerPubB64 === myPubB64)?.role : undefined;
  if (row) return row as SendRole;
  return storedIsAdmin ? 'admin' : 'member';
}

/**
 * Роль, в которой оказывается адресат управляющего конверта ПОСЛЕ его
 * применения. `undefined` — операция роли не меняет и флаг трогать не нужно;
 * `null` — участника в группе больше нет.
 *
 * Нужна ровно для того, чтобы держать `groups.is_admin` в согласии с
 * `group_members` без второго запроса к базе: обработчик уже знает и операцию,
 * и что она про нас.
 */
export function roleAfterCtl(op: string, role?: string | null): SendRole | null | undefined {
  switch (op) {
    case 'role':
      // Роль из конверта уже проверена разбором: значения вне перечисления
      // до этого места не доходят.
      return role ? (role as SendRole) : undefined;
    case 'ban':
      return 'banned';
    case 'unban':
      return 'member';
    case 'kick':
      return null;
    default:
      return undefined;
  }
}
