/**
 * Разрешение отдавать текст переписки стороннему переводчику (v4.32.486).
 *
 * Проверка «включён ли облачный перевод» стояла в четырёх местах — в личной
 * переписке и в группах, на авто- и на ручном пути, — и все четыре читали
 * запись `allow_cloud_translate`. Записывать её было НЕКОМУ: переключателя, на
 * который ссылались и комментарии, и текст ошибки, в настройках не было.
 * Поэтому перевод в переписке не работал никогда, а человеку предлагалось
 * включить его там, где включать нечего.
 *
 * В ленте при этом действовало второе, отдельное согласие
 * (`feed_translate_consent`): диалог на один тап, после которого текст
 * публикаций уходил тому же сервису. То есть одно и то же действие с одними и
 * теми же последствиями с одного экрана разрешалось одним тапом, а с другого
 * запрещалось навсегда.
 *
 * Здесь оно одно и лежит среди решений о приватности — то есть у каждого
 * аккаунта своё. Обе прежние записи были общими на устройство: аккаунт,
 * заведённый ради того, чтобы его переписка никуда не уходила, наследовал бы
 * чужое согласие, ни разу его не дав.
 *
 * Старое согласие ленты намеренно НЕ переносится. Оно было дано на публикации
 * в ленте — на текст, который человек и так опубликовал; распространять его
 * на личную переписку значило бы расширить согласие за него.
 */
import { privacyPrefSet, privacyPrefTryBoolFor } from '../settings/privacyPrefs';
import { profileManager } from '../identity/profileManager';

/** Имя решения; оно же в PRIVACY_PREF_KEYS — уборка профиля идёт по списку. */
export const CLOUD_TRANSLATE_KEY = 'privacy_allow_cloud_translate' as const;

/** Один и тот же ответ на всех экранах — и он называет, где включить. */
export const CLOUD_TRANSLATE_OFF_MESSAGE =
  'Облачный перевод выключен — включите его в «Настройки → Приватность → Сообщения»';

/**
 * Разрешено ли отдавать текст наружу для названного аккаунта.
 *
 * Не смогли прочитать — «нельзя». Неотправленный текст можно отправить
 * позже, отправленный не отозвать: он уже в журналах сервиса и любого прокси
 * по дороге.
 */
export async function cloudTranslateAllowedFor(profileId: number): Promise<boolean> {
  return (await privacyPrefTryBoolFor(profileId, CLOUD_TRANSLATE_KEY)) === true;
}

/** То же для аккаунта на экране. */
export async function cloudTranslateAllowed(): Promise<boolean> {
  return cloudTranslateAllowedFor(profileManager.getActiveProfile()?.id ?? 1);
}

/** Записать решение аккаунту на экране: его принимает человек, глядя в экран. */
export async function setCloudTranslateAllowed(allowed: boolean): Promise<void> {
  await privacyPrefSet(CLOUD_TRANSLATE_KEY, String(allowed));
}
