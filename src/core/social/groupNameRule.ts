/**
 * groupNameRule — название и описание СВОЕЙ группы: одно правило на всех.
 *
 * v4.32.379. Чужие название и описание чистятся на приёме
 * (groupControlEnvelope, op 'meta' и 'invite'), а своё, набранное в редакторе,
 * получало `.trim()` и `.slice()` — и то не везде. Числа при этом были
 * выписаны прямо в экранах: 128 в одном месте, 512 в другом, а при создании
 * группы предела не было вовсе.
 *
 * Разница не косметическая. Описание группы рисуется обычным <Text> в её
 * карточке — ровно то поле, ради которого писалась sanitizeParagraphText
 * (v4.32.373): пятьсот переводов строки растягивают карточку на весь экран, а
 * U+202E разворачивает текст. На чужом описании это чинили, на своём — нет,
 * поэтому у автора его собственная группа оставалась и растянутой, и
 * перевёрнутой. С названием хуже: разбор конверта-приглашения и разбор ссылки
 * требуют непустого названия и отбрасывают то, где его нет, — а набрать
 * название из одних невидимых символов редактор позволял.
 *
 * Модуль зависит только от sysLineGuard: правило нужно и кодеку конвертов, и
 * сборщику ссылки, и двум экранам, и тащить ради него весь граф кодека незачем.
 */
import { sanitizeDisplayName, sanitizeParagraphText } from './sysLineGuard';

/**
 * Пределы своего названия и описания. Те же числа, что у разбора конверта, —
 * раньше их знали два .slice() в двух разных экранах.
 */
export const OWN_GROUP_NAME_MAX = 128;
export const OWN_GROUP_DESC_MAX = 512;

/**
 * Название группы, которого не может быть.
 *
 * Названия, набранные до v4.32.379, чистку не проходили, и среди них могут
 * лежать пустые по существу. Молча выдать по такой группе ссылку или
 * приглашение, которые не примет ни один получатель, хуже, чем подставить
 * общее слово.
 */
export const FALLBACK_GROUP_NAME = 'Группа';

/**
 * Своё название перед записью — тем же правилом, что и чужое на приёме.
 *
 * Пустая строка значит «названия нет», и вызывающий обязан это заметить:
 * группы без названия в приложении не существует, редактор на пустом поле
 * отказывается сохранять.
 */
export function normalizeOwnGroupName(v: unknown): string {
  return sanitizeDisplayName(v, OWN_GROUP_NAME_MAX) ?? '';
}

/**
 * Своё описание перед записью — тем же правилом, что и чужое на приёме.
 * Пустая строка здесь, в отличие от названия, законна: это «описания нет».
 */
export function normalizeOwnGroupDescription(v: unknown): string {
  return sanitizeParagraphText(v, OWN_GROUP_DESC_MAX) ?? '';
}
