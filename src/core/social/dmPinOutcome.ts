/**
 * Чем закончилась отправка закрепления собеседнику — словами (v4.32.454).
 *
 * Закрепление в личке живёт сразу в двух шапках: моей и его. Отправка уходила
 * как `void sendDmPin(...)`, отказ падал в лог, а повторной отправки у
 * служебного конверта нет — «не ушло» значит «не уйдёт». Получалось молчаливое
 * расхождение: у меня в шапке висит закреплённое, у собеседника пусто, и оба
 * уверены, что видят одно и то же. Особенно неприятно при «Открепить всё»:
 * человек убирает из шапки то, что не хочет видеть на экране, а у второго это
 * остаётся висеть.
 *
 * Текст называет не «ошибку отправки», а расхождение: что именно теперь
 * по-разному у нас двоих — единственное, чего не видно на своём экране.
 */

import type { FanoutResult } from './controlFanout';
import { fanoutReasonText } from './controlFanout';

/**
 * Что не доехало. Открепление — не «закрепление наоборот»: у него расходится
 * ровно противоположное, и общей фразой оба не описать.
 */
export type DmPinOp = 'pin' | 'unpin' | 'clear';

/**
 * Итог вместе с операцией, которой он принадлежит. Операция вшита в итог, а не
 * передаётся отдельно в текстовку: иначе отказ открепления можно по недосмотру
 * объявить отказом закрепления — а это противоположные по смыслу фразы.
 */
export type DmPinOutcome = { op: DmPinOp } & FanoutResult;

/** Record по всем операциям: новая не соберётся, пока ей не написали фразу. */
const DIVERGENCE: Record<DmPinOp, string> = {
  pin: 'Сообщение закреплено только у вас — у собеседника в шапке чата ничего не появилось',
  unpin: 'Сообщение откреплено только у вас — у собеседника оно осталось в шапке',
  clear: 'Закреплённые убраны только у вас — у собеседника они остались в шапке',
};

/** Текст расхождения, либо null — если конверт приняли к отправке. */
export function dmPinProblem(outcome: DmPinOutcome): string | null {
  if (outcome.sent) return null;
  return `${DIVERGENCE[outcome.op]} (${fanoutReasonText(outcome.reason, 'dm')}).`;
}
