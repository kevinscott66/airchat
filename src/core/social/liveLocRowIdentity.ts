/**
 * liveLocRowIdentity — какой строке в переписке принадлежит посылка живой
 * геолокации и стоит ли её применять.
 *
 * v4.32.568. Живая геолокация — это ОДНА строка в переписке, которая
 * обновляется каждые полминуты, пока идёт сессия. Так она и задумана: пузырь
 * с картой, зелёная плашка LIVE, точка ползёт. На деле каждая посылка
 * заводила новую строку — с обеих сторон.
 *
 * У получателя строка складывалась по номеру конверта (`em.messageId`), а
 * отправитель берёт под каждую посылку свежий `uuidv4()`. Ветка «обновить на
 * месте» в handleDecrypted искала прежнюю строку по тому же номеру конверта —
 * то есть по номеру, которого в базе быть не могло: проверка чуть выше уже
 * отбрасывала конверт, если строка с таким номером существовала
 * (`chatMessageExists`, ровно тот же SQL). Ветка была недостижима целиком,
 * вместе с проверкой авторства из v4.32.239.
 *
 * Что видел человек: за восьмичасовую трансляцию — около девятисот шестидесяти
 * пузырей подряд, столько же прибавлений к счётчику непрочитанного и столько
 * же всплывающих плашек внутри приложения. Переписка становилась непригодной.
 *
 * У отправителя то же самое своим путём: экран честно кладёт свою строку под
 * номером сессии (`payload.liveId`), а следом `sendMessage` сохранял ВТОРУЮ,
 * под номером конверта. Одна сессия — одна строка от экрана и девятьсот
 * шестьдесят от отправки.
 *
 * Правило, которое всё это чинит, помещается в одну строку: **номер строки
 * живой геолокации — это номер сессии, а не номер конверта.** Тогда первая
 * посылка создаёт строку, а каждая следующая находит её и обновляет текст;
 * счётчик непрочитанного и плашка срабатывают ровно один раз, на первой.
 *
 * Номер конверта при этом остаётся своим у каждой посылки — он нужен защите
 * от повторов и разбору маршрутов доставки. Разделять эти два номера
 * приходится именно потому, что раньше они были одним.
 *
 * Отдельно — устаревшая посылка. Раз номер конверта у каждого такта свой,
 * прежняя защита от повтора живую геолокацию больше не прикрывает: чужой
 * ретранслятор мог бы придержать посылку и подсунуть её позже, отодвинув
 * метку на карте назад, к уже пройденному месту. Поэтому применяется только
 * посылка не старше уже показанной — по времени отправки `ts`, которое едет
 * внутри шифротекста с v4.32.563.
 *
 * Модуль без импортов: правило проверяется отдельно от базы, шифрования и
 * разбора конвертов.
 */

/** Номер сессии длиннее этого не бывает — тот же потолок, что в parseLiveLoc. */
export const MAX_LIVE_ID_LEN = 128;

/**
 * То, по чему сравниваются две посылки одной сессии. Поле необязательное:
 * отправитель до v4.32.563 его не клал, и придумывать за него время нельзя.
 */
export type LiveLocStamp = { readonly ts?: number };

export type LiveLocUpdateVerdict = { kind: 'apply' } | { kind: 'skip'; code: 'stale' };

/**
 * Номер строки в переписке для входящей или исходящей посылки.
 *
 * Живая геолокация ложится под номер сессии, всё остальное — под номер
 * конверта. Пустой или неправдоподобно длинный номер сессии до сюда дойти не
 * должен (его отбрасывает parseLiveLoc), но если дойдёт — строка получит
 * номер конверта, то есть поведение вернётся к прежнему, а не сломается.
 */
export function chatRowIdForLiveLoc(
  liveId: string | null | undefined,
  envelopeMessageId: string
): string {
  if (typeof liveId !== 'string') return envelopeMessageId;
  if (liveId.length === 0 || liveId.length > MAX_LIVE_ID_LEN) return envelopeMessageId;
  return liveId;
}

/**
 * Применять ли пришедшую посылку поверх уже показанной.
 *
 * Без времени отправки хоть с одной стороны сравнивать нечего — применяем:
 * молча выбросить посылку старого отправителя значило бы, что у него живая
 * геолокация не двигается вовсе.
 */
export function decideLiveLocUpdate(
  prev: LiveLocStamp | null | undefined,
  next: LiveLocStamp
): LiveLocUpdateVerdict {
  const before = prev?.ts;
  const after = next.ts;
  if (typeof before !== 'number' || !Number.isFinite(before)) return { kind: 'apply' };
  if (typeof after !== 'number' || !Number.isFinite(after)) return { kind: 'apply' };
  // Равенство — это повтор той же посылки: применить её ещё раз безвредно
  // (текст тот же), а отбрасывать незачем.
  if (after < before) return { kind: 'skip', code: 'stale' };
  return { kind: 'apply' };
}
