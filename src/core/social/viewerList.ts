/**
 * Список ключей, который может не открыться: кто посмотрел и кто прочитал
 * (v4.32.590, обобщён в v4.32.591).
 *
 * Таких списков в базе два, и устроены они одинаково: `stories.viewed_by` —
 * кто посмотрел сторис, `group_messages.seen_by` — кто прочитал сообщение в
 * группе. Оба это JSON-массивы ключей, зашифрованные ключом данных, и у обоих
 * одна и та же история.
 *
 * Запись давно осторожна: с v4.32.544 ни `markStoryViewed`, ни
 * `markGroupMessageSeen` не переписывают столбец, который не открылся, — иначе
 * один сегодняшний читатель стёр бы всех вчерашних. А чтение оставалось
 * двухсостоянийным: `decryptAtRestNullable` при неудаче отдаёт пустую строку,
 * `JSON.parse('')` бросает, пустой `catch` глотает — и наверх уходит пустой
 * массив, то есть «никто не смотрел» и «никто не прочитал».
 *
 * Из пустого массива следуют две неправды. Своя сторис показывает «0
 * просмотров», своё сообщение в группе — «Никто ещё не прочитал», при том что
 * и просмотры, и прочтения записаны и лежат рядом. И, что хуже, чужая сторис
 * считается непрочитанной: кружок зажигается по правилу
 * `!viewers.includes(me)`, а в пустом массиве нет никого. Кружок горит,
 * человек открывает сторис, `markStoryViewed` отказывается писать в
 * непрочитанный столбец — и кружок горит снова. Навсегда, пока сторис не
 * истечёт.
 *
 * Отсюда решение про кружок: при неизвестном списке он не горит. Смысл
 * значка — «посмотри, и он погаснет»; значок, который не гаснет ни от чего,
 * не сообщает ничего, а только приучает не обращать на него внимания.
 * Пропущенная новая сторис при этом никуда не девается — она в той же ленте,
 * на том же месте.
 *
 * Заодно здесь собран разбор JSON, выписанный до этого четырьмя одинаковыми
 * копиями — дважды в `StoriesRow`, в `listGroupMessages` и в обоих путях
 * записи: `JSON.parse`, `Array.isArray`, отсев не-строк, пустой `catch`.
 *
 * Модуль без единого импорта: правило проверяется без базы, без ключей и без
 * отрисовки.
 */

/**
 * Список посмотревших и признак того, что он вообще неизвестен.
 *
 * Пустой список и неизвестный список — разные вещи, и вся суть модуля в том,
 * чтобы их не путать: у первого «никто не смотрел» — факт, у второго это
 * догадка, которую нам нечем подтвердить.
 */
export type ViewerList = {
  viewers: string[];
  unknown: boolean;
};

/**
 * Разобрать столбец `viewed_by`.
 *
 * `unreadable` приходит от слоя чтения — он один знает, был ли там непустой
 * шифртекст, который не открылся. Отличить это по самой строке нельзя: и у
 * «столбца нет», и у «столбец не открылся» на руках оказывается пустота.
 */
export function parseViewerList(raw: string | null | undefined, unreadable?: boolean): ViewerList {
  if (unreadable === true) return { viewers: [], unknown: true };
  if (!raw) return { viewers: [], unknown: false };
  try {
    const parsed: unknown = JSON.parse(raw);
    if (!Array.isArray(parsed)) return { viewers: [], unknown: false };
    return { viewers: parsed.filter((x): x is string => typeof x === 'string'), unknown: false };
  } catch {
    // Строка есть, но это не JSON: столбец испорчен, а не зашифрован чужим
    // ключом. Числа посмотревших у нас нет ровно так же.
    return { viewers: [], unknown: true };
  }
}

/** Можно ли показывать число посмотревших как число. */
export function mayCountViewers(list: ViewerList): boolean {
  return !list.unknown;
}

/** Сколько человек посмотрело — только когда это известно. */
export function viewerCount(list: ViewerList): number {
  return list.unknown ? 0 : list.viewers.length;
}

/**
 * Зажигать ли кружок «новая сторис».
 *
 * Неизвестный список — не «не смотрел»: значок, который нечем погасить, хуже
 * отсутствующего.
 */
export function storyRingUnread(list: ViewerList, myPubB64: string): boolean {
  if (list.unknown) return false;
  return !list.viewers.includes(myPubB64);
}
