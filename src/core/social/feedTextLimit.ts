/**
 * Потолки длины у ленты — одно правило на отправку и на приём (v4.32.527).
 *
 * Та же история, что была у личных сообщений в v4.32.508, только разъехалось
 * сильнее. Одни и те же величины были выписаны и константами, и числами прямо
 * в разборе входящего конверта — и разошлись в обе стороны сразу:
 *
 *  - пост: публиковать разрешено 10 000 символов, а принималось 8 000. Автор
 *    писал длинный пост, отправка его пропускала, и у КАЖДОГО получателя он
 *    молча терял хвост. Автор об этом не узнавал никогда: у себя он видел свой
 *    полный текст;
 *  - комментарий: писать разрешено 2 000, а принималось 8 000 — вчетверо
 *    больше, чем вообще может отправить честный клиент. Ровно этот запас и
 *    оставался чужому, кто конверт собирает руками;
 *  - правка поста (feed_edit): не проверялась ничем. Ни типа, ни длины — текст
 *    из реле шёл прямо в UPDATE. Транспортный потолок оставляет на конверт
 *    около двух мегабайт, а у каждой правки свой ts, то есть свой ключ
 *    дедупликации: одну и ту же строку можно раздувать повторно. Если же
 *    newText приходил не строкой, шифрование при записи бросало, и внешний
 *    catch это глотал — правка молча не применялась.
 *
 * Правило здесь одно и на всех: столько символов текст ленты может занимать,
 * и ни приём, ни отправка не решают этот вопрос сами.
 *
 * Модуль без импортов.
 */

/**
 * Десять тысяч символов у поста. Столько разрешает форма публикации, столько
 * же обязан принимать получатель — иначе собственный текст автора обрезается
 * по дороге.
 */
export const FEED_POST_MAX_CHARS = 10_000;

/** Две тысячи у комментария — столько же, сколько принимает форма ответа. */
export const FEED_COMMENT_MAX_CHARS = 2_000;

/** Имя автора рядом с постом или комментарием: подпись, а не текст. */
export const FEED_AUTHOR_NAME_MAX_CHARS = 128;

/**
 * Обрезать текст поста по потолку.
 *
 * Не строка — `null`. Для поста это «текста нет» (пост может состоять из одной
 * картинки), и вызывающий оставляет поле как было; для правки это отказ, и
 * вызывающий обязан бросить конверт: правка без текста не имеет смысла.
 */
export function clampFeedPostText(value: unknown): string | null {
  return typeof value === 'string' ? value.slice(0, FEED_POST_MAX_CHARS) : null;
}

/** То же для комментария. */
export function clampFeedCommentText(value: unknown): string | null {
  return typeof value === 'string' ? value.slice(0, FEED_COMMENT_MAX_CHARS) : null;
}

/** Имя автора: не строка — `null`, вызывающий подставит своё «Аноним». */
export function clampFeedAuthorName(value: unknown): string | null {
  return typeof value === 'string' ? value.slice(0, FEED_AUTHOR_NAME_MAX_CHARS) : null;
}

/**
 * Годится ли строка как текст правки поста.
 *
 * Пустая не годится: пустой пост нельзя опубликовать, значит и правкой его
 * опустошать нельзя — иначе стирание чужого текста выглядело бы как правка.
 */
export function isEditableFeedText(value: unknown): value is string {
  return typeof value === 'string' && value.length > 0 && value.length <= FEED_POST_MAX_CHARS;
}
