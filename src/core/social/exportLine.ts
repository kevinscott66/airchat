/**
 * Строка выгруженной переписки (v4.32.604).
 *
 * Экспорт собирался в трёх местах — в чате, в карточке контакта и в группе, —
 * и все три склеивали текст сообщения прямо в строку файла. У сообщения,
 * которое ключ этого устройства не открывает, текста нет: с v4.32.559 это
 * пустая строка при поднятом признаке `unreadable`. В файл она уходила как
 * `[время] Имя: ` — пустая строка, неотличимая от отправленной пустоты. Файл
 * сохраняют, пересылают и на него ссылаются как на всю переписку; молча
 * потерять в нём реплику хуже, чем не выгрузить вовсе, — тем же доводом в
 * v4.32.532 запретили усечённую выгрузку группы.
 *
 * Признак «медиа» дублировался так же: в двух местах из трёх писалось
 * `[Медиа]`, а в карточке контакта служебный префикс уходил в файл как есть.
 *
 * Почему пометка здесь допустима, хотя `outwardName` её запрещает. Разница в
 * том, чем становится строка у читающего. Имя автора подставляется в поле
 * имени, и пометка вместо него читалась бы как имя. Тело же реплики стоит в
 * документе, где `[Медиа]` — уже принятая пометка самого файла, а не слова
 * автора; квадратные скобки и говорят «это примечание выгрузки». Ничего о
 * нашем ключе строка не сообщает: причина не названа намеренно.
 *
 * Модуль чистый: ни хранилища, ни RN, ни времени.
 */

/** Служебный префикс вложения в теле сообщения. */
export const EXPORT_MEDIA_PREFIX = '\x01';

/** Чем в файле обозначено вложение. Было в двух местах из трёх — стало общим. */
export const EXPORT_MEDIA_TEXT = '[Медиа]';

/**
 * Чем в файле обозначена реплика, которую не открыл ключ этого устройства.
 *
 * В скобках — как `[Медиа]`: примечание выгрузки, а не слова автора.
 */
export const EXPORT_UNREADABLE_TEXT = '[Сообщение не удалось прочитать]';

/** Ровно то поле, которое проставляет слой чтения. */
export interface MaybeUnreadableRow {
  text?: string | null;
  unreadable?: boolean;
}

/**
 * Тело реплики в строке выгрузки.
 *
 * Порядок проверок именно такой: сперва «не открылось», иначе пустой текст
 * непрочитанной реплики свалился бы в общий случай и стал бы пустотой снова —
 * ровно тем, от чего пометка и заводится.
 *
 * Управляющие символы вырезаются здесь для всех троих: до этой версии их
 * убирала одна карточка контакта, а в двух других местах недоверенный текст
 * уезжал в файл как есть.
 */
export function exportBody(row: MaybeUnreadableRow | null | undefined): string {
  if (row?.unreadable === true) return EXPORT_UNREADABLE_TEXT;
  const text = typeof row?.text === 'string' ? row.text : '';
  if (text.startsWith(EXPORT_MEDIA_PREFIX)) return EXPORT_MEDIA_TEXT;
  // eslint-disable-next-line no-control-regex -- вырезание control-символов из недоверенного ввода и есть цель
  return text.replace(/[\x00-\x08\x0b\x0c\x0e-\x1f]/g, '');
}
