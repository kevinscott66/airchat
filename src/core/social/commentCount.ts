/**
 * Число комментариев под записью — это длина треда, а не догадка (v4.32.538).
 *
 * Дефект. Экран ленты держит число отдельно от самого треда и правил его
 * прибавлением единицы. Отправка своего комментария дописывала строку в список
 * ТОЛЬКО если её там ещё не было (перезагрузка треда по тику ленты успевает
 * положить её раньше — это штатный случай, ради него и сверяются id), а к числу
 * единица прибавлялась всегда. Симметрично при удалении: строка убиралась из
 * списка по совпадению id — то есть иногда не убиралась ничего, — а единица
 * вычиталась в любом случае. Итог: под записью написано «3 комментария», а в
 * открытом треде их два, и разойтись они могли в обе стороны сразу.
 *
 * Правило здесь одно: пока тред открыт и прочитан, число под записью равно
 * длине прочитанного списка. Оба запроса — и список, и счётчик — ходят в одну
 * таблицу с одним условием, так что это не приближение, а то же самое число.
 *
 * Прежнее значение возвращается ТЕМ ЖЕ объектом, если менять нечего: карта
 * счётчиков идёт в память списка, и новый объект на каждый тик перерисовывал
 * бы ленту целиком.
 *
 * Без зависимостей.
 */

/**
 * Согласовать счётчик открытой записи с длиной её треда.
 *
 * @param counts прежняя карта «запись → число комментариев»;
 * @param postId запись, чей тред открыт и прочитан (null — закрыт);
 * @param size   сколько строк в прочитанном треде.
 *
 * Возвращает `counts` тем же объектом, когда тред закрыт, длина бессмысленна
 * (не целое, отрицательное) или число уже совпадает.
 */
export function commentCountFromThread(
  counts: Readonly<Record<string, number>>,
  postId: string | null,
  size: number,
): Record<string, number> {
  if (!postId) return counts as Record<string, number>;
  if (!Number.isInteger(size) || size < 0) return counts as Record<string, number>;
  if (counts[postId] === size) return counts as Record<string, number>;
  return { ...counts, [postId]: size };
}
