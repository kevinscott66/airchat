/**
 * Отметка, которую база не приняла (v4.32.787).
 *
 * Пометки «я вышел из этой группы» и «этого человека отсюда исключили» —
 * единственное, что стоит между человеком и повтором старого конверта: реле
 * хранит их тридцать суток, темы выводятся из открытых DID, и переслать те же
 * подписанные байты может кто угодно. Строки в составе группы к этому моменту
 * уже нет, и без отметки повтор выглядит как законное первое приглашение.
 *
 * Писались обе гасящей формой записи: та зовёт проверяемую и выбрасывает её
 * ответ, так что собственный `try/catch` у пометок не срабатывал никогда.
 * Занятой на долю секунды базы хватало, чтобы отметки не стало совсем.
 *
 * Отсюда этот запас. Он держит в памяти процесса то, что база отказалась
 * взять, и читающая сторона судит по нему наравне с диском, попутно пробуя
 * дописать. Память процесса — не замена диску, перезапуск её не переживёт; но
 * заминка базы длится секунды, а повтор конверта приходит тогда, когда его
 * пришлют, и чаще всего это та же сессия.
 *
 * Модуль намеренно чистый: ни базы, ни ключей, ни журнала.
 */

/** Потолок: карта растёт в том числе от чужих конвертов об исключении. */
const DEFAULT_LIMIT = 256;

export interface MarkFallback {
  /** Запомнить отметку, которую база не приняла. */
  remember(pid: number, key: string, ts: number): void;
  /** Забыть: отметка легла на диск или снята по существу. */
  forget(pid: number, key: string): void;
  /** Момент отметки, живущей только в памяти, либо null. */
  pending(pid: number, key: string): number | null;
  /** Сколько отметок сейчас держится. Нужен проверкам и журналу. */
  size(): number;
}

export function createMarkFallback(limit: number = DEFAULT_LIMIT): MarkFallback {
  const kept = new Map<string, number>();
  const id = (pid: number, key: string): string => `${pid}\u0000${key}`;

  return {
    remember(pid: number, key: string, ts: number): void {
      const k = id(pid, key);
      // Переставляем в конец: порядок вставки — это и есть порядок вытеснения.
      kept.delete(k);
      kept.set(k, ts);
      // Вытесняем самую давнюю. Выбор произвольный и признан таковым: для
      // вытесненной отметки всё становится ровно так, как было до этой
      // версии, — не хуже. Потолок же нужен потому, что конверты об
      // исключении приходят снаружи и считать их некому.
      while (kept.size > limit) {
        const oldest = kept.keys().next();
        if (oldest.done) break;
        kept.delete(oldest.value);
      }
    },

    forget(pid: number, key: string): void {
      kept.delete(id(pid, key));
    },

    pending(pid: number, key: string): number | null {
      return kept.get(id(pid, key)) ?? null;
    },

    size(): number {
      return kept.size;
    },
  };
}
