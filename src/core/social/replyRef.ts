/**
 * replyRef — ссылка «в ответ на сообщение», пришедшая по сети.
 *
 * v4.32.299. У цитаты две части: id сообщения, к которому её привязали, и
 * короткое превью его текста. Показываются они вместе — блок над пузырём, по
 * нажатию прокручивающий к оригиналу, — и по отдельности бессмысленны:
 * превью без id — просто чужая строка над сообщением, которую некуда нажать
 * и нечем проверить, id без превью — пустая рамка.
 *
 * Обе части приходят от собеседника, то есть это недоверенный ввод, который
 * рисуется на экране. Отсюда правила:
 *
 *  • id обязан быть строкой разумной длины без управляющих символов, иначе
 *    отбрасывается вся ссылка целиком — вместе с превью;
 *  • ответ на самого себя отбрасывается: нажатие на такую цитату прокручивает
 *    к тому же сообщению, над которым она нарисована;
 *  • превью режется по общей длине цитаты (messagePreview.REPLY_PREVIEW_MAX);
 *  • служебный конверт в превью заменяется нейтральной подписью — иначе
 *    цитата напечатала бы сырой JSON с ключом группы или путём к файлу;
 *  • префикс системной строки снимается: иначе цитата притворилась бы
 *    уведомлением самого приложения (тот же приём, что закрыт в v4.32.238
 *    для текста сообщения);
 *  • невидимые символы разворота письма вырезаются — цитата такой же
 *    показываемый текст, как и сам пузырь.
 *
 * Модуль без зависимостей, кроме таких же чистых messagePreview и
 * sysLineGuard: правила применяются в приёме сообщений (SQLite, транспорт), а
 * проверять их надо отдельно от него.
 */
import { isControlOnlyText, previewLabelForText, truncateReplyPreview } from './messagePreview';
import { stripBidiControls, stripSpoofedSysPrefix } from './sysLineGuard';

/**
 * Предел длины id. Свои id — uuid v4 (36 символов); запас взят на случай
 * сборок с другим форматом, а смысл ограничения в том, чтобы в колонку
 * reply_to_id не приезжал текст произвольного размера.
 */
export const REPLY_ID_MAX = 128;

/** Разобранная ссылка на цитируемое сообщение. Обе части либо есть, либо нет. */
export type ReplyRef = { id: string | null; preview: string | null };

/** Цитаты нет. Отдельная константа, чтобы у всех отказов был один вид. */
export const NO_REPLY: ReplyRef = { id: null, preview: null };

/** Годится ли значение в id цитируемого сообщения. */
function validId(value: unknown): value is string {
  if (typeof value !== 'string') return false;
  if (value.length === 0 || value.length > REPLY_ID_MAX) return false;
  // v4.32.369: список полный — C0, C1 и разрывы строки вне обоих. Годным id
  // строка с U+2028 быть не может ровно так же, как строка с '\x0a'.
  // eslint-disable-next-line no-control-regex -- проверка недоверенного ввода на управляющие символы и есть цель
  return !/[\u0000-\u001F\u007F-\u009F\u2028\u2029]/.test(value);
}

/**
 * Привести цитату из чужого конверта к тому, что можно записать в базу.
 *
 * @param selfId id самого сообщения — чтобы отбросить ссылку на себя.
 */
export function sanitizeReplyRef(id: unknown, preview: unknown, selfId?: string): ReplyRef {
  if (!validId(id)) return NO_REPLY;
  if (selfId && id === selfId) return NO_REPLY;
  return { id, preview: sanitizeReplyPreview(preview) };
}

/**
 * Превью цитаты из сети: обрезанное, без служебных конвертов и без подделки
 * под системную строку. Пустое превью — это отсутствие превью: цитата с
 * пустой строкой нарисовалась бы пустой рамкой.
 *
 * Управляющие байты-префиксы (голосовое, документ, геолокация) остаются: по
 * ним экран подставляет подпись «🎤 Голосовое сообщение» и подобные.
 */
export function sanitizeReplyPreview(preview: unknown): string | null {
  if (typeof preview !== 'string') return null;
  const stripped = stripBidiControls(stripSpoofedSysPrefix(preview));
  // Служебный конверт целиком заменяется подписью: показывать его как текст
  // цитаты — значит напечатать содержимое, которого человек не писал.
  const safe = isControlOnlyText(stripped) ? previewLabelForText(stripped) : stripped;
  if (safe.trim().length === 0) return null;
  return truncateReplyPreview(safe);
}
