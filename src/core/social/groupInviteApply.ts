/**
 * Можно ли применять пригласительную ссылку к этому профилю (v4.32.463).
 *
 * Дефект, ради которого написан модуль: обработчик `airchat://join-group/…`
 * применял ссылку безусловно. `createGroup` при уже существующей группе —
 * `INSERT OR IGNORE`, то есть тихо ничего; а следом шёл цикл
 * `upsertGroupMember` с `ON CONFLICT … DO UPDATE SET role = excluded.role`,
 * который переписывал роли из недоверенной ссылки поверх своей таблицы.
 *
 * Что из этого следовало, без всяких гонок и без второго устройства:
 *  - владелец открывает собственную же ссылку (переслал себе, проверяет) —
 *    и понижается до `member` в своей группе: админские кнопки исчезают, а
 *    при «писать могут только администраторы» он теряет и право отправки;
 *  - участник присылает ссылку, где `id` — id настоящей группы жертвы, а
 *    `adminPub` — свой ключ. После «Присоединиться» он становится `admin` в
 *    чужой группе и получает право банить, кикать, переименовывать и
 *    сбрасывать пригласительный токен — `handleIncomingGroupControl` берёт
 *    роль ровно из этой таблицы;
 *  - ссылка на группу, которая уже заведена в другом профиле: группа в
 *    текущем не появлялась никогда (`id` был первичным ключом целиком), зато
 *    ключ текущего профиля ложился в список участников соседнего — два
 *    аккаунта одного человека оказывались связаны там, где он их разделял.
 *    Эта третья дорога закрыта в v4.32.467 самой схемой: ключ `groups` стал
 *    составным, состав участников — профильным, и группа соседа для нас
 *    просто не существует. Вопрос к базе с тех пор задаётся про свой профиль,
 *    а правило ниже осталось прежним.
 *
 * Правило одно и живёт здесь целиком: **ссылка заводит группу, но никогда не
 * переписывает уже заведённую.** Занят идентификатор — ссылка не
 * применяется, ничего не пишется, человеку говорится, что именно произошло.
 * Выход из группы удаляет строку, поэтому вступить заново по той же ссылке
 * по-прежнему можно.
 */

import type { GroupIdState } from '../storage/local';

/** Что делать со ссылкой. `apply` — единственный ответ, при котором пишем в БД. */
export type InviteApplyDecision =
  | { kind: 'apply' }
  /** Группа уже есть в этом профиле. */
  | { kind: 'already_here' }
  /** База не ответила. Отказ, а не разрешение: решение здесь про доверие. */
  | { kind: 'unknown' };

/**
 * Решение принимается только по ответу базы про свой профиль. Ничего из самой
 * ссылки сюда не приходит: содержимое ссылки — недоверенное, и права на
 * перезапись оно давать не может ни при каком поле.
 */
export function decideInviteApply(state: GroupIdState): InviteApplyDecision {
  switch (state.kind) {
    case 'unknown':
      return { kind: 'unknown' };
    case 'free':
      return { kind: 'apply' };
    case 'taken':
      return { kind: 'already_here' };
  }
}

/**
 * Почему ссылка не применена — либо null, если применяем.
 *
 * Тексты объясняют состояние, а не ругают действие: чаще всего сюда попадает
 * не злоумышленник, а человек, открывший собственное приглашение.
 */
export function inviteApplyProblem(decision: InviteApplyDecision, groupName: string): string | null {
  switch (decision.kind) {
    case 'apply':
      return null;
    case 'already_here':
      return `Вы уже состоите в группе «${groupName}» — ссылка ничего не меняет.`;
    case 'unknown':
      return `Не удалось проверить, есть ли уже группа «${groupName}». Попробуйте открыть ссылку ещё раз.`;
  }
}
