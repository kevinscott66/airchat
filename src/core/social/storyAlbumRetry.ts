/**
 * Строка альбома, у которой не вышла общая копия.
 *
 * Кладя историю в альбом, устройство копирует снимок к себе и вдобавок пробует
 * поднять копию на общий адрес — по нему альбом соберётся на втором телефоне
 * того же аккаунта. Загрузка тут необязательная: не вышла — строка всё равно
 * пишется, и на ЭТОМ телефоне альбом выглядит целым.
 *
 * Наверх такая строка не идёт: без общего адреса на втором устройстве ей
 * нечего показать, и она дала бы там пустую плитку навсегда (`hold` в
 * storyAlbumSync). Придержать её — верно. Неверно другое: адрес пишется ровно
 * один раз, при вставке строки, а вставка идёт через INSERT OR IGNORE и
 * повторное добавление той же истории отсекается ещё раньше — как «уже есть».
 * Значит, одна неудачная минута без сети оставляла строку придержанной
 * НАВСЕГДА: на первом телефоне альбом полный, на втором его нет, и ни одно
 * сообщение об этом не выводится — оба состояния выглядят исправными.
 *
 * Отсюда повтор. Он берёт строки, у которых копия на диске есть, а общего
 * адреса нет, и пробует поднять её снова. Порция ограничена: у альбомов сотни
 * строк, а заход синхронизации не должен превращаться в выгрузку всего
 * архива — накопившееся разойдётся за несколько заходов.
 *
 * Нечитаемая копия сюда не попадает: её имя не открылось ключом этого
 * устройства, поднимать нечего, и трогать такую строку нельзя.
 */

/** Сколько придержанных строк пробуем поднять за один заход синхронизации. */
export const ALBUM_UPLOAD_RETRY_BATCH = 12;

export type AlbumUploadCandidate = {
  id: string;
  mediaFile: string | null;
  mediaCid: string | null;
  mediaType: 'image' | 'video';
  /** Когда историю положили в альбом. */
  addedAt: number;
  mediaUnreadable?: boolean;
};

/**
 * Отобрать строки, которым не хватает только общего адреса.
 *
 * Сначала самые давние: чем дольше строка ждёт, тем дольше человек не видит
 * свой альбом на втором устройстве.
 */
export function heldAlbumUploads<T extends AlbumUploadCandidate>(
  items: readonly T[],
  limit: number = ALBUM_UPLOAD_RETRY_BATCH,
): T[] {
  if (!(limit > 0)) return [];
  const held = items.filter((item) => {
    if (item.mediaCid) return false;
    if (!item.mediaFile) return false;
    if (item.mediaUnreadable) return false;
    return Number.isFinite(item.addedAt);
  });
  held.sort((a, b) => a.addedAt - b.addedAt || (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  return held.slice(0, limit);
}
