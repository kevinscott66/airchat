/**
 * Как назвать собеседника на экране — одним правилом (v4.32.372).
 *
 * Правил было два, несовместимых, и жили они вперемешку:
 *
 *   `c.displayName ?? peerPubB64.slice(0, 10)`   — 23 места
 *   `c.displayName || peerName`                  — 6 мест
 *
 * Первое не работает. `Contact.displayName` — это `string`, а не
 * `string | null`: в `listContacts` он собирается как `displayName || peerName`
 * и для контакта, чья карточка ещё не приехала, равен пустой строке. `??`
 * подставляет запасное значение только вместо `null` и `undefined`, поэтому
 * подстановка не срабатывала ни разу за всё время. Безымянный собеседник
 * получал пустой заголовок чата, пустую строку в поиске по сообщениям, пустое
 * всплывающее уведомление и «„“ — не удалось отправить» при пересылке.
 *
 * У групп такой ошибки нет, и не потому, что там писали `||`: там
 * `displayName` действительно `string | null`, а с v4.32.371 пустое имя ещё на
 * границе записи превращается в `null`. То есть чинить это надо было там же,
 * на границе, — но у контактов границы нет, `displayName` не бывает `null` по
 * типу. Значит правило нужно на чтении, и одно.
 *
 * Модуль намеренно чистый: ни React, ни хранилища, ни переводов. Запасное
 * значение выбирает вызывающий — в заголовке чата уместен обрезанный ключ, в
 * списке пересылки «контакт», в системной строке «Участник».
 */
import { isVisiblyBlank } from './sysLineGuard';

/**
 * Имя собеседника или запасное значение, если показывать нечего.
 *
 * «Нечего» — это и `null`, и пустая строка, и строка из невидимых символов
 * (v4.32.371: имя из одних склеек эмодзи или хангыль-заполнителей на экране
 * пустое, а для кода — полноценное).
 *
 * Обрезки по длине здесь нет намеренно: имена приходят сюда уже очищенными на
 * границе хранилища, а урезать их второй раз, да ещё другим пределом, значит
 * показывать в разных экранах разные куски одного имени.
 */
export function contactLabel(name: unknown, fallback: string): string {
  if (typeof name !== 'string' || isVisiblyBlank(name)) return fallback;
  return name;
}

/**
 * То же правило для полей, которые по типу и так `string | null`.
 *
 * У участника группы, подписи под сообщением и заявки на вступление
 * `displayName` действительно бывает `null`, и `?? 'Участник'` рядом с ними
 * написан правильно. Пустым это поле делает не тип, а история: строки,
 * записанные до v4.32.371, лежат в базе с пустым или невидимым именем — тогда
 * пустое имя ещё не превращалось в отсутствие имени на границе записи.
 *
 * Отсюда и место применения: чтение из хранилища. Сорок `??` в экране групп
 * при этом остаются как есть и начинают работать — вместо того чтобы править
 * сорок мест и надеяться, что сорок первое не появится.
 *
 * От `displayNameOrNull` отличается тем, чего не делает: не чистит и не
 * обрезает. Та стоит на границе сети, где имя недоверенное; здесь имя своё,
 * уже очищенное при записи, и резать его вторым пределом нельзя.
 */
export function nameOrNull(name: string | null | undefined): string | null {
  return name != null && !isVisiblyBlank(name) ? name : null;
}

/**
 * Первая буква для кружка-аватара.
 *
 * Записывалась она в тринадцати местах одинаково и одинаково неправильно:
 * `(name ?? '?')[0].toUpperCase()`. Две беды на выражение.
 *
 * Первая: у пустого имени `[0]` — это `undefined`, а `undefined.toUpperCase()`
 * — исключение прямо в отрисовке. `??` пустую строку пропускает, так что
 * достаточно одного безымянного контакта в списке, чтобы экран не открылся.
 * Заявка на вступление в группу приходит по сети: имя в ней задаёт тот, кто
 * просится, — и пустым именем он роняет список заявок у администратора.
 *
 * Вторая: `[0]` — это одна единица UTF-16, а не один символ. У имени,
 * начинающегося с эмодзи, это половина суррогатной пары, и в кружке рисуется
 * пустой прямоугольник. Перебор `for…of` идёт по кодовым точкам и берёт эмодзи
 * целиком.
 *
 * Заодно пропускаются ведущие пробелы и невидимые символы: у имени « Аня»
 * первой буквой была пустота.
 */
export function nameInitial(name: unknown, fallback = '?'): string {
  if (typeof name !== 'string') return fallback;
  for (const ch of name) {
    if (isVisiblyBlank(ch)) continue;
    return ch.toUpperCase();
  }
  return fallback;
}

/**
 * Две буквы для крупного кружка — карточка профиля, экран звонка, список
 * контактов в шторке вложений.
 *
 * v4.32.423: правило и на две буквы жило в трёх видах, из которых совпадал
 * один. Экран звонка брал `w[0]` — единицу UTF-16, то есть половину
 * суррогатной пары: имя «🚀Ракета» рисовалось квадратиком у входящего звонка.
 * Шторка вложений брала `slice(0, 2)` — две буквы ПЕРВОГО слова: «Александр
 * Пушкин» превращался в «АЛ», а «Ким» — в «КИ». И ни одна из трёх не
 * пропускала невидимый ведущий символ, а он приходит по сети вместе с именем:
 * у «U+2060 Аня» (первый символ невидим) кружок оказывался пустым.
 *
 * Слова режутся по любому пробельному, а не по одному пробелу: «Анна  Петрова»
 * с двойным пробелом давала на экране звонка «А» — вторым «словом» была
 * пустота.
 */
export function nameInitials(name: unknown, fallback = '?'): string {
  if (typeof name !== 'string') return fallback;
  const words = name.split(/\s+/).filter((w) => w !== '' && !isVisiblyBlank(w));
  return words.slice(0, 2).map((w) => nameInitial(w, '')).join('') || fallback;
}
