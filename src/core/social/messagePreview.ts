/**
 * messagePreview — короткая подпись сообщения одной строкой.
 *
 * v4.32.238. Одна и та же цепочка «какой префикс — такая подпись» была
 * скопирована четырежды: previewLabelForText в messaging.ts, formatPreview в
 * ChatListScreen, и две отдельные цепочки в GroupsScreen (список групп и
 * поиск по сообщениям). Копии разошлись — каждая знала свой набор префиксов:
 * в списке диалогов не было '\x0bsys:', и системная строка попадала в поиск
 * сырой, вместе с управляющим байтом; в группах не было '\x06doc:' в одной из
 * двух цепочек; формулировки «🔥 Одноразовое» и «🔥 Одноразовое сообщение»
 * отличались между экранами. Добавление любого нового типа сообщения требовало
 * помнить про все четыре места — и ни разу не было сделано полностью.
 *
 * Модуль без транспортных зависимостей: подпись считается в render-пути
 * списков, и её нужно уметь проверять тестами без React, SQLite и транспорта.
 * Единственный импорт — sysLineGuard, такой же модуль без импортов, откуда
 * берётся системный префикс (v4.32.263).
 */
import { SYS_LINE_PREFIX, sanitizeBodyForRender } from './sysLineGuard';

/** Системная строка протокола: её рисует приложение, префикс не показываем. */
const SYS = SYS_LINE_PREFIX;
/** Пересылка: '\x08fwd:Имя\nИсходный текст'. */
const FWD = '\x08fwd:';

/**
 * Управляющие конверты, которым в подписи не место вообще: сообщение группы,
 * отметка о прочтении, ctl-конверты, реакции, закрепление, таймер, presence,
 * сторис, профиль. Такая строка в превью означает утечку служебных данных
 * (ключей, путей к файлам), поэтому подменяется нейтральным текстом.
 *
 * v4.32.247: '\x0agjr:' (заявка на вступление) записан целиком — байт \x0a
 * делят с ним GIF-сообщения ('\x0agif:'), которые показывать как раз надо.
 * Добавлены '\x13' (сторис) и '\x14' (профиль).
 *
 * v4.32.250: добавлен '\x15' — байт делят голос в опросе ('\x15pv:') и его
 * завершение ('\x15pc:', с v4.32.251), показывать не надо ни то, ни другое.
 */
const CONTROL_ONLY = ['\x02', '\x03', '\x0agjr:', '\x0e', '\x0f', '\x10', '\x11', '\x12', '\x13', '\x14', '\x15'];

/**
 * Служебный ли это конверт, которому не место в переписке ВООБЩЕ — ни
 * пузырём, ни строкой в списке диалогов.
 *
 * v4.32.247: до этой версии отправка любого такого конверта (реакция,
 * закрепление, таймер, управление группой, сторис) сохраняла его в
 * chat_messages как исходящее сообщение — в переписке появлялся пузырь с
 * сырым JSON, а в списке диалогов «Системное сообщение» вместо последней
 * реплики. Приём был закрыт давно, отправка — нет.
 */
export function isControlOnlyText(text: string): boolean {
  return !!text && CONTROL_ONLY.some((c) => text.startsWith(c));
}

/**
 * Служебные конверты, ради которых собеседника ВСЁ ЖЕ нужно разбудить: за
 * ними стоит событие, которое он увидит, открыв приложение.
 *
 * '\x02' — сообщение группы, '\x0agjr:' — заявка на вступление (её ждёт
 * администратор), '\x0e' — управление группой, включая приглашение.
 */
const NOTIFIABLE = ['\x02', '\x0agjr:', '\x0e'];

/**
 * Конверт, который не должен вызывать уведомление на телефоне собеседника.
 *
 * v4.32.248: текст push-уведомления на принимающей стороне всегда один и тот
 * же — «Новое сообщение» (расшифровать содержимое там ещё нечем). Поэтому
 * отметка о прочтении, реакция, закрепление, таймер удаления, настройка
 * «показывать ли, что я в сети», сторис и обновление профиля выдавали баннер
 * с вибрацией, за которым в переписке ничего не появлялось. Особенно заметно
 * на реакции и на смене аватара: и то и другое рассылается всем контактам
 * сразу, то есть одно нажатие означало по баннеру на каждом телефоне.
 */
export function isSilentEnvelope(text: string): boolean {
  if (!isControlOnlyText(text)) return false;
  return !NOTIFIABLE.some((c) => text.startsWith(c));
}

/**
 * Одна строка чужого текста для списка.
 *
 * v4.32.328. До этой версии подпись возвращала пришедшее тело как есть, и
 * список диалогов был последним местом, где недоверенная строка доезжала до
 * экрана нетронутой: U+202E переворачивал всю строку списка целиком — включая
 * имя собеседника и время, — а сообщение из одних переводов строки показывало
 * пустую подпись, будто в чате ничего нет.
 *
 * Переносы и табуляции схлопываются в пробел: подпись рисуется одной строкой,
 * и всё, что стоит после первого перевода, иначе просто пропадало.
 */
function previewLine(text: string): string {
  return sanitizeBodyForRender(text).replace(/\s+/g, ' ').trim();
}

/**
 * Подпись для строки сообщения. Обычный текст проходит через previewLine —
 * обрезку по длине делает вызывающий, у списков она разная.
 */
export function previewLabelForText(text: string): string {
  if (!text) return text;
  if (text.startsWith('\x01voice:')) return '🎤 Голосовое сообщение';
  if (text.startsWith('\x04poll:')) return '📊 Опрос';
  if (text.startsWith('\x05contact:')) return '👤 Контакт';
  if (text.startsWith('\x06doc:')) return '📄 Документ';
  if (text.startsWith('\x07loc:')) return '📍 Геолокация';
  if (text.startsWith('\x09vo:')) return '🔥 Одноразовое сообщение';
  if (text.startsWith('\x0agif:')) return '🎞 GIF';
  if (text.startsWith('\x0cliveloc:')) return '📡 Живая геолокация';
  if (text.startsWith(SYS)) return previewLine(text.slice(SYS.length));
  if (text.startsWith(FWD)) {
    // Имя отправителя в подпись не попадает — оно уже показано строкой выше.
    const rest = text.slice(FWD.length);
    const nl = rest.indexOf('\n');
    const original = nl >= 0 ? rest.slice(nl + 1) : rest;
    return `↪ ${original ? previewLabelForText(original) : 'Пересланное сообщение'}`;
  }
  if (isControlOnlyText(text)) return 'Системное сообщение';
  return previewLine(text);
}

/**
 * Сколько символов цитируемого сообщения кладётся в ответ.
 *
 * v4.32.282: одно значение на всех. Личные чаты и группы резали цитату
 * литералом `slice(0, 100)` каждый у себя, а с сети приходило что угодно —
 * длину входящей цитаты не проверял никто, и собеседник мог прислать вместо
 * неё сколь угодно длинный текст, который лёг бы в базу целиком.
 */
export const REPLY_PREVIEW_MAX = 100;

/** Цитата для ответа: обрезанная по REPLY_PREVIEW_MAX, пустая — как её отсутствие. */
export function truncateReplyPreview(text: string | null | undefined): string | null {
  if (typeof text !== 'string' || text.length === 0) return null;
  return text.length > REPLY_PREVIEW_MAX ? text.slice(0, REPLY_PREVIEW_MAX) : text;
}
