/**
 * peerPronouns — местоимения, которые человек указал о себе.
 *
 * v4.32.616. Поле есть в редакторе профиля с v4.32.5xx, но жило только у
 * владельца: правило чистки было записано дважды и обе копии лежали в UI
 * (ProfileScreen и ProfileEditModal), а в конверт профиля поле не входило
 * вовсе. То есть его нельзя было увидеть ни у кого, кроме себя.
 *
 * Модуль повторяет peerStatus по устройству и по причине: строка однострочная,
 * стоит под именем, приезжает от чужого клиента — значит правило у неё то же,
 * что у имени, и оно должно быть одно на отправку, приём и оба своих
 * редактора.
 */

import { displayNameOrNull } from './sysLineGuard';

/**
 * Предел длины. Местоимения — короткая подпись («он/его»), а не второе «О
 * себе»: столько же принимает TextInput в обоих редакторах.
 */
export const PRONOUNS_MAX = 30;

/**
 * Чужие местоимения к виду, годному для показа. null — не заданы: и когда
 * поле пустое, и когда в нём не осталось ничего видимого.
 */
export function sanitizePeerPronouns(v: unknown): string | null {
  return displayNameOrNull(v, PRONOUNS_MAX);
}

/**
 * Свои местоимения перед записью в базу — тем же правилом, что и чужие на
 * приёме. Пустая строка значит «не заданы»: так это поле и хранится.
 */
export function normalizeOwnPronouns(v: unknown): string {
  return sanitizePeerPronouns(v) ?? '';
}
