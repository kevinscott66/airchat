/**
 * linkPreviewPolicy — когда приложению можно сходить по ссылке из сообщения.
 *
 * v4.32.240. Карточка предпросмотра ссылки строится тем, что приложение само
 * загружает страницу по адресу из текста. Для исходящих сообщений и строки
 * ввода это нормально: адрес набрал сам пользователь. Для входящих — это
 * маяк.
 *
 * Достаточно прислать сообщение со ссылкой на свой сервер, и в момент, когда
 * переписка окажется на экране, устройство само сделает запрос: отправитель
 * узнаёт IP-адрес получателя, его провайдера, часовой пояс по времени
 * запроса и сам факт прочтения — даже если «Не отправлять уведомления о
 * прочтении» включено, и даже если сообщение так и не открыли, а просто
 * пролистали ленту чата. Ссылка при этом может быть уникальной для каждого
 * получателя, то есть это ещё и точная привязка «адрес → человек».
 *
 * Поэтому предпросмотр входящих ссылок выключен по умолчанию и включается
 * осознанно в «Настройки → Приватность». Ссылка остаётся нажимаемой — просто
 * запрос делается тогда, когда по ней нажали, а не когда её показали.
 *
 * Модуль без импортов: решение проверяется тестами отдельно от React.
 */

/** Ключ в kv-хранилище. Значение — 'true' | 'false' (по умолчанию выключено). */
export const LINK_PREVIEW_INCOMING_KEY = 'privacy_link_preview_incoming';

/**
 * Разбирает значение настройки. Всё, кроме явного 'true' (включая отсутствие
 * записи), считается «выключено»: умолчание должно быть безопасным.
 */
export function parseIncomingLinkPreviewPref(raw: string | null | undefined): boolean {
  return raw === 'true';
}

/**
 * Можно ли загружать предпросмотр.
 *
 * @param fromPeer ссылка пришла от собеседника (входящее сообщение, сообщение
 *                 группы, запись в ленте), а не набрана самим пользователем.
 * @param incomingAllowed значение настройки.
 */
export function shouldLoadLinkPreview(fromPeer: boolean, incomingAllowed: boolean): boolean {
  return !fromPeer || incomingAllowed;
}
