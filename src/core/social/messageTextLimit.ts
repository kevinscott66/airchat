/**
 * Потолок длины текста сообщения — v4.32.508.
 *
 * Дефект: число 64 000 было выписано в четырёх местах — в приёме группового
 * конверта, в планировщике отложенных (дважды) и в двух разборщиках очереди
 * повторной отправки. Причём в очередях над ним стоял комментарий «столько же,
 * сколько принимает сама отправка», а отправка не принимала НИЧЕГО: ни на
 * отправляющей стороне лички, ни на приёмной ограничения не было вовсе.
 *
 * Из-за этого личный текст любого размера доезжал до базы и до экрана: строка
 * в SQLite, предпросмотр в списке чатов, пузырь в переписке — всё это делалось
 * над многомегабайтной строкой в главном потоке. Групповой путь тот же текст
 * отбрасывал: одно правило, написанное дважды, разъехалось ровно тем концом,
 * который никто не проверял.
 *
 * Правило здесь одно и на всех: столько символов сообщение может занимать, и
 * ни приём, ни очередь, ни планировщик не решают этот вопрос сами.
 *
 * Модуль без импортов.
 */

/**
 * Шестьдесят четыре тысячи символов. Больше человек не пишет и не вставляет:
 * это ~30 страниц сплошного текста. Всё крупнее — либо ошибка отправителя,
 * либо попытка занять приёмный цикл разбором и отрисовкой.
 */
export const MAX_MESSAGE_TEXT = 64_000;

/**
 * Строка ли это и влезает ли она в потолок. Пустая строка допустима: сообщение
 * может состоять из одного вложения.
 */
export function withinMessageTextLimit(value: unknown): value is string {
  return typeof value === 'string' && value.length <= MAX_MESSAGE_TEXT;
}

/**
 * То же, но для мест, где текст обязателен и пустым быть не может:
 * отложенная отправка и очередь повторов ставят в очередь именно текст.
 */
export function isSendableMessageText(value: unknown): value is string {
  return withinMessageTextLimit(value) && value.length > 0;
}
