/**
 * groupInviteToken — секрет, без которого пригласительная ссылка ничего не даёт.
 *
 * v4.32.303. До этой версии ссылка-приглашение была чистой функцией от
 * открытых данных группы: {id, name, adminPub, requireApproval}. Ничего
 * тайного в ней не было — и отозвать её было нечем. Кнопка «Сбросить»
 * существовала до v4.32.260, обнуляла локальную колонку invite_link и
 * рапортовала «Ссылка сброшена», но следующее нажатие «Пригласительная
 * ссылка» выдавало ровно ту же строку, а все ранее разосланные продолжали
 * пускать в группу. Убрали кнопку — осталась честная запись в комментарии, что
 * настоящий отзыв требует токена.
 *
 * Цена отсутствия отзыва — не гипотетическая. Ссылка живёт там, куда её
 * переслали: в чужом чате, в скриншоте, в истории мессенджера, из которого
 * человека давно исключили. Исключение из группы («кик») не закрывало вход:
 * исключённый открывал ту же ссылку и возвращался обычным участником, потому
 * что бан — это строка в списке, а кик её удаляет. Один раз утёкшая ссылка
 * была вечной.
 *
 * Теперь в ссылке лежит токен, а у администраторов группы — его копия. Сброс
 * рождает новый токен: ранее разосланные ссылки несут старый и перестают
 * пускать. Решает, как и в groupJoinPolicy, ПРИНИМАЮЩИЙ: токен из ссылки —
 * недоверенный ввод, он только предъявляется, а сверяется со своим.
 *
 * Модуль чистый (без БД, сети и RN) — как groupInviteLink и groupJoinPolicy,
 * рядом с которыми он работает.
 */

/** 16 байт случайности: угадать за время жизни группы нечем. */
export const INVITE_TOKEN_BYTES = 16;

/**
 * base64url без паддинга: 22 символа. Токен едет внутри ссылки, которую
 * пересылают текстом и печатают в QR, поэтому ни '+', ни '/', ни '=' в нём
 * быть не должно — их калечат переносы строк и URL-кодирование.
 */
const TOKEN_RE = /^[A-Za-z0-9_-]{22}$/;

export type InviteTokenVerdict =
  /** Токен предъявлен и совпал — ссылка действующая. */
  | 'ok'
  /** Ссылка старая или чужая: пускать нельзя. */
  | 'revoked'
  /** Сверять не с чем: токена у нас нет, решение принимают без него. */
  | 'unenforceable'
  /**
   * Токен у нас ЕСТЬ, но столбец не открылся ключом данных (v4.32.601).
   *
   * Отличать это от 'unenforceable' обязательно. Прежде непрочитанный
   * столбец приходил сюда пустой строкой, `isInviteToken('')` отвечал
   * «нет токена» — и проверка молча превращалась в «сверять не с чем».
   * То есть на устройстве администратора, чей ключ перестал открывать этот
   * столбец, любая давно отозванная ссылка снова начинала пускать в группу,
   * и об этом не узнавал никто.
   */
  | 'unverifiable';

/**
 * Пускать ли дальше. Два вердикта из четырёх запрещают вход, и спрашивать о
 * них по отдельности — значит рано или поздно забыть один: до v4.32.601 оба
 * места сравнивали ровно с 'revoked'.
 */
export function inviteTokenBlocks(verdict: InviteTokenVerdict): boolean {
  return verdict === 'revoked' || verdict === 'unverifiable';
}

/**
 * Новый токен. Случайность передаётся аргументом, а не берётся изнутри:
 * иначе модуль перестал бы быть чистым и проверялся бы только на глаз.
 */
export function makeInviteToken(random: (n: number) => Uint8Array): string {
  const bytes = random(INVITE_TOKEN_BYTES);
  if (bytes.length !== INVITE_TOKEN_BYTES) {
    throw new Error('invite_token_bad_random');
  }
  return Buffer.from(bytes)
    .toString('base64')
    .replace(/\+/g, '-')
    .replace(/\//g, '_')
    .replace(/=+$/, '');
}

/** Проверка формы. Всё, что пришло из ссылки или конверта, проходит через неё. */
export function isInviteToken(v: unknown): v is string {
  return typeof v === 'string' && TOKEN_RE.test(v);
}

/**
 * Пускает ли предъявленный токен.
 *
 * Два правила, и оба на стороне принимающего:
 *
 *  1. Нет своего токена — 'unenforceable'. Это не дыра, а единственный
 *     возможный ответ: группы, созданные до этой версии, токена не имеют, и
 *     обычные участники его не имеют никогда (см. ниже). Проверять нечем —
 *     значит решение принимает groupJoinPolicy, как и раньше.
 *  2. Свой токен есть, а предъявленного нет или он другой — 'revoked'.
 *     Отсутствие токена НЕ считается «ну ладно, пропустим»: иначе отзыв
 *     обходился бы вырезанием одного поля из ссылки — ровно та ошибка, из-за
 *     которой в v4.32.259 гейт одобрения не работал вовсе.
 *
 * Токен есть только у администраторов: он и есть право приглашать. Раздавать
 * его всем участникам вместе с рассылкой настроек нельзя — тогда любой из них
 * соберёт действующую ссылку, и отзыв снова станет пустой кнопкой.
 *
 * Сравнение обычное, посимвольное. Времени ответа здесь не измерить: конверт
 * приходит через ретранслятор, применяется в общей очереди, и на несовпадение
 * приложение не отвечает ничем, по чему можно было бы подбирать токен.
 */
export function decideInviteToken(params: {
  /** Наш собственный токен группы; null/undefined — его у нас нет. */
  knownToken: string | null | undefined;
  /**
   * Столбец с нашим токеном не открылся ключом данных (v4.32.601). Это НЕ
   * «токена нет»: сверять действительно нечем, но и пускать нельзя — иначе
   * отозванная ссылка проходит через неисправный ключ.
   */
  knownUnreadable?: boolean;
  /** Токен из ссылки, дошедший до нас в конверте; недоверенный. */
  presented: string | null | undefined;
}): InviteTokenVerdict {
  const { knownToken, knownUnreadable, presented } = params;
  if (knownUnreadable === true) return 'unverifiable';
  if (!isInviteToken(knownToken)) return 'unenforceable';
  if (!isInviteToken(presented)) return 'revoked';
  return presented === knownToken ? 'ok' : 'revoked';
}
