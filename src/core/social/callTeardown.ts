/**
 * Кто кого должен предупредить, когда звонок закончился — и сколько звонить.
 *
 * v4.32.549. Трубку клали двумя разными путями. Нажатие человека (`hangupCall`)
 * посылало собеседнику сигнал; а вот все внутренние завершения — сорок пять
 * секунд без ответа, отказ ICE, разрыв соединения, неудачный запуск — рвали
 * звонок ТОЛЬКО у себя и молчали. Хуже всего это выглядело на исходящем: мы
 * бросали дозваниваться, а телефон собеседника продолжал звонить, потому что
 * останавливать его было нечем и некому.
 *
 * Симметричная дыра на входящем: у звонка, которого не берут, вообще не было
 * срока. Если звонивший исчез, не успев положить трубку (упало приложение,
 * пропала сеть), входящий звонок оставался на экране навсегда.
 *
 * Правило простое: предупреждаем всегда, кроме случая, когда завершение
 * пришло ОТ собеседника — он и так знает.
 *
 * Модуль намеренно без импортов.
 */

export type CallStateName = 'idle' | 'incoming' | 'outgoing' | 'connected' | 'ended';

/** Кто закончил звонок: мы (в том числе по своему таймеру) или собеседник. */
export type TeardownOrigin = 'local' | 'remote';

/**
 * Сколько звоним собеседнику, прежде чем бросить дозваниваться.
 */
export const OUTGOING_RINGING_TIMEOUT_MS = 45_000;

/**
 * Сколько держим на экране входящий, которого не берут.
 *
 * Строго БОЛЬШЕ исходящего срока — и это не запас «на всякий случай», а
 * условие правильной надписи. В обычном случае первым сдаётся звонящий: его
 * таймер гасит звонок и присылает нам сигнал, мы закрываем входящий как
 * «завершён собеседником». Если бы срок здесь был равен или меньше, мы
 * успевали бы ответить «отклонён» — и человек, которому не взяли трубку,
 * читал бы, что его отшили. Этот таймер срабатывает лишь тогда, когда
 * звонивший исчез и сигнала не будет.
 */
export const INCOMING_RINGING_TIMEOUT_MS = 60_000;

/** Состояния, в которых собеседник всё ещё ждёт нас — экран у него занят. */
export function isLiveCallState(state: CallStateName): boolean {
  return state === 'incoming' || state === 'outgoing' || state === 'connected';
}

/**
 * Надо ли сказать собеседнику, что звонок кончился.
 *
 * Нет — только если он сам его и закончил. Во всех остальных случаях молчание
 * оставляет у него звонящий или «идущий» звонок, которого уже нет.
 */
export function shouldNotifyPeer(state: CallStateName, origin: TeardownOrigin): boolean {
  if (origin === 'remote') return false;
  return isLiveCallState(state);
}

/**
 * Через сколько закрывать звонок в этом состоянии, если ничего не изменится.
 *
 * `null` — сроку взяться неоткуда: разговор уже идёт, либо звонка нет.
 */
export function ringingTimeoutMs(state: CallStateName): number | null {
  if (state === 'outgoing') return OUTGOING_RINGING_TIMEOUT_MS;
  if (state === 'incoming') return INCOMING_RINGING_TIMEOUT_MS;
  return null;
}
