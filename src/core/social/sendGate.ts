/**
 * Дойдёт ли служебное сообщение до собеседника прямо сейчас (v4.32.320).
 *
 * Половина того, что приложение отправляет, — не текст от человека, а
 * служебные конверты: профиль, просьба не отмечать время последнего входа,
 * настройка исчезающих сообщений, закреплённые сообщения. Все они уходят через
 * тот же sendMessage, и почти все запоминают у себя «этому уже сообщено», а
 * потом на это полагаются: сказанное второй раз не повторяют.
 *
 * Беда в том, что отказ записывался как доставка: sendMessage отвечает пустым
 * значением на шесть разных поводов, а служебный конверт не оставляет после
 * себя даже строки в переписке. Дальше уже ничего не поправить: повторить
 * некому, отметка «сообщено» стоит.
 *
 * Поэтому спрашиваем ДО отправки. Ответ «нет» здесь значит «не отправляй и не
 * записывай» — в следующий раз попробуем снова.
 *
 * v4.32.715: это половина ответа, а не весь. Здесь видны только два повода из
 * шести — блокировка и выбранный часовой лимит; нет общего ключа, негодный
 * peerDid, исчерпанный лимит служебных конвертов и «нет маршрута в сеть»
 * различимы только по тому, что вернул сам sendMessage. Поэтому каждое место
 * вызова обязано ещё и разобрать ответ, а не полагаться на одну эту проверку.
 *
 * Не путать с canSendMessage: тот не отвечает на вопрос, а тратит одну из
 * пятидесяти попыток.
 */
import { rateLimiter } from '../security/rateLimiter';

export async function canReachPeer(peerPubB64: string): Promise<boolean> {
  // Блок-лист поднимается с диска не мгновенно (v4.32.317).
  await rateLimiter.whenReady();
  if (rateLimiter.isBlocked(peerPubB64)) return false;
  return !rateLimiter.messageLimitReached(peerPubB64);
}
