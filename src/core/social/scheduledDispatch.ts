/**
 * Отправлять ли отложенное сообщение, текста которого мы не смогли прочитать.
 *
 * Измеренный дефект (v4.32.565). Отложенное сообщение лежит в таблице
 * `scheduled_messages` зашифрованным (v4.32.283: оно ждёт своего часа часами
 * или днями, и держать его открытым дольше всего остального — хуже всего).
 * Читается оно через `decryptAtRestString`, а тот при неудачной расшифровке
 * отдаёт пустую строку. Дальше по проходу планировщика эта пустая строка
 * ничем не отличается от настоящего текста:
 *
 *   • в личке она уходит собеседнику как `sendMessage(peer, '')` — то есть у
 *     него появляется пустой пузырь от вас, отправленный «по расписанию»;
 *   • в группе она уходит через `fanoutGroupMessage(groupId, '', …)` — пустой
 *     пузырь у ВСЕХ участников сразу, и в свою историю пишется такой же;
 *   • сразу после отправки строка расписания удаляется как успешно
 *     отправленная. Шифртекст стирается — а вместе с ним последняя копия
 *     написанного текста, который правильным ключом ещё открылся бы.
 *
 * Столбец `media_cids` устроен так же и ломается тише. Не расшифровался — это
 * снова пустая строка, `if (msg.mediaCids)` её не замечает, и сообщение уходит
 * без вложений. Получатель видит текст без единой картинки и не знает, что
 * они были; отправитель не видит вообще ничего.
 *
 * Ключ расходится с базой не в теории: восстановление из копии, перенос
 * профиля, сбой хранилища ключей. Причём расходится он сразу для всех строк —
 * то есть в один тик планировщик разошлёт пустые сообщения по всем адресатам,
 * которым что-либо было назначено, и сотрёт все назначенные тексты.
 *
 * Решение — не отправлять и не удалять. Строка остаётся лежать: она не
 * протухает, у неё нет срока годности, а ключ может вернуться (v4.32.564
 * выбрал ровно этот же размен для вложений — «диск вернётся, стёртое нет»).
 * Пользователю она видна в списке запланированных с честной подписью вместо
 * пустой строки, и он волен удалить её сам.
 *
 * v4.32.596: тем же чтением через пустую строку болел и столбец с именем
 * отправителя. У группового отложенного сообщения подпись бралась как
 * `msg.senderName || '?'`, и непрочитанное имя уходило ВСЕЙ группе знаком
 * вопроса — а следом такой же подписью ложилось в свою историю и в превью
 * списка. Поправить потом нечем: сообщение отправлено, строка расписания
 * удалена. При этом чинить тут особо нечего — подписывается собственное
 * сообщение, и как нас зовут сейчас, мы знаем и без базы. Поэтому здесь
 * правило подписи, а не отказ от отправки: текст-то прочитался, и держать
 * готовое сообщение из-за подписи было бы несоразмерно.
 *
 * Отдельно — про журнал. Проход идёт раз в тридцать секунд, и непрочитанная
 * строка попадала бы в него две тысячи раз в сутки. Поэтому здесь же живёт
 * память о том, о чём уже сказали: модуль без импортов, но с состоянием, и с
 * `resetScheduledHoldLog()` для тестов (тот же приём, что в openIntent.ts).
 *
 * Модуль намеренно без единого импорта: решение здесь — про три состояния
 * столбца и ни про что больше, и проверяется оно без базы, без ключей, без
 * шифра и без сети.
 */

/** Состояние зашифрованного столбца — те же три, что в atRestCell.ts. */
export type ScheduledCellState = 'absent' | 'plain' | 'unreadable';

/** Прочиталась ли строка расписания целиком. */
export type ScheduledReadState = 'ok' | 'text_unreadable' | 'media_unreadable';

/**
 * Состояние строки по состоянию её столбцов.
 *
 * Текст важнее вложений: без него отправлять нечего вовсе, поэтому он и
 * назван первым. `absent` для `media_cids` — законное «вложений не было».
 */
export function scheduledReadState(cells: {
  text: ScheduledCellState;
  media: ScheduledCellState;
}): ScheduledReadState {
  if (cells.text === 'unreadable') return 'text_unreadable';
  if (cells.media === 'unreadable') return 'media_unreadable';
  return 'ok';
}

/** Почему строка не отправляется. */
export type ScheduledHoldCode = 'text_unreadable' | 'media_unreadable' | 'text_empty';

export type ScheduledVerdict = { kind: 'send' } | { kind: 'hold'; code: ScheduledHoldCode };

/**
 * Можно ли отправлять эту строку.
 *
 * `text_empty` — не придирка к пустому сообщению, а вторая сеть под первой.
 * Пустой текст в таблицу не попадает: и `scheduleMessage`, и
 * `scheduleGroupMessage` требуют `isSendableMessageText`, то есть длину
 * больше нуля. Значит пустота на выходе чтения означает, что чтение не
 * удалось, — даже если состояние столбца об этом почему-либо не сказало.
 */
export function decideScheduledSend(row: {
  text: string;
  readState?: ScheduledReadState;
}): ScheduledVerdict {
  const state = row.readState ?? 'ok';
  if (state !== 'ok') return { kind: 'hold', code: state };
  if (typeof row.text !== 'string' || row.text.length === 0) {
    return { kind: 'hold', code: 'text_empty' };
  }
  return { kind: 'send' };
}

/**
 * Что показать вместо текста в списке запланированных.
 *
 * Пустая строка там выглядела как «сообщение без текста, скоро уйдёт», то
 * есть врала дважды: текст есть, и не уйдёт оно никогда.
 */
export function scheduledHoldTitle(code: ScheduledHoldCode): string {
  if (code === 'media_unreadable') return 'Вложение не открывается — не отправится';
  return 'Сообщение не открывается — не отправится';
}

/**
 * Чем подписать уходящее отложенное сообщение группы (v4.32.596).
 *
 * Порядок такой. Сначала — имя, записанное при постановке в расписание: его
 * автор выбрал сам, и именно оно ожидается в группе. Если столбец не
 * прочитался или имени в нём не было — берётся то, как автора зовут сейчас:
 * это мы, и спрашивать базу об этом не нужно. И только когда неизвестно ни
 * то, ни другое, остаётся «?».
 *
 * Пометка «не удалось прочитать» сюда не попадает никогда: подпись уходит
 * наружу, всей группе, и состояние нашего ключа — не имя отправителя.
 */
export function scheduledSenderLabel(
  row: { senderName?: string | null; senderNameUnreadable?: boolean },
  ownName: string | null | undefined
): string {
  const stored = typeof row.senderName === 'string' ? row.senderName.trim() : '';
  if (row.senderNameUnreadable !== true && stored.length > 0) return stored;
  const own = typeof ownName === 'string' ? ownName.trim() : '';
  return own.length > 0 ? own : '?';
}

/**
 * Сколько разных строк помним. Потолок нужен, чтобы память не росла на
 * устройстве, где расписание набито тысячами строк: дальше потолка молчим
 * совсем, а не начинаем повторяться каждые полминуты.
 */
export const SCHEDULED_HOLD_LOG_CAP = 512;

const reportedHolds = new Set<string>();

/**
 * Первый ли это отказ по этой строке за сессию.
 *
 * Возвращает true ровно один раз на каждый id — дальше проход молчит.
 */
export function shouldReportScheduledHold(id: string): boolean {
  if (typeof id !== 'string' || id.length === 0) return false;
  if (reportedHolds.has(id)) return false;
  if (reportedHolds.size >= SCHEDULED_HOLD_LOG_CAP) return false;
  reportedHolds.add(id);
  return true;
}

/** Забыть, о чём уже говорили. Для тестов и для смены профиля. */
export function resetScheduledHoldLog(): void {
  reportedHolds.clear();
}
