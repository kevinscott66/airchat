/**
 * Имя автора, которое ключ этого устройства не открывает (v4.32.589).
 *
 * Имена в ленте лежат зашифрованными: `author_name` у записи и у комментария,
 * `repost_author_name` у репоста, `viewer_name` у просмотра. Читались они
 * через `decryptAtRestNullable`, а он при неудаче отдаёт пустую строку — не
 * `null`. И вот на этом ломается вся защита, написанная вокруг имён.
 *
 * Запасное значение подставлялось двумя разными способами. Там, где написано
 * `authorName || t('common.contact')`, пустая строка ловится и человек видит
 * «Контакт» — то есть беду прячут, но хотя бы не рисуют пустоту. А там, где
 * написано `authorName ?? t('common.contact')` — а таких мест шесть, — пустая
 * строка не ловится вовсе: `??` подставляет запасное значение только вместо
 * `null` и `undefined`. Заголовок закреплённой записи, имя автора комментария,
 * подпись в меню записи становились пустым местом. Ровно та же ошибка, что
 * разбиралась в `contactLabel` для `displayName`, только источник пустоты
 * здесь другой: не «имя не приехало», а «ключ не открывает».
 *
 * Наружу это тоже утекало. «Поделиться» собирает `${authorName ?? 'AirChat'}:
 * ${text}`, репост с комментарием — `↩ ${authorName ?? 'Контакт'}:`, пересылка
 * в чат — `📤 ${authorName ?? 'Публикация'}:`. У непрочитанного имени все три
 * дают строку, начинающуюся с двоеточия, и это уходит собеседнику.
 *
 * И то же самое уезжает в синхронизацию: выгрузка отдаёт расшифрованные
 * строки, а придерживались (v4.32.588) только те, у которых не открылось
 * содержимое. Запись с читаемым текстом и нечитаемым именем уходила наверх
 * новой ревизией с пустым именем — и здоровые устройства перетирали имя у
 * себя.
 *
 * Правило здесь одно и на все четыре поля: показывать пометку, наружу не
 * отдавать ничего, синхронизацию придерживать. Показ и отдача наружу
 * разведены намеренно — пометка на экране честна, а та же пометка,
 * подставленная в пересылаемое сообщение, выдала бы наше внутреннее состояние
 * за имя автора.
 *
 * Модуль чистый: опирается только на такие же чистые `contactLabel` и
 * `unreadableText`.
 */
import { UNREADABLE_NAME_TEXT } from '../storage/unreadableText';
import { contactLabel } from './contactLabel';

/** Ровно то поле, которое проставляет слой чтения. */
export interface MaybeUnreadableName {
  nameUnreadable?: boolean;
}

/** Не открылось ли имя. */
export function nameIsUnreadable(v: MaybeUnreadableName | null | undefined): boolean {
  return v?.nameUnreadable === true;
}

/**
 * Как назвать автора на экране.
 *
 * Порядок именно такой: сначала «не открылось», потом обычное правило
 * `contactLabel`. Иначе непрочитанное имя, пустое по содержанию, свалилось бы
 * в запасное значение и стало бы неотличимо от безымянного автора — то самое,
 * от чего пометка и заводится.
 */
export function shownName(name: unknown, unreadable: boolean | undefined, fallback: string): string {
  if (unreadable === true) return UNREADABLE_NAME_TEXT;
  return contactLabel(name, fallback);
}

/**
 * Как назвать автора в тексте, который уходит наружу: пересылка, «поделиться»,
 * цитата в репосте.
 *
 * Пометка сюда не попадает никогда. Собеседник не должен читать про состояние
 * нашего ключа, и уж тем более эта строка не должна выглядеть как имя автора
 * записи. Вместо неё встаёт то же запасное значение, что и у безымянного
 * автора, — единственное, что здесь честно.
 */
export function outwardName(name: unknown, unreadable: boolean | undefined, fallback: string): string {
  if (unreadable === true) return fallback;
  return contactLabel(name, fallback);
}

/**
 * Подпись автора в строке списка, где имени может не быть вовсе (v4.32.602).
 *
 * Отличается от `shownName` ровно одним: запасного значения нет. В списке
 * групп подпись — необязательная приставка «Имя: » перед текстом реплики, и у
 * канала или у служебной строки её законно нет. Подставить туда «Контакт»
 * значило бы придумать автора; вернуть пустую строку на непрочитанном имени —
 * молча его потерять. Поэтому здесь три исхода, а не два.
 */
export function shownNameOrNull(name: unknown, unreadable: boolean | undefined): string | null {
  if (unreadable === true) return UNREADABLE_NAME_TEXT;
  return typeof name === 'string' && name.trim().length > 0 ? name : null;
}

/** Можно ли вообще подставлять это имя в исходящий текст без запасного значения. */
export function mayReuseName(unreadable: boolean | undefined): boolean {
  return unreadable !== true;
}
