/**
 * Что делать с полем meta-конверта группы: применить и объявить ли об этом.
 *
 * Дефект. Разбор конверта сравнивал присланное со своим значением
 * (`env.name !== group.name`) и на любое расхождение писал в историю строку
 * «Группа переименована в «X»». Своё значение читалось через
 * `decryptAtRestString`, а он на неудачной расшифровке отдаёт пустую строку.
 * Значит, когда ключ данных перестал открывать строку группы, своё название
 * становилось пустым — и ПЕРВЫЙ же служебный конверт от любого администратора
 * (а он приходит и при смене аватара, и при смене настроек, потому что name в
 * нём едет всегда) печатал в переписке событие, которого не было: никто
 * группу не переименовывал. То же с аватаром: «Аватар группы обновлён» на
 * ровном месте.
 *
 * Хуже того, ложь была устойчивой. Название после такого конверта
 * записывалось заново уже читаемым, а строка о переименовании оставалась в
 * истории навсегда и выглядела как действие администратора. Единственный
 * настоящий признак беды — что своя копия не читается — не назывался нигде.
 *
 * Решение. Три различимых случая вместо двух:
 *
 *   присланного нет            — не трогаем ничего;
 *   своё не прочиталось        — применяем (значение приехало от участника
 *                                группы и лечит строку), но НЕ объявляем:
 *                                сравнить было не с чем, и что именно
 *                                изменилось, мы не знаем;
 *   своё прочиталось           — как раньше: применяем и объявляем только
 *                                настоящее расхождение.
 *
 * Модуль без единого импорта: правило здесь — про три состояния одного поля,
 * и проверяется оно без базы, без ключей и без сети.
 */

/** Что делать с полем: записать себе и написать ли об этом в историю. */
/** Что делать с собственной записью описания группы. */
export type OwnDescriptionWrite = { write: boolean; reason: 'ok' | 'emptyOverUnreadable' };

/**
 * v4.32.579: администратор видит карточку, в которой описания нет, потому что
 * столбец не открылся ключом данных. Пустое поле правки, выйдя из фокуса,
 * записало бы пустую строку поверх целого шифртекста — и «не открылось»
 * навсегда стало бы «нет описания», у себя и у всех участников сразу.
 * Пустую запись поверх непрочитанного запрещаем; написанное руками новое
 * описание проходит — оно осмысленная замена, а не молчаливая потеря.
 */
export function decideOwnDescriptionWrite(next: string, ownUnreadable?: boolean): OwnDescriptionWrite {
  if (ownUnreadable === true && next === '') return { write: false, reason: 'emptyOverUnreadable' };
  return { write: true, reason: 'ok' };
}

export type MetaFieldDecision = {
  /** Записать присланное значение в свою строку группы. */
  apply: boolean;
  /** Написать в переписку системную строку о произошедшем. */
  announce: boolean;
};

const NOTHING: MetaFieldDecision = { apply: false, announce: false };

/**
 * Решение по одному текстовому полю конверта.
 *
 * `ownUnreadable` — свой столбец есть, но ключом данных не открывается
 * (см. atRestCell). Пустая своя строка при этом остаётся законным значением:
 * группа без описания и группа без аватара — обычное дело, и объявлять о
 * появлении описания в такой группе правильно.
 */
export function decideMetaField(
  incoming: string | null | undefined,
  own: string,
  ownUnreadable?: boolean
): MetaFieldDecision {
  if (incoming === null || incoming === undefined) return NOTHING;
  if (ownUnreadable === true) return { apply: true, announce: false };
  if (incoming === own) return NOTHING;
  return { apply: true, announce: true };
}
