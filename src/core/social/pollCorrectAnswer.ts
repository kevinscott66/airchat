/**
 * pollCorrectAnswer — куда переезжает отметка «верный ответ», когда из формы
 * викторины удаляют вариант.
 *
 * v4.32.652. В GroupPollCreatorModal correctAnswer — это индекс строки в
 * options, а removeOption перенумеровывал options, не трогая correctAnswer.
 * Отметив «Б» в списке «А, Б, В» и удалив «А», человек получал список
 * «Б, В» с индексом 1 — то есть верным вариантом становилось «В». Ни ошибки,
 * ни предупреждения: галочка просто переезжала, и в группу уходила викторина
 * с чужим правильным ответом. (v4.32.622 закрыл ровно этот сдвиг для пустых
 * вариантов, но не для удалённых.)
 *
 * Удаление самого отмеченного варианта отметку снимает (-1), а не переносит
 * на соседний: молча назначить верным то, чего человек не выбирал, — та же
 * ошибка с другого конца. Форма после этого попросит отметить вариант заново.
 */

/** Нет отмеченного варианта. */
export const NO_CORRECT_ANSWER = -1;

/**
 * Новый индекс верного варианта после удаления варианта с индексом removed.
 */
export function correctAnswerAfterRemove(correct: number, removed: number): number {
  if (correct < 0) return NO_CORRECT_ANSWER;
  if (removed === correct) return NO_CORRECT_ANSWER;
  return removed < correct ? correct - 1 : correct;
}
