/**
 * pollVoteGuard — проверка входящего голоса против самого опроса.
 *
 * v4.32.342. Реакция хранится прямо в строке сообщения, поэтому чужой id в
 * конверте не находит ничего и сам собой ничего не портит. Голос устроен иначе:
 * poll_votes — отдельная таблица, где кроме message_id о сообщении ничего не
 * известно, ни ссылки на него, ни даже того, из какой оно таблицы. Из-за этого
 * приёмная сторона писала строку по любому id, который назвали в конверте.
 *
 * Что это давало отправителю конверта:
 *
 * 1. Обход проверки прав в группе. Проверка «участник и не забанен» стояла
 *    внутри `if (env.groupId)`. Достаточно было не указывать groupId — и тот же
 *    самый голос по тому же message_id ложился в ту же строку, минуя её целиком.
 *    Забаненный участник, вышедший участник и просто посторонний контакт
 *    голосовали в любом групповом опросе, id которого им известен.
 * 2. Голос в чужой переписке. Для личного опроса не проверялось ничего вообще:
 *    контакт голосовал в опросе, который идёт между двумя другими людьми, и в
 *    неанонимном опросе его имя появлялось в списке проголосовавших.
 * 3. Накрутка через multi. Флаг «несколько ответов» брался из конверта, а не из
 *    опроса. С multi: true хранилище не вытесняет прошлый голос того же
 *    человека — и один голосующий занимал все двенадцать вариантов опроса, в
 *    котором ответ полагается ровно один. Счётчик одиночного опроса считает
 *    строки, так что «Всего» вырастал на двенадцать с одного человека.
 * 4. Голос за несуществующий вариант. Индекс ограничивался числом 11 — потолком
 *    формата, а не числом вариантов конкретного опроса. Строка с idx = 9 в
 *    опросе на два варианта не рисуется нигде, но входит в «Всего», из-за чего
 *    проценты у вариантов молча переставали складываться в сто.
 *
 * Лента всё это проверяла с самого начала (feed_poll_vote: пост есть, это
 * опрос, индекс внутри его вариантов, allowMultiple из поста). Здесь ровно тот
 * же набор, только источник фактов — личный чат или группа.
 *
 * Модуль чистый: факты о сообщении собирает вызывающий, здесь только решение.
 */

import { parsePollText } from './pollEnvelope';

/**
 * Что нашлось в БД по message_id из конверта.
 *
 * `missing` — не нашлось ничего: либо id выдуман, либо сообщение-опрос до нас
 * ещё не доехало.
 */
/**
 * `text: null` — строка в базе есть, но своя копия не открывается (v4.32.574).
 * Это не то же самое, что пустой текст: пустой текст — честный ответ «это не
 * опрос», нечитаемая копия — «мы не знаем, опрос это или нет».
 */
export type PollMessageFacts =
  | { kind: 'missing' }
  | { kind: 'dm'; contactPubB64: string; text: string | null }
  | { kind: 'group'; groupId: string; text: string | null };

export type PollVoteVerdict =
  | { ok: true; allowMultiple: boolean }
  | { ok: false; code: PollVoteRejectCode };

export type PollVoteRejectCode =
  | 'unknown_message'
  | 'unreadable_message'
  | 'wrong_group'
  | 'not_in_chat'
  | 'not_a_poll'
  | 'index_out_of_range';

/**
 * Решает, можно ли записать голос.
 *
 * `senderPubB64` — ключ ПОДПИСАННОГО отправителя DM, не поле конверта.
 *
 * Возвращаемый `allowMultiple` берётся из текста опроса и заменяет одноимённое
 * поле конверта: у отправителя голоса нет права решать, вытеснять ли его
 * прошлый выбор.
 */
export function checkIncomingPollVote(
  facts: PollMessageFacts,
  env: { idx: number; groupId?: string },
  senderPubB64: string
): PollVoteVerdict {
  if (facts.kind === 'missing') return { ok: false, code: 'unknown_message' };

  if (env.groupId) {
    // Сообщение обязано лежать именно в той группе, которую назвал конверт.
    // Иначе участник группы А голосует в опросе группы Б: проверка членства
    // выше смотрит на А, а строка пишется по id сообщения из Б.
    if (facts.kind !== 'group' || facts.groupId !== env.groupId) {
      return { ok: false, code: 'wrong_group' };
    }
  } else {
    // Личный опрос: он обязан быть из переписки с самим отправителем. Чей это
    // опрос — его или мой — неважно, важно, что он в этом диалоге.
    if (facts.kind !== 'dm' || facts.contactPubB64 !== senderPubB64) {
      return { ok: false, code: 'not_in_chat' };
    }
  }

  // v4.32.574: своя копия сообщения не открылась. Раньше сюда приходила
  // пустая строка (decryptAtRestString отдаёт '' на осечке), parsePollText
  // честно говорил «не опрос», и в журнале оставался код not_a_poll — то есть
  // след указывал на отправителя голоса, хотя сломано было у нас. Отдельный
  // код не чинит саму строку, но перестаёт врать о причине.
  if (facts.text === null) return { ok: false, code: 'unreadable_message' };

  const poll = parsePollText(facts.text);
  if (!poll) return { ok: false, code: 'not_a_poll' };
  if (env.idx < 0 || env.idx >= poll.options.length) {
    return { ok: false, code: 'index_out_of_range' };
  }
  return { ok: true, allowMultiple: poll.allowMultiple ?? false };
}
