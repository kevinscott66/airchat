/**
 * Пачка отметок о прочтении — v4.32.507.
 *
 * Дефект: приёмная сторона брала `messageIds` из конверта как есть и шла в
 * базу за автором КАЖДОГО идентификатора. Массив ничем не ограничен, а
 * запросы идут по одному и последовательно: сто тысяч строк в конверте —
 * сто тысяч чтений из SQLite подряд, и приёмный цикл встаёт вместе со всем
 * приложением. Повторяющиеся идентификаторы считались отдельными, так что
 * одна и та же строка, размноженная в конверте, стоила ровно столько же.
 *
 * Правило одно на оба конца: отправитель не кладёт в конверт больше, чем
 * получатель готов принять, и получатель верит не конверту, а этому же
 * правилу. Держать его в одном месте — единственный способ не дать концам
 * разъехаться: разъехавшись, они дают либо молча теряемые отметки, либо
 * снова неограниченный вход.
 *
 * Модуль без импортов.
 */

/**
 * Сколько отметок разумно за один конверт. Переписка открывается на
 * страницу в сотню сообщений; двести — запас на пачку, накопленную офлайн.
 */
export const MAX_RECEIPT_IDS = 200;

/** Идентификатор сообщения — uuid; сто двадцать восемь байт с запасом. */
export const MAX_RECEIPT_ID_LEN = 128;

/**
 * Приводит присланный список к тому, что можно отдать в базу: только
 * непустые строки разумной длины, без повторов, не длиннее потолка.
 *
 * Порядок сохраняется, лишнее отсекается с конца: список приходит от
 * свежих сообщений к старым, и потерять хвост менее заметно, чем голову.
 * Возвращает новый массив — исходный не трогается.
 */
export function sanitizeReceiptIds(raw: unknown, max: number = MAX_RECEIPT_IDS): string[] {
  if (!Array.isArray(raw)) return [];
  const limit = Number.isFinite(max) && max > 0 ? Math.trunc(max) : MAX_RECEIPT_IDS;
  const out: string[] = [];
  const seen = new Set<string>();
  for (const item of raw) {
    if (out.length >= limit) break;
    if (typeof item !== 'string') continue;
    if (item.length === 0 || item.length > MAX_RECEIPT_ID_LEN) continue;
    if (seen.has(item)) continue;
    seen.add(item);
    out.push(item);
  }
  return out;
}

/**
 * Сколько записей отброшено — только для журнала. Считается по исходному
 * списку, чтобы в логе была видна разница между «прислали двести» и
 * «прислали сто тысяч».
 */
export function receiptOverflowCount(raw: unknown, kept: number): number {
  if (!Array.isArray(raw)) return 0;
  const extra = raw.length - kept;
  return extra > 0 ? extra : 0;
}
