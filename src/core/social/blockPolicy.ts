/**
 * Что переживает блокировку собеседника (v4.32.491).
 *
 * Блокировка в личке появилась в v4.32.175 и проверялась ровно в двух местах:
 * перед показом «печатает…» и перед сохранением текстовой строки. Всё
 * остальное, что умеет присылать собеседник, диспетчеризовалось ВЫШЕ этой
 * проверки и применялось к базе безусловно: таймер исчезающих сообщений,
 * реакции, закреплённое сообщение, имя с фотографией в моих контактах, сторис
 * в моей ленте, голоса в опросах, отметки о прочтении. То есть заблокированный
 * человек молчал на экране, но продолжал менять состояние приложения — а
 * `\x11dis:` вдобавок рисовал видимую системную строку и запускал стирание
 * переписки. Комментарий над проверкой обещал обратное: «блок не должен быть
 * только скрытием UI».
 *
 * Теперь блок-лист спрашивается один раз, до всей диспетчеризации. Исключение
 * — конверты, которые адресованы не мне лично, а группе: состояние группы
 * задаётся ролями в ней, а не моим личным списком. Если тихо выбрасывать
 * `\x0egctl:` от заблокированного администратора, у меня останется своё
 * представление о составе и правах группы, расходящееся с общим, и починить
 * его будет нечем. Личный список остаётся личным: он молчит собеседника, а не
 * ломает общий чат.
 *
 * Модуль намеренно без импортов — префиксы объявлены рядом с обработчиками
 * (`groupMessaging`, `groupControlEnvelope`), а те тянут за собой базу.
 * Совпадение строк удерживает рэтчет `blockPolicy.test.ts`.
 */

/** Префиксы конвертов, адресованных группе, а не лично мне. */
export const GROUP_SCOPED_PREFIXES = [
  '\x02grp:', // сообщение в группе
  '\x03grpr:', // отметка о прочтении в группе
  '\x0agjr:', // заявка на вступление
  '\x0egctl:', // бан/кик/роль/мета
] as const;

/**
 * Пропускать ли конверт мимо блок-листа.
 *
 * `text` — сырой текст входящего конверта; у служебных payload'ов (`delete`,
 * `edit`, `read_receipt`, `typing`) его нет, и они блокировку не переживают.
 */
export function survivesBlock(text: unknown): boolean {
  if (typeof text !== 'string') return false;
  return GROUP_SCOPED_PREFIXES.some((p) => text.startsWith(p));
}
