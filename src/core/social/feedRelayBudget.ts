/**
 * Сколько чужих конвертов моя нода берётся переслать (v4.32.943).
 *
 * ЧТО ЗДЕСЬ ПРОИСХОДИТ БЕЗ ПРЕДЕЛА. Лента расходится сплетней: конверт,
 * пришедший от соседа, заворачивается обратно и уходит всем моим контактам,
 * кроме автора и того, от кого пришёл (`feedGossipRelay`). Ограничители на
 * этом пути были, но каждый считал не то:
 *
 *   - число прыжков (`FEED_RELAY_MAX_HOPS`) держит глубину, а не частоту;
 *   - отметка «уже переслали» (`feedRelayedKeys`) держит повторы одного и
 *     того же конверта, а не поток разных;
 *   - веер (64 контакта) держит цену одной пересылки, а не число пересылок.
 *
 * То есть всё вместе означало: один конверт стоит до 64 исходящих посылок, а
 * сколько конвертов в минуту — не спрашивал никто. Подписанных конвертов
 * можно наделать сколько угодно: подпись доказывает, что автор их написал, и
 * ничего не говорит о том, сколько их. Меняется `ts` — меняется ключ отметки,
 * и каждый следующий проходит как новый.
 *
 * ЦЕНА. Не «спам в ленте» — спам отсеется у соседей по их же отметке. Цена в
 * том, что платит за него моя нода: радио, батарея, трафик. И платят соседи,
 * для которых источником этого потока выгляжу я, а не тот, кто его завёл.
 * Заблокировать они могут только меня.
 *
 * ПОЧЕМУ СЧЁТ ПО АВТОРУ, А НЕ ПО СОСЕДУ. Сосед назван в заголовке кадра, и
 * заголовок никем не заверен; у интернет-ретранслятора его нет вовсе
 * (`receiveFeedEnvelope`, v4.32.472). Считать по имени, которое отправитель
 * пишет себе сам, — значит считать по тому, что он же и подменит. Автор
 * назван внутри подписанного тела и к этому моменту уже проверен подписью.
 *
 * Своих ключей злоумышленник тоже наделает сколько угодно, и один только
 * счёт по автору его не остановит. Поэтому предела два, и настоящая граница —
 * общий: он назван в посылках, которые моё радио согласно потратить на чужое
 * за минуту. Счёт по автору стоит рядом не вместо него, а чтобы один шумный
 * источник не съедал общую квоту целиком, оставляя остальных без пересылки.
 *
 * ЧТО ТЕРЯЕТСЯ ПРИ ОТКАЗЕ. Только пересылка. Конверт, на котором кончилась
 * квота, разбирается и сохраняется как обычно: отказ здесь — это «дальше я
 * его не понесу», а не «я его не видел». Сеть от этого не рвётся, потому что
 * сплетня избыточна по устройству: у соседа есть свои соседи.
 */

/** Окно, за которое считаются пересылки. */
export const FEED_RELAY_WINDOW_MS = 60_000;

/**
 * Сколько чужих конвертов уходит соседям за минуту — всего.
 *
 * Шестьдесят пересылок это до 64 × 60 ≈ четырёх тысяч исходящих посылок в
 * минуту в худшем случае (полный веер у каждой). Уже немало; брать больше
 * значило бы признать, что предела нет. Живой ленте столько не нужно:
 * пересылается только то, что пришло впервые, и только не-просмотры.
 */
export const FEED_RELAY_MAX_PER_MINUTE = 60;

/** Сколько из них достаётся одному автору. Треть общего: шумный не съедает всё. */
export const FEED_RELAY_MAX_PER_AUTHOR = 20;

/**
 * Учёт пересылок за скользящую минуту.
 *
 * Часы передаются снаружи, а не берутся из `Date.now()`: предел частоты — это
 * ровно утверждение о времени, и класс, который смотрит на часы сам, нечем
 * проверить. Тот же приём, что у `BridgeGuard`.
 */
export class FeedRelayBudget {
  /** Время всех разрешённых пересылок окна. */
  private all: number[] = [];
  /** То же, разложенное по авторам. */
  private byAuthor = new Map<string, number[]>();

  /**
   * Разрешить пересылку и сразу её засчитать.
   *
   * Отдельного «посмотреть, не считая» нет нарочно: вызывающий один, и два
   * шага вместо одного означали бы возможность спросить и не воспользоваться,
   * оставив квоту потраченной.
   *
   * Карта авторов не растёт без предела: запись в ней заводится только при
   * разрешённой пересылке, разрешений за окно не больше `FEED_RELAY_MAX_PER_MINUTE`,
   * а опустевшие записи вычищаются тем же проходом.
   */
  admit(authorDid: string, now: number): boolean {
    this.sweep(now);
    if (this.all.length >= FEED_RELAY_MAX_PER_MINUTE) return false;
    const mine = this.byAuthor.get(authorDid);
    if (mine && mine.length >= FEED_RELAY_MAX_PER_AUTHOR) return false;
    this.all.push(now);
    if (mine) mine.push(now);
    else this.byAuthor.set(authorDid, [now]);
    return true;
  }

  /** Сколько пересылок уже потрачено за окно. Для журнала и проверок. */
  spent(now: number): number {
    this.sweep(now);
    return this.all.length;
  }

  private sweep(now: number): void {
    const cut = now - FEED_RELAY_WINDOW_MS;
    this.all = this.all.filter((t) => t > cut);
    for (const [author, times] of this.byAuthor) {
      const left = times.filter((t) => t > cut);
      if (left.length === 0) this.byAuthor.delete(author);
      else this.byAuthor.set(author, left);
    }
  }
}
