/**
 * liveLocFreshness — в каком состоянии живая геолокация: идёт, замерла или
 * закончилась. Модуль без импортов: решение о том, что показать человеку,
 * проверяется отдельно от карты, тем и SQLite.
 *
 * v4.32.563. Пузырь живой геолокации судил о происходящем по одному лишь
 * `expireAt` — числу, записанному в посылку в момент запуска сессии и с тех пор
 * не менявшемуся. Отсюда два разных обмана, и оба в одну сторону: человек
 * видел «идёт» там, где не шло ничего.
 *
 * Первый. Рассылка живёт обычным setInterval внутри процесса приложения
 * (liveLocationService). Приложение закрыли, система выгрузила его из памяти,
 * профиль переключили — таймер исчезает вместе с ними, и последняя посылка
 * остаётся последней навсегда. Собеседнику об этом не сообщает никто: у него
 * до восьми часов горит зелёная плашка LIVE, стоит подпись «Живая геолокация»
 * и «ещё N мин» — над точкой, которая давно не двигалась. Человек ждёт на
 * перекрёстке, глядя на метку, которая больше не про «сейчас».
 *
 * Поэтому состояние считается ещё и по возрасту последней посылки. Отправитель
 * с этой версии кладёт в посылку время отправки (`ts`), и молчание длиннее
 * нескольких тактов рассылки называется своим именем: «не обновляется»,
 * с указанием, когда была последняя точка. Посылка без `ts` — это старый
 * отправитель, и о нём честнее ничего не выдумывать: для него остаётся прежнее
 * правило «жива до срока». Обратной силы у правки нет, и так и должно быть.
 *
 * Второй обман был грубее и жил в разборе конверта: `parseLiveLoc` отвергал
 * посылку, чей `expireAt` уже прошёл больше минуты назад. То есть ровно
 * закончившуюся сессию — ту самую, ради которой в пузыре написана ветка
 * «Геолокация завершена». Ветка была мертва: через минуту после конца разбор
 * возвращал null, и в личной переписке пузырь схлопывался в пустой прямоугольник,
 * а в группе на экран выпадал сырой конверт со служебным символом и JSON.
 * Проверка нужна была против `expireAt` НА СТО ЛЕТ ВПЕРЁД (вечное «LIVE»),
 * и верхняя граница осталась на месте; прошедший срок — не подделка, а просто
 * законченная сессия, и показывать её надо законченной.
 *
 * Пороги здесь заданы числами, а не импортом из liveLocationService: тот тянет
 * uuid, expo-location и профили. Равенство такта рассылки держит проверка.
 */

/** Идёт / замерла / закончилась. */
export type LiveLocState = 'live' | 'stale' | 'ended';

/**
 * Такт рассылки координат. Копия LIVELOC_UPDATE_INTERVAL_MS из
 * liveLocationService; совпадение проверяется в тестах.
 */
export const LIVELOC_TICK_MS = 30_000;

/**
 * Сколько тактов молчания прощаем, прежде чем сказать «не обновляется».
 * Два пропущенных такта — это ещё сеть или экономия батареи; три — это уже
 * не «сейчас», и молчать об этом нельзя.
 */
export const LIVELOC_STALE_TICKS = 3;

function isNum(v: unknown): v is number {
  return typeof v === 'number' && Number.isFinite(v);
}

/** Порог молчания в миллисекундах. Такт меньше настоящего порог не занижает. */
export function liveLocStaleAfterMs(intervalMs?: number | null): number {
  const tick = isNum(intervalMs) && intervalMs > 0 ? intervalMs : LIVELOC_TICK_MS;
  return Math.max(tick, LIVELOC_TICK_MS) * LIVELOC_STALE_TICKS;
}

export type LiveLocTiming = {
  /** Срок окончания сессии из посылки. */
  expireAt: number;
  /** Сейчас. */
  now: number;
  /** Время последней посылки, если отправитель его прислал. */
  updatedAt?: number | null;
  /** Такт рассылки, если он не обычный. */
  intervalMs?: number | null;
};

export function liveLocState(t: LiveLocTiming): LiveLocState {
  // Нечисловой срок сюда не доходит (конверт такой не разбирается), но если
  // дойдёт — «закончилась» безопаснее «идёт»: обещать живое нечем.
  if (!isNum(t.expireAt) || !isNum(t.now)) return 'ended';
  if (t.now >= t.expireAt) return 'ended';
  if (!isNum(t.updatedAt)) return 'live';
  // Время из будущего — расхождение часов, а не свежесть: считаем свежим,
  // старее не сделаешь. Разбор конверта дальнюю подделку уже отсекает.
  const silence = t.now - t.updatedAt;
  return silence > liveLocStaleAfterMs(t.intervalMs) ? 'stale' : 'live';
}

/** Заголовок пузыря. Три состояния — три разные строки, и ни одна не врёт. */
export function liveLocTitle(state: LiveLocState): string {
  if (state === 'ended') return 'Геолокация завершена';
  if (state === 'stale') return 'Геолокация не обновляется';
  return 'Живая геолокация';
}

/**
 * Строка под координатами. Пустая — значит добавлять к координатам нечего.
 */
export function liveLocDetail(t: LiveLocTiming): string {
  const state = liveLocState(t);
  if (state === 'ended') return '';
  if (state === 'stale') {
    const mins = Math.floor((t.now - (t.updatedAt as number)) / 60_000);
    return mins < 1 ? 'последняя точка меньше минуты назад' : `последняя точка ${mins} мин назад`;
  }
  const mins = Math.floor((t.expireAt - t.now) / 60_000);
  // v4.32.563 (косметика): в последнюю минуту сессии стояло «ещё 0 мин».
  return mins < 1 ? 'ещё меньше минуты' : `ещё ${mins} мин`;
}
