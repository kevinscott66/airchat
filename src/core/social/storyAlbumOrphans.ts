/**
 * Строки альбомов, за которыми альбома не осталось (v4.32.684).
 *
 * `story_album_items` живёт без внешнего ключа на `story_albums` — так же, как
 * все остальные таблицы этой базы: SQLite здесь работает без FK, а связность
 * держат прикладные правила. Из облачной копии строка альбома приезжает
 * отдельной сущностью от самого альбома (`story_album_item` и `story_album` —
 * разные виды с разными счётчиками ревизий), и порядок между ними ничем не
 * закреплён. Строка, приехавшая к альбому, которого на этом устройстве нет и
 * уже не будет, не видна нигде: список альбомов идёт ОТ альбомов, содержимое
 * запрашивают по id альбома, удаление тоже адресуют альбому. При этом она
 * вечно уезжает обратно в облако при каждой выгрузке и держит на диске копию
 * снимка — `storyAlbumFileNames` берёт `media_file` из ВСЕХ строк, и общая
 * уборка файлов считает такой файл нужным.
 *
 * Отсюда правило ниже. Оно намеренно не мгновенное: строка, обогнавшая свой
 * альбом внутри одного захода, — обычное дело, и снести её значило бы потерять
 * то, что человек оставил себе. Сутки — заведомо больше, чем идёт один заход
 * синхронизации, и заведомо меньше, чем «никогда»: альбом, не приехавший за
 * сутки, не приедет.
 */

/** Сколько строка ждёт свой альбом, прежде чем считаться потерянной. */
export const ALBUM_ORPHAN_GRACE_MS = 24 * 60 * 60 * 1000;

/** Минимум полей строки альбома, по которым решается её судьба. */
export type AlbumOrphanCandidate = {
  id: string;
  albumId: string;
  /** Когда историю положили в альбом. */
  addedAt: number;
  mediaUnreadable?: boolean;
};

/**
 * Выбрать строки, потерявшие альбом.
 *
 * Не считаются потерянными: строка живого альбома; строка, чьё имя файла не
 * прочиталось (снести её — потерять единственный адрес копии на диске, ровно
 * та же цена, что у `sweepOrphanAlbumFiles` при неполном списке); строка со
 * временем из будущего или без времени вовсе — про её возраст мы ничего не
 * знаем, а гадать здесь нельзя.
 */
export function orphanAlbumItems<T extends AlbumOrphanCandidate>(
  items: readonly T[],
  albumIds: Iterable<string>,
  now: number,
  graceMs: number = ALBUM_ORPHAN_GRACE_MS,
): T[] {
  const alive = new Set(albumIds);
  return items.filter((item) => {
    if (alive.has(item.albumId)) return false;
    if (item.mediaUnreadable) return false;
    if (!Number.isFinite(item.addedAt)) return false;
    return now - item.addedAt >= graceMs;
  });
}
