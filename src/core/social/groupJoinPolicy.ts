/**
 * groupJoinPolicy — что делать с конвертом 'join' («я вступил по ссылке»).
 *
 * v4.32.259 (CRIT). Гейт «Вход по ссылке требует одобрения» проверяла сама
 * ссылка. Флаг requireApproval лежал прямо в base64-полезной нагрузке
 * приглашения, и App.tsx по нему решал: отправить администратору заявку или
 * сразу представиться конвертом 'join'. А приёмник конверт 'join' применял
 * безоговорочно — добавлял человека в участники и на этом успокаивался.
 *
 * То есть решение о том, нужно ли одобрение, принимал ровно тот, кого оно
 * ограничивает. Достаточно было раскодировать ссылку, поставить
 * requireApproval:false, закодировать обратно и открыть у себя — и любой
 * обладатель ссылки входил мимо одобрения, а владелец группы видел «X
 * вступил(а)» уже постфактум. Настройка держалась до первого, кто о ней узнал.
 *
 * Та же ошибка ловится и без злого умысла: ссылка, выданная до включения
 * одобрения, несёт requireApproval:false навсегда.
 *
 * Правило вынесено сюда, потому что решает его приёмник и только он. Модуль
 * чистый — без БД и сети, поэтому проверяется тестами целиком.
 */
import type { MemberRole } from '../storage/local';

export type JoinVerdict =
  /** Записать в участники и объявить системной строкой. */
  | 'add'
  /** Положить в список заявок — их разбирает администратор. */
  | 'queue'
  /** Ничего не делать: либо уже участник, либо решать не нам. */
  | 'ignore'
  /** Забанен: не возвращается, сколько бы раз ни переслал себе ссылку. */
  | 'banned';

export function decideJoin(params: {
  /** Роль вступающего в НАШЕЙ таблице участников; undefined — незнаком. */
  knownRole: MemberRole | undefined;
  /** Настройка группы у нас. */
  requireApproval: boolean;
  /** Можем ли мы одобрять заявки в этой группе. */
  iAmAdmin: boolean;
  /** Заявитель у нас в контактах. */
  requesterIsContact?: boolean;
  /** Настройка «Добавление в группы — только контакты» включена. */
  onlyContactsMayRequest?: boolean;
}): JoinVerdict {
  const { knownRole, requireApproval, iAmAdmin, requesterIsContact = false, onlyContactsMayRequest = false } = params;
  if (knownRole === 'banned') return 'banned';
  // Уже участник — повторное представление ничего не меняет. Проверка идёт
  // раньше гейта: одобренному не нужно одобряться заново при переустановке.
  if (knownRole !== undefined) return 'ignore';
  if (!requireApproval) return 'add';
  // Конверт 'join' рассылается всем известным вступающему участникам, но
  // заявку кладёт себе только тот, кто её сможет разобрать.
  if (!iAmAdmin) return 'ignore';
  return acceptJoinRequest({ knownRole, requesterIsContact, onlyContactsMayRequest }) ? 'queue' : 'ignore';
}

/**
 * Пускать ли заявку в список администратора.
 *
 * v4.32.264. Заявка попадает к администратору двумя разными дорогами, и до
 * этой версии они расходились в проверках:
 *
 *   '\x0agjr:' (личное сообщение администратору) — отсекал незнакомцев при
 *              включённой настройке «Добавление в группы — только контакты»,
 *              но пускал в список забаненного: администратор видел заявку,
 *              жал «Принять» и получал отказ «заблокирован(а)»;
 *   'join'     (управляющий конверт) — наоборот: бан держал, а фильтр по
 *              контактам не знал вовсе. Достаточно было ссылки со снятым
 *              requireApproval, чтобы незнакомец всё равно оказался в списке
 *              заявок — то есть настройка приватности обходилась той же
 *              правкой ссылки, что и сам гейт одобрения.
 *
 * Обе дороги теперь спрашивают здесь. Функция чистая: «в контактах ли» и
 * «включена ли настройка» вычисляет вызывающий (это БД и kv), а решение —
 * одно на оба пути.
 */
export function acceptJoinRequest(params: {
  knownRole: MemberRole | undefined;
  requesterIsContact: boolean;
  onlyContactsMayRequest: boolean;
}): boolean {
  const { knownRole, requesterIsContact, onlyContactsMayRequest } = params;
  if (knownRole === 'banned') return false;
  if (onlyContactsMayRequest && !requesterIsContact) return false;
  return true;
}
