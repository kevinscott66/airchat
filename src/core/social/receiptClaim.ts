/** Сколько идентификаторов помним. Хватает на любую разумную переписку. */
const DEFAULT_LIMIT = 512;

export interface ReceiptClaims {
  /** Отобрать те, что ещё не отправлялись, и сразу пометить их занятыми. */
  claim(ids: readonly unknown[]): string[];
  /** Вернуть в работу: отправка не удалась, отметка должна уйти позже. */
  release(ids: readonly string[]): void;
  /** Сколько помним сейчас — для проверок. */
  size(): number;
}

export function createReceiptClaims(limit: number = DEFAULT_LIMIT): ReceiptClaims {
  const cap = Number.isFinite(limit) && limit > 0 ? Math.floor(limit) : DEFAULT_LIMIT;
  // Set в JS хранит порядок вставки, поэтому первый ключ — самый старый.
  const taken = new Set<string>();

  const evict = (): void => {
    while (taken.size > cap) {
      const oldest = taken.values().next();
      if (oldest.done) return;
      taken.delete(oldest.value);
    }
  };

  return {
    claim(ids) {
      const fresh: string[] = [];
      for (const raw of ids) {
        if (typeof raw !== 'string') continue;
        const id = raw.trim();
        if (!id || taken.has(id)) continue;
        taken.add(id);
        fresh.push(id);
      }
      evict();
      return fresh;
    },
    release(ids) {
      for (const id of ids) {
        if (typeof id === 'string') taken.delete(id);
      }
    },
    size() {
      return taken.size;
    },
  };
}
