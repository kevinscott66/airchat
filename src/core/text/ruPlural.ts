/**
 * Русское склонение числительных — в одном месте.
 *
 * v4.32.421. Правило было записано трижды. Две копии совпадали до буквы
 * (ui/utils/plural и core/social/disappearEnvelope), а третья — подпись «был(а)
 * N часов назад» — была написана заново и короче:
 *
 *     const plural = hrs === 1 ? 'час' : hrs < 5 ? 'часа' : 'часов';
 *
 * На 1–4 часах она совпадает с правильной, поэтому и прожила долго. Но
 * диапазон-то до 23: собеседник, заходивший 22 часа назад, подписывался
 * «был(а) 22 часов назад», а 21 час назад — «21 часов». Сокращённое правило
 * смотрит на число целиком, а склонение решает последняя цифра — кроме
 * одиннадцати–четырнадцати, где решают две последние.
 */

/** Формы: [1, 2–4, 5+]. Например `['час', 'часа', 'часов']`. */
export type RuPluralForms = readonly [string, string, string];

export function ruPlural(n: number, forms: RuPluralForms): string {
  const abs = Math.abs(n) % 100;
  const n1 = abs % 10;
  if (abs > 10 && abs < 20) return forms[2];
  if (n1 > 1 && n1 < 5) return forms[1];
  if (n1 === 1) return forms[0];
  return forms[2];
}

/**
 * Минуты и часы во фразе — формы здесь, а не рядом с каждой подписью
 * (v4.32.928).
 *
 * Эти две единицы называются в доме чаще всех прочих и по обе стороны границы
 * ядра и интерфейса: «был(а) 20 минут назад» и «ещё 12 минут» считает ядро,
 * «Попробуйте через 5 минут» и подпись просмотра — интерфейс. Ядру нельзя
 * импортировать из `ui/`, так что без общего места список слов расходится по
 * четырём файлам — а расползшееся правило склонения в этом доме уже однажды
 * дало «был(а) 22 часов назад».
 *
 * Падеж винительный. Он один подходит обеим рамкам, в которых это число
 * стоит: «через N» и «N назад». У «часа» винительный совпадает с
 * именительным — слово неодушевлённое, — и потому часы склонялись верно даже
 * там, где падеж никто не выбирал. У «минуты» не совпадает: «1 минуту назад»,
 * а не «1 минута назад». Ровно поэтому минуты дольше всех и прожили обрубком
 * «мин»: сокращение снимало вопрос, которого никто не заметил.
 */
export const MINUTES: RuPluralForms = ['минуту', 'минуты', 'минут'];
export const HOURS: RuPluralForms = ['час', 'часа', 'часов'];
