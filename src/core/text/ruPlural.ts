/**
 * Русское склонение числительных — в одном месте.
 *
 * v4.32.421. Правило было записано трижды. Две копии совпадали до буквы
 * (ui/utils/plural и core/social/disappearEnvelope), а третья — подпись «был(а)
 * N часов назад» — была написана заново и короче:
 *
 *     const plural = hrs === 1 ? 'час' : hrs < 5 ? 'часа' : 'часов';
 *
 * На 1–4 часах она совпадает с правильной, поэтому и прожила долго. Но
 * диапазон-то до 23: собеседник, заходивший 22 часа назад, подписывался
 * «был(а) 22 часов назад», а 21 час назад — «21 часов». Сокращённое правило
 * смотрит на число целиком, а склонение решает последняя цифра — кроме
 * одиннадцати–четырнадцати, где решают две последние.
 */

/** Формы: [1, 2–4, 5+]. Например `['час', 'часа', 'часов']`. */
export type RuPluralForms = readonly [string, string, string];

export function ruPlural(n: number, forms: RuPluralForms): string {
  const abs = Math.abs(n) % 100;
  const n1 = abs % 10;
  if (abs > 10 && abs < 20) return forms[2];
  if (n1 > 1 && n1 < 5) return forms[1];
  if (n1 === 1) return forms[0];
  return forms[2];
}
