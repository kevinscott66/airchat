/**
 * Пустое поверх непрочитанного не пишем — ссылки своей карточки (v4.32.994).
 *
 * Дефект. Окно «Редактировать профиль» читает сайт, имена на 𝕏 и GitHub и две
 * бумаги к ним через `ownFieldGet` — строкой, где «поля нет» и «поле не
 * открылось» сведены к одному `null`. Не открывшееся поле приезжало в окно
 * пустым, и с этого мгновения пустота была не показом, а намерением: кнопка
 * «Сохранить» писала её обратно в базу. Сайт и имена — по общему условию (одна
 * правка любого из трёх пишет все три), а обе бумаги — вообще без условия, на
 * каждое сохранение.
 *
 * Цена. Имя на площадке пропадает из карточки — у себя и у всех, кому она
 * потом уедет (`ownLinks` собирает конверт из тех же полей). Бумага дороже:
 * её нельзя вернуть в приложении. Подтверждение получают, опубликовав на
 * площадке запись со своей подписью и проверив её, — и чтобы вернуть галочку,
 * человеку придётся публиковать заново, снаружи. Молча: запись удавалась,
 * окно закрывалось словами «Профиль сохранён».
 *
 * Правка. То же правило, что у описания группы (`decideOwnDescriptionWrite`,
 * v4.32.579): пустую запись поверх непрочитанного запрещаем, всё остальное
 * пропускаем. Написанное руками новое значение — осмысленная замена, а не
 * молчаливая потеря, и оно проходит.
 *
 * Границы. «Не открылось» здесь — про то чтение, которым окно наполнялось;
 * между ним и сохранением поле могло стать читаемым. Поэтому отказ не вечный:
 * он живёт до следующего открытия окна, и об этом сказано человеку.
 *
 * Модуль без единого импорта: правило здесь — про три состояния одного поля,
 * и проверяется оно без базы, без ключей и без сети.
 */

/** Поля карточки, у которых пустота бывает и значением, и незнанием. */
export type LinkFieldName = 'website' | 'twitter' | 'github' | 'twitter_proof' | 'github_proof';

/** Что делать с одной записью. */
export type LinkFieldWrite = { write: boolean; reason: 'ok' | 'emptyOverUnreadable' };

/**
 * Решение по одному полю.
 *
 * `unreadable` — прежнее значение этого поля не открылось при наполнении окна.
 * Пустое поверх такого не пишем: пустота в поле правки пришла не от человека,
 * а от отказа чтения.
 */
export function decideLinkFieldWrite(next: string, unreadable: boolean): LinkFieldWrite {
  if (unreadable && next === '') return { write: false, reason: 'emptyOverUnreadable' };
  return { write: true, reason: 'ok' };
}

/**
 * Что сказать, когда часть полей не записана.
 *
 * Фраза называет расхождение, а не «ошибку»: человек видел пустые поля и нажал
 * «Сохранить», а прежние значения остались на месте. Не сказав этого, мы
 * оставили бы его в уверенности, что ссылки он стёр.
 *
 * «Откройте окно ещё раз» — потому что причина может пройти сама: поле не
 * открылось один раз, при наполнении окна. Обещания, что оно откроется,
 * здесь нет.
 */
export function linkFieldsKeptText(skipped: readonly LinkFieldName[]): string | null {
  if (skipped.length === 0) return null;
  const proofs = skipped.some((f) => f === 'twitter_proof' || f === 'github_proof');
  const tail = proofs
    ? ' Подтверждение 𝕏 и GitHub заново получают публикацией на площадке, поэтому стирать его вслепую нельзя.'
    : '';
  return (
    'Ссылки остались прежними: их старые значения не открылись, и пустыми их не переписываем.' +
    tail +
    ' Откройте окно ещё раз.'
  );
}
