/**
 * Пустое поле — не всегда пустое поле (v4.32.1040).
 *
 * Дефект. Окно «Редактировать профиль» читает местоимения, статус и «О себе»
 * через `ownFieldGet` — строкой, где «поля нет» и «поле не открылось» сведены
 * к одному `null`. Соседние пять полей того же окна читаются исходом с
 * v4.32.994, эти три остались. Ячейки шифрованные: занятый SQLite или
 * недоступный ключ дают тот же ответ, что и пустая запись.
 *
 * Цена. Стереть их этим уже нельзя — каждое поле пишется по своему сравнению
 * с прежним значением, а прежнее тоже пусто, так что запись не случается.
 * Цена в другом: человек открывает редактор и видит пустое «О себе» там, где
 * лежит текст. Вывод из этого один — «пропало», — и дальше он пишет заново.
 * Новый текст записывается как осмысленная правка, потому что она и есть
 * осмысленная; вот только прежнего, который он и не собирался менять, больше
 * нет. В отличие от ссылки, набранное «О себе» не восстановить ниоткуда: оно
 * нигде не публиковалось и второй копии у него нет.
 *
 * Правка. Не молчать. Поле, которое не открылось, названо прямо над формой:
 * показать нечего, но прежний текст на месте, и он заменится, только если
 * здесь написать. Запрещать правку незачем — человек может как раз и хотеть
 * написать заново.
 *
 * Границы. «Не открылось» — про то чтение, которым наполнялось окно; к
 * моменту сохранения поле могло открыться. Поэтому отказ не вечный, и об этом
 * сказано: «откройте окно ещё раз». Пустое поле без отказа чтения — обычная
 * пустота, и ничего не показывается.
 *
 * Модуль без единого импорта: правило здесь — про три состояния одного поля,
 * и проверяется оно без базы и без экрана (ср. linkFieldWrite, v4.32.994).
 */

/** Поля своей карточки, у которых пустота бывает и значением, и незнанием. */
export type OwnTextFieldName = 'pronouns' | 'status' | 'bio';

/** Как поле называется в окне — тем же словом, что и подпись над ним. */
const TITLE: Record<OwnTextFieldName, string> = {
  pronouns: 'местоимения',
  status: 'статус',
  bio: '«О себе»',
};

/** Порядок перечисления — сверху вниз по форме, а не по порядку в аргументе. */
const ORDER: readonly OwnTextFieldName[] = ['pronouns', 'status', 'bio'];

/**
 * Что сказать над формой, когда часть полей не открылась.
 *
 * `null` — говорить нечего: всё прочиталось. Пустая строка в поле тогда
 * означает ровно то, на что похожа.
 */
export function ownTextFieldsUnreadText(unread: readonly OwnTextFieldName[]): string | null {
  const names = ORDER.filter((f) => unread.includes(f)).map((f) => TITLE[f]);
  if (names.length === 0) return null;
  const list =
    names.length === 1
      ? names[0]
      : `${names.slice(0, -1).join(', ')} и ${names[names.length - 1]}`;
  const one = names.length === 1;
  return (
    `Прочитать не удалось: ${list}. ` +
    `${one ? 'Поле показано пустым' : 'Поля показаны пустыми'}, но записанное на месте — ` +
    `оно заменится, только если написать здесь. Чтобы увидеть прежнее, откройте окно ещё раз.`
  );
}
