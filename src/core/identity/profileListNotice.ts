/**
 * Что лист «Мои профили» вправе утверждать о своём списке (v4.32.1074).
 *
 * Список профилей на этом листе — не украшение: по нему человек решает,
 * остался ли профиль на устройстве, есть ли свободные слоты и не пора ли
 * заводить аккаунт заново. А приходит он из `getAllProfiles()`, который
 * складывает два разных ответа в один массив:
 *
 * - полный список — снимок с диска принят целиком;
 * - УРЕЗАННЫЙ список — снимок был, но принять его целиком не вышло: часть
 *   строк не прошла проверку (profileManager, v4.32.196), либо не разобралась
 *   вовсе и на её месте создан один профиль по умолчанию. Ядро это знает и
 *   называет: `getProfileIdsComplete().complete === false` (v4.32.704).
 *
 * Разница видна человеку как «профиль удалён». Дальше он делает ровно то, что
 * ему предлагает лист: заводит профиль заново — и получает новый
 * `derivationIndex`, то есть ДРУГОЙ адрес, а переписки, привязанные к
 * прежнему номеру, остаются в стороне.
 *
 * Хуже того, любая запись состояния кладёт на диск то, что сейчас в памяти
 * (`persistState`), — то есть урезанный список поверх снимка. После этого
 * пропавшие строки не вернутся и после перезапуска, а их файлы уборка сирот
 * снесёт как ничьи, когда список снова станет полным.
 *
 * Так задумано: v4.32.731 бережёт снимок от НЕУДАЧИ чтения, но осознанную
 * правку списка («завести, переименовать, переключить, удалить») пишет как
 * обычно — «к этому моменту человек уже действовал». Правило верное ровно при
 * одном условии: человек действовал зная. Здесь он как раз не знал, и лист сам
 * звал его действовать счётчиком «Занято 1 из 4». Чинится поэтому не запись, а
 * молчание: лист говорит, что список неполный, и не предлагает завести профиль,
 * пока это так.
 *
 * Модуль без импортов: правило одно на текст, счётчик и запрет, и проверяется
 * без экрана.
 */

/** Что лист знает о своём списке к моменту отрисовки. */
export type ProfileListFacts = {
  /** Сколько строк лист показывает. */
  shown: number;
  /** Предел профилей на устройстве. */
  max: number;
  /** `false` — снимок с диска принят не целиком, список короче правды. */
  complete: boolean;
};

/**
 * Предупреждение над списком; `null` — список полный, говорить не о чем.
 *
 * Про «не создавайте новый» — самое важное: заново заведённый профиль получит
 * другой адрес, а пропавшие строки при первой же записи исчезнут с диска.
 */
export function profileListNotice(facts: ProfileListFacts): string | null {
  if (facts.complete) return null;
  return (
    'Список профилей неполный: часть записей на устройстве сейчас не читается. ' +
    'Пропавшие профили не удалены — не создавайте их заново, новый профиль ' +
    'получит другой адрес. Закройте приложение и откройте снова.'
  );
}

/**
 * Строка счётчика слотов. При неполном списке число — нижняя граница, и
 * сказано это словами: «Занято 1 из 4» человек читает как «свободно три».
 */
export function profileSlotsText(facts: ProfileListFacts): string {
  return facts.complete
    ? `Занято ${facts.shown} из ${facts.max}`
    : `Занято не меньше ${facts.shown} из ${facts.max} — список неполный`;
}

/**
 * Можно ли сейчас предлагать завести профиль.
 *
 * При неполном списке — нет, и дело не только в подсчёте слотов: создание
 * пишет состояние целиком, то есть кладёт урезанный список поверх снимка
 * (v4.32.731 позволяет это осознанной правке — см. шапку). Запрет живёт
 * здесь, а не в ядре: ядро правку человека не отменяет, лист лишь перестаёт
 * звать её вслепую.
 */
export function mayCreateProfile(facts: ProfileListFacts): boolean {
  return facts.complete && facts.shown < facts.max;
}

/** Почему лист спрятал форму создания. Показывается вместо неё. */
export function profileCreateBlockedText(facts: ProfileListFacts): string | null {
  if (!facts.complete) {
    return (
      'Пока список профилей неполный, новый профиль создать нельзя: запись ' +
      'состояния стёрла бы с устройства те профили, которые сейчас не читаются.'
    );
  }
  if (facts.shown >= facts.max) {
    return (
      `Достигнут лимит профилей на устройстве: ${facts.max}.\n` +
      'Удалите один из существующих, чтобы создать новый.'
    );
  }
  return null;
}
