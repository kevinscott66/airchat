/**
 * Чей это ключ (v4.32.457).
 *
 * Службы, работающие с перепиской, создаются под конкретную пару ключей и
 * пересоздаются при каждом переключении профиля. Номер профиля им, однако,
 * доставался чтением глобального «активного»: между расшифровкой конверта и
 * записью в базу стоят await'ы, и человек за это время успевает переключиться —
 * тогда сообщение личного профиля ложится в переписку рабочего.
 *
 * Правило здесь одно: профиль ищется по ключу, которым служба работает. Список
 * профилей передаётся функцией, а не значением, потому что его построение
 * выводит ключевую пару на каждый профиль (PBKDF2, 2048 итераций) — платить за
 * это в обычном случае, когда активен как раз наш профиль, незачем.
 */

/** Минимум, по которому опознают профиль. */
export type ProfileIdentity = {
  id: number;
  did: string;
};

/**
 * Номер профиля, которому принадлежит ключ.
 *
 * @param myDid did ключа, которым работает служба
 * @param active профиль, активный сейчас (может быть чужим или ещё не поднятым)
 * @param allProfiles полный список — вызывается, только если активен не наш
 * @returns номер профиля или null, если профили ещё не подняты
 */
export function ownerPidByDid(
  myDid: string,
  active: ProfileIdentity | null,
  allProfiles: () => ProfileIdentity[],
): number | null {
  if (!active) return null;
  if (active.did === myDid) return active.id;
  return allProfiles().find((p) => p.did === myDid)?.id ?? null;
}

/**
 * Можно ли работать с хранилищем профиля `current`, держа ключ профиля `owner`.
 *
 * Ответ «нет» даётся, только когда оба номера известны и они разные. Незнание
 * номера — не повод останавливать работу: на установке без seed профилей нет
 * вовсе, и там прежнее поведение единственно верное.
 */
export function storageIsOwn(owner: number | null, current: number | null): boolean {
  if (owner === null || current === null) return true;
  return owner === current;
}
