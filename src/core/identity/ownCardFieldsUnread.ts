/**
 * Пустое поле — не всегда пустое поле (v4.32.1040).
 *
 * Дефект. Окно «Редактировать профиль» читает местоимения, статус и «О себе»
 * через `ownFieldGet` — строкой, где «поля нет» и «поле не открылось» сведены
 * к одному `null`. Соседние пять полей того же окна читаются исходом с
 * v4.32.994, эти три остались. Ячейки шифрованные: занятый SQLite или
 * недоступный ключ дают тот же ответ, что и пустая запись.
 *
 * Цена. Стереть их этим уже нельзя — каждое поле пишется по своему сравнению
 * с прежним значением, а прежнее тоже пусто, так что запись не случается.
 * Цена в другом: человек открывает редактор и видит пустое «О себе» там, где
 * лежит текст. Вывод из этого один — «пропало», — и дальше он пишет заново.
 * Новый текст записывается как осмысленная правка, потому что она и есть
 * осмысленная; вот только прежнего, который он и не собирался менять, больше
 * нет. В отличие от ссылки, набранное «О себе» не восстановить ниоткуда: оно
 * нигде не публиковалось и второй копии у него нет.
 *
 * Правка. Не молчать. Поле, которое не открылось, названо прямо над формой:
 * показать нечего, но прежний текст на месте, и он заменится, только если
 * здесь написать. Запрещать правку незачем — человек может как раз и хотеть
 * написать заново.
 *
 * Границы. «Не открылось» — про то чтение, которым наполнялось окно; к
 * моменту сохранения поле могло открыться. Поэтому отказ не вечный, и об этом
 * сказано: «откройте окно ещё раз». Пустое поле без отказа чтения — обычная
 * пустота, и ничего не показывается.
 *
 * Модуль без единого импорта: правило здесь — про три состояния одного поля,
 * и проверяется оно без базы и без экрана (ср. linkFieldWrite, v4.32.994).
 *
 * ---
 *
 * v4.32.1065: те же три состояния — у фото, имени и @имени. Модуль назывался
 * «текстовые поля», но текст тут был ни при чём: правило про поля карточки,
 * чья пустота бывает и ответом, и незнанием, — отсюда новое имя.
 *
 * Дефект тот же и в том же `Promise.all`: `getOwnDisplayName()`,
 * `getOwnUsername()` и `ownAvatarUri()` — все три собирающей формы, и у всех
 * трёх есть форма с исходом (`getOwnDisplayNameTryFor` v4.32.779,
 * `getOwnUsernameTryFor` v4.32.705, `ownAvatarUriTryFor` v4.32.1039), заведённая
 * ровно затем, чтобы из отказа не делали вывода. Докблок последней так и
 * говорит: собирающая форма — для мест, которые просто рисуют кружок.
 *
 * Цена здесь выше, чем у текстовых полей, и у каждого поля своя.
 *
 * Фото. Кружок пуст, под ним написано «Добавить фото». Нажатие ведёт к
 * `saveOwnAvatar`, а тот кладёт новый файл и УДАЛЯЕТ прежний — то есть ту
 * самую фотографию, которую не смогли прочитать. Она же уезжает контактам
 * рассылкой карточки.
 *
 * @имя. Поле пусто, и прежнее значение, с которым сравнивают набранное, тоже
 * пусто: любое имя, набранное здесь, выглядит как «имени не было, а теперь
 * есть», и сохранение идёт занимать НОВОЕ имя в общем реестре. Прежнее — по
 * которому человека находят и пишут ему — остаётся ничьим. Это единственный
 * человекочитаемый адрес в приложении, и второго у него нет.
 *
 * Имя. Пустое имя сохранять запрещено, и окно отвечало «Имя не может быть
 * пустым» — то есть винило человека в том, чего он не делал, и заодно не
 * давало сохранить НИЧЕГО: ни «О себе», ни ссылки.
 *
 * Правка. Фото и имя — как у текстовых полей: назвать над формой и не мешать.
 * @имя — строже: пока прежнее не прочиталось, новое не занимается вовсе
 * (`decideUsernameRename`). Разница в том, что теряется при ошибке: текст
 * человек напишет заново, а отпущенное @имя может занять кто угодно.
 */

/** Поля своей карточки, у которых пустота бывает и значением, и незнанием. */
export type OwnCardFieldName =
  | 'avatar'
  | 'name'
  | 'handle'
  | 'pronouns'
  | 'status'
  | 'bio';

/** Как поле называется в окне — тем же словом, что и подпись над ним. */
const TITLE: Record<OwnCardFieldName, string> = {
  avatar: 'фото',
  name: 'имя',
  handle: '@имя',
  pronouns: 'местоимения',
  status: 'статус',
  bio: '«О себе»',
};

/** Порядок перечисления — сверху вниз по форме, а не по порядку в аргументе. */
const ORDER: readonly OwnCardFieldName[] = [
  'avatar',
  'name',
  'handle',
  'pronouns',
  'status',
  'bio',
];

/**
 * Что сказать над формой, когда часть полей не открылась.
 *
 * `null` — говорить нечего: всё прочиталось. Пустая строка в поле тогда
 * означает ровно то, на что похожа.
 */
export function ownCardFieldsUnreadText(unread: readonly OwnCardFieldName[]): string | null {
  const names = ORDER.filter((f) => unread.includes(f)).map((f) => TITLE[f]);
  if (names.length === 0) return null;
  const list =
    names.length === 1
      ? names[0]
      : `${names.slice(0, -1).join(', ')} и ${names[names.length - 1]}`;
  const one = names.length === 1;
  // v4.32.1065: «написать здесь» стало «задать новое здесь» — фотографию не
  // пишут, а выбирают. Обещание то же: само по себе записанное не пропадёт.
  const base =
    `Прочитать не удалось: ${list}. ` +
    `${one ? 'Поле показано пустым' : 'Поля показаны пустыми'}, но записанное на месте — ` +
    `оно заменится, только если задать новое здесь. Чтобы увидеть прежнее, откройте окно ещё раз.`;
  if (!unread.includes('handle')) return base;
  // У @имени обещание другое, и сказать об этом надо тут же: занять новое
  // поверх непрочитанного значит отпустить прежнее, а его заберут.
  return `${base} @имя до тех пор не меняется вовсе: новое заняло бы место прежнего, а прежнее досталось бы кому угодно.`;
}

/** Что делать с набранным @именем при сохранении. */
export type UsernameRenameDecision =
  /** Поле не трогали — в реестр не ходим. */
  | { act: 'keep' }
  /** Прежнее @имя не прочиталось: сравнивать не с чем, менять нечего. */
  | { act: 'refuse' }
  /** Обычный случай: занимаем набранное. */
  | { act: 'claim' };

/**
 * Занимать ли новое @имя.
 *
 * Порядок проверок важен. Сначала «не трогали»: непрочитанное @имя оставляет
 * поле пустым, и человек, пришедший поправить «О себе», ничего в нём не
 * набирал — ругаться на него не за что. И только потом отказ.
 */
export function decideUsernameRename(
  wanted: string,
  saved: string,
  unread: boolean
): UsernameRenameDecision {
  if (wanted === saved) return { act: 'keep' };
  if (unread) return { act: 'refuse' };
  return { act: 'claim' };
}

/** Почему окно не сохраняет пустое имя — ответ человеку, а не обвинение. */
export function ownNameEmptyText(unread: boolean): string {
  return unread
    ? 'Имя не прочиталось — откройте окно ещё раз, менять его вслепую нечем'
    : 'Имя не может быть пустым';
}
