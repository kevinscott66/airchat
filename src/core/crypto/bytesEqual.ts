/**
 * Сравнение байтовых строк за постоянное время — одно на всё приложение
 * (v4.32.542).
 *
 * Таких сравнений в исходниках было три, и они расходились. Два честно
 * складывали разницу по всем байтам. Третье — в contacts.ts — выходило на
 * первом же несовпадении: время ответа выдавало, сколько байт совпало с
 * начала. Само по себе то место сравнивало открытые ключи, то есть ничего
 * тайного не выдавало; опасна тут не строчка, а имя: следующий, кому
 * понадобится сверить секрет, взял бы ближайшую готовую `bytesEqual`, и
 * которая из трёх окажется ближайшей — вопрос случая.
 *
 * Вторая причина собрать всё сюда: общий вариант жил в `dekDerivation.ts`
 * рядом с выводом ключа из мнемоники, а тот тянет bip39 и noble. Каждый, кому
 * нужно было сравнить два массива байт, тащил за собой разбор словаря BIP39.
 * Здесь нет ни одного импорта.
 *
 * Ветвление по длине оставлено намеренно: длина сравниваемого — не тайна (она
 * задана форматом: 32 байта ключа, 32 байта хэша), а сравнивать разной длины
 * без ветвления всё равно нечего.
 */

/** Равны ли массивы. Время работы не зависит от того, где именно они разошлись. */
export function bytesEqualConstTime(a: Uint8Array, b: Uint8Array): boolean {
  if (a.length !== b.length) return false;
  let diff = 0;
  for (let i = 0; i < a.length; i++) diff |= a[i] ^ b[i];
  return diff === 0;
}
