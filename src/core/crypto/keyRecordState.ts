/**
 * Что именно лежит в хранилище ключей — и можно ли поверх этого писать.
 *
 * v4.32.547. `loadKeyPair()` отвечал `null` и когда ключей нет (первый
 * запуск), и когда они есть, но прочитать их не вышло: хранилище ключей
 * отказало на холодном старте, ключ шифрования оказался другим, запись
 * побилась. `ensureKeyPair()` принимал `null` за первый запуск, заводил новую
 * личность и записывал её поверх старой. Прежний секрет после этого не
 * восстановить ничем: человек теряет свой адрес, а собеседники видят
 * незнакомца вместо него. Ровно та же беда, что с зашифрованными столбцами в
 * v4.32.544, только этажом выше и ценой в целую личность.
 *
 * Второе, что здесь разбирается: секрет и открытый ключ — две отдельные
 * записи, и между ними помещается падение. Секрет самодостаточен, открытый
 * ключ из него выводится, поэтому «секрет есть, открытого нет» — не поломка,
 * а починимая запись. Прежде она тоже отвечала `null` и вела к новой личности.
 *
 * Модуль намеренно без импортов: ни хранилища, ни кривой, ни ключей — только
 * разбор четырёх «да/нет», и его же проверяет тест.
 */

export type KeyRecordState =
  /** Записей нет вовсе — первый запуск. Заводить личность можно. */
  | 'absent'
  /** Открытый ключ есть, секрета нет. Восстанавливать нечего. */
  | 'orphan-public'
  /** Секрет читается, открытый ключ отсутствует или не тот — выведем из секрета. */
  | 'repairable'
  /** Секрет есть, но не читается. Писать поверх нельзя. */
  | 'unreadable'
  /** Обе записи на месте и согласованы. */
  | 'ok';

export type KeyRecordFacts = {
  /** Запись секрета присутствует в хранилище. */
  hasSecret: boolean;
  /** Запись открытого ключа присутствует. */
  hasPublic: boolean;
  /** Секрет удалось расшифровать и он нужной длины. */
  secretUsable: boolean;
  /** Открытый ключ разобран и совпал с выведенным из секрета. */
  publicMatches: boolean;
};

export function classifyKeyRecord(facts: KeyRecordFacts): KeyRecordState {
  if (!facts.hasSecret) return facts.hasPublic ? 'orphan-public' : 'absent';
  // Порядок важен: нечитаемый секрет — это отказ хранилища, а не отсутствие
  // ключей, и никакая согласованность открытого ключа этого не меняет.
  if (!facts.secretUsable) return 'unreadable';
  if (!facts.hasPublic || !facts.publicMatches) return 'repairable';
  return 'ok';
}

/**
 * Можно ли завести новую личность и записать её поверх того, что лежит.
 *
 * Нельзя ровно в одном случае — когда запись есть, но не прочиталась. Всё
 * остальное либо пусто, либо восстановимо из секрета.
 */
export function mayMintNewIdentity(state: KeyRecordState): boolean {
  return state === 'absent' || state === 'orphan-public';
}

/** Годится ли прочитанное к работе — само или после починки открытого ключа. */
export function isUsableRecord(state: KeyRecordState): boolean {
  return state === 'ok' || state === 'repairable';
}

/**
 * Что сказать человеку, если ключ есть, а прочитать его не вышло.
 *
 * Перезапуск — не отговорка: хранилище ключей на Android отказывает, пока
 * устройство не разблокировали после перезагрузки, и второй запуск обычно
 * проходит. Заводить новую личность вместо этого — потерять старую навсегда.
 */
