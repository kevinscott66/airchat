/**
 * Форма публичного ключа Ed25519 в base64 — одна на всё приложение.
 *
 * v4.32.368. Проверка «похоже на ключ» была написана заново в пяти местах, и
 * в четырёх из них она сводилась к длине: 43…48 символов. Длины мало. Ключ —
 * это 32 байта в base64, то есть 43 символа без выравнивания и 44 с ним; но
 * под «43…48 любых символов» подходит и строка из управляющих байтов, и
 * невидимые метки направления письма, и кириллица.
 *
 * Разница видна на управляющем конверте группы: `target` из конверта уезжает
 * в список участников как есть (`upsertGroupMember({ peerPubB64: target })`),
 * чистку имени он не проходит — она для имён. Чужой участник мог прислать
 * `op:'ban'` с ключом из 42 букв и одного управляющего символа, и в группе
 * появлялась запись, которую никто не отдавал и которой не соответствует
 * никакой человек.
 *
 * Пятое место — callService — проверку алфавита делало правильно с самого
 * начала. Здесь она вынесена в общий модуль, чтобы правильный вариант был
 * один и его нельзя было написать заново неправильно.
 *
 * v4.32.427. Сюда же переехала БАЙТОВАЯ форма того же вопроса. «Ключ — это
 * тридцать два байта» было записано семнадцатью строчками в двенадцати
 * файлах, шестью разными способами, и число 32 в них стояло голым литералом
 * — тем же самым, каким рядом проверяется длина симметричного ключа и DEK.
 * Два разных понятия, одно и то же число: любая правка одного читается как
 * правка другого.
 *
 * Три следствия, каждое настоящее:
 *
 *  1. `addContact` не проверял ключ ВООБЩЕ, а из пяти его вызывающих проверку
 *     делал ровно один. Спасало только то, что кривая отвергает точку не той
 *     длины, — то есть защитой служило исключение чужой библиотеки, и текст
 *     этого исключения («"point" expected Uint8Array of length 32, got
 *     length=10») показывался человеку в русском окне как объяснение, почему
 *     не добавился контакт.
 *
 *  2. `Buffer.from(s, 'base64')` не бросает ничего и никогда: недопустимые
 *     символы он молча выбрасывает. Две проверки были написаны как
 *     `try { Buffer.from(...) } catch { отказ }` — то есть не работали, а
 *     комментарий над одной из них обещал защиту, которой не было.
 *
 *  3. После `parseDidKey` длина проверялась ещё раз — хотя парсер её уже
 *     гарантирует. Проверка, которая не может не пройти, выглядит как
 *     проверка и тем опаснее: она создаёт впечатление, что ключ проверен там,
 *     где его никто не проверял.
 */

/** 32 байта в base64: 43 символа без выравнивания, 44 с ним. */
export const PUB_KEY_B64_MIN = 43;
/** Запас до 48 — на исторические записи с лишними символами выравнивания. */
export const PUB_KEY_B64_MAX = 48;

/**
 * Алфавит base64 — обычный и url-safe, вместе с выравниванием. Ключи в базе
 * записаны обычным (`Buffer.toString('base64')`), url-safe встречается в
 * ссылках, и принимать оба безопаснее, чем заводить два разных правила.
 */
const PUB_KEY_B64_CHARS = /^[A-Za-z0-9+/_=-]+$/;

/** Похоже ли значение на публичный ключ Ed25519 в base64. */
export function isPubKeyB64(value: unknown): value is string {
  return (
    typeof value === 'string' &&
    value.length >= PUB_KEY_B64_MIN &&
    value.length <= PUB_KEY_B64_MAX &&
    PUB_KEY_B64_CHARS.test(value)
  );
}

/** Ed25519: открытый ключ — ровно 32 байта. Число здесь одно на всё приложение. */
export const ED25519_PUBLIC_KEY_BYTES = 32;

/**
 * Тридцать два ли это байта — то есть годится ли значение как открытый ключ.
 *
 * Намеренно НЕ type-predicate: `value is Uint8Array` сузил бы отрицательную
 * ветку до `never` там, где на вход и так приходит `Uint8Array`, и вызывающий
 * не смог бы даже написать в журнал фактическую длину.
 */
export function isEd25519PublicKey(value: Uint8Array | null | undefined): boolean {
  return !!value && value.length === ED25519_PUBLIC_KEY_BYTES;
}

/**
 * Строка base64 → открытый ключ, либо null.
 *
 * Проверяются обе стороны: алфавит строки и длина результата. Только длины
 * мало — `Buffer.from` выбрасывает недопустимые символы молча, и строка с
 * управляющим байтом внутри даёт ровно тридцать два байта, ничем не хуже
 * настоящего ключа. Только алфавита тоже мало — 43 символа из алфавита дают
 * 32 байта, а 48 дают 36.
 */
export function publicKeyFromB64(value: unknown): Uint8Array | null {
  if (!isPubKeyB64(value)) return null;
  const bytes = new Uint8Array(Buffer.from(value, 'base64'));
  return isEd25519PublicKey(bytes) ? bytes : null;
}

/** Ed25519: подпись — ровно 64 байта. */
export const ED25519_SIGNATURE_BYTES = 64;

/** Каноническая запись ключа: обе стороны обязаны получить одну и ту же строку. */
export function publicKeyToB64(publicKey: Uint8Array): string {
  return Buffer.from(publicKey).toString('base64');
}
