/**
 * Потолок числа итераций KDF (v4.32.625).
 *
 * Планка снизу у нас была везде: конверт с заниженным `iters` — это попытка
 * удешевить перебор пароля, и её отбивали ещё в v4.32.177. А сверху планки не
 * было ни в одном из трёх мест. Между тем число это приходит СНАРУЖИ: конверт
 * привязки — с сервера, зашифрованная копия — из буфера обмена. `Math.max`
 * поднимает значение и никогда не опускает, поэтому `iters: 1e15` проходил
 * проверку `Number.isSafeInteger` и уезжал прямо в pbkdf2.
 *
 * pbkdf2 из @noble синхронный. Хермес считает его в потоке JS, и приложение
 * замирает НАВСЕГДА: ни отмены, ни спиннера — вход в аккаунт по Apple ID
 * начинается до `setBusy(true)`, так что экран просто перестаёт отвечать.
 *
 * Потолок взят у сервера: `SEED_ENVELOPE_MAX_ITERS` в cloud-vault ровно такой
 * же. Клиент обязан соглашаться ровно с тем, что сервер и так не принимает.
 */
export const MAX_KDF_ITERS = 4_000_000;

/**
 * Годное число итераций или `null`.
 *
 * `null` значит «расшифровать этим мы не сможем», а не «пароль неверный»:
 * решение, что показать человеку, принимает вызывающий — у привязки это
 * молчаливый отказ, у вставленной копии — «копия не распознана».
 */
export function acceptKdfIters(value: unknown, floor: number): number | null {
  if (!Number.isSafeInteger(value)) return null;
  const iters = value as number;
  if (iters < floor || iters > MAX_KDF_ITERS) return null;
  return iters;
}
