/**
 * Единственная планка длины пароля в приложении (v4.32.595).
 *
 * Паролей было два, и они жили по разным правилам: пароль приложения — от
 * четырёх символов, облачный — от двенадцати. Для человека это один и тот же
 * вопрос «какой у меня пароль», и два разных ответа на него — не строгость, а
 * ловушка: облачную копию нельзя было открыть тем, чем открывается само
 * приложение, и второй пароль неизбежно оказывался либо забыт, либо записан
 * рядом с первым.
 *
 * Теперь правило одно и лежит здесь. Модуль намеренно ничего не импортирует:
 * его зовут и `authGuard`, и `cloudVault`, и экраны, а любая общая
 * зависимость между ними — это цикл.
 *
 * Шесть, а не двенадцать: облачный ключ выводится не из одного пароля, а из
 * пароля вместе с ключом, полученным из seed-фразы (см. `deriveCloudKey`).
 * Пароль там — второй множитель, а не весь секрет, и шести цифр PIN-кода для
 * этой роли достаточно. Четырёх — нет: перебор четырёх цифр это десять тысяч
 * вариантов.
 */
export const PASSWORD_MIN_LENGTH = 6;

/**
 * Проверить пароль перед сохранением. `null` — годится.
 *
 * Только на установку и смену: проверять длину при ВХОДЕ нельзя. Пароли,
 * заданные до этой версии, короче — и такая проверка заперла бы человека
 * снаружи собственного приложения вместо того, чтобы попросить сменить пароль.
 */
export function passwordPolicyError(password: string): string | null {
  // Длина — по символам, а не по кодовым единицам UTF-16: три эмодзи это
  // шесть единиц, и планка «минимум шесть символов» пропускала бы их, обещав
  // человеку не то, что проверяет.
  if (typeof password !== 'string' || [...password.normalize('NFC')].length < PASSWORD_MIN_LENGTH) {
    return `Пароль должен содержать минимум ${PASSWORD_MIN_LENGTH} символов.`;
  }
  // Пробел по краям не виден, а вводить его придётся каждый раз — в том числе
  // на другом устройстве при восстановлении из облачной копии.
  if (password.trim() !== password) {
    return 'Пароль не должен начинаться или заканчиваться пробелом.';
  }
  return null;
}
