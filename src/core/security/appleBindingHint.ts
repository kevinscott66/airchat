/**
 * Подсказка «слова привязаны к Apple ID»: три состояния вместо флажка.
 *
 * v4.32.615. Раньше в `kv` лежало `'1'`/`'0'`, и этого не хватало. Конверт со
 * словами лежит на сервере зашифрованным паролем приложения — тем, который был
 * на момент привязки. Пароль сменили — конверт остался под старым, а надпись в
 * настройках продолжала обещать восстановление. Узнал бы человек об этом в
 * единственный день, когда это важно: когда слов на руках уже нет.
 *
 * Перешифровать молча нечем: `putSeedBinding` требует свежий токен Apple, то
 * есть системное окно входа. Поэтому третье состояние — честная пометка
 * «устарела» и предложение привязать заново.
 *
 * Модуль намеренно чистый: экран решает, что показать, а хранилище и сеть
 * остаются снаружи.
 */

/** Что записано в `kv` под ключом подсказки. */
export type AppleBindingHint = 'bound' | 'stale' | 'none';

/** Значение подсказки в хранилище — прежние `'1'`/`'0'` остаются валидными. */
export const APPLE_BINDING_STORED: Record<AppleBindingHint, string> = {
  bound: '1',
  stale: 'stale',
  none: '0',
};

/**
 * Разобрать запись из `kv`.
 *
 * Всё незнакомое — `'none'`: подсказка не источник истины, и выдумывать
 * привязку там, где её не подтвердили, опаснее, чем не показать её вовсе.
 */
export function parseAppleBindingHint(raw: string | null | undefined): AppleBindingHint {
  if (raw === APPLE_BINDING_STORED.bound) return 'bound';
  if (raw === APPLE_BINDING_STORED.stale) return 'stale';
  return 'none';
}

/**
 * Пароль приложения сменился — что стало с подсказкой.
 *
 * `null` означает «ничего не писать»: привязки не было (`none`) или её уже
 * пометили устаревшей (`stale`), и повторная запись только затёрла бы тот же
 * байт и показала бы предупреждение второй раз.
 */
export function hintAfterPasswordChange(current: AppleBindingHint): AppleBindingHint | null {
  return current === 'bound' ? 'stale' : null;
}
