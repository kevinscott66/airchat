/**
 * Чем кончилась попытка пометить копию устаревшей (v4.32.869).
 *
 * Копий, запертых паролем приложения, две: конверт со словами у Apple ID и
 * архив в облаке. Ключ у обоих выводится из пароля, перешифровать молча нечем,
 * и после смены пароля обе перестают открываться. Исход у попытки пометить их
 * тоже один и тот же — поэтому слово общее, а не переписано дважды.
 *
 * - `not_bound` — метить нечего: копии не было или её уже пометили;
 * - `marked` — пометка легла, после перезапуска настройки скажут правду;
 * - `unwritten` — пометить не вышло, и настройки снова покажут прежнее;
 * - `unknown` — прочитать подсказку не вышло, и была ли копия, отсюда не
 *   видно; свидетеля ищет вызывающий, если он у него есть.
 */
export type StaleMark = 'not_bound' | 'marked' | 'unwritten' | 'unknown';
