/**
 * «Что останется, если выйти отсюда».
 *
 * v4.32.870. Подтверждение выхода говорило одно и то же всем: «Восстановление
 * будет возможно только из сохранённой копии слов». Фраза верна ровно для
 * того, кто слова записал. Человеку, который на заведении аккаунта выбрал
 * «Сделаю позже», она обещает копию, которой он никогда не делал, — и экран об
 * этом знает: рядом, отдельной строкой, у него же написано «Секретные слова не
 * проверены».
 *
 * Выход стирает с устройства всё: слова, ключи, переписку. Обратного хода нет,
 * и проверить обещание человек сможет только после того, как согласится.
 *
 * Поэтому здесь собраны все пути назад, какие у аккаунта есть: записанные
 * слова, конверт у Apple ID и архив в облаке. Устаревшая копия путём не
 * считается — она не откроется нынешним паролем (v4.32.868, v4.32.869), — а
 * непрочитанное состояние не считается тем более: молчание тут лучше
 * обещания.
 */
import type { AppleBindingHint } from './appleBindingHint';
import type { CloudVaultCopyHint } from '../backup/cloudVaultCopy';

/**
 * Что известно о путях назад на момент разговора.
 *
 * `null` — «не прочиталось», и это не то же самое, что «нет»: ни обещать, ни
 * пугать по неизвестному нельзя.
 */
export type RecoveryOutlook = {
  /** `true` — слова записаны, `false` — запись отложили и не проверяли. */
  wordsVerified: boolean | null;
  apple: AppleBindingHint | null;
  cloud: CloudVaultCopyHint | null;
};

/** Перечисление по-русски: «а», «а и б», «а, б и в». */
function listRu(items: readonly string[]): string {
  if (items.length < 2) return items[0] ?? '';
  return `${items.slice(0, -1).join(', ')} и ${items[items.length - 1]}`;
}

/** Живой путь назад — тот, которым действительно можно вернуться сегодня. */
export function liveRecoveryRoutes(o: RecoveryOutlook): string[] {
  const routes: string[] = [];
  if (o.wordsVerified === true) routes.push('записанные секретные слова');
  if (o.apple === 'bound') routes.push('копию слов у Apple ID');
  if (o.cloud === 'uploaded') routes.push('зашифрованную копию в облаке');
  return routes;
}

/**
 * Копии, которые есть, но которыми не вернуться: их заперла смена пароля.
 *
 * Для человека это не то же самое, что «копий нет»: здесь ему есть что
 * починить, и починить он это может прямо сейчас, пока слова на устройстве.
 */
export function staleRecoveryRoutes(o: RecoveryOutlook): string[] {
  const routes: string[] = [];
  if (o.apple === 'stale') routes.push('привязка к Apple ID');
  if (o.cloud === 'stale') routes.push('копия в облаке');
  return routes;
}

const LOGOUT_HEAD = 'Секретные слова и все локальные данные будут удалены с этого устройства.';

/** Текст подтверждения выхода — под то, что у человека на самом деле есть. */
export function logoutConfirmText(o: RecoveryOutlook): string {
  const live = liveRecoveryRoutes(o);
  if (live.length > 0) {
    return `${LOGOUT_HEAD}\n\nВернуться в аккаунт можно будет через ${listRu(live)}.`;
  }
  // Живого пути нет ни одного. Назвать, чего именно не хватает: «нечем» без
  // причины человек прочтёт как обычное предупреждение и пройдёт мимо.
  const why: string[] = [];
  if (o.wordsVerified === false) why.push('запись секретных слов вы отложили и не проверяли');
  for (const r of staleRecoveryRoutes(o)) why.push(`${r} не откроется нынешним паролем`);
  if (why.length === 0) {
    // Ничего не прочиталось. Ни обещаний, ни приговора.
    return `${LOGOUT_HEAD}\n\nУбедитесь, что секретные слова записаны: без них вернуться в аккаунт будет нечем.`;
  }
  return `${LOGOUT_HEAD}\n\nВернуться будет нечем: ${listRu(why)}. Отмените выход, пока это можно исправить.`;
}
