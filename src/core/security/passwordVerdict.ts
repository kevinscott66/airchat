/**
 * ДЕФЕКТ (v4.32.1083). Испорченная запись пароля выдавалась за неверный пароль.
 *
 * `verifyPasswordInternal` отвечала `boolean`, а исходов у неё три: пароль
 * сошёлся, пароль не сошёлся и сверять было не с чем — записи нет, она не
 * разбирается как JSON, в ней другая версия формата или нет полей соли и
 * хэша. В последнем случае `bytesEqualConstTime` не вызывался вовсе: приговор
 * выносился без единого сравнения, а наружу уходил тот же `false`, что и у
 * настоящего промаха.
 *
 * ЦЕНА. `checkPasswordOnce` на `false` безусловно списывал одну из пяти
 * попыток, и экран блокировки писал «Неверный пароль. Осталось попыток: 4»,
 * потом 3, 2, 1, потом «Слишком много попыток. Попробуйте через 15 минут».
 * Человек вводит свой настоящий пароль и читает утверждение о нём, которого
 * приложение не проверяло. Вывод, к которому его этим подталкивают, —
 * «я забыл пароль»: экран восстановления, сброс по секретным словам. У того,
 * кто на заведении аккаунта выбрал «Сделаю позже», слов нет, и единственный
 * оставшийся ход — стереть аккаунт вместе со всей перепиской.
 *
 * Сама по себе запись, сделанная `setPassword`, на `JSON.parse` не падает.
 * Настоящие источники другие: оборванная запись в Keychain/Keystore, перенос
 * записи между устройствами и резервными копиями и, главное, ветка
 * `payload.v !== 1` — она заведена ровно под будущий формат, то есть под
 * откат версии приложения после обновления формата.
 *
 * ПРАВКА. Исход сверки называется своим именем: `ok` / `wrong` / `unusable`.
 * Незнание попытку не тратит — тратить её не за что, промаха не было, — и на
 * экране у него свои слова: они говорят про запись, а не про пароль, и ведут
 * туда, где дело поправимо.
 *
 * ГРАНИЦЫ. Доступа незнание не даёт: политика v4.32.176 (отсутствующая запись
 * — не повод пускать) не тронута, `unusable` — это по-прежнему «не пустили».
 * Блокировка при незнании тоже не снимается: заперт человек или нет, решают
 * счётчик и отметка времени, а они читаются отдельно. Верный и неверный
 * пароль работают ровно как прежде.
 */

/**
 * Исход сверки пароля. Три, а не два: сравнить могло быть не с чем.
 *
 * `wrong` отвечает и заблокированная проверка — так было и до правки: сколько
 * осталось ждать, экран узнаёт не отсюда, а из счётчика и отметки времени.
 */
export type PasswordVerdict = 'ok' | 'wrong' | 'unusable';

/**
 * Исход смены пароля. К трём исходам сверки добавлены два своих: новый пароль
 * не проходит по правилам и новый пароль не удалось сохранить. Прежде оба
 * уходили наружу тем же `false`, что и неверный старый пароль, и форма смены
 * говорила «Неверный пароль» о пароле, который был введён правильно.
 */
export type PasswordChange = PasswordVerdict | 'weak' | 'save_failed';

/**
 * Что сказать, когда сверять не с чем.
 *
 * Про запись, а не про пароль: человек не ошибся, и говорить ему «неверный»
 * значит отправлять его вспоминать то, что он помнит. Выход назван прямо —
 * иначе это тупик: пароль верный, а войти нельзя.
 */
export const PASSWORD_UNUSABLE_TEXT =
  'Запись пароля на этом устройстве повреждена — сверить пароль не с чем. Войдите по секретным словам: «Забыли пароль?»';

/**
 * Тратит ли исход одну из пяти попыток. Промах — да, незнание — нет.
 *
 * Отдельной строкой, а не условием внутри: тем же вопросом задаётся и форма
 * смены пароля, и разъезжаться эти два ответа не должны.
 */
export function passwordVerdictCostsAttempt(verdict: PasswordVerdict): boolean {
  return verdict === 'wrong';
}
