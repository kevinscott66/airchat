/**
 * ДЕФЕКТ (v4.32.1084). Отказ хранилища ключей выдавался за чужие слова.
 *
 * `verifyMnemonicMatchesWallet` отвечала `boolean`, а поводов ответить «нет»
 * у неё три: ключа этого устройства не прочитать (`loadKeyPair` вернул
 * `null`), фраза не проходит по bip39 (опечатка, чужое слово, не сошлась
 * контрольная сумма) и настоящее расхождение — слова верные, но от другого
 * аккаунта. Экран восстановления пароля на все три писал одно:
 * «Слова не совпадают с аккаунтом на этом устройстве».
 *
 * ЦЕНА. Первый повод — самый частый и самый дорогой: хранилище ключей на
 * Android отказывает, пока устройство не разблокировали после перезагрузки,
 * и ровно в этот момент человек, забывший пароль, вводит свои настоящие
 * двадцать четыре слова. Приложение отвечает ему, что слова не от этого
 * аккаунта. Проверенный ответ на это — «значит, я записал не ту фразу», и
 * дальше единственный оставшийся ход: стереть аккаунт и завести новый.
 * Переписка, адрес и собеседники теряются навсегда — при том что ключ лежал
 * на месте, а нужно было закрыть приложение и открыть заново.
 *
 * Второй повод дешевле, но тоже уводит не туда: при опечатке в одном слове
 * человеку говорят про аккаунт, хотя чинится это перечитыванием своей же
 * бумажки. Своё имя есть только у третьего повода — и оно досталось всем.
 *
 * ПРАВКА. Исход сверки называется своим именем, и у каждого имени свои
 * слова: про хранилище — те же, что при нечитаемом ключе на запуске
 * (см. keyRecordState.ts), про фразу — про фразу, про аккаунт — про аккаунт.
 *
 * ГРАНИЦЫ. Пускают по-прежнему только при `match`: ни незнание, ни отказ
 * хранилища доступа не дают, и `resetPasswordWithVerifiedSeed` проверяет
 * слова сам, как и с v4.32.316.
 */
import { KEY_STORE_UNREADABLE_TEXT, type KeyRecordState } from '../crypto/keyRecordState';

/**
 * Итог сверки секретных слов с ключом устройства.
 *
 * `mismatch` — сверка состоялась и слова от другого аккаунта. Остальные три
 * «нет» сверкой не были: сравнивать было либо нечего, либо не с чем.
 */
export type SeedMatch = 'match' | 'mismatch' | 'invalid_words' | 'key_unreadable' | 'no_identity';

/** Единственный исход, который открывает дверь. */
export function seedMatchIsMatch(verdict: SeedMatch): boolean {
  return verdict === 'match';
}

/** Слова верные по форме, но от другого аккаунта. Прежний текст экрана. */
export const SEED_MISMATCH_TEXT = 'Слова не совпадают с аккаунтом на этом устройстве';

/**
 * Фраза не сходится сама с собой: bip39 считает контрольную сумму по всем
 * словам сразу, поэтому одна опечатка валит всю фразу. Про аккаунт здесь
 * говорить не о чем — сверки с ним не было.
 */
export const SEED_INVALID_WORDS_TEXT =
  'Проверьте слова: такой фразы не существует — где-то опечатка или слово не из списка. С аккаунтом это не связано.';

/**
 * Ключа на устройстве нет вовсе. Пароль восстанавливать не для чего: сначала
 * нужно вернуть сам аккаунт, и делается это теми же словами, но на входе.
 */
export const SEED_NO_IDENTITY_TEXT =
  'На этом устройстве нет ключа аккаунта — сверять слова не с чем. Восстановите аккаунт по этим же словам на экране входа.';

/**
 * Во что превращается состояние записи ключа до всякой сверки слов.
 *
 * `null` — запись прочитана, дальше решают слова. `orphan-public` идёт к
 * «нет аккаунта», а не к «не прочитали»: секрета нет, восстанавливать нечего,
 * и ровно так же эту запись понимает {@link mayMintNewIdentity}.
 */
export function seedMatchFromKeyRecord(
  state: KeyRecordState
): 'key_unreadable' | 'no_identity' | null {
  if (state === 'unreadable') return 'key_unreadable';
  if (state === 'absent' || state === 'orphan-public') return 'no_identity';
  return null;
}

/** Что сказать человеку. `null` — говорить нечего, слова подошли. */
export function seedMatchText(verdict: SeedMatch): string | null {
  switch (verdict) {
    case 'match':
      return null;
    case 'mismatch':
      return SEED_MISMATCH_TEXT;
    case 'invalid_words':
      return SEED_INVALID_WORDS_TEXT;
    case 'key_unreadable':
      return KEY_STORE_UNREADABLE_TEXT;
    case 'no_identity':
      return SEED_NO_IDENTITY_TEXT;
  }
}
