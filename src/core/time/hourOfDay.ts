/**
 * Час суток как настройка человека — разбор и подпись.
 *
 * v4.32.929. Это не момент времени, а число от 0 до 23, которое человек выбрал
 * стрелками: начало ночной темы, граница тишины. Поэтому и модуль отдельный от
 * `ruDateTime`: там форматируются метки времени (`clockTime(ts)`), здесь —
 * значение настройки, и общего у них ровно ничего, кроме двоеточия в выводе.
 *
 * Подпись «22:00» была выписана от руки семь раз в пяти строках — четырежды в
 * настройках и раз в самом шаговом выборе часа, который эти настройки как раз
 * и показывают. Семь копий одного `padStart` не дали бы разной подписи, но они
 * скрыли то, что за подписью не стоит никакой проверки: сколько бы ни пришло
 * в неё, оно попадёт на экран как есть.
 *
 * А приходить может что угодно. Границы «не беспокоить» разбираются с
 * проверкой (`parseDndHour`, v4.32.195: испорченное значение в kv давало NaN и
 * тихо выключало тишину), размер шрифта рядом — тоже (`[13,15,17,20].includes`),
 * а часы ночной темы читались голым `parseInt`. Испорченная запись давала
 * NaN — и «Тёмная: NaN:00 – NaN:00» на экране, при том что сравнения с NaN
 * всегда ложны и тема не переключалась вовсе.
 *
 * Импортов здесь нет намеренно: `parseDndHour` живёт отдельно в слое
 * уведомлений ровно потому, что его зовёт фоновый обработчик push в своём
 * контексте, куда слой уведомлений целиком не затащить. Слить их в один
 * вызов — значит либо потянуть туда лишнее, либо перенести окно тишины сюда;
 * ни то ни другое эта правка не делает. Здесь только то, что нужно интерфейсу.
 */

/** Час границы: 0…23. Всё остальное — мусор в kv, NaN, дробь — запасное. */
export function parseHourOfDay(raw: string | null | undefined, fallback: number): number {
  const n = parseInt(raw ?? '', 10);
  return Number.isInteger(n) && n >= 0 && n <= 23 ? n : fallback;
}

/**
 * «22:00», «07:00». Пустая строка — значит пришёл не час.
 *
 * Пустоту здесь видно: подпись «Тёмная:  – » бросается в глаза и ведёт к
 * настройке. «NaN:00» тоже бросается, но выглядит поломкой приложения, а не
 * настройки. Не давать сюда не-час — дело `parseHourOfDay` на входе.
 */
export function hourOfDayLabel(hour: number): string {
  if (!Number.isInteger(hour) || hour < 0 || hour > 23) return '';
  return `${hour < 10 ? `0${hour}` : hour}:00`;
}

/**
 * Попадает ли час в окно «с такого-то по такой-то» (v4.32.975).
 *
 * Окно полуоткрытое: начало включительно, конец нет. Равные границы означают
 * пустое окно, а не круглые сутки: человек, выставивший 22–22, хотел скорее
 * ничего, чем включить режим навсегда.
 *
 * Окон в приложении два — тишина «не беспокоить» и ночная тема, — и формула у
 * них была выписана дважды: в `dndWindow` и внутри `ThemeContext`. Совпадали
 * они до последней ветки, включая переход через полночь, но проверялась только
 * первая. Разойтись двум копиям ничего не мешало: править переход через
 * полночь пришли бы в ту, из-за которой пожаловались.
 *
 * Здесь же, а не в `dndWindow`, потому что тишину зовёт фоновый обработчик
 * push в своём контексте, куда слой уведомлений целиком не затащить (см.
 * докблок выше). У этого модуля импортов нет — затаскивать нечего.
 */
export function isWithinHourWindow(start: number, end: number, hour: number): boolean {
  if (start === end) return false;
  if (start < end) return hour >= start && hour < end;
  // Переход через полночь: 22–8 — это 22, 23, 0…7.
  return hour >= start || hour < end;
}
