/**
 * calendarTime — «сегодня», «вчера» и день недели считаются по КАЛЕНДАРЮ.
 *
 * v4.32.421. Правило «как назвать момент времени» было записано в ШЕСТИ
 * местах — список чатов, список групп, presence, разделитель дней в переписке,
 * разделитель дней в группах и список просмотревших ленту — и каждое из шести
 * считало календарь разностью в миллисекундах. Разность в миллисекундах на
 * этот вопрос не отвечает: между «вчера в 23:59» и «сегодня в 00:01» две
 * минуты, а между «сегодня в 00:01» и «сегодня в 23:59» — почти сутки.
 *
 * Отсюда четыре расхождения, каждое из которых видно на экране:
 *
 *  1. В списке чатов «вчера» проверялось по числу и месяцу БЕЗ года. Сообщение
 *     от 18 августа 2025, открытое 19 августа 2026, подписано «вчера».
 *
 *  2. Ветка дня недели включалась при `diff < 7 суток`. Семь суток — это ровно
 *     тот же день недели: сообщение от понедельника 23:30 недельной давности,
 *     открытое в понедельник в 23:00, подписано «пн», то есть сегодняшним
 *     днём. В presence это читается как «был в сети час назад» вместо «неделю
 *     назад».
 *
 *  3. В глобальном поиске по группам у даты не было года вовсе: «12 мар»
 *     позапрошлого года не отличить от «12 мар» этого.
 *
 *  4. Групповой разделитель дней не получил правку v4.32.185 — защиту от
 *     испорченной отметки времени, — потому что копия о ней не знала.
 *
 * Здесь всё то же самое считается от местной полуночи. Модуль намеренно без
 * зависимостей и без текста интерфейса: он отвечает на вопрос «какой это
 * день», а как этот день назвать — дело слоя, который рисует.
 */

/**
 * Годится ли отметка времени как дата вообще.
 *
 * Отметка приходит из строки таблицы: испорченная запись, миграция, чужой
 * клиент. Пустая подпись честнее «undefined» и «Invalid Date».
 */
export function isUsableTimestamp(ts: number): boolean {
  return Number.isFinite(ts) && ts > 0;
}

/** Короткие названия дней недели, индекс = `Date#getDay()`. */
export const WEEKDAY_SHORT_RU = ['вс', 'пн', 'вт', 'ср', 'чт', 'пт', 'сб'] as const;

/**
 * Местная полночь того дня, которому принадлежит момент.
 *
 * Именно местная: пользователь читает список глазами, а не в UTC, и день у
 * него начинается там, где показывают часы на его телефоне.
 */
function localMidnight(ts: number): number {
  const d = new Date(ts);
  return new Date(d.getFullYear(), d.getMonth(), d.getDate()).getTime();
}

/** Один ли это календарный день по местному времени. */
export function isSameCalendarDay(a: number, b: number): boolean {
  return localMidnight(a) === localMidnight(b);
}

/**
 * Сколько календарных дней назад был момент: 0 — сегодня, 1 — вчера.
 *
 * Округление обязательно: в сутки перехода на летнее время между полуночями
 * 23 или 25 часов, и деление без округления дало бы 0.958 дня вместо одного.
 * Момент в будущем даёт отрицательное число — это не ошибка, а честный ответ;
 * решать, что с ним делать, обязан вызывающий.
 */
export function calendarDaysAgo(ts: number, now: number): number {
  return Math.round((localMidnight(now) - localMidnight(ts)) / 86_400_000);
}

/**
 * Сколько дней назад название дня недели ещё читается однозначно.
 *
 * Шесть, а не семь: седьмой день назад — это сегодняшний день недели, и
 * подпись «пн» на нём означает не «неделю назад», а «сегодня».
 */
export const WEEKDAY_LABEL_MAX_DAYS_AGO = 6;

/**
 * Индекс дня недели, если по нему момент опознаётся однозначно, иначе null.
 *
 * null — не отказ, а указание вызывающему назвать день датой: на этом
 * расстоянии название дня недели уже двусмысленно. Отдаётся индекс, а не
 * готовая строка, потому что в списке день зовут «пн», а в разделителе
 * переписки — «Понедельник».
 */
export function unambiguousWeekdayIndex(ts: number, now: number): number | null {
  const daysAgo = calendarDaysAgo(ts, now);
  if (daysAgo < 1 || daysAgo > WEEKDAY_LABEL_MAX_DAYS_AGO) return null;
  return new Date(ts).getDay();
}

/** Короткое название дня недели, либо null — см. unambiguousWeekdayIndex. */
export function weekdayLabel(ts: number, now: number): string | null {
  const i = unambiguousWeekdayIndex(ts, now);
  return i === null ? null : WEEKDAY_SHORT_RU[i];
}

/** Один ли это календарный год по местному времени. */
export function isSameCalendarYear(a: number, b: number): boolean {
  return new Date(a).getFullYear() === new Date(b).getFullYear();
}
