/**
 * Что из адреса и CID попадает в журнал (v4.32.944).
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Сообщения с префиксом `ipfs_` — одно из семейств,
 * которые release-сборка дублирует в системный журнал устройства (см.
 * `mirrorJsonToConsoleInRelease`). Правило «адрес целиком туда не кладём»
 * держалось на том, что автор каждой строки помнил про `slice`. Помнили не
 * везде и по-разному: где-то `slice(0, 40)`, где-то `slice(0, 64)`, а на
 * путях отказа — адрес целиком. То есть на удачном запросе правило
 * соблюдалось, а на сломанном, где строк больше всего, — нет.
 *
 * ЧЕМ ЭТО ПЛОХО. Адрес узла — это, во-первых, чей это узел: свой ли шлюз,
 * чужой ли, в какой сети. Во-вторых, ключ: у Kubo RPC доступ ходит и в
 * `user:пароль@`, и в параметрах запроса. Системный журнал читается с
 * подключённого компьютера и попадает в диагностические выгрузки, то есть
 * уходит дальше устройства вместе с тем, что в нём лежит.
 *
 * CID — это опознаватель содержимого. Целиком он говорит, что именно человек
 * скачивал; начала хватает, чтобы связать строки одного запроса между собой,
 * и не хватает, чтобы достать содержимое.
 *
 * ПОЧЕМУ НЕ ПРОСТО ОБРЕЗАТЬ. Слепой обрез оставляет то, что случайно попало в
 * первые сорок знаков, — а ключ в адресе почти всегда лежит в параметрах, то
 * есть в хвосте, и на коротком адресе хвост в обрез попадает. Поэтому сначала
 * выбрасывается то, чему в журнале не место по смыслу (имя с паролем,
 * параметры запроса, якорь), и только потом ограничивается длина.
 */

/** Дальше этого адрес в журнале не читают. */
const URL_MAX = 80;
/** Столько знаков CID хватает, чтобы связать строки одного запроса. */
const CID_KEEP = 12;

/**
 * Адрес в том виде, в каком его можно положить в журнал.
 *
 * Остаются схема, узел и путь — по ним видно, куда ходили и что не вышло.
 * Уходят `user:пароль@`, параметры запроса и якорь.
 */
export function urlForLog(url: string): string {
  const noUserinfo = url.replace(/^([a-z][a-z0-9+.-]*:\/\/)[^/@]*@/i, '$1');
  const noQuery = noUserinfo.split(/[?#]/)[0] ?? '';
  return noQuery.length > URL_MAX ? `${noQuery.slice(0, URL_MAX)}…` : noQuery;
}

/** Начало CID: столько же, сколько кладут удачные пути. */
export function cidForLog(cid: string): string {
  return cid.length > CID_KEEP ? `${cid.slice(0, CID_KEEP)}…` : cid;
}
