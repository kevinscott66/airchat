/**
 * Набор подписчиков на событие сети, которое рассылается всем сразу.
 *
 * Зачем отдельный помощник, а не `Set` на месте. В рассылке есть два тонких
 * места, и оба стоят дорого, если забыть про них в очередной копии:
 *
 *   1. Обход идёт по КОПИИ набора — подписчик вправе отписаться прямо из своего
 *      обработчика (экран настроек так и делает, когда закрывается по этому же
 *      событию), а правка набора во время его перебора роняет обход.
 *   2. Исключение одного подписчика не отменяет остальных. Иначе упавший экран
 *      молча отменял бы починку туннеля — то есть заметная поломка пряталась бы
 *      за незаметной.
 *
 * Имя события для журнала передаётся снаружи: в журнале должно быть видно, чей
 * именно подписчик упал, — «какой-то обработчик сети» искать негде.
 *
 * Живёт рядом с наблюдателем за сетью, а не в общих утилитах: пользуются им
 * ровно наблюдатель пути (`networkReconnectWatcher`) и защита туннеля
 * (`vpn/openFluxNetworkGuard`), которая слушает те же события сети.
 */
import { log } from '../logger';

export type ListenerSet<T> = {
  /** Подписаться. Возвращает отписку. */
  add: (fn: (value: T) => void) => () => void;
  /** Разослать всем; упавший подписчик не мешает остальным. */
  notify: (value: T) => void;
};

export function createListenerSet<T>(failureEvent: string): ListenerSet<T> {
  const listeners = new Set<(value: T) => void>();
  return {
    add(fn) {
      listeners.add(fn);
      return () => {
        listeners.delete(fn);
      };
    },
    notify(value) {
      for (const fn of Array.from(listeners)) {
        try {
          fn(value);
        } catch (e) {
          log.warn(failureEvent, { err: e instanceof Error ? e.message : String(e) });
        }
      }
    },
  };
}
