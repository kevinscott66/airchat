/**
 * Выключатель long-range конвейера (Wi-Fi Direct группа + обнаружение +
 * ретрансляция + синхронизация при встрече).
 *
 * Держится ВЫКЛЮЧЕННЫМ, пока конвейер не доведён: подсистема сейчас
 * поднимает нативную группу Wi-Fi Direct и крутит обнаружение, но полезной
 * работы не делает. Что нужно, чтобы включить:
 *
 * 1. `deliverPayload` для OpportunisticSync — формат кадра (kind + байты) и
 *    ПРИЁМНАЯ сторона: подписка на входящие сообщения react-native-wifi-p2p
 *    (`receiveMessage`) с разбором кадра и передачей в `ingestTopologyFrame`
 *    и в ретрансляцию. Без приёмника отправка в эфир — выдуманный протокол.
 * 2. `sendToTransport` для RelayService — отправка RelayPacket соседу по
 *    найденному пути (сейчас без неё ретрансляция только копит очередь).
 * 3. Настоящий источник координат для GeographicRouter (разрешение на
 *    геолокацию + expo-location). Жёсткая точка (0,0) убрана: без координат
 *    маршрутизатор честно не строит путь.
 * 4. Живое обнаружение через `subscribeOnPeersUpdates` вместо одного
 *    снимка `getAvailablePeers` сразу после старта обнаружения.
 *
 * HF и LoRa сюда не относятся — они выключены продуктовым решением и
 * этим флагом не включаются.
 *
 * Флаг вынесен в отдельный модуль, чтобы тесты могли подменить его и
 * проверить включённый путь, не трогая константу в проде.
 */
export const LONG_RANGE_PIPELINE_ENABLED = false;

export function isLongRangePipelineEnabled(): boolean {
  return LONG_RANGE_PIPELINE_ENABLED;
}
