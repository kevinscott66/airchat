/**
 * Сколько времени сообщение имеет право пролежать в пути.
 *
 * v4.32.614. Раньше это число жило в трёх местах и в двух из них было другим:
 * relay (свой сервер) держит накопленное 30 суток и честно отдаёт его при
 * подписке, а получатель молча выбрасывал всё, чему больше семи дней. То есть
 * человек, не заходивший неделю, скачивал месяц накопленного и не видел из
 * него ничего старше недели — ровно тот случай, ради которого хранение и
 * поднимали до 30 суток.
 *
 * Здесь один срок на всё: и «насколько глубоко просить у relay», и «что ещё
 * считать свежим при приёме». Разъехаться они больше не могут.
 *
 * Почему широкое окно не ломает защиту от повторного вброса: пойманный кадр и
 * так лежит на relay весь этот срок и будет доставлен заново при каждом
 * переподключении — окно приёма ничего к этому не добавляет. От повтора
 * защищает не срок, а идемпотентность приёма: dedup по messageId/postId,
 * INSERT OR IGNORE и надгробия удалённого. Срок нужен от вброса «через год»,
 * когда кадра на relay давно нет, — и тридцать суток эту задачу решают.
 *
 * Модуль намеренно без импортов: его тянут и @stable-транспорт, и слой
 * сообщений, и лента; любая зависимость здесь стала бы циклом.
 */

/** Срок хранения на relay и он же — окно приёма. 30 суток. */
export const RELAY_RETENTION_MS = 30 * 24 * 60 * 60 * 1000;

/**
 * Тот же срок в формате параметра `?since=` ntfy.
 *
 * Только go-duration: часы, минуты, секунды. На `30d` сервер отвечает 400,
 * поэтому тридцать суток пишутся как 720 часов.
 */
export const RELAY_RETENTION_PARAM = '720h';
