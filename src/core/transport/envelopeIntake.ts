/**
 * Что стало с принятым конвертом — v4.32.730.
 *
 * Relay отдаёт накопленное по метке «докуда прочитано» (`relayBacklog`), и
 * метка двигается по тем кадрам, которые приёмник разобрал. Приёмники же
 * объявлены `Promise<void>` и о беде сообщают одним лишь `return`: справочник
 * контактов не прочитался, служба переписки ещё не поднята, состав группы
 * недоступен, профиль переключился посреди разбора. Снаружи это ничем не
 * отличалось от «разобрано», метка перешагивала кадр — и сообщение, живущее на
 * relay ещё тридцать суток, не запрашивалось больше никогда. Отправитель при
 * этом видит «Доставлено».
 *
 * Поэтому исход теперь называется словом:
 *
 * - `consumed` — разобран или признан мусором. Перезапрашивать нечего: не
 *   разобранный по подписи или по формату кадр не станет годным и на второй
 *   раз, а метку он держал бы вечно.
 * - `deferred` — сейчас разобрать не смогли, причина уйдёт сама. Метку держим:
 *   кадр надо перезапросить при следующем подключении.
 */
export type EnvelopeIntake = 'consumed' | 'deferred';
