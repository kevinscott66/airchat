/**
 * Отказ хранилища ключей «телефон заблокирован» — и почему он не поломка.
 *
 * v4.32.613. Записи в хранилище ключей закреплены за разблокированным
 * состоянием (см. `secureStoreQueued`). Если iOS поднимает приложение, пока
 * телефон ещё заблокирован — переход по ссылке из другого приложения, запуск
 * по уведомлению, предварительный прогрев, — первое же чтение бросает
 * `errSecInteractionNotAllowed`, и наружу это выходит строкой вида
 * «Calling the 'getValueWithKeyAsync' function has failed → Caused by: User
 * interaction is not allowed.».
 *
 * Прежде эта строка доходила до экрана запуска как есть: красный заголовок,
 * английская строка из недр модуля и ни одного выхода. При этом ничего не
 * сломано — достаточно разблокировать телефон. Модуль отвечает ровно на один
 * вопрос: «это тот самый отказ?», чтобы запуск показал человеческий текст и
 * повторил попытку сам.
 *
 * Намеренно без импортов: разбор строки и ничего больше, его же проверяет тест.
 */

/**
 * Признаки, по которым узнаётся отказ «нет доступа, пока устройство
 * заблокировано». Сравнение по нижнему регистру: текст исключения собирают
 * несколько слоёв (нативный модуль, мост, JS), и регистр между версиями
 * expo-secure-store уже менялся.
 */
const LOCKED_MARKERS = [
  'user interaction is not allowed',
  'errsecinteractionnotallowed',
  // Числовой код того же OSStatus — на случай, если текст до нас не доедет.
  '-25308',
];

export function isKeychainLockedMessage(message: string): boolean {
  const lower = message.toLowerCase();
  return LOCKED_MARKERS.some((m) => lower.includes(m));
}

