/**
 * Полон ли обход ссылок настолько, чтобы по нему УДАЛЯТЬ файлы.
 *
 * Дефект (v4.32.564). Кэш расшифрованных вложений убирается по одному
 * правилу: файл, на который не ссылается ни одна уцелевшая строка базы,
 * считается сиротой и стирается. Список живых ссылок собирает
 * `liveAttachmentRefs`: он расшифровывает `text` и `media_cids` каждой строки
 * пяти таблиц и вынимает оттуда имена файлов.
 *
 * Расшифровывал он их через `decryptAtRestString`, а тот при неудаче отдаёт
 * ПУСТУЮ СТРОКУ. Из пустой строки не вынимается ни одного имени. То есть
 * строка, которую не удалось прочитать нашим ключом, молча объявляла: «я ни
 * на какие файлы не ссылаюсь». Её вложение немедленно становилось сиротой и
 * стиралось с диска — необратимо.
 *
 * Хуже всего это ведёт себя ровно там, где и без того плохо. Ключ данных
 * расходится с данными не по одной строке: при восстановлении из копии, при
 * переносе профиля, при сбое хранилища ключей перестаёт читаться ВСЯ история
 * сразу. Тогда список живых ссылок выходил пустым целиком, и первая же уборка
 * сносила весь кэш вложений — то есть единственные расшифрованные копии
 * фотографий и голосовых, — как раз в тот момент, когда правильный ключ ещё
 * можно было вернуть и всё прочитать заново. Сообщения после возврата ключа
 * открылись бы; файлы — нет.
 *
 * Осторожность в самой уборке при этом уже была написана, только срабатывать
 * ей было не от чего: `sweepMediaCache` останавливается целиком, если список
 * живых ссылок не удалось получить, и объясняет почему — «место на диске
 * вернётся при следующем запуске, удалённое вложение не вернётся никогда».
 * Но неудачная расшифровка ничего не бросала и ни о чём не сообщала: обход
 * возвращал короткий список, неотличимый от честного короткого списка.
 *
 * Правило здесь одно и грубое намеренно: если хотя бы одна ячейка не
 * открылась, обход неполон, и удалять по нему нельзя ничего. Мягче нельзя —
 * непрочитанная ячейка может держать ссылку на любой файл, и какой именно,
 * неизвестно ровно потому, что она не прочиталась.
 *
 * Модуль без единого импорта: правило здесь — про два счётчика и один запрет,
 * и проверяется оно без базы, без ключей и без файловой системы.
 */

/** Сколько строк обошли и скольким ячейкам не смогли заглянуть внутрь. */
export interface RefScanTally {
  /** Просмотрено строк. */
  rows: number;
  /** Ячеек с непустым шифртекстом, который не открылся нашим ключом. */
  unreadableCells: number;
}

export function emptyRefScanTally(): RefScanTally {
  return { rows: 0, unreadableCells: 0 };
}

/** Отметить просмотренную строку. */
export function countScannedRow(t: RefScanTally): void {
  t.rows += 1;
}

/**
 * Отметить прочитанную ячейку по её состоянию.
 *
 * `absent` и `plain` — законные состояния (столбца нет либо он прочитан, в том
 * числе пустой строкой): ссылок в них ровно столько, сколько нашлось.
 * Неизвестным содержимое остаётся только у `unreadable`.
 */
export function countScannedCell(t: RefScanTally, state: 'absent' | 'plain' | 'unreadable'): void {
  if (state === 'unreadable') t.unreadableCells += 1;
}

/** Сложить два обхода: таблицы обходятся по очереди, а решение общее. */
export function mergeRefScanTally(into: RefScanTally, add: RefScanTally): void {
  into.rows += add.rows;
  into.unreadableCells += add.unreadableCells;
}

/**
 * Виден ли обходу весь набор ссылок.
 *
 * Пустая база полна: нечего читать — нечему и не прочитаться. Отдельного
 * случая для неё нет намеренно, иначе первое же удаление на чистом устройстве
 * пришлось бы разрешать особым правилом.
 */
export function refScanIsComplete(t: RefScanTally): boolean {
  return t.unreadableCells === 0;
}

/**
 * Можно ли стирать файлы, на которые обход не нашёл ссылок.
 *
 * То же условие, названное со стороны решения: единственное место, где
 * неполнота обхода превращается в необратимое действие.
 */
export function mayDeleteUnreferenced(t: RefScanTally): boolean {
  return refScanIsComplete(t);
}

/** Что написать в журнал, когда уборка остановлена. Числа, а не текст. */
export function refScanReport(t: RefScanTally): { rows: number; unreadable: number } {
  return { rows: t.rows, unreadable: t.unreadableCells };
}
