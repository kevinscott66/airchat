/**
 * Повтор чтения, проигравшего гонку за базу.
 *
 * Холодный старт — самая занятая секунда у SQLite: экран открывается
 * одновременно с восстановлением сессии, синхронизацией аккаунта и разбором
 * очереди доставки. Одиночное «database is locked» здесь — обычное дело, а не
 * потеря данных, и предупреждать о нём человека значит пугать его тем, что
 * пройдёт само через долю секунды. Сначала повторяем, и только если повтор
 * тоже не прошёл — это правда сбой, о котором надо сказать.
 *
 * v4.32.749: теми же паузами повторяется и запись — журнал звонков
 * (callService). Имена остались про чтение, потому что менять их значило бы
 * трогать закреплённые строки ради буквы; причина у обоих обращений одна и та
 * же занятая секунда, а не направление.
 */

/** Сколько раз повторить чтение, прежде чем признать его сбоем. */
export const READ_RETRY_ATTEMPTS = 2;

/** Верхняя граница паузы: дольше человек уже чувствует задержку. */
export const READ_RETRY_MAX_MS = 600;

/**
 * Пауза перед повтором номер `attempt` (нумерация с единицы), мс.
 *
 * Растёт линейно: первая попытка почти сразу — блокировка чаще всего снимается
 * за один тик, — каждая следующая ждёт дольше, но не дольше `READ_RETRY_MAX_MS`.
 */
export function readRetryDelayMs(attempt: number): number {
  if (!Number.isFinite(attempt) || attempt < 1) return 0;
  return Math.min(READ_RETRY_MAX_MS, 150 * Math.floor(attempt));
}
