/**
 * Лента: что в её базе лежит шифртекстом (v4.32.305).
 *
 * Продолжение atRestColumns.ts — отдельным файлом только потому, что лента
 * живёт в отдельной SQLite на профиль (`airchat_feed_p<id>.db`), а тот список
 * описывает главную базу и служит источником SQL для перешифровки при смене
 * DEK. Смешивать их нельзя: перешифровка ходит по своей базе, и таблицы
 * `feed`/`feed_comments` она там просто не найдёт.
 *
 * Почему список вообще понадобился: до v4.32.305 база ленты была открытым
 * текстом целиком. Переписку прячут под enc2 с самого начала, сторис — тоже
 * (`stories`: media_uri, text, viewed_by), а лента — ровно такая же рассылка
 * написанного человеком по своим контактам — лежала рядом в соседнем файле
 * как есть: текст поста, имя автора, комментарии с именами, кто что просмотрел.
 * То есть достаточно было открыть второй файл, чтобы прочитать всё, что первый
 * файл прятал.
 *
 * ВАЖНО про смену DEK. Единственная в приложении смена ключа —
 * migrateDekRandomToDeterministic: разовая, на старте, до загрузки профиля, с
 * отметкой в kv главной базы. База ленты в этот момент не открыта, и enc2 в
 * ней быть не может — шифровать её начали этой версией, а установка, у которой
 * та миграция ещё не отмечена, старше самой этой версии. Если смена ключа
 * когда-нибудь станет обычной операцией (смена seed без переустановки), базу
 * ленты придётся перешифровывать вместе с главной — по этому самому списку.
 */

export type FeedAtRestColumnSpec = { table: string; columns: readonly string[] };

export const FEED_AT_REST_COLUMNS: ReadonlyArray<FeedAtRestColumnSpec> = [
  {
    table: 'feed',
    columns: [
      // text и author_name — сам пост и подпись под ним.
      'text', 'author_name',
      // repost_author_name — имя автора оригинала: по нему читается, кого
      // человек репостит, даже если самого оригинала в базе уже нет.
      'repost_author_name',
      // media_cids — для inline-вложений это синтетический `inline:` ключ, но
      // для остальных здесь лежит адрес файла, вплоть до `nb:`-дескриптора,
      // который несёт ключ расшифровки (blobRef.ts).
      'media_cids',
      // documents — имена приложенных файлов: «выписка_из_егрн.pdf» говорит о
      // человеке не меньше, чем текст поста.
      'documents',
      // reactions — emoji → список DID. Та же причина, что и в v4.32.302 для
      // сообщений: по реакциям читается, кто на что откликнулся.
      'reactions',
    ],
  },
  { table: 'feed_comments', columns: ['text', 'author_name', 'reactions'] },
  // viewer_name — список тех, кто молча прочитал пост. Ровно то же, что
  // stories.viewed_by и group_messages.seen_by.
  { table: 'feed_post_views', columns: ['viewer_name'] },
];

/**
 * Разбор JSON-колонки в массив строк.
 *
 * Вынесено из feedStorage, где один и тот же разбор был скопирован
 * четырежды — по разу на каждый способ достать пост (лента, один пост,
 * закладки, архив), — и каждый раз в виде безымянной функции прямо в
 * литерале объекта. С шифрованием к нему добавился ещё и вызов расшифровки,
 * так что четыре копии стали бы четырьмя местами, где можно забыть
 * расшифровать.
 */
export function parseStringArrayColumn(raw: string | null): string[] | null {
  if (!raw) return null;
  try {
    const v: unknown = JSON.parse(raw);
    return Array.isArray(v) ? (v as string[]) : null;
  } catch {
    return null;
  }
}

/**
 * Разбор JSON-колонки в объект (реакции, метаданные документов).
 *
 * Массив здесь тоже допустим (documents — массив объектов), поэтому проверка
 * одна: разобралось ли вообще. Не разобралось — null, а не исключение: в
 * колонке может лежать что угодно, включая не расшифровавшийся шифртекст,
 * который приходит сюда пустой строкой.
 */
export function parseJsonColumn<T>(raw: string | null): T | null {
  if (!raw) return null;
  try {
    const v: unknown = JSON.parse(raw);
    return v === null ? null : (v as T);
  } catch {
    return null;
  }
}
