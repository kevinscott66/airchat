/**
 * Русское число в подписи (v4.32.584).
 *
 * Правило окончаний одно и то же везде, где мы говорим человеку «N чего-то не
 * прочиталось»: 11–14 берут форму «многих», иначе решает последняя цифра. До
 * этой версии оно жило внутри searchScan одной копией на одно слово, и второе
 * такое же место (галерея вложений) обязано было бы завести вторую копию —
 * расходятся такие копии молча и заметны только на числах вроде 111.
 *
 * Модуль без единого импорта: считать окончание можно без базы, ключей и
 * отрисовки.
 */

/**
 * Форма слова для числа: `one` — 1, 21, 101; `few` — 2–4, 22–24; `many` —
 * 0, 5–20, 11–14 и всё остальное.
 *
 * Знак и дробная часть отбрасываются: подпись всегда про количество строк.
 */
export function pluralRu(n: number, one: string, few: string, many: string): string {
  const abs = Math.abs(Math.trunc(n));
  const tens = abs % 100;
  // 11–14 всегда «многих», иначе последняя цифра решает.
  if (tens >= 11 && tens <= 14) return many;
  const last = abs % 10;
  if (last === 1) return one;
  if (last >= 2 && last <= 4) return few;
  return many;
}
