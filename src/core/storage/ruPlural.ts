/**
 * Русское число в подписи (v4.32.584).
 *
 * Правило окончаний одно и то же везде, где мы говорим человеку «N чего-то не
 * прочиталось»: 11–14 берут форму «многих», иначе решает последняя цифра.
 *
 * v4.32.614: правило здесь было записано заново — четвёртой копией, ровно так,
 * как запрещает докблок core/text/ruPlural. Прожило оно потому, что сторож
 * копий искал имя `ruPlural`, а тут имя другое; совпадали копии до последней
 * цифры, и разошлись бы они молча. Осталась только подпись с четырьмя
 * аргументами — её зовут три модуля, — а считает окончание общее правило.
 */
import { ruPlural } from '../text/ruPlural';

/**
 * Форма слова для числа: `one` — 1, 21, 101; `few` — 2–4, 22–24; `many` —
 * 0, 5–20, 11–14 и всё остальное.
 *
 * Знак и дробная часть отбрасываются: подпись всегда про количество строк.
 */
export function pluralRu(n: number, one: string, few: string, many: string): string {
  return ruPlural(Math.trunc(n), [one, few, many]);
}
