/**
 * Что сказать человеку после импорта копии диалогов (v4.32.844).
 *
 * Дефект. `importDialogBackupJson` отвечал одним числом — сколько сообщений
 * восстановлено, — и все остальные исходы сходились в ноль. А исходов десять:
 * нет кошелька, база не ответила, история не пуста, файл велик, файл не
 * разбирается, файл от другого аккаунта, шесть разных превышений по числу
 * строк. Экран на любой ноль печатал одно:
 *
 *   «Копия не импортирована: проверьте секретные слова и убедитесь, что
 *    история на этом устройстве пуста.»
 *
 * Из десяти случаев это правда в двух. В остальных совет уводит от настоящей
 * причины: слова верные, история пуста, а не вышло совсем по другому поводу.
 *
 * Хуже другое. Шаги импорта идут порознь (v4.32.717), и сбой одного не
 * отменяет остальные — но список упавших уходил только в журнал
 * (`dialog_backup_import_partial`). Экран печатал «Восстановлено сообщений: N»
 * и молчал о том, что двенадцать групп не вернулись. Повторить импорт уже
 * нельзя: `existing > 0` его не пустит, а локальный файл — единственное, чем
 * группа восстанавливается вообще. То есть человек видел успех ровно в тот
 * момент, когда терял группы навсегда.
 *
 * Здесь только слова: ни базы, ни файловой системы, ни криптографии.
 */

import { ruPlural } from '../text/ruPlural';

/** Почему импорт не начался. `null` — начался. */
export type DialogBackupRefusal =
  | 'no_wallet'
  | 'db_unreadable'
  | 'db_not_empty'
  | 'file_oversize'
  | 'bad_json'
  | 'bad_format'
  | 'wallet_mismatch'
  | 'rows_oversize';

/** Шаги импорта. Каждый фиксируется своей транзакцией и падает сам по себе. */
export type DialogBackupStep = 'messages' | 'kv' | 'conversations' | 'meta' | 'groups';

export type DialogBackupImportResult = {
  /** Сообщения — личные и групповые вместе. */
  messages: number;
  groups: number;
  /** Шаги, которые не прошли. Пусто — прошли все. */
  failed: DialogBackupStep[];
  refused: DialogBackupRefusal | null;
};

export const DIALOG_BACKUP_NOTHING: DialogBackupImportResult = {
  messages: 0,
  groups: 0,
  failed: [],
  refused: null,
};

export function dialogBackupRefused(refusal: DialogBackupRefusal): DialogBackupImportResult {
  return { ...DIALOG_BACKUP_NOTHING, refused: refusal };
}

/**
 * Причина отказа — словами, и с тем действием, которое вправду поможет.
 *
 * Совет «проверьте секретные слова» тут ровно там, где слова и правда ни при
 * чём не подходят, — а не на каждом нуле подряд.
 */
const REFUSAL_TEXT: Record<DialogBackupRefusal, string> = {
  no_wallet:
    'Кошелёк на устройстве не найден, и сверить копию не с чем. Восстановите секретные слова, потом импортируйте копию.',
  db_unreadable:
    'База переписки не ответила. Импорт остановлен нарочно: пока неизвестно, что в ней лежит, запись поверх может стереть живую переписку. Перезапустите приложение и попробуйте снова.',
  db_not_empty:
    'На устройстве уже есть переписка. Импортировать можно только в пустую историю — иначе два набора сообщений смешаются, и разделить их будет нечем.',
  file_oversize: 'Файл копии слишком велик — такой не читается.',
  bad_json: 'Файл повреждён: он не разбирается как копия.',
  bad_format: 'Это не файл копии AirChat — или он сделан несовместимой версией.',
  wallet_mismatch:
    'Копия сделана под другим аккаунтом: её секретные слова не те, что на этом устройстве.',
  rows_oversize: 'В копии слишком много строк — столько не бывает у настоящей.',
};

const STEP_NAME: Record<DialogBackupStep, string> = {
  messages: 'сообщения',
  kv: 'контакты и настройки',
  conversations: 'список переписок',
  meta: 'настройки переписок',
  groups: 'группы',
};

function restoredPart(r: DialogBackupImportResult): string {
  const said: string[] = [];
  if (r.messages > 0) {
    said.push(`${r.messages} ${ruPlural(r.messages, ['сообщение', 'сообщения', 'сообщений'])}`);
  }
  if (r.groups > 0) {
    said.push(`${r.groups} ${ruPlural(r.groups, ['группа', 'группы', 'групп'])}`);
  }
  return said.join(', ');
}

export type DialogBackupReport = { ok: boolean; text: string };

/**
 * Итог импорта одной фразой.
 *
 * `ok: false` — человеку надо что-то сделать. Частичный импорт тоже `false`:
 * он выглядит успехом, а на деле это единственный момент, когда ещё можно
 * спасти файл копии, — повторить импорт после него уже не дадут.
 */
export function dialogBackupReport(r: DialogBackupImportResult): DialogBackupReport {
  if (r.refused) return { ok: false, text: REFUSAL_TEXT[r.refused] };

  const got = restoredPart(r);
  if (r.failed.length > 0) {
    const lost = r.failed.map((s) => STEP_NAME[s]).join(', ');
    const head = got ? `Восстановлено: ${got}.` : 'Восстановить не удалось почти ничего.';
    // Самое важное в этой фразе — последнее предложение. Повтор упрётся в
    // непустую историю, а локальный файл для групп безальтернативен: если не
    // сохранить его сейчас, восстанавливать будет нечем.
    return {
      ok: false,
      text: `${head} Не восстановлено: ${lost}. Повторить импорт в эту же историю уже нельзя — сохраните файл копии и напишите в поддержку.`,
    };
  }

  if (!got) {
    // Все шаги прошли, но возвращать было нечего: копия пустая.
    return { ok: true, text: 'Копия прочитана, но восстанавливать в ней нечего: она пуста.' };
  }
  return { ok: true, text: `Восстановлено: ${got}. Перезапустите приложение.` };
}
