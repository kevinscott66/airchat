/**
 * Сообщение, которое не открылось нашим ключом, и то, как оно выглядит.
 *
 * Дефект. `decryptAtRestString` при неудачной расшифровке отдаёт пустую
 * строку. Про запись это уже закрыто (v4.32.544 — не переписывать непрочитанный
 * столбец, v4.32.556 — не затирать им производную подпись диалога), про журнал
 * тоже (v4.32.556 — неудача перестала быть безмолвной). А про показ так и
 * оставалось написано «для показа это верно: пустой пузырь читается лучше, чем
 * enc2:AAAA…».
 *
 * Пустой пузырь и правда читается лучше шифртекста. Но он читается ровно так
 * же, как сообщение без текста, — а такие бывают: подпись к фотографии можно
 * не писать. Человек видит в переписке пустое место и не знает, что перед ним:
 * собеседник ничего не написал, или написал, а прочитать это устройство
 * больше не может. Второе — повод спасать данные, снимать копию, не менять
 * ключ дальше; первое — не повод ни для чего. Показывая их одинаково, мы
 * прятали единственный признак беды именно от того, кто может на неё
 * ответить.
 *
 * Причём беда не редкая и не выдуманная: ровно из-за неё существуют
 * atRestCell, keyRecordState и dekPolicy. Ключ данных расходится с данными при
 * восстановлении из копии, при переносе профиля, при сбое хранилища ключей —
 * и тогда пустеет не одно сообщение, а вся история сразу.
 *
 * Что здесь. Признак «эта ячейка не прочиталась» и текст, который встаёт
 * вместо неё. Признак живёт рядом с самим сообщением, а не подменяет его
 * текст: подменённый текст пришлось бы отличать от настоящего в двух десятках
 * мест — пересылка, цитата, поиск, перевод, копирование — и рано или поздно
 * он утёк бы в отправку как обычный текст.
 *
 * Модуль без единого импорта: правило здесь — про два состояния и одну
 * строку, и проверяется оно без базы, без ключей и без отрисовки.
 */

