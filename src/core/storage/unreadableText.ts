/** Ровно те поля сообщения, которые нужны решению. */
export interface MaybeUnreadable {
  /** Проставляет слой чтения, увидев непрочитанный столбец. */
  unreadable?: boolean;
}

/**
 * Признак непрочитанного текста по состоянию столбца.
 *
 * `absent` и `plain` — законные состояния: столбца нет либо он прочитан (в том
 * числе пустой строкой). Непрочитанным считается только непустой шифртекст,
 * который не открылся, — то самое, что раньше приходило к показу пустотой.
 */
export function unreadableFromCellState(state: 'absent' | 'plain' | 'unreadable'): boolean {
  return state === 'unreadable';
}

/** Стоит ли рисовать вместо текста пометку о неудачном чтении. */
export function isUnreadableMessage(m: MaybeUnreadable | null | undefined): boolean {
  return m?.unreadable === true;
}

/**
 * Можно ли пользоваться текстом сообщения: копировать, пересылать, цитировать,
 * править, переводить.
 *
 * У непрочитанного сообщения текста нет — есть пустая строка. Скопировать её
 * молча, переслать её собеседнику или подставить её в правку значит выдать
 * пустоту за содержимое ещё раз, теперь уже наружу.
 */
export function mayReuseMessageText(m: MaybeUnreadable | null | undefined): boolean {
  return !isUnreadableMessage(m);
}
