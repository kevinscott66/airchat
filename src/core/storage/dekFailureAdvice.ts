/**
 * Отказ «данные не открываются» — человеческим языком, и что с ним делать.
 *
 * v4.32.603. `DekUnavailableError` — единственная ошибка, после которой
 * приложение не запускается вовсе, и до сих пор она доезжала до экрана как
 * есть: `local data key unavailable: key_lost_data_present`. Строка верна и
 * бесполезна — из неё не следует ни что случилось, ни есть ли выход; человек
 * видит красный заголовок и латиницу и остаётся с неработающим приложением.
 *
 * Причины делятся на две разные ситуации, и путать их нельзя:
 *
 *  - ключа больше нет, а данные под ним остались. Прочитать их нечем: это не
 *    поломка, а итог. Выход один и он разрушительный — стереть локальные
 *    данные и войти заново по секретным словам. Предлагать его можно только
 *    явно и с предупреждением, что вернётся лишь то, что успело уйти на
 *    сервер;
 *  - хранилище не отвечает (браузер заблокировал доступ, Keystore занят). Тут
 *    терять нечего и стирать нечего: данные, скорее всего, целы, и правильный
 *    совет — перезапустить, а не удалять. Предложить здесь сброс значило бы
 *    уговорить человека уничтожить переписку из-за временного сбоя.
 *
 * Модуль чистый: ни хранилища, ни платформы, ни React. Разбор текста ошибки
 * отделён от экрана намеренно — на экране его не проверишь.
 */

/** Префикс сообщения `DekUnavailableError` (см. localEncryption). */
export const DEK_FAILURE_PREFIX = 'local data key unavailable: ';

export type DekFailureAdvice = {
  /** Что случилось — без слов «ключ», «канарейка» и «DEK». */
  text: string;
  /** Помогает ли здесь полный сброс локальных данных. */
  resettable: boolean;
};

const LOST =
  'Данные на этом устройстве зашифрованы, а того, чем их открыть, здесь больше нет — ' +
  'так бывает после выхода из учётной записи или очистки данных сайта в браузере. ' +
  'Прочитать их уже нечем, и подобрать замену нельзя: любая попытка записала бы пустоту ' +
  'поверх прежней переписки.';

const LOST_WAY_OUT =
  ' Можно начать заново: удалить локальные данные и войти по секретным словам. ' +
  'Вернётся всё, что успело уйти на сервер; то, что оставалось только на этом устройстве, — нет.';

const BUSY =
  'Приложение не смогло добраться до своего защищённого хранилища. Данные при этом на месте — ' +
  'их просто некому было отдать. Закройте приложение полностью и откройте заново; в браузере ' +
  'обновите страницу, а если рядом открыты другие вкладки AirChat — обновите и их.';

/**
 * Разбор сообщения `DekUnavailableError`; `null` — ошибка не про это, и
 * подменять её догадкой нельзя (тот же контракт, что у diagnoseStorageFailure).
 */
export function dekFailureAdvice(message: string): DekFailureAdvice | null {
  if (!message.startsWith(DEK_FAILURE_PREFIX)) return null;
  const reason = message.slice(DEK_FAILURE_PREFIX.length).trim();

  switch (reason) {
    // Ключа нет (или он не тот), а данные под ним есть.
    case 'key_lost_data_present':
    case 'stored_does_not_match_data':
    case 'key_malformed':
      return { text: LOST + LOST_WAY_OUT, resettable: true };

    // Хранилище молчит: сбрасывать нечего и незачем — удаление тут тоже не пройдёт.
    case 'key_unreadable':
    case 'key_and_canary_unreadable':
    case 'seed_unreadable':
      return { text: BUSY, resettable: false };

    // Ключ пропал между решением и его исполнением: гонка, а не потеря.
    case 'stored_vanished':
    case 'derived_vanished':
      return { text: BUSY, resettable: false };

    default:
      // Причина новая. Сказать «данные не открылись» честно; предлагать
      // необратимое удаление, не зная почему, — нет.
      return { text: LOST, resettable: false };
  }
}
