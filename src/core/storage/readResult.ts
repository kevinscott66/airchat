/**
 * У чтения из базы три исхода, а не два (v4.32.528, обобщено в v4.32.532).
 *
 * Читающие обёртки над SQLite ловят любое исключение и возвращают пустой
 * массив. Для вызывающего это неотличимо от честного «строк нет»: одна
 * секундная блокировка базы (соседняя транзакция записи, миграция, ротация
 * ключа шифрования) — и обновление приносит ноль строк.
 *
 * Дальше пустота идёт по цепочке как факт. Впервые это разобрали на ленте:
 * склейка головы трактует неполную голову как «всё уместилось в одну
 * страницу» и выбрасывает хвост, экран ставит `offset = 0`, гасит `hasMore`
 * и рисует «Лента пуста». Человек, долиставший до трёхсотого поста, на
 * очередном тике видит пустой экран, подгрузка выключена, ошибки не
 * показано — ничего не сломалось, просто «у вас ничего нет». Та же форма
 * встречается везде, где список читают страницами: сбой чтения переписки
 * группы выглядит как пустая группа и вдобавок отмечает её прочитанной.
 *
 * Отсюда правило: пусто, страница, сбой. Сбой не даёт права ни менять
 * список, ни делать вывод о конце — про конец неудавшееся чтение не знает
 * ничего, и уж тем более не даёт права на побочные действия, которые
 * оправданы только успешным чтением. `null` здесь и есть этот третий исход,
 * и он обязан быть в типе, иначе про него забудут снова.
 *
 * Модуль живёт в `storage`, а не в `social`: правило про чтение, а не про
 * ленту. Без зависимостей: сюда не должны просачиваться ни хранилище, ни
 * React.
 */

/** Результат чтения страницы ленты: строки либо `null` — чтение не удалось. */
export type DbRead<T> = readonly T[] | null;

/** Решение по подгруженной странице: применять ли её и знаем ли мы про конец ленты. */
export type PageDecision = {
  /** Дописывать ли строки в список. */
  apply: boolean;
  /** Достоверно ли известно, что дальше ничего нет. Сбой чтения — не известно. */
  endOfList: boolean;
};

/** Чтение провалилось (в отличие от «прочитали и там пусто»). */
export function isReadFailure(read: DbRead<unknown>): boolean {
  return !Array.isArray(read);
}

/**
 * Можно ли класть свежую голову на место списка.
 *
 * Сужает тип, чтобы забыть проверку было нельзя: без неё `null` не пройдёт
 * дальше по коду, а не превратится молча в пустой список.
 */
export function shouldApplyRows<T>(head: DbRead<T>): head is readonly T[] {
  return Array.isArray(head);
}

/**
 * Что делать с результатом подгрузки следующей страницы.
 *
 * Сбой — не трогаем ничего: список остаётся как был, флаг «есть ещё» тоже,
 * человек потянет ещё раз. Пустая страница — конец ленты, дописывать нечего.
 * Неполная страница — дописываем и это конец. Полная — дописываем, продолжаем.
 *
 * Некорректный размер страницы трактуется как конец: строки не потеряются,
 * а вот бесконечная подгрузка одной и той же страницы была бы хуже.
 */
export function decidePage(page: DbRead<unknown>, pageSize: number): PageDecision {
  if (!Array.isArray(page)) return { apply: false, endOfList: false };
  if (page.length === 0) return { apply: false, endOfList: true };
  if (!Number.isFinite(pageSize) || pageSize <= 0) return { apply: true, endOfList: true };
  return { apply: true, endOfList: page.length < pageSize };
}
