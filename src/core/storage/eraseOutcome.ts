/**
 * Что стало с расшифрованными копиями вложений, когда сообщения стёрли.
 *
 * Дефект. «Все сообщения этой переписки будут удалены на этом устройстве» —
 * обещание про устройство, а не про строки в базе. Снимок и голосовое лежат
 * не в строке: строка держит только ссылку, а сам файл расшифровывается один
 * раз и остаётся отдельным файлом в кэше приложения. Стирание строк уносит
 * ссылку; файл уносит уборщик кэша следом.
 *
 * Уборщик не трогает файл сразу в двух случаях, и оба молчали. Первый —
 * часть строк не прочиталась ключом данных: тогда нельзя понять, не нужен ли
 * этот файл уцелевшей переписке, и осторожность тут правильная (v4.32.564) —
 * одно и то же вложение при пересылке принадлежит двум сообщениям, и снести
 * его вместе с первым значило бы сломать второе. Второй — файловая система
 * отказала в удалении: `deleteCachedBlobs` и `deleteCachedFileUris` пропускают
 * такой файл и отдают счётчик снесённых, а не исключение.
 *
 * Цена одинаковая в обоих случаях: в приложении переписки больше нет, а
 * фотографии и голосовые из неё лежат на диске расшифрованными — их видно
 * файловому менеджеру и видно в резервной копии устройства. Человек прочитал
 * «Переписка удалена» и считает, что на телефоне не осталось ничего.
 *
 * Правка — сказать, а не дочистить: осторожность уборщика защищает вложения
 * ДРУГИХ переписок, и отменить её значит сломать их ради этой.
 *
 * Модуль без единого импорта: правило здесь — про два исхода, и проверяется
 * оно без базы, без файловой системы и без отрисовки.
 */

/**
 * `clean` — расшифрованных копий стёртых сообщений на устройстве не осталось.
 * `kept` — остались: либо не с чем было сверяться, либо файл не удалился.
 */
export type BlobCacheSweep = 'clean' | 'kept';
