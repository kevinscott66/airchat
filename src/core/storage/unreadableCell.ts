/**
 * Что делать со столбцом, который не открылся (v4.32.556).
 *
 * `decryptAtRestString` при неудачной расшифровке отдаёт пустую строку. Для
 * показа это верно — пустой пузырь лучше, чем `enc2:AAAA…`, — и в v4.32.544
 * эту же пустоту перестали пускать туда, где столбец читают, дополняют и
 * пишут обратно. Но оставались две вещи, из-за которых непрочитанная строка
 * так и оставалась незаметной и при этом успевала навредить.
 *
 * Первое. Производные записи. Список диалогов хранит подпись последней
 * реплики отдельным столбцом, и уборка её пересчитывает: берёт текст
 * последнего сообщения, делает подпись, записывает. Если текст не открылся,
 * подписью становилась пустая строка — и записывалась поверх прежней. Прежняя
 * при этом была ВЕРНОЙ: её сложили тогда, когда сообщение ещё читалось. Так
 * одна неудачная расшифровка стирала последнюю осмысленную строку диалога
 * навсегда, хотя само сообщение никуда не делось и правильным ключом ещё
 * открылось бы.
 *
 * Второе. Молчание. Мест, читающих зашифрованные столбцы, около семидесяти, и
 * ни одно из них не оставляло следа при неудаче. Переписка, показанная
 * пустыми пузырями, и переписка, которой нет, выглядели в журнале одинаково —
 * то есть ответить на вопрос «ключ разошёлся с данными или данных правда
 * нет?» было нечем. Но и писать в журнал на каждую строку нельзя: один список
 * — это сотни чтений подряд, и предупреждение о первой утонуло бы в
 * собственном повторе.
 *
 * Модуль без единого импорта: обе связки решаются числом и двумя булями, и
 * проверяются без базы, без ключей и без шифра.
 */

/** Что сделать с производной подписью, когда её пересчитывают. */
export type PreviewAction =
  /** Источник прочитан — подпись пересобрать и записать. */
  | 'write'
  /** Источник не открылся — оставить прежнюю: она может быть верной. */
  | 'keep'
  /** Источника больше нет — подпись очистить, ей нечего описывать. */
  | 'clear';

/**
 * Решение по производной подписи.
 *
 * Порядок проверок важен: «источника нет» сильнее «источник не читается».
 * Удалённой переписке подпись оставлять нельзя — иначе в списке диалогов
 * останется строка от сообщения, которого уже не существует (ровно то, что
 * чинила уборка).
 */
export function previewAction(hasSource: boolean, sourceReadable: boolean): PreviewAction {
  if (!hasSource) return 'clear';
  return sourceReadable ? 'write' : 'keep';
}

/** Записывать ли новую подпись поверх прежней. */
export function mayWritePreview(action: PreviewAction): boolean {
  return action !== 'keep';
}

/**
 * Говорить ли в журнал об этой по счёту неудачной расшифровке.
 *
 * Первые три — всегда: по ним видно, что беда началась. Дальше только круглые
 * числа, десятками и сотнями, — по ним видно, что она продолжается, и при
 * этом одно длинное чтение не превращает журнал в одну строку, повторённую
 * пятьсот раз.
 */
export function shouldReportFailure(count: number): boolean {
  if (!Number.isInteger(count) || count < 1) return false;
  if (count <= 3) return true;
  let step = 10;
  while (step <= count) {
    if (count === step) return true;
    step *= 10;
  }
  return false;
}
