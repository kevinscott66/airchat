/**
 * Прочиталась ли ячейка — и можно ли её переписывать.
 *
 * Измеренный дефект (v4.32.544). `decryptAtRestString` при неудачной
 * расшифровке возвращает пустую строку. Так задумано и для показа это верно:
 * пустой пузырь читается лучше, чем `enc2:AAAA…`. Но ровно та же пустая
 * строка приходит и туда, где столбец сначала читают, потом дополняют, потом
 * записывают обратно, — а там она означает уже не «нечего показать», а
 * «прежнего содержимого не было». Найдено пять таких мест:
 *
 *   • реакции в переписке и в группе (toggleReaction),
 *   • список прочитавших сообщение в группе (seen_by),
 *   • список посмотревших сторис (viewed_by),
 *   • реакции на пост в ленте (addReaction / removeReaction).
 *
 * Что происходило. Столбец не открылся нашим ключом — вернулась пустая
 * строка — разобралась в пустую карту — к пустой карте добавили одну новую
 * реакцию — и записали. Все прежние реакции, все прочитавшие, все
 * посмотревшие исчезали безвозвратно: старый шифртекст перетёрт, а новый
 * ключ его не открывал и раньше. Один тап по эмодзи стирал столбец.
 *
 * Что важно: это не выдуманный случай. Комментарий в самом коде переноса
 * ключа (`local.ts`, v4.32.520) прямо называет его причиной осторожности —
 * «первая же реакция перетрёт шифртекст этой пустотой». Осторожность в
 * переносе появилась, а сама разрушающая запись так и осталась незакрытой.
 *
 * Разница, которой не хватало, — между тремя состояниями, а не двумя:
 *
 *   absent      столбец NULL. Терять нечего, писать можно.
 *   plain       прочитано. В том числе пустой строкой и ещё не зашифрованным
 *               текстом — обе законны, писать можно.
 *   unreadable  непустой шифртекст, который не открылся. Писать НЕЛЬЗЯ:
 *               запись уничтожит то, что, возможно, ещё удастся прочитать
 *               правильным ключом.
 *
 * Модуль намеренно без единого импорта: решение здесь — про три состояния и
 * ни про что больше, и проверяется оно без базы, без ключей и без шифра.
 */

/** Три различимых состояния зашифрованного столбца. */
export type AtRestCell =
  | { state: 'absent' }
  | { state: 'plain'; text: string }
  | { state: 'unreadable' };

/**
 * Состояние по тому, что лежало в столбце и что вернул расшифровщик.
 *
 * `decoded` — результат `tryDecryptAtRest`, то есть варианта, который
 * отличает неудачу (null) от пустой строки. Именно на этом различии всё и
 * держится: обычный `decryptAtRestString` обе беды сводит к `''`.
 */
export function classifyAtRestCell(
  stored: string | null | undefined,
  decoded: string | null,
): AtRestCell {
  if (stored === null || stored === undefined) return { state: 'absent' };
  if (decoded === null) return { state: 'unreadable' };
  return { state: 'plain', text: decoded };
}

/**
 * Можно ли записывать в столбец поверх прежнего содержимого.
 *
 * Единственный запрет — непрочитанный шифртекст. «Пусто» и «нет столбца»
 * запретом не являются: это законные состояния, с которых всё и начинается.
 */
export function mayOverwrite(cell: AtRestCell): boolean {
  return cell.state !== 'unreadable';
}

/**
 * Текст ячейки для разбора, либо null.
 *
 * Отсутствующий столбец и непрочитанный дают здесь одинаковый null — и это
 * правильно ровно до тех пор, пока запись отдельно спросила `mayOverwrite`.
 * Читающим местам (показать реакции, показать прочитавших) различие не нужно:
 * им нечего показать в обоих случаях.
 */
export function cellTextOrNull(cell: AtRestCell): string | null {
  return cell.state === 'plain' ? cell.text : null;
}
