/**
 * Счётчик, который может врать, и обязан в этом признаться (v4.32.585).
 *
 * Статистика профиля показывает «голосовых: N». Число это не считается в SQL:
 * пометка голосового ('\x01voice:') дописывается в текст ДО шифрования,
 * поэтому LIKE по шифртексту не совпадает никогда. Вместо этого выбираются
 * последние 10 000 исходящих сообщений, каждое расшифровывается и проверяется
 * на префикс. У такого счёта два честных повода ошибиться, и оба до этой
 * версии молчали:
 *
 *  • строка, которую не открыл ключ данных, в цикле пропускалась через
 *    `catch {}` — то есть уверенно объявлялась не-голосовой;
 *  • обход упирается в потолок в 10 000 строк, и об этом писалось в журнал,
 *    которого человек не видит.
 *
 * В обоих случаях на экран выходило точное на вид число, которое на деле
 * является нижней границей. Хуже всего это при расхождении ключа: не
 * прочиталось всё, и «голосовых: 0» читается как «я их никогда не отправлял».
 *
 * Правило: число и причины его неточности едут вместе, а подпись под ним
 * пишется из этих причин, а не из догадки.
 *
 * Единственная зависимость — такой же чистый модуль с окончаниями (ruPlural):
 * счёт проверяется без базы, ключей и отрисовки.
 */
import { pluralRu } from './ruPlural';

/** Посчитанное число вместе с причинами, по которым оно может быть занижено. */
export type ApproxCount = {
  /** Сколько насчитали наверняка. */
  value: number;
  /** Сколько строк не открылось ключом данных — про них ничего не известно. */
  unreadable: number;
  /** Обход упёрся в потолок: до старых строк дело не дошло. */
  capped: boolean;
};

/** Счётчик, которому нечего скрывать. */
export function exactCount(value: number): ApproxCount {
  return { value, unreadable: 0, capped: false };
}

/** Точен ли счётчик: ни одной непрочитанной строки и потолок не задет. */
export function approxIsExact(c: ApproxCount): boolean {
  return c.unreadable <= 0 && !c.capped;
}

/**
 * Число для показа. Неточное показывается со знаком «не меньше»: это
 * единственное, что мы про него знаем наверняка.
 */
export function approxCountLabel(c: ApproxCount): string {
  const v = Math.max(0, Math.trunc(c.value));
  return approxIsExact(c) ? String(v) : `≥ ${v}`;
}

/**
 * Подпись под числом. null — счётчик точен, объяснять нечего.
 *
 * Причины складываются в одну фразу, потому что бывают вместе: ключ разошёлся
 * с данными И переписка длиннее потолка.
 */
export function approxCountNotice(c: ApproxCount): string | null {
  if (approxIsExact(c)) return null;
  const reasons: string[] = [];
  const n = Math.trunc(c.unreadable);
  if (Number.isFinite(n) && n > 0) {
    reasons.push(`${n} ${pluralRu(n, 'сообщение', 'сообщения', 'сообщений')} не удалось прочитать`);
  }
  if (c.capped) reasons.push('просмотрены не все сообщения');
  if (reasons.length === 0) return null;
  return `точное число неизвестно: ${reasons.join(', ')}`;
}
