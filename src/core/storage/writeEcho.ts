/**
 * Эхо записи: будить подписчиков хранилища только на настоящем изменении.
 *
 * v4.32.526. Открытый групповой чат перезагружался примерно десять раз в
 * секунду, и это не оценка сверху, а замкнутый круг из трёх звеньев:
 *
 *   loadMessages() → markGroupRead() → emitChatWrites() → подписка → loadMessages()
 *
 * GroupsScreen подписан на записи в хранилище и на каждый сигнал перечитывает
 * переписку; в конце чтения он снимает непрочитанные; а markGroupRead будил
 * подписчиков всегда — даже когда UPDATE не менял ровным счётом ничего,
 * потому что счётчик уже был нулём со второго круга. Дебаунс внутри
 * emitChatWrites (100 мс) круг не рвёт: он задаёт ему период.
 *
 * Цена для человека: пока открыта любая группа, телефон каждые ~100 мс заново
 * чистит исчезающие сообщения, читает и расшифровывает шестьдесят строк и
 * перерисовывает весь экран, а следом по новой рассылает отметки о прочтении —
 * до двадцати адресатов за круг, то есть десятки сетевых отправок в секунду.
 * Снаружи это выглядит как «греется и садится батарея», и ни одной ошибки в
 * журнале при этом нет.
 *
 * Отсюда правило: сигнал — следствие изменения, а не следствие вызова. SQLite
 * сам отвечает на вопрос «изменилось ли что-нибудь» полем changes, надо лишь
 * перестать его выбрасывать. Второе условие — чтобы changes был честным:
 * UPDATE, проставляющий колонке то же самое значение, для SQLite всё равно
 * изменение, поэтому у таких запросов условие обязано отсеивать строки, где
 * менять нечего (`... AND unread_count != 0`). Одно без другого не работает.
 *
 * Модуль намеренно без импортов: тип результата описан структурно, чтобы его
 * можно было проверить без expo-sqlite и без базы на диске.
 */

/** То, что возвращает `runAsync`. Допускает null/undefined: вызов мог не дойти. */
export type WriteResult = { changes?: number | null } | null | undefined;

/**
 * Сколько строк на самом деле изменил запрос.
 *
 * Всё, что не конечное положительное число (нет поля, null, NaN, минус —
 * разные обёртки SQLite ведут себя по-разному), считается нулём: «не знаю»
 * здесь обязано читаться как «не менялось», иначе неизвестность снова
 * превращается в бесконечный сигнал.
 */
export function changedRows(res: WriteResult): number {
  const n = res?.changes;
  if (typeof n !== 'number' || !Number.isFinite(n) || n <= 0) return 0;
  return Math.floor(n);
}

/**
 * Стоит ли будить подписчиков после набора запросов.
 *
 * Для функций, которые пишут в несколько таблиц сразу (пометить прочитанным и
 * диалоги, и группы): достаточно одного настоящего изменения.
 */
export function anyChanged(...results: WriteResult[]): boolean {
  return results.some((r) => changedRows(r) > 0);
}
