/**
 * Прочитать секретный kv, дополнить, записать обратно — и не стереть при этом
 * то, что не открылось.
 *
 * Измеренный дефект (v4.32.552). В v4.32.544 три состояния зашифрованной
 * ячейки (`atRestCell`) закрыли столбцы таблиц: реакции, прочитавших,
 * посмотревших. Ключ-значение осталось снаружи, а живёт в нём ровно та же
 * схема «прочитал — дополнил — записал», причём над данными, которые больше
 * взять неоткуда:
 *
 *   • корзина «недавно удалённые» в переписке (ChatScreen),
 *   • та же корзина в группе — и при удалении, и при восстановлении,
 *   • личная заметка о человеке (ProfileChatBlock в карточке профиля).
 *
 * Что происходило. `kvGetSecret` внутри звал `decryptAtRestString`, а тот при
 * неудачной расшифровке отдаёт пустую строку. Пустая строка falsy, поэтому
 * список разбирался в `[]`, к пустому списку добавлялась одна свежая запись —
 * и она уходила в базу поверх прежнего шифртекста. До полусотни удалённых
 * сообщений, которые пользователь как раз и рассчитывал вернуть, исчезали от
 * одного нажатия «Удалить». Заметка о человеке — от одного «Сохранить»: поле
 * показывалось пустым, потому что не открылось, и сохранение пустоты
 * уничтожало текст.
 *
 * Отдельно про перенос из общей области в область профиля
 * (`kvGetSecretScoped`): он срабатывал, когда своя запись «пустая», то есть в
 * том числе когда она не прочиталась, — и клал чужую запись поверх своей
 * нечитаемой. Причём v4.32.293 уже учила этот код осторожности с обратной
 * стороны (не удалять исходник, пока копия не легла); неоткрывшийся приёмник
 * тогда не заметили.
 *
 * Правило здесь одно и то же для всех вызывающих: непрочитанный шифртекст
 * запрещает запись. Не «пусто» и не «нет записи» — те законны и начинают
 * любой список с нуля, — а именно «есть непустой шифртекст, и он не наш».
 *
 * Модуль без единого импорта: решение про три состояния и два сравнения
 * проверяется без базы, без ключей и без шифра.
 */

/** Три различимых состояния секретной записи — те же, что у `AtRestCell`. */
export type SecretCellState = 'absent' | 'plain' | 'unreadable';

/** Что делать с попыткой записи. */
export type SecretUpdateOutcome = 'write' | 'skip-unchanged' | 'refuse-unreadable';

/**
 * Текст для пользователя, когда запись отклонена.
 *
 * Формулировка обещает ровно то, что код делает: не открылось И не перетёрто.
 * Обещать «попробуйте позже» было бы неправдой — ключ сам не вернётся.
 */
export const SECRET_UNREADABLE_TEXT =
  'Эта запись зашифрована другим ключом и не открывается. Она сохранена как есть, а не перезаписана.';

/** Открылась ли запись. Отсутствие записи — это тоже «открылась»: терять нечего. */
export function isReadableSecret(state: SecretCellState): boolean {
  return state !== 'unreadable';
}

/**
 * Решение о записи поверх секретной записи.
 *
 * Порядок проверок важен: запрет идёт первым. Иначе «новое совпало со
 * старым» на непрочитанной записи выглядело бы как безобидное «нечего
 * писать», хотя `current` там null не потому, что пусто, а потому, что
 * не открылось.
 *
 * `next === null` — способ вызывающего сказать «передумал»: значение не
 * изменилось, писать нечего.
 */
export function decideSecretUpdate(
  state: SecretCellState,
  current: string | null,
  next: string | null,
): SecretUpdateOutcome {
  if (!isReadableSecret(state)) return 'refuse-unreadable';
  if (next === null) return 'skip-unchanged';
  return next === current ? 'skip-unchanged' : 'write';
}
