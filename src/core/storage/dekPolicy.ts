/**
 * Что делать с ключом шифрования локальных данных (v4.32.520).
 *
 * Дефект, ради которого модуль появился: getOrCreateDataEncryptionKey не
 * различал «ключа ещё нет» и «ключ не прочитался». Оба случая выглядели как
 * null из SecureStore, и оба вели в одну ветку — сгенерировать новый случайный
 * ключ и записать его поверх. Записать поверх чего? Поверх единственного
 * экземпляра ключа, которым зашифрована вся переписка. После этого:
 *
 *  - decryptAtRestString отдаёт '' на каждую строку (так задумано: показывать
 *    пользователю сырой шифртекст хуже, чем ничего);
 *  - переписка выглядит как набор пустых сообщений, а лента — как пустая;
 *  - любая запись — поставленная реакция, отметка о прочтении, правка — берёт
 *    эту пустоту и шифрует НОВЫМ ключом поверх старого шифртекста.
 *
 * Третий шаг необратим. Причём поводом хватало мелочи: обрезанная запись в
 * Keychain, отказ Android Keystore на холодном старте, сбой чтения мнемоники
 * внутри `try { … } catch { /* fallback: random DEK *\/ }`.
 *
 * Отличать эти случаи можно только по внешнему свидетельству, поэтому рядом с
 * ключом теперь лежит канарейка — известная строка, зашифрованная самим
 * ключом. Канарейка отвечает на единственный вопрос: «этим ли ключом
 * зашифрованы данные?» — и отвечает про любой ключ-кандидат, а не только про
 * тот, что нашёлся в хранилище. Отсюда и восстановление: если в SecureStore
 * ключ устарел, а выведенный из мнемоники канарейку открывает, работать надо
 * вторым, а не первым.
 *
 * Решение вынесено отдельно от чтения хранилища намеренно: здесь нет ни
 * SecureStore, ни криптографии, ни базы — только разбор случаев. Их девять, и
 * половина возникает раз в жизни установки на чужом телефоне; проверить их
 * можно либо тестом, либо никак.
 *
 * Отдельно про «отказать». Отказ означает, что приложение не откроется, — и
 * это осознанный выбор. Данные при отказе остаются на диске нетронутыми:
 * починив хранилище или переустановив приложение и восстановившись по seed,
 * пользователь получает их обратно. Молчаливая перегенерация ключа не
 * оставляет и такой возможности.
 */

/** Что нашлось в SecureStore по ключу DEK. */
export type StoredKeyState =
  /** Прочитан ключ верной длины. */
  | 'valid'
  /** Записи нет вовсе. */
  | 'absent'
  /** Запись есть, но это не 32 байта — обрезана или испорчена. */
  | 'malformed'
  /** Хранилище отказало на чтении. */
  | 'unreadable';

/** Что нашлось в SecureStore по ключу канарейки. */
export type CanaryState = 'present' | 'absent' | 'unreadable';

/** Что известно про сохранённую мнемонику. */
export type MnemonicState = 'present' | 'absent' | 'unreadable';

export type DekObservation = {
  stored: StoredKeyState;
  canary: CanaryState;
  /** Открывается ли канарейка ключом из SecureStore. null — проверять было нечем. */
  storedOpensCanary: boolean | null;
  mnemonic: MnemonicState;
  /** Открывается ли канарейка ключом, выведенным из мнемоники. null — проверять было нечем. */
  derivedOpensCanary: boolean | null;
};

export type DekAction = 'use-stored' | 'use-derived' | 'create-random' | 'refuse';

export type DekDecision = {
  action: DekAction;
  /** Записать канарейку выбранным ключом. При отказе всегда false. */
  writeCanary: boolean;
  /** Короткий машинный повод: идёт в текст ошибки и в журнал. */
  reason: string;
};

const REFUSE = (reason: string): DekDecision => ({ action: 'refuse', writeCanary: false, reason });

/**
 * Единственное правило, из которого выведены все ветки ниже: новый ключ можно
 * заводить только там, где заведомо нечего терять. «Заведомо» — это когда нет
 * ни ключа, ни канарейки, ни непрочитанного хранилища; всё остальное
 * толкуется в пользу того, что данные на диске уже есть.
 */
export function decideDek(o: DekObservation): DekDecision {
  if (o.stored === 'valid') {
    if (o.canary === 'present') {
      if (o.storedOpensCanary === true) {
        return { action: 'use-stored', writeCanary: false, reason: 'stored_verified' };
      }
      if (o.derivedOpensCanary === true) {
        // Ключ в хранилище есть, но данные зашифрованы не им, а тем, что
        // выводится из seed. Так бывает после восстановления копии на телефон,
        // где приложение уже жило: запись пережила переустановку, данные — нет.
        return { action: 'use-derived', writeCanary: false, reason: 'stored_stale_seed_matches' };
      }
      return REFUSE('stored_does_not_match_data');
    }
    if (o.canary === 'absent') {
      // Установка, поднявшаяся до появления канарейки: ключ из хранилища и есть
      // тот, которым всё зашифровано, — других в этой истории не было.
      return { action: 'use-stored', writeCanary: true, reason: 'stored_adopted' };
    }
    // Канарейку не прочитать. Ключ на месте, перезаписывать нечего — работаем
    // как раньше и не трогаем канарейку: записать её сейчас значило бы
    // закрепить ключ, который мы не смогли проверить.
    return { action: 'use-stored', writeCanary: false, reason: 'canary_unreadable' };
  }

  if (o.canary === 'present') {
    if (o.derivedOpensCanary === true) {
      return { action: 'use-derived', writeCanary: false, reason: 'key_lost_seed_matches' };
    }
    // Канарейка есть — значит, был и ключ, и данные под ним. Ключа больше нет,
    // и seed его не воспроизводит. Придумать новый здесь — это стереть всё.
    return REFUSE('key_lost_data_present');
  }
  if (o.canary === 'unreadable') {
    return REFUSE('key_and_canary_unreadable');
  }

  if (o.stored !== 'absent') {
    // Запись есть, но прочитать её нечем: обрезана или хранилище отказало.
    // Ровно тот случай, который раньше был неотличим от чистой установки.
    return REFUSE(`key_${o.stored}`);
  }
  if (o.mnemonic === 'present') {
    return { action: 'use-derived', writeCanary: true, reason: 'first_run_from_seed' };
  }
  if (o.mnemonic === 'absent') {
    return { action: 'create-random', writeCanary: true, reason: 'first_run' };
  }
  // Мнемоника, возможно, есть — прочитать не вышло. Случайный ключ разошёлся бы
  // с тем, который выведется из seed на следующем запуске.
  return REFUSE('seed_unreadable');
}
