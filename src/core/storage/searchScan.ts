/**
 * Поиск и строки, которые не открылись (v4.32.581).
 *
 * Все четыре поиска по сообщениям устроены одинаково: столбец с текстом
 * расшифровывается, полученная строка сравнивается с запросом. Расшифровка
 * шла через `decryptAtRestString`, а он на неудаче отдаёт пустую строку —
 * значит непрочитанное сообщение просто не совпадало ни с чем и молча
 * выпадало из выдачи. Человеку показывали «0» или «Ничего не найдено» ровно
 * так же, как если бы искомого в переписке никогда и не было. При
 * разошедшемся ключе данных нечитаемой становится вся история сразу, и поиск
 * начинал уверенно врать обо всём.
 *
 * Сказать «не найдено» честно можно только вместе с числом строк, до которых
 * поиск не смог добраться. Модуль считает это число и складывает из него
 * человеческую строку — с русским склонением, потому что «1 сообщение», «3
 * сообщения» и «11 сообщений» здесь встречаются одинаково часто.
 *
 * Единственная зависимость — такой же чистый модуль с окончаниями
 * (ruPlural, v4.32.584): счёт и склонение проверяются без базы, ключей и
 * шифра.
 */

/** Сколько строк поиск прочитал и сколько не смог. */
import { pluralRu } from './ruPlural';

export type SearchScan = {
  scanned: number;
  unreadable: number;
};

export function emptySearchScan(): SearchScan {
  return { scanned: 0, unreadable: 0 };
}

/**
 * Отметить обойдённую строку.
 *
 * Считаются все прочитанные строки, а не только совпавшие: доля непрочитанного
 * имеет смысл лишь рядом с тем, сколько всего смотрели.
 */
export function noteSearchedRow(scan: SearchScan, readable: boolean): void {
  scan.scanned += 1;
  if (!readable) scan.unreadable += 1;
}

/**
 * Правильное окончание для числа сообщений: 1 — «сообщение», 2–4 —
 * «сообщения», иначе «сообщений».
 *
 * v4.32.584: само правило окончаний переехало в ruPlural — второе место с
 * такой же подписью (галерея вложений) иначе завело бы вторую копию, а
 * копии расходятся молча.
 */
export function messageWordForCount(n: number): string {
  return pluralRu(n, 'сообщение', 'сообщения', 'сообщений');
}

/**
 * Строка под выдачей поиска. null — жаловаться не на что.
 *
 * Множественное число меняет и глагол: «оно не участвовало» против «они не
 * участвовали». Без этого строка выглядит как машинный перевод ровно в тот
 * момент, когда человеку и без того тревожно.
 */
export function searchSkippedNotice(scan: SearchScan): string | null {
  const n = Math.trunc(scan.unreadable);
  if (!Number.isFinite(n) || n <= 0) return null;
  const tail = messageWordForCount(n) === 'сообщение' ? 'оно не участвовало в поиске' : 'они не участвовали в поиске';
  return `${n} ${messageWordForCount(n)} не удалось прочитать — ${tail}`;
}

/** Короткая пометка рядом со счётчиком совпадений. null — жаловаться не на что. */
export function searchSkippedBadge(scan: SearchScan): string | null {
  const n = Math.trunc(scan.unreadable);
  if (!Number.isFinite(n) || n <= 0) return null;
  return `⚠ ${n}`;
}
