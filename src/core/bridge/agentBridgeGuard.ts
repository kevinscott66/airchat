/**
 * Что мост соглашается исполнить, а что отбрасывает, не читая (v4.32.723).
 *
 * ЗАЧЕМ ЭТО ВООБЩЕ ЕСТЬ. Ретранслятор хранит сообщения 30 суток
 * (`server/ntfy-vps/server.yml`), а подписка открывается с `?since=` — то
 * есть при каждом переподключении история проигрывается заново. Без защиты
 * от повтора команда «включи туннель», отправленная агентом неделю назад,
 * выполнялась бы сама собой при каждом перезапуске приложения, и человек
 * видел бы включающийся сам по себе туннель без всякой причины. Это не
 * теоретическая атака — это обычное поведение подписки.
 *
 * ДВЕ ПРОВЕРКИ, А НЕ ОДНА, и каждая закрывает то, что не закрывает другая.
 *
 * Срок годности (`FRESHNESS_WINDOW_MS`). Отсекает всю накопленную историю
 * разом: команде недельной давности место в мусоре независимо от её номера.
 * Одной этой проверки не хватает, потому что часы у агента и у телефона свои,
 * и внутри окна повтор остаётся возможным.
 *
 * Номер команды (`seq`). Строго больше предыдущего принятого. Закрывает
 * повтор внутри окна: та же команда, пойманная и отправленная заново через
 * минуту, имеет тот же номер и не проходит. Одной этой проверки тоже не
 * хватает — и вот почему.
 *
 * ЧТО СО СЧЁТЧИКОМ ПОСЛЕ ПЕРЕУСТАНОВКИ. На Android SecureStore уходит вместе
 * с приложением: пропадает и секрет, и счётчик. Новый секрет — новая тема и
 * новый ключ, старые кадры не расшифровываются вовсе, вопрос снят. На iOS
 * записи связки ключей переживают удаление приложения (и мы сами просим
 * `AFTER_FIRST_UNLOCK_THIS_DEVICE_ONLY`, а не «удалять вместе с
 * приложением»), а база SQLite — нет. Если бы счётчик лежал в kv, он после
 * переустановки обнулился бы при живом секрете, и все 30 суток накопленных
 * команд стали бы снова годными. Поэтому счётчик лежит в SecureStore рядом с
 * секретом (`agentBridgeKeys`): у них общая судьба. А срок годности остаётся
 * последней преградой на случай, если общая судьба всё-таки разойдётся.
 *
 * ЧАСТОТА. Агент не человек, он может слать команды в цикле; каждая из них
 * это запись файла настроек и, возможно, перезапуск транспорта. Предел здесь
 * стоит не против злоумышленника (у него нет ключа), а против собственного
 * агента в цикле — и он же не даёт сбойному агенту израсходовать батарею.
 */

/**
 * Насколько свежей должна быть команда.
 *
 * Пять минут — это и допуск на расхождение часов, и верхняя оценка времени
 * доставки через ретранслятор при плохой сети. Больше брать незачем: команда,
 * добиравшаяся полчаса, почти наверняка описывает уже не ту обстановку, ради
 * которой её отправляли.
 */
export const FRESHNESS_WINDOW_MS = 5 * 60_000;

/** Сколько команд мост берётся исполнить за минуту. */
export const RATE_LIMIT_MAX = 20;
export const RATE_LIMIT_WINDOW_MS = 60_000;

/** Причина отказа. Машинный опознаватель; текст для человека — в `describeRefusal`. */
export type BridgeRefusal = 'stale' | 'from_future' | 'replayed' | 'rate_limited';

export type GuardVerdict = { ok: true } | { ok: false; reason: BridgeRefusal };

export function describeRefusal(reason: BridgeRefusal): string {
  switch (reason) {
    case 'stale':
      return 'Команда слишком старая: мост исполняет только свежие, не старше пяти минут.';
    case 'from_future':
      return 'Время команды в будущем: проверьте часы на стороне агента.';
    case 'replayed':
      return 'Такой номер команды уже исполнялся. Повторы мост не исполняет.';
    case 'rate_limited':
      return 'Слишком часто. Мост исполняет не больше двадцати команд в минуту.';
  }
}

/**
 * Состояние проверок между кадрами.
 *
 * Часы передаются снаружи, а не берутся из `Date.now()`: проверка на давность
 * — это ровно проверка часов, и класс, который смотрит на них сам, проверить
 * нечем.
 */
export class BridgeGuard {
  private acceptedSeq: number;
  /** Время принятых команд — для предела частоты. */
  private recent: number[] = [];

  constructor(acceptedSeq = 0) {
    this.acceptedSeq = acceptedSeq;
  }

  /** Номер, до которого команды уже исполнены. Его пишет вызывающий в хранилище. */
  lastAcceptedSeq(): number {
    return this.acceptedSeq;
  }

  /**
   * Пропустить кадр или отказать. Ничего не меняет.
   *
   * Порядок проверок не случаен: сначала дешёвые и безусловные (давность,
   * повтор), потом предел частоты. Обратный порядок означал бы, что
   * переигранная история расходует квоту живого агента.
   *
   * ПРОВЕРКА И ПРИЁМ РАЗДЕЛЕНЫ НАРОЧНО. Заголовок кадра лежит открытым, и
   * посмотреть на номер можно до расшифровки — это и нужно, чтобы не считать
   * криптографию на тридцати сутках переигранной истории. Но продвигать
   * счётчик по непроверенному номеру нельзя: тема выведена из секрета и
   * угадать её нельзя, а вот если она всё-таки утекла, достаточно было бы
   * одного кадра с `seq = 2^53`, чтобы настоящий агент навсегда получал
   * «уже исполнялось» на любую свою команду. Поэтому `accept` вызывают
   * только после того, как кадр расшифровался: AEAD связывает номер с телом,
   * и подменить его в заголовке, не имея ключа, невозможно.
   */
  admit(seq: number, at: number, now: number): GuardVerdict {
    if (now - at > FRESHNESS_WINDOW_MS) return { ok: false, reason: 'stale' };
    if (at - now > FRESHNESS_WINDOW_MS) return { ok: false, reason: 'from_future' };
    if (seq <= this.acceptedSeq) return { ok: false, reason: 'replayed' };
    if (this.freshRecent(now).length >= RATE_LIMIT_MAX) {
      return { ok: false, reason: 'rate_limited' };
    }
    return { ok: true };
  }

  /**
   * Запомнить исполненную команду.
   *
   * Вызывается только для расшифрованного кадра. При отказе по частоте номер
   * НЕ продвигается: команда не исполнена, и агент вправе повторить её тем же
   * номером, когда квота освободится.
   */
  accept(seq: number, now: number): void {
    this.recent = this.freshRecent(now);
    this.recent.push(now);
    if (seq > this.acceptedSeq) this.acceptedSeq = seq;
  }

  private freshRecent(now: number): number[] {
    return this.recent.filter((t) => now - t < RATE_LIMIT_WINDOW_MS);
  }
}
