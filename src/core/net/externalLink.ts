/**
 * externalLink — единственная дверь наружу из приложения.
 *
 * v4.32.420. Правило «открывать только http и https» было записано в СЕМИ
 * местах одной и той же строкой-проверкой начала адреса: предпросмотр ссылки,
 * форматированный текст в личных чатах и в группах, лента, документ, и по
 * вкладке «ссылки» в личных и групповых общих файлах. Восьмое место —
 * биография в профиле — писало то же правило иначе, через разбор `new URL`.
 * А девятое, ссылка на сайт в профиле, писало так:
 *
 *     const url = isHttp(site) ? site : `https://${site}`;
 *     if (!isHttp(url)) return;   // <- всегда истина
 *
 * — то есть проверка там уже выродилась в пустую строку и ничего не стерегла.
 * Это ровно тот случай, когда правило надо не чинить в девяти копиях, а
 * сделать так, чтобы его нельзя было написать иначе.
 *
 * Почему это важно. Адрес приходит ИЗ СЕТИ: собеседник присылает текст, из
 * текста разбираются ссылки, и по нажатию они уходят в `Linking.openURL`. На
 * Android эта функция открывает не только браузер: `intent://…#Intent;…;end`
 * запускает произвольную activity любого установленного приложения,
 * `file:///…` отдаёт локальный файл, `content://…` — чужого провайдера.
 * Схема — это и есть граница доверия.
 *
 * Здесь правило одно и разбирается парсером, а не началом строки: адрес
 * должен разбираться как URL, иметь схему http или https, непустой хост и не
 * содержать управляющих символов. Проверка чистая — её видно тестам.
 */

/** Максимальная длина адреса: дальше начинается не ссылка, а полезная нагрузка. */
const MAX_URL_LENGTH = 2048;

/**
 * Есть ли внутри адреса управляющий символ, пробел или DEL — признак склейки, а не
 * адреса. Перевод строки внутри `intent://` умеет разрывать разбор у части
 * парсеров, и проще не пропускать такие символы вовсе.
 */
function hasControlOrSpace(value: string): boolean {
  for (let i = 0; i < value.length; i++) {
    const code = value.charCodeAt(i);
    if (code <= 0x20 || code === 0x7f) return true;
  }
  return false;
}

/**
 * Схема как граница доверия — проверяется до всякого разбора. Хост обязателен
 * прямо здесь: `https://` без хоста не адрес, а `new URL` на нём бросает, то
 * есть без этой части запасной путь вернул бы пустышку наружу.
 */
const HTTP_PREFIX = /^https?:\/\/[^/?#]+/i;

/**
 * Разбирает адрес и возвращает его каноническую форму, либо null.
 *
 * Возврат null — не ошибка и не повод показать сообщение: значит, по этому
 * месту просто нечего открывать.
 */
export function safeExternalUrl(raw: unknown): string | null {
  if (typeof raw !== 'string') return null;
  const trimmed = raw.trim();
  if (!trimmed || trimmed.length > MAX_URL_LENGTH) return null;
  if (hasControlOrSpace(trimmed)) return null;
  // Схема проверяется БЕЗ парсера и первой. Разбор ниже только уточняет: если
  // на устройстве `URL` окажется урезанным (в React Native он таким бывал),
  // поведение обязано выродиться в сегодняшнее — «открываем http и https», —
  // а не в «не открываем ничего». Правило должно уметь ослабнуть до прежнего,
  // но не до дырявого.
  if (!HTTP_PREFIX.test(trimmed)) return null;
  try {
    const parsed = new URL(trimmed);
    if (parsed.protocol !== 'http:' && parsed.protocol !== 'https:') return null;
    if (!parsed.hostname) return null;
    return parsed.toString();
  } catch {
    return trimmed;
  }
}

/**
 * Дописывает `https://`, если владелец профиля ввёл адрес без схемы.
 *
 * Только для ПОЛЕЙ, которые заполняет сам пользователь: «example.com» в поле
 * сайта — опечатка удобства, а не попытка обойти правило. К тексту, пришедшему
 * от собеседника, эта функция не применяется: там отсутствие схемы означает,
 * что ссылки нет.
 */
export function safeTypedUrl(raw: unknown): string | null {
  if (typeof raw !== 'string') return null;
  const trimmed = raw.trim();
  if (!trimmed) return null;
  const withScheme = /^[a-z][a-z0-9+.-]*:/i.test(trimmed) ? trimmed : `https://${trimmed}`;
  return safeExternalUrl(withScheme);
}
