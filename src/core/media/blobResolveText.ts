import type { BlobResolveFailure } from './mediaBlob';

/** Что именно не открылось — от этого зависит только название вложения. */
export type BlobSubject = 'file' | 'video' | 'photo' | 'voice';

/**
 * Название вложения в двух падежах.
 *
 * Отдельной таблицей, а не готовыми строками на каждый случай: иначе восемь
 * причин на четыре вида вложения — это тридцать две фразы, которые разъедутся
 * при первой же правке. Глаголы во всех текстах либо безличные, либо в
 * настоящем времени, поэтому род нигде не участвует: «видео не открылся» так
 * получиться не может.
 */
const SUBJECT: Readonly<Record<BlobSubject, { nom: string; acc: string }>> = {
  file: { nom: 'Файл', acc: 'файл' },
  video: { nom: 'Видео', acc: 'видео' },
  photo: { nom: 'Фото', acc: 'фото' },
  voice: { nom: 'Голосовое сообщение', acc: 'голосовое сообщение' },
};

/**
 * Почему вложение не открылось — словами, которые можно показать человеку.
 *
 * Дефект, ради которого это написано: `resolveBlobToLocalFile` отвечал одним
 * `null` на все причины сразу, а нажатие на карточку файла просто ничего не
 * делало — ни «подождите», ни «файла больше нет». Человек жмёт второй и третий
 * раз, и каждый раз не происходит ничего.
 *
 * Правило здесь одно: не называть причину, которой мы не знаем. Поэтому у
 * `unknown` нет никакого объяснения, а «больше не хранится» говорится только
 * там, где сервер ответил об этом прямо (404/410 на релее).
 */
export function blobResolveText(reason: BlobResolveFailure, subject: BlobSubject): string {
  const { nom, acc } = SUBJECT[subject];
  switch (reason) {
    case 'offline':
      return `Не удалось скачать ${acc}: сервер не ответил. Попробуйте ещё раз`;
    case 'gone':
      return `${nom} больше не хранится на сервере. Попросите отправить снова`;
    case 'corrupt':
      return `Не удалось расшифровать ${acc}: вложение повреждено. Попросите отправить снова`;
    case 'blocked-host':
      return `${nom} лежит на чужом сервере — открывать его оттуда небезопасно`;
    case 'bad-key':
      return `К этому вложению нет ключа: ${acc} не расшифровать. Попросите отправить снова`;
    case 'unsupported':
      return `Не удалось открыть ${acc}: приложение не разобрало ссылку на вложение`;
    case 'storage':
      return `Некуда сохранить ${acc}: на устройстве не нашлось места`;
    case 'unknown':
    default:
      return `Не удалось открыть ${acc}. Попробуйте ещё раз`;
  }
}
