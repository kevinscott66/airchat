/**
 * cacheSweepPolicy — что уборщику кэша вложений позволено стереть.
 *
 * v4.32.518. Дефект: sweepMediaCache удалял файл по одному только возрасту.
 * Слово «кэш» в имени каталога вводило в заблуждение — восстановить оттуда
 * можно далеко не всё:
 *
 *   • `airchat_blobcache_<32hex>.bin` — шифротекст вложения, доставленного по
 *     LAN. Ссылки на сеть у такого дескриптора нет вовсе (`u` отсутствует), а
 *     облачная копия по умолчанию выключена. Этот файл — единственная копия
 *     вложения на устройстве.
 *   • `airchat_media_<id>.<ext>` — расшифрованная копия. Выводится заново из
 *     шифротекста, но если шифротекст приехал по HTTP с релея, он нигде не
 *     сохраняется, а вложение на ntfy живёт около трёх часов. Через сутки
 *     ссылка мертва, и расшифрованная копия — тоже единственная.
 *
 * То есть через 24 часа приложение стирало вложения из живой переписки: строка
 * сообщения на месте, превью на месте, а по нажатию — ничего. Восстановить
 * нечем и неоткуда.
 *
 * Правило после исправления одно на оба вида файлов: возраст — необходимое
 * условие, но не достаточное. Стереть можно только то, на что не ссылается ни
 * одна уцелевшая строка базы. Всё остальное — «оставить», и решается это в
 * пользу сохранения при любой неопределённости: невыясненный файл занимает
 * место, а удалённый не возвращается.
 *
 * Модуль без зависимостей: приставки имён принадлежат blobRef и lanBlob,
 * множество живых ссылок — хранилищу, а решение проверяется без файловой
 * системы, базы и сети.
 */

/** Что за файл встретился уборщику. */
export type CacheFileClass =
  /** Не наш файл — снимок из галереи, чужой временный файл. Не трогаем. */
  | 'foreign'
  /** Наш и свежий: моложе TTL. */
  | 'fresh'
  /** Наш и старый: кандидат на удаление, если на него никто не ссылается. */
  | 'expired';

export type SweepVerdict = 'keep' | 'delete';

/**
 * id из имени файла кэша: `<приставка><id>.<расширение>` → id.
 *
 * Расширение произвольное (`.bin`, `.jpg`, `.m4a`), поэтому режем по последней
 * точке. Имя без точки — целиком id. Пустой id (`airchat_media_.jpg`) — не наш
 * файл: иначе расширение сошло бы за id.
 */
export function cacheFileBlobId(name: string, prefixes: readonly string[]): string | null {
  const prefix = prefixes.find((p) => p.length > 0 && name.startsWith(p));
  if (prefix === undefined) return null;
  const rest = name.slice(prefix.length);
  const dot = rest.lastIndexOf('.');
  const id = dot >= 0 ? rest.slice(0, dot) : rest;
  return id.length > 0 ? id : null;
}

/**
 * id, который сканер ссылок вывести не способен, — значит, сверить файл со
 * списком живых ссылок нельзя.
 *
 * blobCacheIdsIn ищет в тексте две формы: 32 шестнадцатеричных знака (LAN-id) и
 * `/file/<токен>` (адрес на релее). Но у дескриптора с адресом без `/file/`
 * имя файла выводится хешированием всего адреса — `hex(url).slice(0, 24)`, — и
 * такой id в тексте сообщения не встречается никогда. Для сверки он бесполезен:
 * «нет в списке живых» для него значит не «сирота», а «проверить нечем».
 *
 * Ровно 24 шестнадцатеричных знака — форма именно этого хеша. Токен с релея
 * такой длины и состава теоретически возможен; тогда файл просто останется
 * лежать. Это цена в сторону сохранения, и она правильная.
 */
export function isUnverifiableBlobId(id: string): boolean {
  return /^[0-9a-f]{24}$/.test(id);
}

/** Наш ли файл и вышел ли его срок. */
export function classifyCacheFile(
  name: string,
  ageMs: number,
  ttlMs: number,
  prefixes: readonly string[]
): CacheFileClass {
  if (cacheFileBlobId(name, prefixes) === null) return 'foreign';
  return ageMs > ttlMs ? 'expired' : 'fresh';
}

/**
 * Решение по одному файлу.
 *
 * `liveIds === null` — список живых ссылок получить не удалось (база занята,
 * ключ недоступен, чтение упало). Тогда не удаляется ничего: пропущенная
 * уборка стоит места на диске, ошибочная — переписки.
 */
export function sweepVerdict(
  name: string,
  ageMs: number,
  ttlMs: number,
  prefixes: readonly string[],
  liveIds: ReadonlySet<string> | null
): SweepVerdict {
  if (classifyCacheFile(name, ageMs, ttlMs, prefixes) !== 'expired') return 'keep';
  if (liveIds === null) return 'keep';
  const id = cacheFileBlobId(name, prefixes);
  if (id === null || isUnverifiableBlobId(id)) return 'keep';
  return liveIds.has(id) ? 'keep' : 'delete';
}
