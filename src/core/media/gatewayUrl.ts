/**
 * gatewayUrl — сборка адреса IPFS-шлюза из CID, пришедшего по сети.
 *
 * v4.32.243. CID подставлялся в `${gateway}/ipfs/${cid}` почти везде без
 * проверки: фотографии в личных чатах и группах, аватары групп, вложения в
 * списке общих файлов, лента. Проверка была только у документов — там адрес
 * уходит в Linking.openURL, и её однажды добавили точечно.
 *
 * А в CID из сети может лежать что угодно. Символы '/', '..', '?', '#', ':'
 * и '@' значащие в адресе, поэтому чужой «CID» вида '../../..' или
 * 'x/../../evil.example/p.png' превращает адрес шлюза в адрес чужого сервера.
 * Дальше этот адрес попадает в <Image>, а картинка грузится САМА при отрисовке
 * — то есть собеседник получает IP-адрес получателя и точное время открытия
 * чата, даже если отчёты о прочтении выключены (тот же класс маяка, что и
 * предпросмотр ссылок, см. core/social/linkPreviewPolicy).
 *
 * Поэтому адрес собирается только здесь и только из CID разрешённой формы.
 *
 * v4.32.432: сама форма переехала в core/cid — она нужна не только адресу
 * шлюза, а девяти местам, где была выписана от руки.
 */

import { isPlainCid } from '../cid';

/** Адрес шлюза без хвостовых слэшей, либо '' если шлюз не задан или не http(s). */
export function normalizeGateway(gateway: string | null | undefined): string {
  const gw = (gateway ?? '').trim().replace(/\/+$/, '');
  return /^https?:\/\/[^\s]+$/i.test(gw) ? gw : '';
}

/** Возвращает адрес для загрузки или '' — тогда показывать нечего. */
export function gatewayUrl(gateway: string | null | undefined, cid: unknown): string {
  const gw = normalizeGateway(gateway);
  if (!gw || !isPlainCid(cid)) return '';
  return `${gw}/ipfs/${cid}`;
}
