/**
 * Дробный размер писался через точку (v4.32.918).
 *
 * Дефект. `formatByteSize` собирала подпись как `${shown} ${unit.suffix}`, а
 * `shown` — число: `String(1.5)` даёт «1.5». Точка — английский десятичный
 * разделитель; в русском это запятая. Дробь появляется только у мегабайтов и
 * гигабайтов (у байтов и килобайтов `decimals: 0`), зато у них — везде: вес
 * фотографии в ленте и в «Общих файлах» чата и группы, размер документа под
 * сообщением, объём кэша в настройках, подпись предела в отказе загрузки,
 * итог выкладывания сторис. Одна функция, восемь мест.
 *
 * Цена. Единственная дробь во всём приложении была набрана не по-русски — и
 * вдобавок спорила с соседкой. Отказ «Пост слишком большой» показывает текст
 * из `ru.json`, набранный руками: «превышает лимит 1.8 МБ». В том же окне, на
 * том же экране записи, вторая рукописная строка про документы пишет «Тяжелее
 * 1,2 МБ» — уже с запятой. Два предела одного экрана, два разделителя.
 *
 * Почему рукописные строки вообще разошлись: сторож «единицы размера пишутся
 * только в byteSize» (v4.32.422, byteSize.test.ts) обходит `src/**` по маске
 * `\.tsx?$`. `src/i18n/ru.json` под неё не попадает, поэтому две подписи
 * размера жили там незамеченными. Здесь они ловятся отдельно.
 *
 * Правка. Дробная часть отделяется запятой, и рукописный предел в `ru.json`
 * приведён к тому же виду. Числа не тронуты: «1,8 МБ» и «1,2 МБ» — округление
 * вниз от настоящих пределов (1 887 436 Б и 1 258 291 Б), то есть подпись
 * по-прежнему не обещает больше, чем пропустит проверка. Само же то, что эти
 * два числа набраны руками, а не посчитаны из констант, — отдельный хвост;
 * он закрыт в v4.32.919, и проверки ниже подправлены под подстановку.
 */
import { readFileSync } from 'fs';
import { join } from 'path';

import { formatByteSize } from '../byteSize';
import { MAX_BLOB_BYTES } from '../blobRef';
import { formatLimit } from '../uploadRoute';
import { FEED_MAX_DOC_BYTES, FEED_POST_MAX_BYTES } from '../../social/composeDraft';

const RU = JSON.parse(
  readFileSync(join(__dirname, '..', '..', '..', 'i18n', 'ru.json'), 'utf8')
) as { feed: Record<string, string> };

describe('ПРОВЕРКА НЕ ПУСТАЯ', () => {
  it('подпись вообще собирается', () => {
    expect(formatByteSize(1_500_000)).toContain('МБ');
    expect(formatByteSize(1_500_000).length).toBeGreaterThan(3);
  });

  it('оба текста предела в ru.json на месте', () => {
    // Иначе проверки на их вид молча пусты. v4.32.919: число в них больше не
    // набрано руками, поэтому спрашиваем про подстановку, а не про «МБ».
    expect(RU.feed.postTooLargeDetail).toContain('{{limit}}');
    expect(RU.feed.docSkippedTooBig).toContain('{{limit}}');
  });
});

describe('дробь отделяется запятой', () => {
  it('мегабайты', () => {
    expect(formatByteSize(1_500_000)).toBe('1,5 МБ');
    expect(formatByteSize(52_428_800)).toBe('52,4 МБ');
  });

  it('гигабайты', () => {
    expect(formatByteSize(2_500_000_000)).toBe('2,5 ГБ');
  });

  it('округление вниз — тоже', () => {
    expect(formatLimit(1_570_000)).toBe('1,5 МБ');
    expect(formatByteSize(8_990_000, { roundDown: true })).toBe('8,9 МБ');
  });

  it('точки не остаётся ни при одном размере', () => {
    // Полсотни значений по всем четырём единицам и по обоим округлениям.
    for (let p = 0; p <= 12; p++) {
      for (const k of [1, 1.234, 2.5, 7.77, 9.99]) {
        const bytes = Math.round(10 ** p * k);
        expect(formatByteSize(bytes)).not.toContain('.');
        expect(formatByteSize(bytes, { roundDown: true })).not.toContain('.');
      }
    }
  });

  it('предел в отказе записи подставляется с запятой', () => {
    // v4.32.919: в самой строке число больше не стоит — подставляется отсюда.
    expect(formatLimit(FEED_POST_MAX_BYTES)).toBe('1,8 МБ');
    expect(RU.feed.postTooLargeDetail).not.toContain('1.8');
  });
});

describe('до правки было верно и осталось верно', () => {
  it('целые числа пишутся без разделителя вовсе', () => {
    expect(formatByteSize(400)).toBe('400 Б');
    expect(formatByteSize(12_345)).toBe('12 КБ');
    expect(formatByteSize(8_000_000)).toBe('8 МБ');
    expect(formatLimit(MAX_BLOB_BYTES)).toBe('8 МБ');
  });

  it('неизвестный размер по-прежнему пустая строка, а не «0 Б»', () => {
    for (const bad of [null, undefined, NaN, Infinity, -1]) {
      expect(formatByteSize(bad as number)).toBe('');
    }
  });

  it('переход через единицу считается после округления', () => {
    expect(formatByteSize(999_999)).toBe('1 МБ');
    expect(formatByteSize(999_999, { roundDown: true })).toBe('999 КБ');
  });

  it('единицы остались русскими и с пробелом', () => {
    // Про разделитель эта проверка нарочно не спрашивает — она стоит ради
    // единицы и пробела перед ней, и верна была до правки так же, как после.
    expect(formatByteSize(1_500_000)).toMatch(/^[0-9][0-9.,]* (Б|КБ|МБ|ГБ)$/);
  });

  it('предел документа — тоже с запятой, и это то же число, что и было', () => {
    expect(formatLimit(FEED_MAX_DOC_BYTES)).toBe('1,2 МБ');
  });
});
