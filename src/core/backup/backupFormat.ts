/**
 * backupFormat — узнать зашифрованную резервную копию по самому тексту.
 *
 * v4.32.376. Копию seed-фразы приложение умело только ВЫДАВАТЬ. Кнопка
 * «Резервная копия» в профиле просит пароль, шифрует фразу и отдаёт JSON через
 * системное «Поделиться» — человек кладёт его в заметки или в облако. А обратно
 * этот JSON загрузить было негде: importEncryptedBackup существовал в ядре, но
 * его не вызывал ни один экран, и восстановление принимало только 24 слова.
 * То есть приложение предлагало сделать копию, которой нельзя воспользоваться.
 *
 * Отдельного экрана для неё не нужно: копию вставляют в то же поле, что и
 * слова, а приложение само видит, что вставили. Отсюда эта функция — и она
 * чистая, потому что seedPhrase тянет за собой SecureStore, bip39 и криптографию.
 *
 * Проверка нарочно смотрит только на форму, не на содержимое: решение «пароль
 * верный или нет» принимает расшифровка, и подменять его догадкой нельзя.
 */

/**
 * Потолок вставленного текста. Настоящая копия — около двухсот байт; многомегабайтная
 * вставка вешает поток на разборе JSON. Тот же предел стоит на входе импорта.
 */
export const BACKUP_TEXT_MAX = 4096;

/**
 * Похоже ли вставленное на зашифрованную резервную копию.
 *
 * Ошибиться в сторону «да» на списке слов невозможно: слова bip39 — строчные
 * латинские буквы, фигурной скобки среди них нет.
 */
export function looksLikeEncryptedBackup(raw: unknown): boolean {
  if (typeof raw !== 'string') return false;
  const text = raw.trim();
  if (!text.startsWith('{') || text.length > BACKUP_TEXT_MAX) return false;

  let parsed: unknown;
  try {
    parsed = JSON.parse(text);
  } catch {
    return false;
  }
  if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) return false;

  const o = parsed as { v?: unknown; saltB64?: unknown; blobB64?: unknown };
  return (
    o.v === 1 &&
    typeof o.saltB64 === 'string' &&
    o.saltB64.length > 0 &&
    typeof o.blobB64 === 'string' &&
    o.blobB64.length > 0
  );
}
