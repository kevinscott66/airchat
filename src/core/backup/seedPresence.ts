/**
 * Есть ли на устройстве секретные слова — и что об этом сказать (v4.32.993).
 *
 * Дефект был двойной, и оба его конца сходились на одной строке экрана
 * профиля: «Секретные слова на этом устройстве не найдены — при необходимости
 * пройдите настройку заново».
 *
 * Первое. Ответа ждали, начав с `useState(false)`, а сам вопрос задавали
 * четвёртым по счёту — после `ipfsId()` и после `runSyncIfOnline()`, то есть
 * после похода в сеть. Всё это время предупреждение висело на экране у любого
 * человека с целым кошельком. Не редкий случай, а каждое открытие вкладки.
 *
 * Второе. `hasStoredMnemonic` не двузначна: `readSeedRecord` намеренно
 * пробрасывает всё, кроме `SecureStoreUnreadableError`, — «Keystore заперт» это
 * не «запись испорчена», а «сейчас не ответили». Ветка эффекта ловушки не
 * имела, поэтому бросок не только оставлял `false` навсегда, но и обрывал
 * остаток загрузки: имя, аватар, «О себе», @имя, счётчики. Экран становился
 * похож на первый запуск после переустановки — и этим подтверждал текст.
 *
 * Цена. Текст не просто неверен, он зовёт к действию: «пройдите настройку
 * заново». Кнопка «Создать новый аккаунт» пишет новую фразу и новую пару
 * ключей поверх прежних, и прежний кошелёк с привязанной к нему перепиской не
 * возвращается ничем. Ровно эту потерю закрывали в ядре v4.32.615 и v4.32.717:
 * там «запись есть, но не открылась» перестали выдавать за «записи нет».
 * Экран остался на двух состояниях и сводил ту работу на нет.
 *
 * Модуль без единого импорта: решение здесь про четыре состояния и два текста,
 * и проверяется оно без хранилища ключей и без React.
 */

/** Что мы знаем о секретных словах прямо сейчас. */
export type SeedPresence =
  /** Ещё не спросили или ответа нет. Молчим: тревожить нечем. */
  | 'asking'
  /** Слова на месте. */
  | 'yes'
  /** Слов нет — настоящая, проверенная пустота. */
  | 'no'
  /** Хранилище ключей не ответило. Ни «есть», ни «нет». */
  | 'unknown';

/** Проверенная пустота. Текст прежний: этот случай и раньше был назван верно. */
export const SEED_ABSENT_TEXT =
  'Секретные слова на этом устройстве не найдены — при необходимости пройдите настройку заново.';

/**
 * Хранилище ключей не ответило.
 *
 * Прямо запрещает то, к чему звал прежний текст: настройку заново проходить не
 * нужно. Это единственное, что человеку здесь важно, и единственное, чего он
 * не может увидеть сам. Обещания «сейчас починится» нет — причина отказа
 * отсюда не видна.
 */
export const SEED_UNKNOWN_TEXT =
  'Проверить секретные слова не удалось — хранилище ключей не ответило. Это не значит, что их нет: ' +
  'настройку заново проходить не нужно. Откройте этот экран ещё раз.';

/**
 * Что показать под кнопкой сохранения копии. `null` — не показывать ничего.
 *
 * Молчание на `asking` умышленно: предупреждение это справка, а не срочность,
 * и сказать его через полсекунды дешевле, чем сказать неправду сразу.
 */
export function seedWarningText(presence: SeedPresence): string | null {
  if (presence === 'no') return SEED_ABSENT_TEXT;
  if (presence === 'unknown') return SEED_UNKNOWN_TEXT;
  return null;
}
