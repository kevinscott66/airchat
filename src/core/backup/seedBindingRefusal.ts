/**
 * Почему конверт привязки не открылся — словами (v4.32.1079).
 *
 * ДЕФЕКТ. `decryptSeedBinding` отвечала `null` на семь разных случаев, и
 * экран восстановления показывал на все семь одну подпись: «Неверный пароль
 * приложения.» Из этих семи паролю принадлежит ровно один — тот, где
 * `decryptSymmetric` не сошёлся на метке. Остальные шесть про конверт: он
 * новее здешней версии, у него занижен или задран `iters`, соль не той
 * длины, поля не строки, шифртекст длиннее предела, или внутри оказались не
 * слова.
 *
 * ЦЕНА. Пароль приложения у человека один, и путь сюда — единственный, когда
 * двадцати четырёх слов на руках нет. Услышав «неверный пароль», он вводит
 * тот же пароль снова, потом решает, что забыл его, и уходит заводить новый
 * аккаунт. Между тем при конверте новее подпись должна была сказать
 * «обновите приложение», а при порченом — что подбирать тут нечего.
 *
 * ГРАНИЦЫ. Ни один из текстов не сообщает ничего о самом пароле сверх того,
 * что человек и так знает. Разница между «не тот пароль» и «слова внутри не
 * распознаны» видна только тому, кто пароль уже ввёл верно: метка AEAD
 * сошлась, то есть ключ верный. Враждебный сервер и так знает, какой конверт
 * он прислал.
 */

/** Разряд отказа. Ровно один из них — про пароль. */
export type SeedBindingRefusal =
  | 'no_envelope'
  | 'newer_envelope'
  | 'broken_envelope'
  | 'wrong_password'
  | 'broken_words';

const TEXT: Record<SeedBindingRefusal, string> = {
  no_envelope: 'Привязка не пришла. Войдите через Apple ID ещё раз.',
  newer_envelope:
    'Эта привязка сохранена более новой версией AirChat, и здешняя её не открывает. ' +
    'Обновите приложение и повторите — пароль тут ни при чём.',
  broken_envelope:
    'Запись привязки пришла в неожиданном виде и не читается. Пароль тут ни при чём: ' +
    'подбирать нечего. Повторите позже или введите секретные слова вручную.',
  wrong_password: 'Неверный пароль приложения.',
  broken_words:
    'Пароль подошёл, но секретные слова внутри не распознаны — запись повреждена. ' +
    'Введите слова вручную, если они у вас сохранены.',
};

/** Что сказать человеку. Один разряд — одна подпись, без «попробуйте ещё раз» поверх. */
export function seedBindingRefusalText(why: SeedBindingRefusal): string {
  return TEXT[why];
}
