/**
 * storedPhraseState — «фразы нет» и «фраза не открылась» это разные ответы
 * (v4.32.651).
 *
 * Дефект. Экран приветствия спрашивал `hasStoredMnemonic()`, затем
 * `getStoredMnemonic()`, и на пустой ответ второго просто выходил из эффекта —
 * тем же `return`, что и при отсутствии фразы. Но `getStoredMnemonic()`
 * отвечает `null` и когда фразы нет вовсе, и когда она есть, а расшифровать её
 * не удалось: с v4.32.615 негодные байты намеренно не стираются, вдруг
 * хранилище починится. Оба случая приводили на обычный welcome, где живая
 * кнопка «Создать новый аккаунт» вызывает `generateMnemonicAndStore`, а тот
 * пишет новую фразу и новую пару ключей поверх старых. Прежний кошелёк после
 * этого не вернуть ничем.
 *
 * Различить их есть чем: `hasStoredMnemonic()` смотрит на наличие записи, а не
 * на её читаемость. Присутствие без чтения — это и есть отказ ЧТЕНИЯ, и
 * превращать его в необратимую ЗАПИСЬ молча нельзя.
 *
 * Запрещать создание совсем тоже нельзя: у кого запись действительно
 * испорчена, тот остался бы без единственного выхода. Поэтому решение здесь
 * только называет состояние, а экран на `unreadable` предупреждает и
 * переспрашивает.
 */

export type StoredPhraseState = 'none' | 'unreadable' | 'ready';

/**
 * Четвёртый ответ: спросить хранилище не вышло (v4.32.1072).
 *
 * ДЕФЕКТ. Решение выше различает «записи нет» и «запись есть, но не
 * открылась», — и оба ответа честные, потому что оба получены. А получить их
 * можно не всегда: `hasStoredMnemonic` отказы хранилища пробрасывает
 * НАМЕРЕННО (см. `readSeedRecord`: «это не «запись испорчена», а «сейчас не
 * ответили»»). Экран приветствия ловил этот бросок общим `catch` и уходил на
 * обычный welcome — то есть на тот же экран, что и чистая установка.
 *
 * ЦЕНА. Та самая, от которой заводили v4.32.651, только зашедшая в другую
 * дверь. На welcome кнопка «Создать новый аккаунт» живая, и предупреждение
 * при нечитаемой записи показывается по флагу, который в этом случае остался
 * `false`. Одно нажатие — и `generateMnemonicAndStore` пишет новую фразу и
 * новые ключи поверх старых, не спросив ничего. Прежний аккаунт не вернуть
 * ничем. Отказы хранилища как раз и случаются в первые секунды после
 * перезагрузки телефона, когда Keychain ещё заперт, — то есть ровно тогда,
 * когда человек открывает приложение и видит welcome.
 *
 * ПРАВКА. «Не знаем» — отдельный ответ, и он тоже переспрашивает перед
 * необратимой записью. Своими словами: обещать «на устройстве уже есть
 * аккаунт» здесь нельзя — его может и не быть.
 *
 * ГРАНИЦЫ. Создание не запрещается ни в одном из двух случаев: у кого запись
 * правда испорчена и у кого хранилище правда не отвечает, — это их
 * единственный выход. Разница только в том, что он сделан осознанно.
 */
export type PhraseAskState = StoredPhraseState | 'unknown';

/**
 * О чём переспросить перед созданием аккаунта поверх. `null` — спрашивать не
 * о чем: мы знаем, что записи нет, или знаем, что она читается.
 */
export function phraseOverwriteWarning(
  state: PhraseAskState
): { title: string; body: string } | null {
  if (state === 'unreadable') {
    return {
      title: 'На устройстве уже есть аккаунт',
      body:
        'Его секретные слова не удалось прочитать — это бывает временным сбоем хранилища. ' +
        'Новый аккаунт сотрёт их навсегда. Если слова у вас записаны, выберите ' +
        '«Восстановить аккаунт».',
    };
  }
  if (state === 'unknown') {
    return {
      title: 'Не удалось проверить устройство',
      body:
        'Хранилище не ответило, есть ли здесь аккаунт. Если есть, новый сотрёт его ' +
        'секретные слова навсегда. Так бывает в первые секунды после перезагрузки: ' +
        'закройте приложение и откройте снова.',
    };
  }
  return null;
}

/** Что написать на самом welcome. `null` — писать нечего. */
export function phraseAskBanner(state: PhraseAskState): string | null {
  if (state === 'unreadable') {
    return (
      'На этом устройстве уже есть аккаунт, но его секретные слова сейчас не читаются. ' +
      'Не создавайте новый — он сотрёт их навсегда. Выберите «Восстановить аккаунт».'
    );
  }
  if (state === 'unknown') {
    return (
      'Не удалось проверить, есть ли на этом устройстве аккаунт: хранилище не ответило. ' +
      'Если аккаунт есть, новый сотрёт его секретные слова навсегда. Откройте приложение ' +
      'заново через минуту.'
    );
  }
  return null;
}

/**
 * @param present ответ `hasStoredMnemonic()` — есть ли запись
 * @param phrase ответ `getStoredMnemonic()`; `null` и на «нет», и на «не открылась»
 */
export function decideStoredPhraseState(
  present: boolean,
  phrase: string | null | undefined
): StoredPhraseState {
  if (!present) return 'none';
  if (!phrase?.trim()) return 'unreadable';
  return 'ready';
}
