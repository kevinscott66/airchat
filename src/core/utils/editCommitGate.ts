/**
 * editCommitGate — «одна правка поля равна одному сохранению» (v4.32.515).
 *
 * Поле, которое правят на месте (нажал на название — оно стало полем ввода —
 * ушёл с него — сохранилось), спрашивают ДВА события сразу: onSubmitEditing по
 * клавише «готово» и onBlur, потому что submit у однострочного поля снимает
 * фокус. Оба зовут один и тот же обработчик, и оба успевают войти в него до
 * первого await.
 *
 * Отсечь второй вход сравнением с текущим значением группы не выходило: это
 * значение приходит пропом из навигационного состояния, а оно заводится один
 * раз при переходе на экран и после записи в базу не обновляется. То есть
 * пропом заморожено то, что было при входе на карточку, — и второй вход
 * сравнивает новое имя со старым, видит разницу и пишет ещё раз.
 *
 * Отсюда две беды сразу, и обе у того, кто правит:
 *
 *   • запись, тост и системная строка задваивались — а получатели конверта
 *     повтор отбрасывают (`env.name !== group.name` в ветке 'meta'), так что
 *     лишняя строка «Группа переименована в «X»» оставалась ровно в одной
 *     истории из всех и деться оттуда уже не могла;
 *   • вернуть прежнее название в том же сеансе было нельзя. Переименовали
 *     A→B, тут же B→A: сравнение с замороженным пропом (A) отвечает «менять
 *     нечего», поле закрывается, на экране A — а в базе B. Расхождение
 *     держится до следующего открытия карточки.
 *
 * Правило: сравнивать надо с тем, что сохранили САМИ и в последний раз, а не с
 * пропом; и пока запись в полёте, второго захода не пускать вовсе.
 *
 * Модуль без импортов: это чистая машина состояний из двух полей, и её место —
 * рядом с semaphore, а не в экране на пять тысяч строк.
 */

export interface EditCommitGate {
  /**
   * Начать сохранение `value`. false означает «не надо»: либо запись уже в
   * полёте, либо ровно это значение и сохранено последним.
   */
  begin(value: string): boolean;
  /** Запись удалась: теперь сохранено `value`. */
  commit(value: string): void;
  /**
   * Запись сорвалась: снять полёт, не трогая сохранённое. Звать после commit
   * безвредно — сохранённое значение он не откатывает, потому что оно уже на
   * диске.
   */
  rollback(): void;
  /** Что, по мнению калитки, лежит на диске. */
  last(): string;
}

/**
 * @param initial значение, с которого поле открыли, — оно же и на диске.
 */
export function createEditCommitGate(initial: string): EditCommitGate {
  let saved = initial;
  let busy = false;
  return {
    begin(value: string): boolean {
      if (busy || value === saved) return false;
      busy = true;
      return true;
    },
    commit(value: string): void {
      saved = value;
      busy = false;
    },
    rollback(): void {
      busy = false;
    },
    last(): string {
      return saved;
    },
  };
}
