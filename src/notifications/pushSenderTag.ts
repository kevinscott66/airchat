import { sha256 } from '@noble/hashes/sha2.js';

/**
 * Метка отправителя в push вместо его DID (v4.32.614).
 *
 * Дефект. Ретранслятор клал в нагрузку FCM открытый DID отправителя, и дальше
 * эта строка ехала через Google, а на iOS ещё и через Apple. Токен получателя
 * говорит посреднику, чей это телефон; DID в AirChat публичен и разрешается в
 * профиль, юзернейм и ленту. Складывая одно с другим, посредник собирал
 * готовый граф «кто кому и когда пишет» с настоящими именами — ту самую
 * метаинформацию, ради сокрытия которой переписка и шифруется. Тексты при этом
 * не утекали никогда (баннер собирается на устройстве), а отправители — все.
 *
 * Метка — первые 128 бит sha256 от пары ключей. Посреднику она не говорит
 * ничего: обратного хода у хеша нет, а перебор упирается в соль.
 *
 * Соль — ключ получателя, и в ней весь смысл. Без неё метка отправителя была
 * бы одна на всех получателей: список DID открыт (юзернеймы, лента), и
 * радужная таблица по нему строится за один проход. С солью посреднику надо
 * сперва узнать, чей это телефон в терминах AirChat, — а именно такого
 * сопоставления у него и нет: FCM-токен знает он, а ключ AirChat — мы.
 *
 * Побочное следствие того же выбора: один и тот же отправитель даёт разные
 * метки разным получателям, поэтому связать двух собеседников одного человека
 * по совпадению меток нельзя.
 *
 * Форму метки описывает SENDER_TAG_SHAPE в openIntent — там, где её и
 * проверяют при разборе уведомления, и там, где нельзя заводить импортов.
 *
 * Обратное преобразование делает получатель — перебором своих контактов, см.
 * senderTagLookup. Их десятки, а не миллионы, и ключа для этого не нужно:
 * ровно поэтому проверка работает и в фоне, при запертом телефоне, где
 * SecureStore недоступен.
 */

/**
 * Зеркало собственных peerId в открытом kv.
 *
 * Пишет `registerTokenWithSignaling` — там же, где peerId сообщается
 * ретранслятору, и ровно теми же значениями. Читает фоновый обработчик push,
 * которому спросить их больше не у кого: личность лежит в SecureStore, а он
 * при запертом телефоне не отвечает. То же решение и по той же причине, что у
 * `active_profile_id` (см. backgroundNotifyPrefs).
 *
 * Секретом значения не являются: это открытые ключи, они и так видны всякому
 * собеседнику.
 *
 * v4.32.615: зеркало стало списком. Хранилась одна строка — та, которой
 * регистрировались последней, — а токен FCM на устройстве один на все
 * личности, и ретранслятор помнит регистрацию каждой. Уведомление, посланное
 * личности, под которой сейчас не сидят, приходило на тот же телефон, соль в
 * метке была от неё, а разворачивали метку ключом активной: совпадений не
 * бывало никогда. Промах здесь тихий и стоит дорого — мимо него проходят и
 * «беззвучно», и «не показывать при открытом чате», и блок-лист.
 */
export const SELF_PEER_MIRROR_KEY = 'push_self_peer';

/**
 * Сколько своих ключей помнить. Профилей не больше четырёх (profileManager),
 * а пятый ключ означает, что личность пересоздали: самый давний и вытесняем.
 */
export const SELF_PEER_MIRROR_MAX = 4;

/**
 * Разобрать зеркало. Записи до v4.32.615 — одна голая строка, не JSON; они
 * читаются как список из одного ключа.
 */
export function parseSelfPeerMirror(raw: string | null | undefined): string[] {
  if (!raw) return [];
  if (!raw.startsWith('[')) return [raw];
  try {
    const parsed: unknown = JSON.parse(raw);
    if (!Array.isArray(parsed)) return [];
    return parsed.filter((x): x is string => typeof x === 'string' && x.length > 0);
  } catch {
    return [];
  }
}

/** Добавить свой ключ в зеркало, самым свежим. Возвращает значение для kv. */
export function mergeSelfPeerMirror(raw: string | null | undefined, peerId: string): string {
  const rest = parseSelfPeerMirror(raw).filter((x) => x !== peerId);
  return JSON.stringify([peerId, ...rest].slice(0, SELF_PEER_MIRROR_MAX));
}

/**
 * Метка отправителя для этой пары. Оба ключа — сырые 32 байта в base64, ровно
 * в той форме, в какой их знает ретранслятор (см. pushEnvelope.peerIdFromDid).
 */
export function pushSenderTag(targetPeerB64: string, senderPeerB64: string): string {
  const digest = sha256(
    new TextEncoder().encode(`airchat-push-sender-v1|${targetPeerB64}|${senderPeerB64}`)
  );
  return Buffer.from(digest).toString('hex').slice(0, 32);
}
