/**
 * «Не беспокоить»: окно часов и разбор его границ.
 *
 * v4.32.248. Вынесено из pushNotifications отдельным модулем без единого
 * импорта — по двум причинам. Первая: ровно та же проверка нужна фоновому
 * обработчику push (firebaseMessagingBackground), а тот работает в отдельном
 * контексте и тянуть в него слой уведомлений целиком нельзя. Вторая: окно с
 * переходом через полночь — единственное место здесь, где легко ошибиться, а
 * проверить его в приложении можно только дождавшись нужного часа.
 *
 * v4.32.975: сама формула окна переехала в `core/time/hourOfDay` — та же
 * проверка нужна ночной теме, и копия жила там отдельной строкой. Имя и место
 * вызова здесь прежние: фоновому обработчику по-прежнему хватает этого модуля,
 * а у нового импортов нет.
 *
 * v4.32.1036: туда же ушёл и разбор границы. Держать свою копию имело смысл,
 * пока модуль был без единого импорта, — но с v4.32.975 он и так зовёт
 * `core/time/hourOfDay`, и довод исчез, а копия осталась. Разбор часа теперь
 * один на оба окна, тишину и ночную тему: подкрутят проверку — подкрутят
 * сразу обеим, а не той, из-за которой пожаловались.
 */
import { isWithinHourWindow, parseHourOfDay } from '../core/time/hourOfDay';

/** Час границы окна: 0…23, всё остальное (мусор в kv, NaN) — запасное значение. */
export function parseDndHour(raw: string | null | undefined, fallback: number): number {
  return parseHourOfDay(raw, fallback);
}

/**
 * Попадает ли час в окно тишины.
 *
 * Окно полуоткрытое: начало включительно, конец нет. Равные границы означают
 * пустое окно, а не круглосуточную тишину: человек, выставивший 22–22, хотел
 * скорее ничего, чем выключить уведомления навсегда.
 */
export function isWithinDndWindow(start: number, end: number, hour: number): boolean {
  return isWithinHourWindow(start, end, hour);
}
