/**
 * notifyDedup — учёт уже показанных баннеров, чтобы одно сообщение не
 * показывалось дважды и не пропадало совсем.
 *
 * v4.32.571. Одно и то же сообщение доезжает разными путями: приёмом по сети
 * и следом push-уведомлением, а сотовый оператор ещё и повторяет доставку.
 * С v4.32.131 от второго баннера защищает список последних cid.
 *
 * Отметка ставилась ДО показа — за четыре await до него — и не снималась
 * никогда: список умеет только добавлять. Значит, любая осечка на пути к
 * показу (чтение настроек, сам notifee) означала, что баннера не будет ни
 * сейчас, ни при повторной доставке, ни по любому другому пути: cid уже
 * отмечен как показанный. Сообщение пропадало молча и навсегда — до
 * перезапуска приложения.
 *
 * Это не теория. До v4.32.567 notifee отвергал рисунок вибрации с ведущим
 * нулём, и показ падал исключением КАЖДЫЙ раз; отметка при этом исправно
 * ставилась. Как только показ починили, осталась вторая половина: любой
 * будущий отказ так же тихо съедал бы сообщение.
 *
 * Правило: отметка — это бронь, а не запись в летопись. Бронь берётся до
 * показа (иначе две одновременные доставки покажут два баннера) и снимается,
 * если показать не вышло. Пустой cid не бронируется вовсе: ключа нет, и
 * запрет по нему запретил бы все такие сообщения разом.
 *
 * Модуль без импортов: учёт проверяется отдельно от notifee, настроек и сети.
 */

/** Столько последних cid помнит процесс. Дальше — вытеснение по очереди. */
export const NOTIFY_DEDUP_MAX = 200;

export type NotifyDedup = {
  /** Взять бронь на показ. false — этот cid уже показан или показывается. */
  reserve(cid: string): boolean;
  /** Вернуть бронь: показать не вышло, пусть следующая доставка попробует. */
  release(cid: string): void;
  /** Показывали ли уже. Пустой cid не помнится никогда. */
  has(cid: string): boolean;
  size(): number;
};

export function createNotifyDedup(max: number = NOTIFY_DEDUP_MAX): NotifyDedup {
  const cap = typeof max === 'number' && Number.isFinite(max) && max >= 1 ? Math.floor(max) : NOTIFY_DEDUP_MAX;
  const seen: string[] = [];
  const usable = (cid: string): boolean => typeof cid === 'string' && cid.length > 0;
  return {
    reserve(cid: string): boolean {
      // Без ключа дедупликации нет: иначе первое же сообщение без cid
      // запретило бы все остальные такие же.
      if (!usable(cid)) return true;
      if (seen.includes(cid)) return false;
      seen.push(cid);
      while (seen.length > cap) seen.shift();
      return true;
    },
    release(cid: string): void {
      if (!usable(cid)) return;
      const i = seen.indexOf(cid);
      if (i >= 0) seen.splice(i, 1);
    },
    has(cid: string): boolean {
      return usable(cid) && seen.includes(cid);
    },
    size(): number {
      return seen.length;
    },
  };
}
