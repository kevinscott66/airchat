/**
 * Однодорожечная очередь для запуска и разбора службы.
 *
 * v4.32.496. Push-служба поднимается и разбирается из эффекта личности, и оба
 * вызова там огонь-и-забыли: разбор стоит в снятии эффекта (`void
 * dispose()`), запуск — в теле следующего витка (`void init()`). Разбор
 * внутри дожидается сети (удаление FCM-токена) и только в самом конце
 * выставляет `initialized = false`. То есть запуск успевает начаться поверх
 * ещё не закончившегося разбора и увидеть чужое, уже неверное состояние.
 *
 * Правило простое: сколько бы вызовов ни пришло и в каком угодно порядке,
 * следующий начинается только после того, как предыдущий закончился. Тогда
 * `init` всегда читает состояние, оставленное завершившимся `dispose`, а
 * `dispose` не затирает ссылки на отписки, поставленные уже завершившимся
 * `init`.
 *
 * Модуль намеренно без импортов: правило про порядок, а не про push.
 */

/** Ставит задачу в конец дорожки и отдаёт её же результат. */
export type SerialRunner = <T>(task: () => Promise<T>) => Promise<T>;

export function createSerialRunner(): SerialRunner {
  // Хвост дорожки. Всегда успешный: падение одной задачи не должно
  // останавливать очередь — иначе первая же ошибка сети в `dispose`
  // навсегда заблокировала бы уведомления.
  let tail: Promise<void> = Promise.resolve();

  return <T>(task: () => Promise<T>): Promise<T> => {
    const run = tail.then(task, task);
    tail = run.then(
      () => undefined,
      () => undefined,
    );
    return run;
  };
}
