/**
 * activeChatSuppress — когда баннер о личном сообщении не нужен.
 *
 * v4.32.525. Смысл проверки всегда был один: не показывать уведомление о
 * сообщении из переписки, которую человек прямо сейчас и читает. Проверялось
 * же другое — «этот собеседник когда-то был зарегистрирован как открытый».
 *
 * Экран переписки ставил отметку один раз при монтировании ветки и снимал её
 * при размонтировании. Но вкладки в AirChat живут дальше: MainTabs держит
 * смонтированный экран под display:none, чтобы переключение табов не
 * пересобирало тяжёлое дерево. Значит, при переходе на Ленту, Группы или
 * Настройки ветка переписки не размонтируется — отметка остаётся стоять, и
 * все уведомления от этого человека молча выбрасываются до перезапуска
 * приложения. Человек открыл диалог один раз и с этого момента перестал
 * получать от собеседника уведомления вообще.
 *
 * Сюда же входит вторая половина того же вопроса: приложение, свёрнутое с
 * открытой перепиской. Никакой переписки в этот момент человек не видит —
 * экран погашен, — а баннер всё равно подавлялся. Телефон молчал ровно про
 * того, с кем идёт разговор.
 *
 * Решение вынесено в модуль без импортов: три источника состояния (какая
 * ветка открыта, какая вкладка активна, в каком состоянии приложение) сходятся
 * в одном месте, и проверить их сочетания можно, не поднимая notifee, SQLite и
 * React.
 */

/** Что известно о том, видна ли переписка или группа прямо сейчас. */
export type OpenChatState = {
  /** DID собеседника, чью ветку смонтировал экран переписки, либо null. */
  peerDid: string | null;
  /** Идентификатор группы, чью ветку смонтировал экран групп, либо null. */
  groupId: string | null;
  /** Имя активной вкладки нижней панели, либо null, если ещё неизвестно. */
  tab: string | null;
  /** AppState.currentState: 'active' | 'background' | 'inactive' и т.п. */
  appState: string | null;
};

/**
 * Подавить ли баннер о сообщении от `contactDid`.
 *
 * Подавляем только при совпадении всех трёх условий: это тот самый
 * собеседник, открыта вкладка переписки, приложение на переднем плане.
 * Любое сомнение — показываем: лишний баннер человек закроет, пропущенное
 * сообщение он не увидит никогда.
 */
export function shouldSuppressDmBanner(
  state: OpenChatState,
  contactDid: string | null | undefined,
): boolean {
  if (!contactDid || !state.peerDid) return false;
  if (contactDid !== state.peerDid) return false;
  if (state.tab !== 'chat') return false;
  return state.appState === 'active';
}

/**
 * Подавить ли баннер о сообщении в группе `groupId`.
 *
 * v4.32.560. Той же проверки у групп не было ни в каком виде: системное
 * уведомление показывалось и тогда, когда человек читает ровно эту группу и
 * видит новое сообщение своими глазами. Внутриэкранный баннер группу-то
 * различал (App.tsx сверяет открытый groupJump), а показ в шторке — нет, и
 * телефон дёргался на каждую строку открытой переписки.
 *
 * Условия те же три и в том же порядке строгости: та самая группа, вкладка
 * групп, приложение на переднем плане. Любое сомнение — показываем.
 */
export function shouldSuppressGroupBanner(
  state: OpenChatState,
  groupId: string | null | undefined,
): boolean {
  if (!groupId || !state.groupId) return false;
  if (groupId !== state.groupId) return false;
  if (state.tab !== 'groups') return false;
  return state.appState === 'active';
}
