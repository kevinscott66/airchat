/**
 * Звонок, доехавший до закрытого приложения.
 *
 * v4.32.573. Звонок жил ровно в одном месте — в живом сокете сигналинга. Пока
 * приложение открыто, offer приходит и экран звонка поднимается; стоит свернуть
 * или закрыть приложение — сокета нет, сервер отвечает звонящему
 * `peer_unavailable`, и звонок обрывается на первой же секунде словом
 * «Недоступен». То есть дозвониться можно было только до человека, который и
 * так смотрит в телефон.
 *
 * Закрывается это тем же конвертом, которым уже ходят уведомления о
 * сообщениях: короткий push будит устройство, а само предложение звонка
 * звонящий повторяет по сокету, пока тот, кому звонят, не появится в сети.
 * Ни sdp, ни ICE через push не едут и ехать не должны: в них лежат адреса
 * устройства, и чужой сервер их видеть не обязан. Push несёт ровно два поля —
 * случайный номер звонка и DID звонящего.
 *
 * Текст баннера сочиняется здесь, на устройстве получателя, а не сервером:
 * то же правило, что и у сообщений (HIGH-4). Сервер не должен уметь написать
 * на чужом экране блокировки произвольную строку.
 *
 * Модуль намеренно без импортов: его читает фоновый обработчик push, который
 * живёт в отдельном запуске JS и не должен тянуть за собой ни базу, ни
 * транспорт, ни WebRTC.
 */

/** Значение поля `kind` в конверте push для звонка. */
export const CALL_PUSH_KIND = 'call';

export const CALL_BANNER_TITLE = 'AirChat';
export const CALL_BANNER_BODY = 'Входящий звонок';

/**
 * Сколько баннер звонка висит, если приложение так и не подняли.
 *
 * v4.32.746: было 60 секунд — на пятнадцать больше, чем звонящий вообще звонит
 * (OUTGOING_RINGING_TIMEOUT_MS = 45 с). Эти пятнадцать секунд телефон звал к
 * трубке, за которой уже никого не было, и отделаться от зова человек не мог:
 * баннер выставлен `ongoing`, то есть не смахивается. Нажатие приводило в
 * приложение, где никакого звонка нет.
 *
 * Теперь срок равен сроку дозвона. Ровной секунды в секунду не выйдет:
 * отсчёт начинается с показа баннера, а push идёт до устройства какое-то
 * время. Уточнять его нечем — время начала звонка приезжало бы от сервера, а
 * значит, сервер мог бы гасить чужие звонки в момент показа.
 *
 * Значение обязано совпадать с OUTGOING_RINGING_TIMEOUT_MS; их совпадение
 * сторожит проверка в notifications/__tests__/callPush.test.ts. Числом, а не
 * импортом, — см. оговорку про отсутствие импортов в шапке файла.
 */
export const CALL_BANNER_TIMEOUT_MS = 45_000;

/** Один баннер на звонок: повторный push того же звонка заменяет прежний. */
export function callBannerId(callId: string): string {
  return `call:${callId}`;
}

/**
 * Номер звонка из случайных байтов — шестнадцатеричный, 32 знака.
 *
 * Форма выбрана под уже существующие проверки: сервер пропускает `cid` только
 * из букв и цифр, а разбор уведомления на устройстве — только hex от 16 до 128
 * знаков. Номер ничего не значит и ни с чем не связан: он нужен, чтобы два
 * звонка подряд не склеились в один баннер.
 */
export function newCallId(bytes: Uint8Array): string {
  let out = '';
  for (const b of bytes) out += b.toString(16).padStart(2, '0');
  return out.slice(0, 32).padEnd(32, '0');
}
