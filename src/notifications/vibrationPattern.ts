/**
 * Рисунок вибрации уведомления — и почему он не имеет права начинаться с нуля.
 *
 * Измеренный дефект (v4.32.567). Все четыре места, показывающие баннер,
 * передавали notifee один и тот же рисунок:
 *
 *     vibrationPattern: vibrate ? [0, 250, 150, 250] : []
 *
 * Ведущий ноль здесь — привычка из Android: в `VibrationEffect.createWaveform`
 * нулевой элемент означает «начать без задержки». Но до платформы этот массив
 * не доходит. notifee проверяет его сам, в JS, и правило у него другое —
 * `node_modules/@notifee/react-native/dist/validators/validate.js`:
 *
 *     if (pattern.length % 2 !== 0) return false;
 *     ...
 *     if (ms <= 0) return false;
 *
 * То есть значения обязаны быть строго положительными. Ноль первым элементом
 * проваливает проверку, `validateAndroidNotification` бросает «expected an
 * array containing an even number of positive values», и `displayNotification`
 * отказывает ДО обращения к нативной части.
 *
 * Чем это обернулось. Вибрация включена по умолчанию (`notify_vibrate` не
 * задан → `!== 'false'` → true), поэтому ветка с нулём была не редкой, а
 * единственной. Каждый вызов бросал, а каждый вызывающий исключение глушил:
 * три места писали `log.debug(..._notify_failed)` (в release не виден вовсе),
 * фоновый обработчик — пустой `catch` без единой записи в журнал. В итоге приложение
 * не показывало ни одного баннера о сообщении: ни личного, ни группового, ни
 * ленты, ни при закрытом приложении, — и молчало об этом. Работали ровно два
 * уведомления во всём приложении: «собеседник в сети» и напоминание, потому
 * что они не передают рисунок вовсе.
 *
 * Что изменилось. Задержка перед первым импульсом — 1 мс вместо 0. Она
 * законна по правилу notifee, неотличима на слух от нуля и сохраняет прежний
 * ритм целиком. Плюс `sanitizeVibrationPattern`: любой рисунок приводится к
 * тому, что notifee примет, — потому что подобрать здесь недопустимое число
 * второй раз слишком легко, а расплата за это невидима.
 *
 * Модуль намеренно без единого импорта: правило проверяется без notifee, без
 * Android и без уведомлений — это арифметика над массивом чисел.
 */

/** Кому вибрируем: сообщение (личное, групповое, push) или событие ленты. */
export type VibrationKind = 'message' | 'feed';

/**
 * Ритм для сообщения: короткая пауза, импульс, пауза, импульс.
 *
 * Первое число — задержка перед началом. Ноль здесь и был дефектом; 1 мс —
 * наименьшее значение, которое notifee считает допустимым.
 */
export const MESSAGE_VIBRATION: readonly number[] = [1, 250, 150, 250];

/** Ритм для ленты: одиночный короткий импульс, событие менее срочное. */
export const FEED_VIBRATION: readonly number[] = [1, 150];

/**
 * Правило notifee, повторённое здесь дословно.
 *
 * Держать его копию рядом — не дублирование, а единственный способ проверить
 * рисунок в тестах: сам валидатор лежит в модуле, который тянет react-native
 * и в jest не грузится. Рэтчет сверяет эту копию с текстом валидатора.
 */
export function isNotifeeVibrationPattern(pattern: readonly number[]): boolean {
  if (!Array.isArray(pattern)) return false;
  if (pattern.length % 2 !== 0) return false;
  for (const ms of pattern) {
    if (typeof ms !== 'number' || !Number.isFinite(ms)) return false;
    if (ms <= 0) return false;
  }
  return true;
}

/**
 * Привести рисунок к тому, что notifee примет.
 *
 * Не «проверить и отказать», а именно привести: отказ здесь означал бы снова
 * отсутствующее уведомление, то есть ту же беду с другой стороны. Ноль,
 * отрицательное число и NaN становятся 1 мс — на слух это тот же старт без
 * задержки; дробное округляется; нечётный хвост отбрасывается, потому что
 * рисунок читается парами «пауза, импульс». Пустой вход и не-массив дают
 * пустой массив: он законен и означает «без вибрации».
 */
export function sanitizeVibrationPattern(input: readonly number[] | null | undefined): number[] {
  if (!Array.isArray(input) || input.length === 0) return [];
  const out: number[] = [];
  for (const raw of input) {
    const ms = typeof raw === 'number' && Number.isFinite(raw) ? Math.round(raw) : 1;
    out.push(ms < 1 ? 1 : ms);
  }
  if (out.length % 2 !== 0) out.pop();
  return out;
}

/**
 * Рисунок для баннера с учётом настройки «вибрация».
 *
 * Выключенная вибрация — это пустой массив, а не отсутствие поля: notifee
 * принимает пустой (длина чётная, цикл не выполняется), и именно им прежний
 * код глушил вибрацию. Эта ветка и работала — вторая нет.
 */
export function vibrationFor(vibrate: boolean, kind: VibrationKind): number[] {
  if (!vibrate) return [];
  return sanitizeVibrationPattern(kind === 'feed' ? FEED_VIBRATION : MESSAGE_VIBRATION);
}
