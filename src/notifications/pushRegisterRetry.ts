/**
 * Когда повторить запись адреса доставки на сигналинге (v4.32.734).
 *
 * Адрес доставки записывается один раз, при запуске. Если в эту секунду сети
 * не было — а запуск приложения и есть та самая секунда, когда её чаще всего
 * нет, — ретранслятору некуда слать уведомление, и push молча не работает до
 * следующего запуска. Исход записи с v4.32.733 называется вслух
 * (`PushTokenRegistration`), но пользоваться им было некому: отказ просто
 * уходил в журнал.
 *
 * Повторять имеет смысл только `'unreachable'` — сервер не ответил или
 * отказал. `'unsupported'` (некуда или нечем писать) от повтора не изменится,
 * и долбить сигналинг в этом случае значило бы жечь батарею впустую.
 *
 * Лестница короткая и конечная: пять секунд, двадцать, минута, пять минут. За
 * ней стоит возвращение в приложение — оно сбрасывает счётчик и пробует
 * заново. Это не украшение: если телефон пролежал час в метро, лестница
 * догорит вхолостую, и без сброса дефект вернулся бы в точности — просто
 * отложенный на пять минут.
 */

/** Пауза перед каждой следующей попыткой, в порядке номера попытки. */
export const PUSH_REGISTER_RETRY_DELAYS_MS: readonly number[] = [5_000, 20_000, 60_000, 300_000];

/**
 * Сколько ждать перед попыткой номер `attempt` (считая с нуля).
 *
 * `null` — лестница кончилась: дальше ждём возвращения в приложение, а не
 * следующего срока.
 */
export function nextRetryDelayMs(attempt: number): number | null {
  if (!Number.isInteger(attempt) || attempt < 0) return null;
  return PUSH_REGISTER_RETRY_DELAYS_MS[attempt] ?? null;
}
