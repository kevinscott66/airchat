/**
 * Как убрать баннер звонка (v4.32.746).
 *
 * Баннер входящего звонка нарочно не смахивается: он выставлен `ongoing` и
 * `autoCancel: false`, чтобы окно звонка не исчезало с заблокированного экрана
 * от случайного касания (см. firebaseMessagingBackground). Обратная сторона —
 * убрать его может только тот, кто знает, что звонка больше нет; сам он
 * держится до `CALL_BANNER_TIMEOUT_MS`.
 *
 * Знающих двое: служба звонков, к которой доехало предложение по сокету, и
 * нажатие на сам баннер. Раньше гасила только первая, и то из своей приватной
 * копии этой функции; нажатие не гасило ничего, и человек, откликнувшийся на
 * звонок, возвращался к тому же баннеру в шторке.
 *
 * Модуль тянет notifee по требованию, а не импортом: его зовут и из фонового
 * обработчика push (отдельный запуск JS), и из службы звонков, которой слой
 * уведомлений на старте не нужен.
 */
import { callBannerId } from './callPush';

/**
 * Погасить баннер звонка с этим номером.
 *
 * Молчит во всех случаях, когда гасить нечего или нечем: баннера уже нет,
 * notifee не подключён (тесты, Expo Go), уведомлений на этой платформе нет.
 * Позвать её лишний раз безвредно — это и есть расчёт: знающих несколько, и
 * договариваться между собой им незачем.
 */
export function dismissCallBanner(callId: string): void {
  try {
    // eslint-disable-next-line @typescript-eslint/no-require-imports
    const notifee = require('@notifee/react-native').default as {
      cancelNotification(id: string): Promise<void>;
    };
    void notifee.cancelNotification(callBannerId(callId)).catch(() => { /* уже погашен */ });
  } catch { /* notifee не подключён (тесты, Expo Go) */ }
}
