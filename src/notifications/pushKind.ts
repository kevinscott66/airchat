/**
 * Личное это сообщение или групповое — с точки зрения push-уведомления.
 *
 * v4.32.572. Сообщение в группе едет к каждому участнику тем же личным
 * конвертом, что и переписка один на один (groupMessaging → sendMessage), и
 * push о нём уходит той же дорогой. На принимающей стороне при закрытом
 * приложении об этом сообщении известно ровно две вещи: ключ сообщения и DID
 * того, кто его прислал. Ни идентификатора группы, ни намёка на то, что это
 * вообще группа, в уведомлении нет.
 *
 * Из-за этого фоновый обработчик применял к групповому push настройки личной
 * переписки, и получалось две несуразности сразу:
 *
 *   • выключенный «Личные сообщения» глушил и группы, а выключенные «Группы»
 *     не глушили ничего — фоновый путь этот выключатель не читал вовсе;
 *   • «без звука» для человека глушило его сообщения в общей группе, а
 *     заглушённая группа продолжала будить телефон, потому что глушение
 *     проверялось по DID отправителя, а не по группе.
 *
 * Здесь — один бит: чем было сообщение, ради которого шлётся push. Не
 * идентификатор группы: он поехал бы к чужому серверу открытым текстом и
 * рассказал бы ему, кто в какой группе состоит. Бита хватает, чтобы выбрать
 * правильный выключатель и не применять к группе личное «без звука».
 *
 * Чего бит не даёт. Глушение отдельной группы при закрытом приложении
 * по-прежнему невозможно: чтобы его проверить, нужно знать, какая это группа,
 * а знать это серверу не положено. Заглушённая группа при закрытом приложении
 * баннер покажет — обещать обратное было бы враньём.
 *
 * Достоверность. Бит приходит через чужой сервер и может быть переставлен.
 * Хуже от этого не становится: тот же сервер и сейчас волен прислать push с
 * любым DID и получить баннер «Новое сообщение» в обход любого глушения —
 * глушение спрашивается по DID, который сервер и называет. Текст баннера в
 * фоне один на оба случая и содержимого не раскрывает, так что переставленный
 * бит меняет ровно одно: покажется ли лишний безличный баннер.
 *
 * Модуль без импортов: его читает и фоновый обработчик push, который живёт в
 * отдельном запуске JS и не должен тянуть за собой ни базу, ни транспорт.
 */

/** Чем было сообщение, ради которого шлётся push. */
export type PushKind = 'dm' | 'group';

/**
 * Префикс конверта группового сообщения. Копия `GROUP_MSG_PREFIX` из
 * core/social/groupMessaging: тянуть оттуда импорт значит тянуть в фоновый
 * контекст весь слой групп. Равенство копии и оригинала стережёт рэтчет.
 */
const GROUP_MSG_PREFIX = '\x02grp:';

/**
 * Какой это push по телу конверта.
 *
 * Групповым считается только само сообщение в группе. Приглашение, заявка на
 * вступление и управление группой едут от человека и человеку — их глушит
 * личное «без звука», как и любое другое сообщение от него.
 */
export function classifyPushKind(text: string | null | undefined): PushKind {
  return typeof text === 'string' && text.startsWith(GROUP_MSG_PREFIX) ? 'group' : 'dm';
}

/**
 * Бит из полезной нагрузки уведомления.
 *
 * Всё, что не «group», считается личным сообщением: так же ведут себя старые
 * уведомления, где поля нет вовсе, и так безопаснее — личная ветка проверяет
 * на одно правило больше.
 */
export function parsePushKind(raw: unknown): PushKind {
  return raw === 'group' ? 'group' : 'dm';
}
