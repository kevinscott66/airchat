/**
 * Куда ведёт нажатие на уведомление.
 *
 * Дефект. Уведомление о личном сообщении показывали три разных места: обычный
 * приём по сети (showDmBanner), входящий push при открытом приложении и
 * фоновый обработчик push при закрытом. Все три клали в уведомление cid и DID
 * собеседника — то есть всё, что нужно, чтобы открыть нужную переписку. Но
 * нажатие не открывало её никогда, ни в одном из трёх случаев.
 *
 * Разбиралось это на три отдельные поломки, и каждая закрывала свой путь.
 *
 * Первая: обработчик нажатия при открытом приложении звал
 * `options.onOpenChat?.(cid, contactDid)`, а `onOpenChat` не передавал никто —
 * единственный вызов init() в App.tsx отдаёт только peerId. Необязательное
 * поле с вопросительным знаком молча превращало нажатие в пустое место.
 *
 * Вторая: обработчик нажатия при закрытом приложении не был зарегистрирован
 * вовсе. notifee требует `onBackgroundEvent` вне дерева компонентов и без него
 * пишет предупреждение в лог; у нас его не было ни в index.ts, ни где-либо
 * ещё. Нажатие в шторке при свёрнутом приложении просто разворачивало окно на
 * той вкладке, где его оставили.
 *
 * Третья: `getInitialNotification` не читали никогда. Когда процесс убит,
 * нажатие не приходит событием — оно приходит как «приложение запущено вот
 * этим уведомлением», и прочитать его можно только один раз при старте. Мы не
 * читали, и уведомление, ради которого человек и открыл приложение,
 * растворялось на старте.
 *
 * Четвёртая, общая: даже если бы событие пришло, приходит оно раньше, чем
 * появляется тот, кто умеет открывать переписку. Экран вкладок монтируется
 * после разбора личности, а нажатие при холодном старте случается до неё.
 * Событие, доставленное в пустоту, теряется навсегда.
 *
 * Что здесь. Разбор полезной нагрузки уведомления (он был скопирован в трёх
 * местах слово в слово) и хранение намерения до появления получателя.
 * Намерение, пришедшее раньше получателя, не теряется, а ждёт его; получатель,
 * появившись, забирает ожидающее намерение сразу. Один и тот же cid не
 * открывает переписку дважды: при холодном старте одно и то же нажатие
 * приходит и событием, и ответом getInitialNotification, и без этой отметки
 * приложение дважды дёргало бы сеть за одним и тем же сообщением.
 *
 * Модуль намеренно ни от чего не зависит: его зовут и из дерева компонентов, и
 * из фонового обработчика, который живёт в отдельном запуске JS и не должен
 * тянуть за собой ни базу, ни транспорт, ни notifee.
 *
 * ── v4.32.560 ───────────────────────────────────────────────────────────────
 *
 * Пятая поломка, оставленная прошлым разом «рядом»: у уведомления о сообщении
 * в группе полезной нагрузки не было вовсе. Показ звал displayNotification без
 * `data`, поэтому разбирать было нечего, и нажатие на групповой баннер вело
 * туда же, куда вело раньше нажатие на любой другой, — в приложение на той
 * вкладке, где его свернули. Половина всех уведомлений в мессенджере с
 * группами и каналами никуда не вела и после v4.32.558.
 *
 * Шестая — в самой отметке о повторе. Правило «тот же ключ второй раз не
 * отдаём» писалось против одного случая: при холодном старте одно нажатие
 * приходит дважды, событием и ответом getInitialNotification. Но записано оно
 * было без оглядки на источник, а значит гасило и второе настоящее нажатие:
 * открыть переписку из шторки, вернуться в список, нажать тот же баннер ещё
 * раз — и не произойдёт ничего. У группового баннера это стало бы правилом, а
 * не редкостью: он один на всю группу и живёт в шторке, пока его не смахнут.
 * Теперь повтором может быть только чтение на старте; нажатие человека —
 * никогда.
 */

/** Открыть переписку: сообщение и, если известен, собеседник. */
export interface ChatOpenIntent {
  kind: 'chat';
  /** Идентификатор сообщения из полезной нагрузки уведомления. */
  cid: string;
  /** DID собеседника; в старых уведомлениях его может не быть. */
  contactDid?: string;
}

/** Открыть группу или канал. */
export interface GroupOpenIntent {
  kind: 'group';
  /** Идентификатор группы из полезной нагрузки уведомления. */
  groupId: string;
  /**
   * Сообщение, о котором показали баннер. Открытие им не пользуется: групповой
   * баннер один на всю группу и несёт последнее сообщение. Нужен он ровно для
   * того, чтобы два нажатия по одному баннеру в разное время не выглядели
   * одинаково — см. отметку о повторе ниже.
   */
  msgId?: string;
}

/**
 * Поднять экран входящего звонка.
 *
 * v4.32.573: звонок доезжал только до открытого приложения — см.
 * notifications/callPush. Само соединение поднимает не нажатие: оно лишь
 * выводит приложение вперёд, а предложение звонка звонящий к этому времени уже
 * повторяет по сокету. Поэтому здесь нет ни sdp, ни адресов — только номер
 * звонка и, если он годной формы, DID звонящего.
 */
export interface CallOpenIntent {
  kind: 'call';
  /** Случайный номер звонка из полезной нагрузки уведомления. */
  callId: string;
  /** DID звонящего; нужен, чтобы показать, кто звонит. */
  contactDid?: string;
}

/** Куда ведёт нажатие. Разные ветки открывают разные экраны. */
export type OpenIntent = ChatOpenIntent | GroupOpenIntent | CallOpenIntent;

/** Каким путём пришло нажатие. Нужно только для журнала. */
export type IntentSource = 'foreground-press' | 'background-press' | 'cold-start';

/** Тот, кто умеет открыть переписку. Ставит экран вкладок. */
export type IntentConsumer = (intent: OpenIntent, source: IntentSource) => void;

/**
 * Что стало с намерением: отдано получателю, оставлено ждать получателя, или
 * отброшено как повтор уже виденного нажатия.
 */
export type DeliveryOutcome = 'delivered' | 'held' | 'duplicate';

/** cid — шестнадцатеричный, от 16 до 128 знаков. */
const CID_SHAPE = /^[a-f0-9]{16,128}$/i;
/** did:метод:идентификатор, без запаса на что-либо ещё. */
const DID_SHAPE = /^did:[a-z0-9]+:[A-Za-z0-9._-]+$/;
const DID_MAX_LEN = 256;
/**
 * Идентификатор группы и сообщения: печатные знаки без пробелов, до 128 —
 * ровно тот предел, что проверяет разбор конверта в groupMessaging. Форма
 * узкая нарочно: значение приходит из сети и уезжает в запрос к базе.
 */
const ROW_ID_SHAPE = /^[A-Za-z0-9._:-]{1,128}$/;

/** Идентификатор строки, если он годной формы. */
function rowId(value: unknown): string | undefined {
  return typeof value === 'string' && ROW_ID_SHAPE.test(value) ? value : undefined;
}

/** DID собеседника или звонящего, если он годной формы. */
function contactDidOf(data: Record<string, unknown>): string | undefined {
  const raw = data.contactDid ?? data.senderDid;
  return typeof raw === 'string' && raw.length <= DID_MAX_LEN && DID_SHAPE.test(raw)
    ? raw
    : undefined;
}

/**
 * Разбирает `data` уведомления в намерение.
 *
 * Данные приходят из сети и недостоверны: всё, что попадёт в запрос к базе или
 * в навигацию, проверяется по форме. Звонок решает первым — он один помечает
 * себя полем kind, — затем группа: её баннер несёт groupId и не несёт cid, а
 * личный — наоборот, так что перепутать их нечем.
 * Без cid личного намерения нет — открывать было бы нечего. Без DID намерение
 * есть: переписку по нему открыть нельзя, но сообщение подтянуть и вкладку
 * показать можно.
 */
export function parseOpenIntent(data: Record<string, unknown> | null | undefined): OpenIntent | null {
  if (!data || typeof data !== 'object') return null;
  // v4.32.573: звонок решает раньше всех. Его конверт неотличим от личного —
  // тот же `cid`, тот же `senderDid`, — и без этой ветки push о звонке был бы
  // разобран как сообщение, а приложение полезло бы тянуть из сети сообщение
  // с номером звонка вместо ключа.
  const call = parseCallOpenIntent(data);
  if (call) return call;
  const groupId = rowId(data.groupId);
  if (groupId) {
    const msgId = rowId(data.msgId);
    return msgId ? { kind: 'group', groupId, msgId } : { kind: 'group', groupId };
  }
  const rawCid = data.cid;
  if (typeof rawCid !== 'string' || !CID_SHAPE.test(rawCid)) return null;
  const contactDid = contactDidOf(data);
  return contactDid ? { kind: 'chat', cid: rawCid, contactDid } : { kind: 'chat', cid: rawCid };
}

/**
 * Намерение поднять экран звонка.
 *
 * Отдельный разбор нужен фоновому обработчику: у него ветка звонка идёт до
 * ветки сообщения и не должна зависеть от порядка проверок в parseOpenIntent.
 */
export function parseCallOpenIntent(
  data: Record<string, unknown> | null | undefined,
): CallOpenIntent | null {
  if (!data || typeof data !== 'object' || data.kind !== 'call') return null;
  const rawId = data.cid;
  if (typeof rawId !== 'string' || !CID_SHAPE.test(rawId)) return null;
  const did = contactDidOf(data);
  return did ? { kind: 'call', callId: rawId, contactDid: did } : { kind: 'call', callId: rawId };
}

/**
 * Намерение открыть переписку — для путей, которым нужен именно cid.
 *
 * Входящее FCM-сообщение и фоновый обработчик push подтягивают сообщение по
 * cid; ни групповой полезной нагрузки, ни звонка там быть не должно, и молча
 * принять их за личное сообщение нельзя — запрос ушёл бы с идентификатором
 * группы или номером звонка вместо ключа сообщения.
 */
export function parseChatOpenIntent(
  data: Record<string, unknown> | null | undefined,
): ChatOpenIntent | null {
  const intent = parseOpenIntent(data);
  return intent && intent.kind === 'chat' ? intent : null;
}

/** Чем одно нажатие отличается от другого. Только для отметки о повторе. */
function intentKey(intent: OpenIntent): string {
  if (intent.kind === 'chat') return `chat:${intent.cid}`;
  if (intent.kind === 'call') return `call:${intent.callId}`;
  return `group:${intent.groupId}:${intent.msgId ?? ''}`;
}

let consumer: IntentConsumer | null = null;
let held: { intent: OpenIntent; source: IntentSource } | null = null;
let lastKey: string | null = null;

/**
 * Отдаёт намерение получателю, а если его ещё нет — оставляет ждать.
 *
 * Ровно здесь закрывается «нажатие в пустоту»: у функции нет исхода, при
 * котором намерение бесследно исчезает. Оно либо отдано, либо ждёт, либо
 * отброшено как повтор.
 *
 * Повтором бывает только чтение уведомления на старте: при холодном старте
 * одно нажатие приходит и событием, и ответом getInitialNotification. Само
 * нажатие повтором не бывает никогда — второе нажатие по тому же баннеру
 * человек делает намеренно, и гасить его (v4.32.558 гасил) значит снова
 * оставлять нажатие без последствий.
 */
export function deliverOpenIntent(intent: OpenIntent, source: IntentSource): DeliveryOutcome {
  const key = intentKey(intent);
  if (source === 'cold-start' && lastKey === key) return 'duplicate';
  lastKey = key;
  if (consumer) {
    consumer(intent, source);
    return 'delivered';
  }
  held = { intent, source };
  return 'held';
}

/**
 * Ставит получателя и сразу отдаёт ему то, что ждало.
 *
 * Возвращает снятие — экран вкладок зовёт его при размонтировании, и с этого
 * момента намерения снова копятся, а не пропадают.
 */
export function setOpenIntentConsumer(next: IntentConsumer | null): () => void {
  consumer = next;
  if (next && held) {
    const pending = held;
    held = null;
    next(pending.intent, pending.source);
  }
  return () => {
    if (consumer === next) consumer = null;
  };
}

/** Намерение, ждущее получателя. Только для проверок и журнала. */
export function heldOpenIntent(): OpenIntent | null {
  return held ? held.intent : null;
}

/** Сброс между тестами: своего состояния между запусками приложения нет. */
export function resetOpenIntents(): void {
  consumer = null;
  held = null;
  lastKey = null;
}
