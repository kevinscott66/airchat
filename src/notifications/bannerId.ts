/**
 * Имя баннера для личного сообщения (v4.32.502).
 *
 * Баннер о личном сообщении показывают два независимых пути: обработчик push
 * при закрытом приложении и приём сообщения в самом приложении. От двойного
 * показа защищала только память процесса (`notifyDedup`), а фоновый
 * обработчик живёт в отдельном контексте, который поднимается на каждый push,
 * — этой памяти он не видит и видеть не может. Одно сообщение давало два
 * баннера: сначала безличное «Новое сообщение», следом — с именем отправителя.
 *
 * Решение — не третья попытка договориться через хранилище, а имя баннера.
 * notifee считает уведомления с одинаковым id одним и тем же: второй показ
 * заменяет первый вместо того, чтобы встать рядом. Безличный баннер из фона
 * превращается в именной, когда приложение доберётся до сообщения, а порядок
 * между двумя контекстами перестаёт что-либо значить.
 *
 * Без зависимостей: один из двух вызывающих — фоновый контекст, которому
 * нельзя тянуть за собой слой хранилища.
 */
export function bannerIdForCid(cid: string): string {
  return `dm:${cid}`;
}

/**
 * Имя баннера для сообщения в группе или канале (v4.32.560).
 *
 * У группового показа имени не было вовсе, и notifee ставил каждому баннеру
 * своё. Двадцать сообщений в оживлённой группе давали двадцать строк в шторке
 * — по одной на каждое, — притом что открыть они вели бы в одно и то же место.
 * У переписки эта беда закрыта с v4.32.502; группам она досталась заодно с
 * полезной нагрузкой, без которой нажатие всё равно никуда не вело.
 *
 * Имя одно на группу, а не на сообщение: новый баннер заменяет прежний, и в
 * шторке остаётся последнее сообщение группы — то же, что показывает список.
 */
export function bannerIdForGroup(groupId: string): string {
  return `group:${groupId}`;
}
